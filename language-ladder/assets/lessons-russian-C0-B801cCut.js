<!-- hl-knowledge: introduces=[RU-ETYMON-PISAT-PAINT]; assesses=[RU-ETYMON-CHITAT-COUNT-HONOUR, RU-ETYMON-DUMAT-DUMA, RU-ETYMON-PONIMAT-TAKE-HOLD, RU-LEX-PONIMAT, RU-LEX-DUMAT] -->

