//! # Bounded-exhaustive soundness, completeness and differential tests
//!
//! Random testing samples; this file *enumerates*. The domain is every CNF
//! formula over variables x1..x3 with at most three clauses, each clause
//! being the empty clause, a unit, or an ordered pair of literals (so pairs
//! include duplicate literals `(x x)` and tautologies `(x -x)`). Formulas are
//! multisets of such clauses, so duplicate clauses occur too.
//!
//! ```text
//!   clause universe  = 1 (empty) + 6 (units) + 36 (ordered pairs)  = 43
//!   formulas         = C(43,0)+C(44,1)+C(45,2)+C(46,3)             = 15 180
//! ```
//!
//! (the exact counts are asserted below, not trusted from this comment).
//!
//! Satisfiability is decided by brute force over the 8 assignments, which
//! is the oracle the kernel is *not* allowed to disagree with:
//!
//! * **Soundness (VER11 3.4.1).** For every satisfiable formula, *no*
//!   candidate proof is accepted: the empty proof, every one-step proof, and
//!   every two-step proof (additions and deletions, over a proof alphabet
//!   that also uses a fresh variable x4 so RAT definitions are exercised),
//!   each with and without a final empty clause.
//! * **Completeness on the bounded domain.** For every unsatisfiable
//!   formula, a proof generated by a tiny resolution-saturation reference
//!   (every resolvent is RUP) is accepted, in several syntactic variants.
//! * **Differential.** The watched-literal kernel and an independent
//!   full-scan checker written in this file agree on verdict *and step*
//!   over the same enumerated proofs (UNSAT formulas included, which is
//!   where RAT-vs-RUP and deletion interplay matter).

// `is_multiple_of` is too new for older toolchains the repo still builds on.
#![allow(unknown_lints, clippy::manual_is_multiple_of)]

use drat_check::{check, Rejection};

type Clause = Vec<i32>;

/// The 43 clauses of the formula universe over x1..x3.
fn formula_universe() -> Vec<Clause> {
    let lits: Vec<i32> = vec![1, -1, 2, -2, 3, -3];
    let mut u: Vec<Clause> = vec![vec![]];
    for &a in &lits {
        u.push(vec![a]);
    }
    for &a in &lits {
        for &b in &lits {
            u.push(vec![a, b]);
        }
    }
    u
}

/// The proof alphabet: the formula universe plus clauses using the fresh
/// variable x4 (units and pairs with every x1..x3 literal, both polarities
/// of x4), so that RAT lemmas on a brand-new variable occur.
fn proof_universe() -> Vec<Clause> {
    let mut u = formula_universe();
    for &f in &[4, -4] {
        u.push(vec![f]);
        for &l in &[1, -1, 2, -2, 3, -3] {
            u.push(vec![f, l]);
            u.push(vec![l, f]);
        }
    }
    u
}

/// Every multiset of at most `max_clauses` clauses from `universe`
/// (as index-nondecreasing sequences).
fn formulas(universe: &[Clause], max_clauses: usize) -> Vec<Vec<Clause>> {
    let mut out: Vec<Vec<Clause>> = vec![vec![]];
    let mut frontier: Vec<Vec<usize>> = vec![vec![]];
    for _ in 0..max_clauses {
        let mut next = Vec::new();
        for f in &frontier {
            let start = f.last().copied().unwrap_or(0);
            for i in start..universe.len() {
                let mut g = f.clone();
                g.push(i);
                out.push(g.iter().map(|&k| universe[k].clone()).collect());
                next.push(g);
            }
        }
        frontier = next;
    }
    out
}

fn satisfiable(vars: u32, f: &[Clause]) -> bool {
    (0u32..1 << vars).any(|m| {
        f.iter().all(|c| {
            c.iter().any(|&l| {
                let bit = (m >> (l.unsigned_abs() - 1)) & 1 == 1;
                if l > 0 {
                    bit
                } else {
                    !bit
                }
            })
        })
    })
}

fn formula_text(f: &[Clause]) -> String {
    let mut s = format!("p cnf 3 {}\n", f.len());
    for c in f {
        for l in c {
            s.push_str(&format!("{l} "));
        }
        s.push_str("0\n");
    }
    s
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Step {
    Add(Clause),
    Del(Clause),
}

fn proof_text(p: &[Step]) -> String {
    let mut s = String::new();
    for st in p {
        let c = match st {
            Step::Add(c) => c,
            Step::Del(c) => {
                s.push_str("d ");
                c
            }
        };
        for l in c {
            s.push_str(&format!("{l} "));
        }
        s.push_str("0\n");
    }
    s
}

// ---------------------------------------------------------------------------
// An independent full-scan reference checker (no watches, no hash maps).
// ---------------------------------------------------------------------------

#[derive(Debug, PartialEq, Eq)]
enum Verdict {
    Accepted,
    NotImplied(usize),
    DeleteAbsent(usize),
    NoEmptyClause,
}

/// Does assuming every literal in `assumed` true, then propagating over
/// `db` until nothing changes, produce a conflict?
fn conflict(db: &[Clause], assumed: &[i32]) -> bool {
    // truth[v] for v in 1..=4: 0 unknown, 1 true, -1 false.
    let mut truth = [0i8; 5];
    let set = |truth: &mut [i8; 5], l: i32| -> bool {
        let want = if l > 0 { 1 } else { -1 };
        let v = l.unsigned_abs() as usize;
        if truth[v] == -want {
            return false; // clash
        }
        truth[v] = want;
        true
    };
    for &l in assumed {
        if !set(&mut truth, l) {
            return true;
        }
    }
    loop {
        let mut changed = false;
        for c in db {
            let mut sat = false;
            let mut open: Vec<i32> = Vec::new();
            for &l in c {
                let t = truth[l.unsigned_abs() as usize] * if l > 0 { 1 } else { -1 };
                if t == 1 {
                    sat = true;
                } else if t == 0 && !open.contains(&l) {
                    open.push(l);
                }
            }
            if sat {
                continue;
            }
            match open.len() {
                0 => return true,
                1 => {
                    set(&mut truth, open[0]);
                    changed = true;
                }
                _ => {}
            }
        }
        if !changed {
            return false;
        }
    }
}

fn ref_rup(db: &[Clause], lemma: &[i32]) -> bool {
    let neg: Vec<i32> = lemma.iter().map(|&l| -l).collect();
    conflict(db, &neg)
}

fn ref_rat(db: &[Clause], lemma: &[i32]) -> bool {
    let Some(&p) = lemma.first() else { return false };
    db.iter().filter(|d| d.contains(&-p)).all(|d| {
        let mut r = lemma.to_vec();
        r.extend(d.iter().copied().filter(|&l| l != -p));
        ref_rup(db, &r)
    })
}

fn as_set(c: &[i32]) -> Vec<i32> {
    let mut s = c.to_vec();
    s.sort_unstable();
    s.dedup();
    s
}

fn ref_check(f: &[Clause], proof: &[Step]) -> Verdict {
    let mut db = f.to_vec();
    for (i, st) in proof.iter().enumerate() {
        match st {
            Step::Del(c) => match db.iter().position(|d| as_set(d) == as_set(c)) {
                Some(p) => {
                    db.remove(p);
                }
                None => return Verdict::DeleteAbsent(i),
            },
            Step::Add(c) => {
                if !(ref_rup(&db, c) || ref_rat(&db, c)) {
                    return Verdict::NotImplied(i);
                }
                if c.is_empty() {
                    return Verdict::Accepted;
                }
                db.push(c.clone());
            }
        }
    }
    Verdict::NoEmptyClause
}

fn kernel(f: &[Clause], proof: &[Step]) -> Verdict {
    match check(&formula_text(f), &proof_text(proof)) {
        Ok(_) => Verdict::Accepted,
        Err(Rejection::NotImplied { step, .. }) => Verdict::NotImplied(step),
        Err(Rejection::DeleteAbsent { step, .. }) => Verdict::DeleteAbsent(step),
        Err(Rejection::NoEmptyClause) => Verdict::NoEmptyClause,
        Err(e) => panic!("generated input rejected as {e:?}"),
    }
}

// ---------------------------------------------------------------------------
// Enumerators of candidate proofs.
// ---------------------------------------------------------------------------

/// The proof alphabet with every step pre-rendered, so the hot loops only
/// concatenate strings. The last entry is the empty-clause step `0`.
struct Alphabet {
    steps: Vec<Step>,
    text: Vec<String>,
    zero: usize,
}

impl Alphabet {
    fn new() -> Alphabet {
        let mut steps = Vec::new();
        for c in proof_universe() {
            if c.is_empty() {
                continue;
            }
            steps.push(Step::Add(c.clone()));
            steps.push(Step::Del(c));
        }
        steps.push(Step::Add(vec![]));
        steps.push(Step::Del(vec![]));
        let zero = steps.len() - 2;
        let text = steps.iter().map(|s| proof_text(std::slice::from_ref(s))).collect();
        Alphabet { steps, text, zero }
    }

    fn render(&self, p: &[usize]) -> String {
        p.iter().map(|&i| self.text[i].as_str()).collect()
    }

    fn steps_of(&self, p: &[usize]) -> Vec<Step> {
        p.iter().map(|&i| self.steps[i].clone()).collect()
    }

    /// Every proof of length 0 and 1, plus a deterministic 1-in-`stride`
    /// sample of the length-2 proofs, each in two forms: as is, and with a
    /// final empty-clause step appended.
    fn proofs(&self, stride: usize) -> Vec<Vec<usize>> {
        let n = self.steps.len();
        let mut out: Vec<Vec<usize>> = vec![vec![]];
        out.extend((0..n).map(|a| vec![a]));
        for a in 0..n {
            for b in 0..n {
                if (a * n + b) % stride == 0 {
                    out.push(vec![a, b]);
                }
            }
        }
        let zeroed: Vec<Vec<usize>> = out
            .iter()
            .map(|p| {
                let mut q = p.clone();
                q.push(self.zero);
                q
            })
            .collect();
        out.extend(zeroed);
        out
    }
}

#[test]
fn domain_sizes_are_what_the_docs_say() {
    let u = formula_universe();
    assert_eq!(u.len(), 43);
    assert_eq!(proof_universe().len(), 43 + 2 * (1 + 12));
    let fs = formulas(&u, 3);
    // multisets of size 0..=3 from 43 items: 1 + 43 + 946 + 14190.
    assert_eq!(fs.len(), 1 + 43 + 946 + 14190);
    let sat = fs.iter().filter(|f| satisfiable(3, f)).count();
    let unsat = fs.len() - sat;
    println!("formulas={} sat={sat} unsat={unsat}", fs.len());
    assert!(sat > 1000 && unsat > 1000, "both classes must be well populated");
}

#[test]
fn soundness_no_candidate_proof_is_accepted_for_any_satisfiable_formula() {
    let t0 = std::time::Instant::now();
    let alpha = Alphabet::new();
    let fs = formulas(&formula_universe(), 3);
    let sat: Vec<&Vec<Clause>> = fs.iter().filter(|f| satisfiable(3, f)).collect();
    let totals = par_sum(&sat, |f, acc| {
        let text = formula_text(f);
        // Every 0/1-step proof for every satisfiable formula; the length-2
        // proofs are sampled more densely for the small formulas.
        let stride = if f.len() <= 2 { SOUND_STRIDE_SMALL } else { SOUND_STRIDE_LARGE };
        for p in alpha.proofs(stride) {
            acc[0] += 1;
            let r = check(&text, &alpha.render(&p));
            assert!(r.is_err(), "ACCEPTED a proof for a SATISFIABLE formula!\nformula:\n{text}proof:\n{}", alpha.render(&p));
        }
    });
    println!("soundness: sat formulas={} proofs tried={} in {:?}", sat.len(), totals[0], t0.elapsed());
    assert!(totals[0] > 1_000_000);
}

/// Run `f` over `items` on all available cores; each call adds into a small
/// counter array, and the per-thread arrays are summed.
fn par_sum<T: Sync>(items: &[T], f: impl Fn(&T, &mut [usize; 5]) + Sync) -> [usize; 5] {
    let n = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1).min(8);
    let f = &f;
    std::thread::scope(|sc| {
        let hs: Vec<_> = (0..n)
            .map(|t| {
                sc.spawn(move || {
                    let mut acc = [0usize; 5];
                    for item in items.iter().skip(t).step_by(n) {
                        f(item, &mut acc);
                    }
                    acc
                })
            })
            .collect();
        let mut tot = [0usize; 5];
        for h in hs {
            let a = h.join().unwrap_or_else(|e| std::panic::resume_unwind(e));
            for i in 0..5 {
                tot[i] += a[i];
            }
        }
        tot
    })
}

/// Sampling strides for two-step proofs (1 = every pair). Tuned so the whole
/// file runs in about a minute in a debug build.
const SOUND_STRIDE_SMALL: usize = 29;
const SOUND_STRIDE_LARGE: usize = 1_000_000;
const DIFF_STRIDE_SMALL: usize = 53;
const DIFF_STRIDE_LARGE: usize = 1_000_000;
const DIFF_FORMULA_SAMPLE: usize = 6;

// --- resolution reference generator ---------------------------------------

/// A resolution refutation by saturation: repeatedly resolve all pairs of
/// non-tautological clauses, recording each new resolvent in order, until
/// the empty clause appears. Every recorded resolvent is RUP in the database
/// holding its two premises. Returns the lemmas *including* the final empty
/// clause, or `None` if the formula has no refutation (it is satisfiable).
fn refutation(f: &[Clause]) -> Option<Vec<Clause>> {
    let mut db: Vec<Clause> = Vec::new();
    for c in f {
        let s = as_set(c);
        let taut = s.iter().any(|l| s.contains(&-l));
        if !taut && !db.contains(&s) {
            db.push(s);
        }
    }
    let mut lemmas: Vec<Clause> = Vec::new();
    if db.iter().any(|c| c.is_empty()) {
        return Some(vec![vec![]]);
    }
    loop {
        let mut fresh: Option<Clause> = None;
        'search: for i in 0..db.len() {
            for j in (i + 1)..db.len() {
                for &l in &db[i] {
                    if db[j].contains(&-l) {
                        let mut r: Vec<i32> = db[i].iter().copied().filter(|&x| x != l).collect();
                        r.extend(db[j].iter().copied().filter(|&x| x != -l));
                        let r = as_set(&r);
                        if r.iter().any(|x| r.contains(&-x)) || db.contains(&r) {
                            continue;
                        }
                        fresh = Some(r);
                        break 'search;
                    }
                }
            }
        }
        let r = fresh?;
        db.push(r.clone());
        lemmas.push(r.clone());
        if r.is_empty() {
            return Some(lemmas);
        }
    }
}

#[test]
fn completeness_every_unsatisfiable_formula_has_an_accepted_resolution_proof() {
    let fs = formulas(&formula_universe(), 3);
    let (mut unsat, mut lemma_total, mut longest) = (0usize, 0usize, 0usize);
    for f in &fs {
        let sat = satisfiable(3, f);
        let r = refutation(f);
        assert_eq!(r.is_none(), sat, "resolution completeness vs brute force on {f:?}");
        let Some(lemmas) = r else { continue };
        unsat += 1;
        lemma_total += lemmas.len();
        longest = longest.max(lemmas.len());
        let text = formula_text(f);
        let base: Vec<Step> = lemmas.iter().cloned().map(Step::Add).collect();
        let ok = check(&text, &proof_text(&base)).unwrap_or_else(|e| panic!("rejected a valid proof: {e}\n{text}{}", proof_text(&base)));
        assert_eq!(ok.lemmas, lemmas.len());
        assert_eq!(ok.rat_lemmas, 0, "resolvents are RUP, never need RAT");
        assert_eq!(ok.deletions, 0);
        assert_eq!(ok.empty_clause_line, lemmas.len());

        // Variant: every lemma's literals reversed (RUP is order-free).
        let rev: Vec<Step> = lemmas.iter().map(|c| Step::Add(c.iter().rev().copied().collect())).collect();
        assert!(check(&text, &proof_text(&rev)).is_ok(), "reversed literal order must not matter (RUP)");

        // Variant: valid steps after the empty clause are never checked.
        let mut tail = proof_text(&base);
        tail.push_str("d 1 2 3 0\n7 0\n0\n");
        let ok2 = check(&text, &tail).unwrap();
        assert_eq!(ok2.lemmas, lemmas.len());

        // Variant: without the final empty clause the proof is incomplete.
        if !lemmas.is_empty() {
            let cut = &base[..base.len() - 1];
            assert_eq!(check(&text, &proof_text(cut)), Err(Rejection::NoEmptyClause), "{text} {cut:?}");
        }

        // Variant: each lemma duplicated (adding a clause twice is legal and
        // the second copy is trivially RUP).
        let dup: Vec<Step> = lemmas.iter().flat_map(|c| [Step::Add(c.clone()), Step::Add(c.clone())]).collect();
        let dup_ok = check(&text, &proof_text(&dup));
        assert!(dup_ok.is_ok(), "{dup_ok:?}");

        // Variant: delete the duplicate copies just added (set-matched,
        // reversed literals) before continuing.
        let mut with_del: Vec<Step> = Vec::new();
        for c in &lemmas {
            if c.is_empty() {
                with_del.push(Step::Add(vec![]));
            } else {
                with_del.push(Step::Add(c.clone()));
                with_del.push(Step::Add(c.clone()));
                with_del.push(Step::Del(c.iter().rev().copied().collect()));
            }
        }
        assert!(check(&text, &proof_text(&with_del)).is_ok());
    }
    println!("unsat formulas={unsat} lemmas total={lemma_total} longest={longest}");
    assert!(unsat > 1000);
}

#[test]
fn differential_against_the_full_scan_reference_on_all_enumerated_proofs() {
    let t0 = std::time::Instant::now();
    let alpha = Alphabet::new();
    let fs = formulas(&formula_universe(), 3);
    let items: Vec<(usize, &Vec<Clause>)> = fs.iter().enumerate().collect();
    let t = par_sum(&items, |&(idx, f), acc| {
        // Three-clause formulas: every fifth one (the reference is slow).
        if f.len() == 3 && idx % DIFF_FORMULA_SAMPLE != 0 {
            return;
        }
        let stride = if f.len() <= 2 { DIFF_STRIDE_SMALL } else { DIFF_STRIDE_LARGE };
        for p in alpha.proofs(stride) {
            let steps = alpha.steps_of(&p);
            let (k, r) = (kernel(f, &steps), ref_check(f, &steps));
            assert_eq!(k, r, "kernel and reference disagree\nformula: {f:?}\nproof: {steps:?}");
            acc[0] += 1;
            acc[match k {
                Verdict::Accepted => 1,
                Verdict::NotImplied(_) => 2,
                Verdict::DeleteAbsent(_) => 3,
                Verdict::NoEmptyClause => 4,
            }] += 1;
        }
    });
    println!(
        "differential: compared={} accepted={} not_implied={} delete_absent={} no_empty={} in {:?}",
        t[0], t[1], t[2], t[3], t[4], t0.elapsed()
    );
    assert!(t[1] > 1000 && t[2] > 1000 && t[3] > 1000 && t[4] > 1000);
}
