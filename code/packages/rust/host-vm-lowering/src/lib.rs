#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FrameLayout {
    pub block_id: usize,
    pub depth: usize,
    pub static_parent_id: Option<usize>,
    pub header_size: usize,
    pub word_size: usize,
    pub slots: Vec<FrameSlot>,
}

impl FrameLayout {
    pub fn new(block_id: usize, depth: usize, static_parent_id: Option<usize>) -> Self {
        Self {
            block_id,
            depth,
            static_parent_id,
            header_size: FRAME_HEADER_SIZE,
            word_size: FRAME_WORD_SIZE,
            slots: Vec::new(),
        }
    }

    pub fn frame_size(&self) -> usize {
        self.header_size + self.slots.iter().map(|slot| slot.size).sum::<usize>()
    }

    pub fn allocate_scalar(
        &mut self,
        symbol_id: usize,
        name: impl Into<String>,
        type_name: AlgolType,
    ) -> FrameSlot {
        let slot = FrameSlot {
            symbol_id,
            name: name.into(),
            type_name,
            offset: self.frame_size(),
            size: type_name.frame_slot_size(),
            storage_class: StorageClass::Frame,
        };
        self.slots.push(slot.clone());
        slot
    }

    pub fn allocate_descriptor(
        &mut self,
        symbol_id: usize,
        name: impl Into<String>,
        type_name: AlgolType,
    ) -> FrameSlot {
        let slot = FrameSlot {
            symbol_id,
            name: name.into(),
            type_name,
            offset: self.frame_size(),
            size: self.word_size,
            storage_class: StorageClass::Frame,
        };
        self.slots.push(slot.clone());
        slot
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FrameBlockSummary {
    pub block_id: usize,
    pub frame_size: usize,
}

pub fn layout_frame_offsets(
    blocks: &[FrameBlockSummary],
) -> Result<BTreeMap<usize, usize>, LoweringError> {
    let mut offsets = BTreeMap::new();
    let mut cursor = 0usize;
    for block in blocks {
        offsets.insert(block.block_id, cursor);
        cursor = cursor
            .checked_add(block.frame_size)
            .ok_or_else(|| LoweringError::new("frame layout overflow"))?;
    }
    if RUNTIME_STATE_BYTES + cursor > FRAME_MEMORY_BYTES {
        return Err(LoweringError::new(format!(
            "ALGOL frame memory requires {cursor} frame bytes plus {RUNTIME_STATE_BYTES} runtime bytes, exceeding the {FRAME_MEMORY_BYTES} byte limit"
        )));
    }
    Ok(offsets)
}

