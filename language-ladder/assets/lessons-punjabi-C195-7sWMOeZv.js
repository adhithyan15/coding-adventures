<!-- hl-knowledge: introduces=[PA-FORM-VALE-MASC-OBLIQUE-195]; assesses=[PA-GRAMMAR-VALA-ASSOCIATIVE-195, PA-LEX-C67-FOOD67-04, PA-LEX-C71-HOME71-01, PA-PLACE-KAMRE-ROOM-01, PA-POSTPOSITION-VICH-01] -->

