//! Go emitter — walks a SIR module and produces Go source.
//!
//! Layout (per SIR15):
//!
//! ```text
//! // banner
//! package main
//! import ( "fmt"; "strconv" )
//! // ── inlined SIR runtime ────────────────────────────────────
//! // ── user functions ───────────────────────────────────────────
//! func main() {
//!     _init()           // if module has _init
//!     _sir_user_main()  // SIR's `main`
//! }
//! ```

use std::cell::RefCell;
use std::collections::HashMap;
use std::fmt::Write;

use semantic_ir::{
    Block, Expr, Function, Global, Module, Scope, Stmt,
};

use crate::runtime::RUNTIME;

pub fn emit_module(m: &Module) -> String {
    FN_ARITY.with(|t| {
        let mut t = t.borrow_mut();
        t.clear();
        for f in &m.functions {
            t.insert(f.name.clone(), f.params.len());
        }
    });

    let mut out = String::new();
    emit_banner(&mut out, m);
    out.push_str("package main\n\n");
    out.push_str("import (\n\t\"fmt\"\n\t\"strconv\"\n)\n\n");
    // Suppress unused-import linter complaints if a tiny module
    // happens not to reference them (the runtime always does, so
    // we're fine — but blank-import the packages defensively in
    // case future minimal runtimes drop them).  Actually no:
    // blank-imports would have side effects; just rely on the
    // runtime.
    out.push_str(RUNTIME);
    emit_globals(&mut out, &m.globals);
    for f in &m.functions {
        out.push('\n');
        emit_function(&mut out, f);
    }
    emit_main(&mut out, m);

    FN_ARITY.with(|t| t.borrow_mut().clear());

    out
}

fn emit_banner(out: &mut String, m: &Module) {
    let _ = writeln!(
        out,
        "// Generated by semantic-ir-to-go v0.1 from SIR module `{}`.",
        sanitize_comment(&m.name)
    );
    if let Some(lang) = &m.metadata.source_language {
        let _ = writeln!(out, "// Source language: {}", sanitize_comment(lang));
    }
    let _ = writeln!(out, "// Do not edit by hand.");
    out.push('\n');
}

fn emit_globals(out: &mut String, globals: &[Global]) {
    if globals.is_empty() {
        return;
    }
    out.push_str("\n// Globals (initialised in _init): ");
    let mut first = true;
    for g in globals {
        if !first {
            out.push_str(", ");
        }
        first = false;
        out.push_str(&sanitize_comment(&g.name));
    }
    out.push('\n');
}

fn emit_main(out: &mut String, m: &Module) {
    out.push_str("\nfunc main() {\n");
    if m.functions.iter().any(|f| f.name == "_init") {
        out.push_str("\t_init()\n");
    }
    if m.functions.iter().any(|f| f.name == "main") {
        out.push_str("\t_sir_user_main()\n");
    }
    out.push_str("}\n");
}

// ---------------------------------------------------------------------------
// Functions
// ---------------------------------------------------------------------------

fn emit_function(out: &mut String, f: &Function) {
    let _ = writeln!(out, "// SIR span: {}", sanitize_comment(&f.span.to_string()));
    let _ = write!(out, "func {}(", function_emit_name(&f.name));

    let mut first = true;
    for c in &f.captures {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{} Value", sanitize_ident(&c.name));
    }
    for p in &f.params {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{} Value", sanitize_ident(&p.name));
    }
    out.push_str(") Value {\n");

    emit_function_body(out, &f.body, 1);

    out.push_str("}\n");
}

fn function_emit_name(name: &str) -> String {
    if name == "main" {
        "_sir_user_main".to_string()
    } else {
        sanitize_ident(name)
    }
}

fn emit_function_body(out: &mut String, b: &Block, indent: usize) {
    let pad = indent_str(indent);
    for s in &b.stmts {
        emit_stmt(out, s, indent);
    }
    let _ = write!(out, "{}return ", pad);
    emit_expr(out, &b.value, indent);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Statements
// ---------------------------------------------------------------------------

fn emit_stmt(out: &mut String, s: &Stmt, indent: usize) {
    let pad = indent_str(indent);
    match s {
        Stmt::LetBinding { name, value, .. } | Stmt::LetStarBinding { name, value, .. } => {
            // Use `:=` for declare-and-assign.  Add a `_ = <name>`
            // line afterwards so unused-let bindings don't break Go
            // compilation.
            let safe = sanitize_ident(name);
            let _ = write!(out, "{}{} := ", pad, safe);
            emit_expr(out, value, indent);
            out.push('\n');
            // Defensive: silence Go's strict unused-variable check
            // when the binding turns out to be unused.
            let _ = writeln!(out, "{}_ = {}", pad, safe);
        }
        Stmt::ExprStmt { expr, .. } => {
            if let Some((global, value)) = pick_global_set(expr) {
                let _ = write!(out, "{}_sir_globals[{}] = ", pad, quote_go_string(global));
                emit_expr(out, value, indent);
                out.push('\n');
            } else {
                // Go requires expression statements to use the value
                // or assign to `_`.  Use `_ = expr`.
                let _ = write!(out, "{}_ = ", pad);
                emit_expr(out, expr, indent);
                out.push('\n');
            }
        }
    }
}

fn pick_global_set<'a>(e: &'a Expr) -> Option<(&'a str, &'a Expr)> {
    if let Expr::BuiltinCall { name, args, .. } = e {
        if name == "global_set" && args.len() == 2 {
            if let Expr::SymLit { name: gn, .. } = &args[0] {
                return Some((gn.as_str(), &args[1]));
            }
        }
    }
    None
}

// ---------------------------------------------------------------------------
// Expressions
// ---------------------------------------------------------------------------

fn emit_expr(out: &mut String, e: &Expr, indent: usize) {
    match e {
        Expr::IntLit { value, .. } => {
            // Type-annotate as int64 so the runtime's type switches
            // hit the int64 arm consistently.  Cast to Value
            // implicitly via interface{}.
            let _ = write!(out, "Value(int64({}))", value);
        }
        Expr::BoolLit { value, .. } => {
            let _ = write!(out, "Value({})", value);
        }
        Expr::NilLit { .. } => {
            // Go's `nil` is typed; cast to Value for consistency.
            out.push_str("Value(nil)");
        }
        Expr::SymLit { name, .. } => {
            let _ = write!(out, "_sir_intern({})", quote_go_string(name));
        }
        Expr::StrLit { value, .. } => {
            let _ = write!(out, "Value({})", quote_go_string(value));
        }
        Expr::VarRef { name, scope, .. } => emit_var_ref(out, name, *scope),
        Expr::If { cond, then_branch, else_branch, .. } => {
            // Go has no expression-position `if`; lift to an IIFE.
            out.push_str("func() Value {\n");
            let pad = indent_str(indent + 1);
            let _ = write!(out, "{}if _sir_truthy(", pad);
            emit_expr(out, cond, indent + 1);
            out.push_str(") {\n");
            let pad2 = indent_str(indent + 2);
            let _ = write!(out, "{}return ", pad2);
            emit_block_as_expr(out, then_branch, indent + 2);
            out.push('\n');
            let _ = write!(out, "{}}}\n", pad);
            let _ = write!(out, "{}return ", pad);
            emit_block_as_expr(out, else_branch, indent + 1);
            out.push('\n');
            let _ = write!(out, "{}}}()", indent_str(indent));
        }
        Expr::Block(b) => emit_block_as_expr(out, b, indent),
        Expr::DirectCall { fn_name, args, .. } => {
            let _ = write!(out, "{}(", function_emit_name(fn_name));
            emit_args(out, args, indent);
            out.push(')');
        }
        Expr::IndirectCall { target, args, .. } => {
            out.push_str("_sir_apply(");
            emit_expr(out, target, indent);
            out.push_str(", []Value{");
            emit_args(out, args, indent);
            out.push_str("})");
        }
        Expr::BuiltinCall { name, args, .. } => emit_builtin_call(out, name, args, indent),
        Expr::MakeClosure { fn_name, captures, .. } => {
            // _sir_make_closure is `(fn func([]Value) Value,
            // captures []Value) Value`.  The runtime helper builds
            // a Closure whose `Fn` prepends `captures` to the
            // runtime call args and invokes `fn`.
            //
            // Our synthesised lambda functions have positional
            // signatures `func __lambda_N(c0 Value, ..., cK Value,
            //                              p0 Value, ..., pM Value) Value`
            // where K = len(captures) and M = function's param
            // count.  The adapter must splat exactly K + M args
            // from `combined` into the positional call.
            let params_arity = FN_ARITY.with(|t| t.borrow().get(fn_name).copied().unwrap_or(0));
            let total_arity = captures.len() + params_arity;
            let fname = function_emit_name(fn_name);
            out.push_str("_sir_make_closure(func(__args []Value) Value { return ");
            let _ = write!(out, "{}(", fname);
            for i in 0..total_arity {
                if i > 0 {
                    out.push_str(", ");
                }
                let _ = write!(out, "__args[{}]", i);
            }
            out.push_str(") }, []Value{");
            for (i, c) in captures.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                emit_expr(out, &c.value, indent);
            }
            out.push_str("})");
        }
        Expr::Intrinsic { name, span, .. } => {
            panic!(
                "emit reached an Intrinsic `{}` at {} — backend should have rejected it",
                name, span
            );
        }
    }
}

fn emit_var_ref(out: &mut String, name: &str, scope: Scope) {
    match scope {
        Scope::Local | Scope::Param | Scope::Capture => {
            out.push_str(&sanitize_ident(name));
        }
        Scope::Global => {
            let _ = write!(out, "_sir_global_get_static({})", quote_go_string(name));
        }
        Scope::Builtin => {
            let _ = write!(out, "_sir_builtin_closure({})", quote_go_string(name));
        }
    }
}

fn emit_args(out: &mut String, args: &[Expr], indent: usize) {
    for (i, a) in args.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        emit_expr(out, a, indent);
    }
}

fn emit_builtin_call(out: &mut String, name: &str, args: &[Expr], indent: usize) {
    // All variadic-ish builtins in the Go runtime take []Value and
    // return Value.  Same calling shape for fixed-arity ones to keep
    // the emitter simple.
    let helper = match name {
        "+" => "_sir_plus",
        "-" => "_sir_minus",
        "*" => "_sir_times",
        "/" => "_sir_divide",
        "=" => "_sir_eq",
        "<" => "_sir_lt",
        ">" => "_sir_gt",
        "cons" => "_sir_cons",
        "car" => "_sir_car",
        "cdr" => "_sir_cdr",
        "null?" => "_sir_is_null",
        "pair?" => "_sir_is_pair",
        "number?" => "_sir_is_number",
        "symbol?" => "_sir_is_symbol",
        "print" => "_sir_print",
        "global_set" => {
            // Two args, special signature.
            out.push_str("_sir_global_set(");
            if args.len() >= 1 {
                emit_expr(out, &args[0], indent);
            }
            out.push_str(", ");
            if args.len() >= 2 {
                emit_expr(out, &args[1], indent);
            } else {
                out.push_str("Value(nil)");
            }
            out.push(')');
            return;
        }
        "global_get" => {
            out.push_str("_sir_global_get(");
            if !args.is_empty() {
                emit_expr(out, &args[0], indent);
            }
            out.push(')');
            return;
        }
        _ => {
            let _ = write!(out, "_sir_call_builtin_by_name({}, []Value{{", quote_go_string(name));
            emit_args(out, args, indent);
            out.push_str("})");
            return;
        }
    };
    let _ = write!(out, "{}([]Value{{", helper);
    emit_args(out, args, indent);
    out.push_str("})");
}

fn emit_block_as_expr(out: &mut String, b: &Block, indent: usize) {
    if b.stmts.is_empty() {
        emit_expr(out, &b.value, indent);
        return;
    }
    // IIFE: func() Value { stmts...; return value }()
    out.push_str("func() Value {\n");
    let inner_indent = indent + 1;
    for s in &b.stmts {
        emit_stmt(out, s, inner_indent);
    }
    let pad = indent_str(inner_indent);
    let _ = write!(out, "{}return ", pad);
    emit_expr(out, &b.value, inner_indent);
    out.push('\n');
    let _ = write!(out, "{}}}()", indent_str(indent));
}

