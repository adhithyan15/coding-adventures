//! Jetpack Compose backend pipeline emitter.

use std::fmt::Write;

use moslayout_compiler::{LayoutDef, LayoutNode, LayoutProp, LayoutPropValue};
use mosmodel_compiler::{
    EmitDecl, EmitPayloadType, ListInnerType, MosmodelComponent, SlotDecl, SlotType,
};
use mosstyle_compiler::StyleDef;

/// Errors the Compose pipeline emitter can return.
#[derive(Debug)]
pub enum PipelineEmitError {
    UnknownPrimitive(String),
    UnsafeSlotName(String),
    UnsafeEmitName(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the Compose emitter"
            ),
            Self::UnsafeSlotName(n) => write!(f, "unsafe slot name '{n}' (post conversion)"),
            Self::UnsafeEmitName(n) => write!(f, "unsafe emit name '{n}' (post conversion)"),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

/// The result of a successful emission.
#[derive(Debug, Clone)]
pub struct PipelineEmitResult {
    pub output: String,
    pub component_name: String,
}

/// Emit one Composable function for the three-file triple.
///
/// `_style` is accepted but not yet consumed — Compose styling lands
/// on `Modifier` chains, which v0.1.0 does not yet emit.  Future
/// versions will lower mosstyle blocks to `Modifier.background(...)`
/// / `Modifier.padding(...)` / etc.
pub fn from_pipeline(
    component: &MosmodelComponent,
    layout: &LayoutDef,
    _style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    let name = component.component.clone();
    // Defence in depth: validate the component name before we
    // interpolate it into Kotlin identifier positions (sealed class
    // name, function name, event union member, etc.).  The mosmodel
    // grammar already restricts component names to PascalCase ASCII,
    // but re-validating here protects against:
    //   - a grammar regression that admits surprising characters
    //   - a hand-built `MosmodelComponent` struct fed in by test or
    //     fuzz harness code with a hostile name
    validate_safe_identifier(&name).map_err(PipelineEmitError::UnsafeSlotName)?;
    let mut out = String::new();

    writeln!(out, "// Auto-generated by mosaic-emit-compose. Do not edit.").unwrap();
    writeln!(out).unwrap();
    // We don't know the host's package; emit the standard
    // `androidx.compose.*` imports and leave a TODO for the host
    // to add its own package declaration.  In practice the host's
    // build script can prepend `package com.example.foo` before
    // wiring the file into the source set.
    writeln!(out, "import androidx.compose.foundation.layout.Box").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Column").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Row").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Spacer").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.fillMaxWidth").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.size").unwrap();
    writeln!(out, "import androidx.compose.foundation.background").unwrap();
    writeln!(out, "import androidx.compose.foundation.clickable").unwrap();
    writeln!(out, "import androidx.compose.foundation.text.BasicTextField").unwrap();
    writeln!(out, "import androidx.compose.material.Button").unwrap();
    writeln!(out, "import androidx.compose.material.Text").unwrap();
    writeln!(out, "import androidx.compose.runtime.Composable").unwrap();
    writeln!(out, "import androidx.compose.ui.Modifier").unwrap();
    writeln!(out, "import androidx.compose.ui.unit.dp").unwrap();
    writeln!(out).unwrap();

    out.push_str(&emit_event_sealed_class(&name, &component.emits)?);
    writeln!(out).unwrap();
    out.push_str(&emit_composable_function(
        &name,
        &component.slots,
        &layout.root,
        &component.emits,
    )?);

    Ok(PipelineEmitResult {
        output: out,
        component_name: name,
    })
}

// =====================================================================
// Event sealed class
// =====================================================================

fn emit_event_sealed_class(
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "sealed class {component_name}Event {{").unwrap();
    for e in emits {
        let case = pascalize(&strip_on_prefix(&e.name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        if e.params.is_empty() {
            // Parameterless events are singletons in Kotlin — `data object`
            // is the idiomatic shape and exposes `equals` / `hashCode`
            // automatically.
            writeln!(
                out,
                "    data object {case} : {component_name}Event()"
            )
            .unwrap();
        } else {
            let params: Vec<String> = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    let ty = emit_payload_type_to_kotlin(&p.r#type);
                    format!("val {field}: {ty}")
                })
                .collect();
            writeln!(
                out,
                "    data class {case}({params}) : {component_name}Event()",
                params = params.join(", ")
            )
            .unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    Ok(out)
}

// =====================================================================
// Composable function
// =====================================================================

fn emit_composable_function(
    component_name: &str,
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "@Composable").unwrap();
    writeln!(out, "fun {component_name}(").unwrap();
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        let ty = slot_type_to_kotlin(&s.r#type);
        // Optional slots in the IR become nullable Kotlin types.
        let suffix = if s.required { "" } else { "?" };
        writeln!(out, "    {field}: {ty}{suffix},").unwrap();
    }
    writeln!(
        out,
        "    dispatch: ({component_name}Event) -> Unit,"
    )
    .unwrap();
    writeln!(out, ") {{").unwrap();
    out.push_str(&emit_compose_tree(layout_root, 1, component_name, emits)?);
    writeln!(out, "}}").unwrap();
    Ok(out)
}

// =====================================================================
// Layout tree walker
// =====================================================================

fn emit_compose_tree(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    match node.tag.as_str() {
        "Box" => emit_container(node, "Box", depth, component_name, emits),
        "Row" => emit_container(node, "Row", depth, component_name, emits),
        "Column" => emit_container(node, "Column", depth, component_name, emits),
        "Text" => emit_text(node, depth),
        "Spacer" => Ok(format!(
            "{pad}Spacer(modifier = Modifier.weight(1f))\n"
        )),
        "HostInput" => emit_host_input(node, depth, component_name, emits),
        "HostButton" => emit_host_button(node, depth, component_name, emits),
        // UI26 §6.2 — Grid userland primitive.  See [`emit_grid`]
        // for the slot/emit mapping; produces a Column-of-Rows
        // layout via Jetpack Compose's `itemsIndexed` + nested
        // `forEach`.
        "Grid" => emit_grid(node, depth, component_name, emits),
        other => Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    }
}

/// Lower the `Grid` userland primitive (UI26 §6.2 v2 shape) to
/// Jetpack Compose / Compose Multiplatform.
///
/// ## Slot / emit mapping
///
/// | Mosaic prop      | Compose usage                                       |
/// |------------------|-----------------------------------------------------|
/// | `headers`        | Required.  `List<String>`.  Header row of cells.    |
/// | `rows`           | Required.  `List<List<String>>`.  Body rows.        |
/// | `column-widths`  | Accepted but not yet plumbed (v0.2.0).              |
/// | `selected-row`   | Optional.  Indexes the highlighted cell.            |
/// | `selected-col`   | Optional.                                           |
/// | `onNavigate`     | Optional emit.  Each cell's `Modifier.clickable`    |
/// |                  | dispatches it.  Arity-aware: parameterless ->       |
/// |                  | `dispatch(<C>Event<Case>)`; ≥1-param ->             |
/// |                  | `dispatch(<C>Event<Case>(row, col))`.               |
///
/// ## Shape
///
/// ```kotlin
/// Column {
///     Row {                                          // header row
///         headers.forEach { h ->
///             Box(modifier = Modifier.size(96.dp, 24.dp).background(...)) {
///                 Text(text = h)
///             }
///         }
///     }
///     rows.forEachIndexed { r, row ->                // body rows
///         Row {
///             row.forEachIndexed { c, v ->
///                 Box(modifier = Modifier
///                     .size(96.dp, 22.dp)
///                     .background(if (r == selectedRow && c == selectedCol) ... else ...)
///                     .clickable { dispatch(<C>Event<Case>(row = r, col = c)) }) {
///                     Text(text = v)
///                 }
///             }
///         }
///     }
/// }
/// ```
fn emit_grid(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let p1 = "    ".repeat(depth + 1);
    let p2 = "    ".repeat(depth + 2);
    let p3 = "    ".repeat(depth + 3);
    let p4 = "    ".repeat(depth + 4);

    let headers_slot = find_slot_ref_prop(node, "headers").ok_or_else(|| {
        PipelineEmitError::UnsafeSlotName("Grid missing required prop 'headers'".to_string())
    })?;
    let rows_slot = find_slot_ref_prop(node, "rows").ok_or_else(|| {
        PipelineEmitError::UnsafeSlotName("Grid missing required prop 'rows'".to_string())
    })?;
    let headers_var = to_camel_case_first_lower(headers_slot);
    let rows_var = to_camel_case_first_lower(rows_slot);
    validate_safe_identifier(&headers_var).map_err(PipelineEmitError::UnsafeSlotName)?;
    validate_safe_identifier(&rows_var).map_err(PipelineEmitError::UnsafeSlotName)?;

    let selected_row_var = find_slot_ref_prop(node, "selected-row").map(to_camel_case_first_lower);
    let selected_col_var = find_slot_ref_prop(node, "selected-col").map(to_camel_case_first_lower);
    if let Some(v) = selected_row_var.as_deref() {
        validate_safe_identifier(v).map_err(PipelineEmitError::UnsafeSlotName)?;
    }
    if let Some(v) = selected_col_var.as_deref() {
        validate_safe_identifier(v).map_err(PipelineEmitError::UnsafeSlotName)?;
    }
    let selected_expr = match (&selected_row_var, &selected_col_var) {
        (Some(r), Some(c)) => format!("r == {r} && c == {c}"),
        _ => "false".to_string(),
    };

    let on_navigate_call: Option<String> = if let Some(emit_name) = find_emit_ref_prop(node, "onNavigate") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits.iter().find(|e| e.name == *emit_name)
            .map(|e| e.params.len()).unwrap_or(0);
        Some(if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!("dispatch({component_name}Event.{case}(row = r, col = c))")
        })
    } else {
        None
    };

    let mut out = String::new();
    writeln!(out, "{pad}Column {{").unwrap();

    // Header row.
    writeln!(out, "{p1}Row {{").unwrap();
    writeln!(out, "{p2}{headers_var}.forEach {{ h ->").unwrap();
    writeln!(out, "{p3}Box(modifier = Modifier.size(96.dp, 24.dp)) {{").unwrap();
    writeln!(out, "{p4}Text(text = h)").unwrap();
    writeln!(out, "{p3}}}").unwrap();
    writeln!(out, "{p2}}}").unwrap();
    writeln!(out, "{p1}}}").unwrap();

    // Body rows.
    writeln!(out, "{p1}{rows_var}.forEachIndexed {{ r, row ->").unwrap();
    writeln!(out, "{p2}Row {{").unwrap();
    writeln!(out, "{p3}row.forEachIndexed {{ c, v ->").unwrap();
    let p5 = "    ".repeat(depth + 5);
    let cell_modifier = if on_navigate_call.is_some() {
        format!(
            "Modifier\n{p5}    .size(96.dp, 22.dp)\n{p5}    .background(if ({selected_expr}) androidx.compose.ui.graphics.Color(0xFF264F78) else androidx.compose.ui.graphics.Color(0xFF1E1E1E))\n{p5}    .clickable {{ {} }}",
            on_navigate_call.unwrap()
        )
    } else {
        format!(
            "Modifier\n{p5}    .size(96.dp, 22.dp)\n{p5}    .background(if ({selected_expr}) androidx.compose.ui.graphics.Color(0xFF264F78) else androidx.compose.ui.graphics.Color(0xFF1E1E1E))"
        )
    };
    writeln!(out, "{p4}Box(modifier = {cell_modifier}) {{").unwrap();
    writeln!(out, "{p5}Text(text = v)").unwrap();
    writeln!(out, "{p4}}}").unwrap();
    writeln!(out, "{p3}}}").unwrap();
    writeln!(out, "{p2}}}").unwrap();
    writeln!(out, "{p1}}}").unwrap();

    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

fn emit_container(
    node: &LayoutNode,
    composable: &str,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let mut out = String::new();
    if node.children.is_empty() {
        writeln!(out, "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{ }}").unwrap();
        return Ok(out);
    }
    writeln!(out, "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{").unwrap();
    for child in &node.children {
        out.push_str(&emit_compose_tree(child, depth + 1, component_name, emits)?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

fn emit_text(node: &LayoutNode, depth: usize) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let value_expr = match find_prop_value(node, "content") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Expr(text)) => text.clone(),
        _ => "\"\"".to_string(),
    };
    Ok(format!("{pad}Text(text = {value_expr})\n"))
}

fn emit_host_input(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);

    let value_expr = match find_prop_value(node, "value") {
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Expr(text)) => text.clone(),
        _ => "\"\"".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}BasicTextField(").unwrap();
    writeln!(out, "{inner}value = {value_expr},").unwrap();

    // onChange — wraps the new value in a dispatched event whose
    // case mirrors the .mil declaration.  The strict-Flux contract
    // matches mosaic-emit-flutter's `dispatch(<Component>Event<Case>(value:
    // value))` shape — same naming, same arity, same idiomatic shape
    // adapted to Kotlin's `data class` / `data object`.
    if let Some(emit_name) = find_emit_ref_prop(node, "onChange") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        let dispatch_call = if arity == 0 {
            format!("{component_name}Event.{case}")
        } else {
            format!("{component_name}Event.{case}(v)")
        };
        writeln!(
            out,
            "{inner}onValueChange = {{ v -> dispatch({dispatch_call}) }},"
        )
        .unwrap();
    } else {
        // Without an onChange we still need an onValueChange to
        // satisfy BasicTextField's required parameter — emit a
        // no-op closure.
        writeln!(out, "{inner}onValueChange = {{ }},").unwrap();
    }

    // read-only -> enabled = !readOnly (Compose negates the polarity)
    if let Some(slot) = find_slot_ref_prop(node, "read-only") {
        let camel = to_camel_case_first_lower(slot);
        validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
        writeln!(out, "{inner}enabled = !{camel},").unwrap();
    }

    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

fn emit_host_button(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);

    // onTap → onClick dispatch
    let on_click = if let Some(emit_name) = find_emit_ref_prop(node, "onTap") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        // Buttons have no inherent payload; only emit the dispatch
        // call if the signal is parameterless.  A button wired to a
        // payload-carrying signal won't know what to pass; surface
        // that as `(/* TODO: ... */)` deliberately so the codegen
        // is visibly incomplete rather than silently lying.
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!(
                "dispatch({component_name}Event.{case}(/* TODO: payload */))"
            )
        }
    } else {
        "/* no onTap bound */".to_string()
    };

    let label = match find_prop_value(node, "label") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        _ => "\"\"".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}Button(onClick = {{ {on_click} }}) {{").unwrap();
    writeln!(out, "{inner}Text(text = {label})").unwrap();
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

