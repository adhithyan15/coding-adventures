<!-- hl-knowledge: introduces=[]; assesses=[RU-LEX-I-01, RU-GRAMMAR-I-TWO-CLAUSES-01, RU-LEX-PONIMAT, RU-ETYMON-PONIMAT-TAKE-HOLD, RU-LEX-CHITAT, RU-ETYMON-CHITAT-COUNT-HONOUR, RU-GRAMMAR-NO-PROGRESSIVE, RU-DIALOGUE-COURTESY-01, RU-PRAGMATICS-GREETING-REGISTER, RU-LEX-DA, RU-LEX-NET] -->

