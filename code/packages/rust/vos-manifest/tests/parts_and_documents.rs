fn sample() -> (Part, Part, Part, Part) {
    (
        part("  record Impl(x: U8)\n  model m() -> U8 = 1u8\n"),
        part("  op init() -> Impl\n"),
        part("  claim a:\n    true\n"),
        part("  claim p:\n    true\n"),
    )
}

fn build(impl_pkg: &str, contract_pkg: &str, c: &Part, i: &Part, o: &[(Tier, &Part)]) -> String {
    assemble(&AssembleInput {
        impl_package: impl_pkg,
        contract_package: contract_pkg,
        contract: c,
        implementation: i,
        obligations: o,
    })
    .expect("assembles")
}

#[test]
fn a_document_has_the_shape_of_the_listing_and_reads_back() {
    let (c, i, a, p) = sample();
    let doc = build(
        "vos-ready-bitmap",
        "vos-ready-contract",
        &c,
        &i,
        &[(Tier::Policy, &p), (Tier::Safety, &a)],
    );
    let expect = format!(
        "warrant vos_ready_bitmap v1\n  -- vos02:generated by vos-link gen-doc; do not edit; contract-package=vos_ready_contract\n  -- vos02:contract-begin sha256={}\n{}  -- vos02:contract-end\n  -- vos02:impl-begin\n{}  -- vos02:impl-end\n  -- vos02:obligations-begin tier=policy sha256={}\n{}  -- vos02:obligations-end\n  -- vos02:obligations-begin tier=safety sha256={}\n{}  -- vos02:obligations-end\n{}",
        c.digest(), c.text(), i.text(), p.digest(), p.text(), a.digest(), a.text(), TRAILER
    );
    assert_eq!(doc, expect);

    let l = parse_layout(doc.as_bytes()).expect("reads back");
    assert_eq!(l.header, "warrant vos_ready_bitmap v1");
    assert_eq!(l.contract_package, "vos_ready_contract");
    assert_eq!(l.contract.body, c.text());
    assert_eq!(
        l.contract.marker_sha256.as_deref(),
        Some(c.digest().as_str())
    );
    assert_eq!(l.contract.computed_sha256(), c.digest());
    assert_eq!(l.contract.begin_line, 3);
    assert_eq!(l.implementation.body, i.text());
    assert_eq!(l.implementation.marker_sha256, None);
    assert_eq!(l.obligations.len(), 2);
    assert_eq!(l.obligations[0].0, Tier::Policy);
    assert_eq!(l.obligations[1].1.body, a.text());
    assert_eq!(l.trailer, TRAILER);
    assert_eq!(&doc[l.trailer_offset..], TRAILER);
}

#[test]
fn a_document_with_no_obligations_is_valid() {
    let (c, i, _, _) = sample();
    let doc = build("a", "b", &c, &i, &[]);
    let l = parse_layout(doc.as_bytes()).unwrap();
    assert!(l.obligations.is_empty());
}

#[test]
fn assembly_is_deterministic() {
    let (c, i, a, p) = sample();
    let o = [(Tier::Policy, &p), (Tier::Safety, &a)];
    assert_eq!(build("x", "y", &c, &i, &o), build("x", "y", &c, &i, &o));
}

#[test]
fn assembly_refuses_bad_names_unsorted_tiers_and_oversize() {
    let (c, i, a, p) = sample();
    let run = |ip: &str, cp: &str, o: &[(Tier, &Part)]| {
        assemble(&AssembleInput {
            impl_package: ip,
            contract_package: cp,
            contract: &c,
            implementation: &i,
            obligations: o,
        })
        .unwrap_err()
    };
    assert_eq!(run("Vos", "b", &[]).kind, DocErrorKind::BadName);
    assert_eq!(run("a", "b_c", &[]).kind, DocErrorKind::BadName);
    assert_eq!(
        run("a", "b", &[(Tier::Safety, &a), (Tier::Policy, &p)]).kind,
        DocErrorKind::TierOrder
    );
    assert_eq!(
        run("a", "b", &[(Tier::Safety, &a), (Tier::Safety, &a)]).kind,
        DocErrorKind::TierOrder
    );
    // Over the document cap: the parts fit, their sum does not.
    let line = format!("  {}\n", "x".repeat(60));
    let big_text = line.repeat((600 * 1024) / line.len());
    let big = part(&big_text);
    let e = assemble(&AssembleInput {
        impl_package: "a",
        contract_package: "b",
        contract: &big,
        implementation: &big,
        obligations: &[],
    })
    .unwrap_err();
    assert_eq!(e.kind, DocErrorKind::TooLarge);
    assert!(e.is_cap());
}

fn doc() -> String {
    let (c, i, a, p) = sample();
    build(
        "impl-x",
        "contract-x",
        &c,
        &i,
        &[(Tier::Policy, &p), (Tier::Safety, &a)],
    )
}

fn layout_err(doc: &str) -> vos_manifest::DocError {
    parse_layout(doc.as_bytes()).expect_err(doc)
}

#[test]
fn nc17_a_duplicated_marker_fails() {
    let d = doc();
    for marker in [
        "  -- vos02:contract-end\n",
        "  -- vos02:impl-begin\n",
        "  -- vos02:impl-end\n",
        "  -- vos02:obligations-end\n",
    ] {
        let twice = d.replacen(marker, &format!("{marker}{marker}"), 1);
        assert_eq!(layout_err(&twice).kind, DocErrorKind::Structure, "{marker}");
    }
    // The generated marker twice.
    let gen_line = d.lines().nth(1).unwrap();
    let twice = d.replacen(gen_line, &format!("{gen_line}\n{gen_line}"), 1);
    assert_eq!(layout_err(&twice).kind, DocErrorKind::Structure);
    // A whole second contract block.
    let begin = d.lines().nth(2).unwrap().to_string();
    let twice = d.replacen(
        "  -- vos02:contract-end\n",
        &format!("  -- vos02:contract-end\n{begin}\n  -- vos02:contract-end\n"),
        1,
    );
    assert_eq!(layout_err(&twice).kind, DocErrorKind::Structure);
}

#[test]
fn nc17_a_missing_marker_fails() {
    let d = doc();
    for marker in [
        "  -- vos02:contract-end\n",
        "  -- vos02:impl-begin\n",
        "  -- vos02:impl-end\n",
        "  -- vos02:obligations-end\n",
    ] {
        let gone = d.replacen(marker, "", 1);
        assert_eq!(layout_err(&gone).kind, DocErrorKind::Structure, "{marker}");
    }
    let gen_line = format!("{}\n", d.lines().nth(1).unwrap());
    assert_eq!(
        layout_err(&d.replacen(&gen_line, "", 1)).kind,
        DocErrorKind::Structure
    );
    let begin = format!("{}\n", d.lines().nth(2).unwrap());
    assert_eq!(
        layout_err(&d.replacen(&begin, "", 1)).kind,
        DocErrorKind::Structure
    );
}

#[test]
fn nc17_a_reordered_marker_fails() {
    let d = doc();
    // impl before contract
    let ibegin = "  -- vos02:impl-begin\n";
    let iend = "  -- vos02:impl-end\n";
    let i_start = d.find(ibegin).unwrap();
    let i_end = d.find(iend).unwrap() + iend.len();
    let impl_block = d[i_start..i_end].to_string();
    let without = format!("{}{}", &d[..i_start], &d[i_end..]);
    let c_start = without.find("  -- vos02:contract-begin").unwrap();
    let swapped = format!(
        "{}{}{}",
        &without[..c_start],
        impl_block,
        &without[c_start..]
    );
    assert_eq!(layout_err(&swapped).kind, DocErrorKind::Structure);
    // generated marker after the contract block
    let gen_line = format!("{}\n", d.lines().nth(1).unwrap());
    let moved = d.replacen(&gen_line, "", 1).replacen(
        "  -- vos02:contract-end\n",
        &format!("  -- vos02:contract-end\n{gen_line}"),
        1,
    );
    assert_eq!(layout_err(&moved).kind, DocErrorKind::Structure);
    // an end marker before its begin
    let swapped_ends = d.replacen("  -- vos02:contract-end\n", "  -- vos02:IMPL-TMP\n", 1);
    assert!(parse_layout(swapped_ends.as_bytes()).is_err());
}

#[test]
fn nc17_tiers_out_of_order_or_repeated_fail() {
    let (c, i, a, p) = sample();
    // Build by hand: the tools never emit this order.
    let good = build("x", "y", &c, &i, &[(Tier::Policy, &p), (Tier::Safety, &a)]);
    let start = good
        .find("  -- vos02:obligations-begin tier=policy")
        .unwrap();
    let mid = good
        .find("  -- vos02:obligations-begin tier=safety")
        .unwrap();
    let end = good.find("  assume platform:").unwrap();
    let swapped = format!(
        "{}{}{}{}",
        &good[..start],
        &good[mid..end],
        &good[start..mid],
        &good[end..]
    );
    let e = layout_err(&swapped);
    assert_eq!(e.kind, DocErrorKind::TierOrder);
    let repeated = format!(
        "{}{}{}{}",
        &good[..start],
        &good[start..mid],
        &good[start..mid],
        &good[end..]
    );
    assert_eq!(layout_err(&repeated).kind, DocErrorKind::TierOrder);
}

#[test]
fn nc17_an_unknown_or_malformed_marker_fails() {
    let d = doc();
    for bad in [
        d.replace("tier=policy", "tier=fast"),
        d.replace("  -- vos02:impl-begin\n", "  -- vos02:impl-begin x\n"),
        d.replace("  -- vos02:impl-begin\n", "    -- vos02:impl-begin\n"),
        d.replace("sha256=", "sha256=0"),
        d.replace("do not edit", "do edit"),
        d.replace(
            "  -- vos02:impl-begin\n",
            "  -- vos02:impl-begin\n  -- vos02:surprise\n",
        ),
        d.replace(
            "  record Impl",
            "  record Impl  -- vos02:impl-end\n  record Impl",
        ),
        // inside a string literal, in a block
        d.replace(
            "  model m() -> U8 = 1u8",
            "  example e: s == \"-- vos02:impl-end\"",
        ),
        // a marker in the trailer
        format!("{d}  -- vos02:impl-end\n"),
    ] {
        assert_eq!(layout_err(&bad).kind, DocErrorKind::Structure, "{bad}");
    }
}

#[test]
fn a_document_reads_the_trailer_and_the_header() {
    let d = doc().replace(
        "  assume environment:\n    none\n",
        "  assume environment:\n    x == 1\n",
    );
    let l = parse_layout(d.as_bytes()).unwrap();
    assert!(l.trailer.contains("x == 1"));
    assert_eq!(l.header, "warrant impl_x v1");
    // A different header line is still a structure; its meaning is the Warrant parser's.
    let l = parse_layout(d.replacen("warrant impl_x v1", "anything", 1).as_bytes()).unwrap();
    assert_eq!(l.header, "anything");
}

#[test]
fn document_bytes_are_admitted_like_parts() {
    let d = doc();
    assert_eq!(
        layout_err(&d.replace('\n', "\r\n")).kind,
        DocErrorKind::Bytes
    );
    assert_eq!(
        layout_err(&d.replace("model", "mod\u{e9}l")).kind,
        DocErrorKind::Bytes
    );
    let e = parse_layout(&vec![b'a'; 1024 * 1024 + 1]).unwrap_err();
    assert_eq!(e.kind, DocErrorKind::TooLarge);
    assert!(e.is_cap());
    let long = format!("{d}{}\n", "a".repeat(4_097));
    let e = layout_err(&long);
    assert_eq!(e.kind, DocErrorKind::LineTooLong);
    assert!(e.is_cap());
    assert!(e.to_string().starts_with("line "));
}

#[test]
fn a_blank_line_in_a_block_is_part_of_the_block() {
    let (_, i, a, p) = sample();
    let c = part("  record Impl(x: U8)\n\n  model m() -> U8 = 1u8\n");
    let d = build("x", "y", &c, &i, &[(Tier::Policy, &p), (Tier::Safety, &a)]);
    let l = parse_layout(d.as_bytes()).unwrap();
    assert_eq!(l.contract.body, c.text());
    assert_eq!(l.contract.computed_sha256(), c.digest());
}

#[test]
fn a_big_document_reads_in_reasonable_time() {
    // About 900 KiB of block lines: the engine must not go quadratic on the line count.
    let line = format!("  -- {}\n", "x".repeat(40));
    let c = part(&line.repeat(15_000));
    let (_, i, _, _) = sample();
    let d = build("x", "y", &c, &i, &[]);
    assert!(d.len() > 600_000);
    let t = std::time::Instant::now();
    let l = parse_layout(d.as_bytes()).unwrap();
    assert_eq!(l.contract.body, c.text());
    assert!(
        t.elapsed() < std::time::Duration::from_secs(60),
        "{:?}",
        t.elapsed()
    );
}
