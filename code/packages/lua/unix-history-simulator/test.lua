local simulator = require("unix_history")
local slots = simulator.descriptors(2)
assert(slots:allocate(2) == 0)
assert(slots:allocate(2) == 1)
assert(slots:allocate(2) == nil)
assert(slots:advance(0, 4))
assert(slots:get(1).offset == 0)
assert(not slots:close(-1))
assert(slots:close(0))
assert(slots:allocate(3) == 0)
assert(slots:get(0).offset == 0)
local image = simulator.demo_image()
assert(simulator.resolve(image, "//etc/../etc/./notes") == 5)
local _, err = simulator.resolve(image, "/hello/..")
assert(err == "ENOTDIR")
assert(simulator.read_inode(image, 2, 7, 3) == "Uni")
assert(simulator.read_inode(image, 2, 13, 8) == "")
local kernel = simulator.kernel(image, simulator.descriptors(2))
local opened = kernel:open("/hello")
assert(opened.fd == 0 and opened.inode == 2)
local first_read, data = kernel:read(opened.fd, 5)
assert(first_read.offset == 0 and first_read.nextOffset == 5 and data == "Hello")
assert(kernel:close(opened.fd).call == "close")
assert(kernel:read(opened.fd, 1).error == "EBADF")
