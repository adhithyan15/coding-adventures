//! # The differential oracle: MacroOct's IIR must be Oct's IIR.
//!
//! This is the acceptance criterion for PREP01 slice 1, and the reason
//! MacroOct exists at all.
//!
//! A preprocessor is backend-agnostic by construction: it rewrites a token
//! stream and then gets out of the way. So a preprocessed program must lower
//! to **the same IIR** as its hand-expanded equivalent — and because MacroOct
//! is a dialect of Oct, that hand-expanded equivalent is a *valid Oct
//! program*, compiled by Oct's own untouched frontend.
//!
//! That is a far stronger statement than "the MacroOct program runs and prints
//! the right thing", and it costs zero backend work:
//!
//! | Claim | What it would take to check | What it proves |
//! |---|---|---|
//! | "it runs correctly" | 8 backends × N programs | the selected branch behaves |
//! | **"identical IIR"** | one `assert_eq!` per program | the preprocessor contributed *nothing* beyond selecting text — so every backend result follows for free |
//!
//! The eight-backend agreement is then established by the `lang-aot` matrix
//! rows, which run the MacroOct programs on real toolchains. Those rows and
//! this file answer different questions: the matrix asks "does it work
//! everywhere", this file asks "is it the same program".
//!
//! ## What "identical" is allowed to exclude, and why that is not a loophole
//!
//! `IIRFunction::source_map` is a per-instruction **provenance** side table —
//! the line and column each instruction came from. A MacroOct program and its
//! hand-expanded Oct equivalent are different *text*: the MacroOct one has
//! extra lines, because `@if`, `@else` and `@end` occupy lines of their own.
//! So their instructions genuinely do come from different line numbers, and
//! demanding equality there would be demanding that a preprocessor not
//! preprocess.
//!
//! Excluding it would nevertheless be a hole if it were left at that — a
//! structural divergence could hide inside the excluded field. So it is not
//! left at that:
//!
//! - [`macrooct_and_oct_agree_on_everything_except_instruction_provenance`]
//!   compares every other field, and additionally asserts the source maps are
//!   the same **length** (the lockstep invariant with `instructions`).
//! - [`line_aligned_sources_produce_byte_identical_iir_including_provenance`]
//!   then removes the exclusion entirely: it pads the Oct source so the two
//!   programs' lines coincide, and compares the full `{:#?}`, source map
//!   included. If the difference in the test above were anything more than a
//!   line shift, this one would fail.
//!
//! Together those say: the IIR is identical, and the provenance differs by
//! exactly the offset the directives introduce.

use coding_adventures_macrooct_iir_compiler::{compile_source, compile_source_with_includes};
use interpreter_ir::IIRModule;

/// Every program pair the oracle checks: a MacroOct source, and the Oct source
/// a human would write to mean the same thing.
///
/// The Oct side is *hand-expanded by a reader*, not produced by any part of
/// this crate. That matters: if the expected output were generated by the
/// preprocessor, the test would be comparing the implementation against
/// itself.
struct Pair {
    what: &'static str,
    macrooct: &'static str,
    oct: &'static str,
}

const PAIRS: &[Pair] = &[
    Pair {
        what: "a taken @if with no @else",
        macrooct: "@if 1\nfn main() { out(1, 42); }\n@end\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "a false @if with no @else — the whole program is dropped except main",
        macrooct: "@if 0\nfn unused() -> u8 { return 7; }\n@end\nfn main() { out(1, 42); }\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "@if/@else, then branch",
        macrooct: "@if 1\nfn main() { out(1, 42); }\n@else\nfn main() { out(1, 7); }\n@end\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "@if/@else, else branch",
        macrooct: "@if 0\nfn main() { out(1, 42); }\n@else\nfn main() { out(1, 7); }\n@end\n",
        oct: "fn main() { out(1, 7); }\n",
    },
    Pair {
        what: "a comparison condition, the form the PREP01 spec's own example uses",
        macrooct: "@if 1 == 1\nfn main() { out(1, 200); }\n@else\nfn main() { out(0, 200); }\n@end\n",
        oct: "fn main() { out(1, 200); }\n",
    },
    Pair {
        what: "an undefined name compares equal to 0 (slice 1 has no macro table)",
        macrooct: "@if LED_PORT == 0\nfn main() { out(1, 42); }\n@else\nfn main() { out(1, 7); }\n@end\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "&& and || in a condition",
        macrooct: "@if 1 == 1 && 2 != 3\nfn main() { out(1, 42); }\n@else\nfn main() { out(1, 7); }\n@end\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "nested conditionals",
        macrooct: "@if 1\n@if 0\nfn main() { out(1, 7); }\n@else\nfn main() { out(1, 42); }\n@end\n@end\n",
        oct: "fn main() { out(1, 42); }\n",
    },
    Pair {
        what: "a conditional selecting between two whole multi-function programs",
        macrooct: "@if 1\nfn pick() -> u8 { return 42; }\nfn main() { out(1, pick()); }\n\
                   @else\nfn pick() -> u8 { return 7; }\nfn main() { out(1, pick()); }\n@end\n",
        oct: "fn pick() -> u8 { return 42; }\nfn main() { out(1, pick()); }\n",
    },
    Pair {
        what: "directives around a static global, u8 wrap, and a loop",
        macrooct: "static counter: u8 = 250;\n@if 1\nfn bump() { counter = counter + 10; }\n@end\n\
                   fn main() { let i: u8 = 0; while i < 3 { bump(); i = i + 1; } out(1, counter); }\n",
        oct: "static counter: u8 = 250;\nfn bump() { counter = counter + 10; }\n\
              fn main() { let i: u8 = 0; while i < 3 { bump(); i = i + 1; } out(1, counter); }\n",
    },
    Pair {
        what: "a conditional wrapping nothing at all — the empty group",
        macrooct: "@if 1\n@end\nfn main() { out(1, 42); }\n",
        oct: "fn main() { out(1, 42); }\n",
    },
];

/// The same oracle for `@include`, which needs a virtual filesystem and so
/// cannot ride in [`PAIRS`].
struct IncludePair {
    what: &'static str,
    macrooct: &'static str,
    includes: &'static [(&'static str, &'static str)],
    oct: &'static str,
}

const INCLUDE_PAIRS: &[IncludePair] = &[
    IncludePair {
        what: "a single include pulling in one function",
        macrooct: "@include \"helper.macrooct\"\nfn main() { out(1, helper()); }\n",
        includes: &[("helper.macrooct", "fn helper() -> u8 { return 42; }\n")],
        oct: "fn helper() -> u8 { return 42; }\nfn main() { out(1, helper()); }\n",
    },
    IncludePair {
        what: "an include whose own content is conditional",
        macrooct: "@include \"helper.macrooct\"\nfn main() { out(1, helper()); }\n",
        includes: &[(
            "helper.macrooct",
            "@if 1\nfn helper() -> u8 { return 42; }\n@else\nfn helper() -> u8 { return 7; }\n@end\n",
        )],
        oct: "fn helper() -> u8 { return 42; }\nfn main() { out(1, helper()); }\n",
    },
    IncludePair {
        what: "a nested include chain",
        macrooct: "@include \"outer.macrooct\"\nfn main() { out(1, helper()); }\n",
        includes: &[
            ("outer.macrooct", "@include \"inner.macrooct\"\n"),
            ("inner.macrooct", "fn helper() -> u8 { return 42; }\n"),
        ],
        oct: "fn helper() -> u8 { return 42; }\nfn main() { out(1, helper()); }\n",
    },
    IncludePair {
        what: "the same file included twice, non-nested — legal, and not a cycle",
        macrooct: "@include \"a.macrooct\"\n@include \"b.macrooct\"\nfn main() { out(1, one() + two()); }\n",
        includes: &[
            ("a.macrooct", "fn one() -> u8 { return 1; }\n"),
            ("b.macrooct", "fn two() -> u8 { return 2; }\n"),
        ],
        oct: "fn one() -> u8 { return 1; }\nfn two() -> u8 { return 2; }\n\
              fn main() { out(1, one() + two()); }\n",
    },
    IncludePair {
        what: "an include selected by a conditional",
        macrooct: "@if 1\n@include \"good.macrooct\"\n@else\n@include \"bad.macrooct\"\n@end\n\
                   fn main() { out(1, helper()); }\n",
        includes: &[
            ("good.macrooct", "fn helper() -> u8 { return 42; }\n"),
            ("bad.macrooct", "fn helper() -> u8 { return 7; }\n"),
        ],
        oct: "fn helper() -> u8 { return 42; }\nfn main() { out(1, helper()); }\n",
    },
];

// ===========================================================================
// Comparison
// ===========================================================================

/// Render a module for comparison, optionally blanking instruction
/// provenance.
///
/// `{:#?}` rather than a field-by-field walk, deliberately. `IIRModule` and
/// `IIRFunction` do not derive `PartialEq`, and a hand-written comparison
/// would silently stop covering any field added later — which is precisely the
/// failure this oracle exists to catch. `Debug` covers every field by
/// construction, so a new field joins the comparison the day it is added.
fn render(module: &IIRModule, keep_provenance: bool) -> String {
    let mut module = module.clone();
    if !keep_provenance {
        for f in &mut module.functions {
            f.source_map.clear();
        }
    }
    format!("{module:#?}")
}

/// The full diff, trimmed, for a failure message that is readable rather than
/// two 300-line dumps.
fn first_difference(left: &str, right: &str) -> String {
    for (n, (a, b)) in left.lines().zip(right.lines()).enumerate() {
        if a != b {
            return format!("first difference at line {}:\n  MacroOct: {a}\n  Oct:      {b}", n + 1);
        }
    }
    format!(
        "the common prefix agrees; lengths differ ({} vs {} lines)",
        left.lines().count(),
        right.lines().count()
    )
}

fn assert_same_iir(what: &str, macrooct: &IIRModule, oct: &IIRModule, keep_provenance: bool) {
    let a = render(macrooct, keep_provenance);
    let b = render(oct, keep_provenance);
    assert_eq!(
        a,
        b,
        "PREP01 slice 1's acceptance criterion failed for: {what}\n\
         A MacroOct program must lower to IIR IDENTICAL to its hand-expanded Oct \
         equivalent. It did not, which means the preprocessor contributed something \
         beyond selecting source text.\n{}",
        first_difference(&a, &b)
    );

    // The lockstep invariant `IIRFunction::source_map` documents: one entry
    // per instruction. Checked even when provenance is excluded from the
    // comparison, so "excluded" never means "unchecked".
    for (m, o) in macrooct.functions.iter().zip(oct.functions.iter()) {
        assert_eq!(
            m.source_map.len(),
            m.instructions.len(),
            "{what}: MacroOct's `{}` broke the source_map/instructions lockstep",
            m.name
        );
        assert_eq!(
            m.source_map.len(),
            o.source_map.len(),
            "{what}: `{}` has a different number of source positions than Oct's",
            m.name
        );
    }
}

