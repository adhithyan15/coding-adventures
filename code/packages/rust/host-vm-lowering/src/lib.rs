#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WasmControlFlowStrategy {
    Structured,
    DispatchLoop,
}

pub fn wasm_strategy_for_branch_targets<'a>(
    targets: impl IntoIterator<Item = &'a str>,
) -> WasmControlFlowStrategy {
    if targets.into_iter().all(is_structured_wasm_branch_target) {
        WasmControlFlowStrategy::Structured
    } else {
        WasmControlFlowStrategy::DispatchLoop
    }
}

pub fn is_structured_wasm_branch_target(label: &str) -> bool {
    let mut parts = label.split('_');
    let Some(prefix) = parts.next() else {
        return false;
    };
    let Some(index) = parts.next() else {
        return false;
    };
    let Some(suffix) = parts.next() else {
        return false;
    };
    if parts.next().is_some() || index.parse::<usize>().is_err() {
        return false;
    }
    (prefix == "if" && matches!(suffix, "else" | "end"))
        || (prefix == "loop" && matches!(suffix, "start" | "end"))
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AlgolType {
    Integer,
    Boolean,
    Real,
    String,
    Procedure,
}

impl AlgolType {
    pub fn frame_slot_size(self) -> usize {
        if self == AlgolType::Real {
            FRAME_REAL_SIZE
        } else {
            FRAME_WORD_SIZE
        }
    }

    pub fn array_element_width(self) -> usize {
        if self == AlgolType::Real {
            ARRAY_REAL_BYTES
        } else {
            ARRAY_WORD_BYTES
        }
    }

    pub fn array_element_tag(self) -> i32 {
        if self == AlgolType::Real {
            2
        } else {
            1
        }
    }

    pub fn source_name(self) -> &'static str {
        match self {
            AlgolType::Integer => "integer",
            AlgolType::Boolean => "boolean",
            AlgolType::Real => "real",
            AlgolType::String => "string",
            AlgolType::Procedure => "procedure",
        }
    }

    fn scalar_dispatch_tag(self) -> Result<&'static str, LoweringError> {
        match self {
            AlgolType::Integer => Ok("i32"),
            AlgolType::Boolean => Ok("bool"),
            AlgolType::Real => Ok("f64"),
            AlgolType::String => Ok("str"),
            AlgolType::Procedure => Err(LoweringError::new(
                "procedure is not a scalar dispatch type",
            )),
        }
    }
}

