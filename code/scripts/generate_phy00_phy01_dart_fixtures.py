"""Generate authority-free Dart inputs from strict PHY00/PHY01 JSON fixtures."""

from __future__ import annotations

import argparse
import base64
import json
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
FIXTURE_ROOT = ROOT / "code" / "specs" / "fixtures" / "phy00-phy01-v1"
OUTPUT = FIXTURE_ROOT / "dart" / "generated_cases.dart"


def reject_duplicate_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def reject_float(value: str) -> None:
    raise ValueError(f"native JSON floating-point value is forbidden: {value}")


def load_strict(path: Path) -> dict[str, Any]:
    raw = path.read_bytes()
    if len(raw) > 1_000_000:
        raise ValueError(f"fixture exceeds byte limit: {path}")
    if raw.startswith(b"\xef\xbb\xbf"):
        raise ValueError(f"UTF-8 BOM is forbidden: {path}")
    value = json.loads(
        raw.decode("utf-8", errors="strict"),
        object_pairs_hook=reject_duplicate_pairs,
        parse_float=reject_float,
        parse_constant=reject_float,
    )
    if not isinstance(value, dict):
        raise TypeError(f"top-level fixture must be an object: {path}")
    return value


def encoded(document: dict[str, Any]) -> str:
    canonical = json.dumps(
        document,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("ascii")
    return base64.b64encode(canonical).decode("ascii")


def dart_constant(name: str, value: str) -> str:
    chunks = textwrap.wrap(value, width=96)
    lines = [f"const String {name} ="]
    lines.extend(f"    '{chunk}'" for chunk in chunks)
    lines[-1] += ";"
    return "\n".join(lines)


def render() -> str:
    trig = load_strict(FIXTURE_ROOT / "cases" / "trig.json")
    wave = load_strict(FIXTURE_ROOT / "cases" / "wave.json")
    return (
        "// Generated by code/scripts/generate_phy00_phy01_dart_fixtures.py.\n"
        "// Do not edit: the Python contract test verifies an exact canonical mirror.\n\n"
        f"{dart_constant('phy00TrigFixtureBase64', encoded(trig))}\n\n"
        f"{dart_constant('phy01WaveFixtureBase64', encoded(wave))}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                "generated Dart fixtures are stale; run "
                "python code/scripts/generate_phy00_phy01_dart_fixtures.py"
            )
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
