//! The web host's theme tokens are *generated* from TaskApp.{light,dark}.msl.
//!
//! # Why the host needs colours at all
//!
//! The emitted TaskApp component inlines its styles and exposes no token to read back,
//! yet the web host has to paint a few things the component cannot:
//!
//! ```text
//!   page ground behind the app ........ before React mounts / on theme switch
//!   startup "loading" / "failed" text . before the engine (and so the component) exists
//!   progress ring conic-gradient ...... a UI36-bound value computed per render
//!   board column accent bars .......... a UI36-bound value computed per For-row
//! ```
//!
//! Each of those must look like the part of the stylesheet it stands in for. Until now
//! `host/web/src/theme.ts` held its own copies of the hex values, with comments saying
//! "if the .msl changes, change it here too" — a promise nothing kept. A re-tinted
//! `app-shell` would have left the ground and the startup text the old colour, silently.
//!
//! # How the copy is removed
//!
//! This test reads both stylesheets with the real mosstyle front end (so a value is
//! whatever the compiler sees, not what a regex guesses), picks the handful of
//! `part.property` pairs the host needs, renders them as a TypeScript module, and
//! compares that with the committed `host/web/src/theme-tokens.generated.ts`.
//! `theme.ts` imports the module instead of spelling any hex itself.
//!
//! ```text
//!   TaskApp.light.msl ─┐                                  theme.ts: GROUND,
//!                      ├─ this test ─▶ theme-tokens ─▶  STARTUP, RING_*,
//!   TaskApp.dark.msl ──┘  (checks;     .generated.ts      BOARD_ACCENT
//!                          or writes)
//! ```
//!
//! A stylesheet edit therefore fails `cargo test` until the module is regenerated:
//!
//! ```text
//!   UPDATE_TASK_APP_HOST_TOKENS=1 cargo test --test host_theme_tokens
//! ```
//!
//! (`index.html`'s pre-mount ground is an OS-preference *guess* painted before any
//! script runs; `applyThemeGround` overwrites it from these tokens as soon as the theme
//! resolves, so the guess cannot outlive the first frame.)

use std::fs;
use std::path::PathBuf;

/// Every token the host needs, as `(token name, part, property)`.
///
/// The token names describe the *role* the colour plays for the host, which is why
/// they are not simply the part names: `group-head`'s text colour is the board's
/// "next" accent because the board reuses the established muted ink rather than
/// inventing a new colour.
const TOKENS: &[(&str, &str, &str)] = &[
    ("ground", "app-shell", "background"),
    ("ink", "app-shell", "color"),
    ("fontFamily", "app-shell", "font-family"),
    ("alert", "storage-warning", "color"),
    ("accent", "brand-mark", "background"),
    ("hairline", "rail", "border-right-color"),
    ("muted", "group-head", "color"),
    ("ok", "pill-ok", "color"),
];

const THEMES: &[&str] = &["light", "dark"];

const GENERATED: &str = "host/web/src/theme-tokens.generated.ts";

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// The base (non-state) value of `part.property` in one theme's stylesheet.
///
/// A missing part or property is a hard failure naming both: the host must never fall
/// back to a stale or default colour because a part was renamed in the .msl.
fn base_value(def: &mosstyle_compiler::StyleDef, theme: &str, part: &str, prop: &str) -> String {
    let part_style = def
        .parts
        .iter()
        .find(|p| p.name == part)
        .unwrap_or_else(|| {
            panic!("TaskApp.{theme}.msl has no part `{part}`, which the web host reads")
        });
    part_style
        .base
        .iter()
        .find(|p| p.name == prop)
        .map(|p| p.value.trim_matches('"').to_string())
        .unwrap_or_else(|| {
            panic!(
                "TaskApp.{theme}.msl part `{part}` has no base `{prop}`, which the web host reads"
            )
        })
}

/// A TypeScript string literal for `value`.
///
/// The values are stylesheet literals (hex colours, a font stack), but a stylesheet is
/// still input: escape the two characters that could end or bend the literal rather
/// than trusting that it never contains them.
fn ts_string(value: &str) -> String {
    let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

/// Render the module from the stylesheets currently on disk.
fn render() -> String {
    let mut out = String::new();
    out.push_str("// GENERATED by code/programs/mosaic/task-app/tests/host_theme_tokens.rs from\n");
    out.push_str("// src/TaskApp.{light,dark}.msl. Do not edit: change the stylesheet, then run\n");
    out.push_str("//   UPDATE_TASK_APP_HOST_TOKENS=1 cargo test --test host_theme_tokens\n");
    out.push_str(
        "// from code/programs/mosaic/task-app. `cargo test` fails while this is stale.\n",
    );
    out.push_str("//\n");
    out.push_str("// Each token is `part.property` from the stylesheet:\n");
    for (token, part, prop) in TOKENS {
        out.push_str(&format!("//   {token:<10} {part}.{prop}\n"));
    }
    out.push_str("\nexport const MSL_TOKENS = {\n");
    for theme in THEMES {
        let path = manifest_dir()
            .join("src")
            .join(format!("TaskApp.{theme}.msl"));
        let source = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
        let ast = mosstyle_compiler::parse_style(&source)
            .unwrap_or_else(|e| panic!("TaskApp.{theme}.msl does not parse: {e}"));
        let def = mosstyle_compiler::analyze(&ast)
            .unwrap_or_else(|e| panic!("TaskApp.{theme}.msl does not analyze: {}", e.message));
        out.push_str(&format!("  {theme}: {{\n"));
        for (token, part, prop) in TOKENS {
            let value = base_value(&def, theme, part, prop);
            out.push_str(&format!("    {token}: {},\n", ts_string(&value)));
        }
        out.push_str("  },\n");
    }
    out.push_str("} as const;\n");
    out
}

#[test]
fn web_host_theme_tokens_match_the_stylesheets() {
    let path = manifest_dir().join(GENERATED);
    let expected = render();
    if std::env::var("UPDATE_TASK_APP_HOST_TOKENS").as_deref() == Ok("1") {
        fs::write(&path, &expected)
            .unwrap_or_else(|e| panic!("failed to write {}: {e}", path.display()));
        return;
    }
    let committed = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
    assert!(
        committed == expected,
        "{GENERATED} is stale against TaskApp.{{light,dark}}.msl; regenerate with \
         UPDATE_TASK_APP_HOST_TOKENS=1 cargo test --test host_theme_tokens\n\
         --- committed\n{committed}\n--- expected\n{expected}"
    );
}

/// The two themes must supply every token, and differ where a theme should: a dark
/// ground identical to the light one would mean the dark stylesheet was never read.
#[test]
fn each_theme_supplies_its_own_ground() {
    let rendered = render();
    let grounds: Vec<&str> = rendered
        .lines()
        .filter(|l| l.trim_start().starts_with("ground:"))
        .collect();
    assert_eq!(grounds.len(), THEMES.len(), "one ground per theme");
    assert_ne!(grounds[0], grounds[1], "light and dark grounds must differ");
}
