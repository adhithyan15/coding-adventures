<!-- hl-knowledge: introduces=[]; assesses=[AR-CULTURE-SHUKRAN-22, AR-CONCEPT-C07-ASIF-01, AR-CONCEPT-C06-MIN-FADLIK-02, AR-SCRIPT-JOINING-FORMS-04] -->

