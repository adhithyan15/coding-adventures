#!/usr/bin/env bash
#
# build.sh — regenerate the FormulaBar HTML fragment from the Mosaic
# pipeline (mosaic-compile --backend html).
#
# Per the VisiCalc cross-backend demo plan (Phase 2 — VC2-html):
# this is the simplest possible cross-backend demo — open `index.html`
# in a browser and see VisiCalc.
#
# Today we only compile FormulaBar through the pipeline. The Grid
# fragment is hand-written in index.html as a static HTML <table>
# placeholder, because the `Grid` built-in primitive isn't yet wired
# into the mosaic-emit-html pipeline (only the React emitter knows
# how to lower it). When the HTML Grid emitter lands, this script
# gains a second `mosaic-compile --backend html ...` line for Grid
# and index.html switches to including `build/Grid.html` instead of
# its hand-written placeholder.
#
# Usage:
#   cd code/programs/typescript/visicalc-html
#   bash scripts/build.sh
#
# Output:
#   code/programs/typescript/visicalc-html/build/FormulaBar.html
#
# Open `code/programs/typescript/visicalc-html/index.html` in any browser to view.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$DEMO_DIR/../../../.." && pwd)"

MOSAIC_COMPILE="$REPO_ROOT/code/packages/rust/target/debug/mosaic-compile"

# Always (re)build mosaic-compile so emitter fixes reach the generated code.
# cargo is incremental, so this is ~free when nothing changed. The old
# `if [ ! -x "$MOSAIC_COMPILE" ]` guard skipped the build whenever ANY stale
# binary already existed, silently serving pre-fix output (this is what hid the
# Compose formula-bar textStyle fix — the demo kept using an old mosaic-compile).
echo "Building mosaic-compile..."
(cd "$REPO_ROOT/code/packages/rust" && cargo build -p mosaic-compile)

SRC="$REPO_ROOT/code/programs/mosaic/visicalc"
OUT_DIR="$DEMO_DIR/build"
mkdir -p "$OUT_DIR"

# UI30/UI-G multi-variant matrix. The FormulaBar is generated across the full
# LAYOUT × THEME grid — layout (desktop Row vs touch Column) comes from the .mll
# variant, theme (dark vs light) from the .msl style. Same FormulaBar.mil
# interface for all four; only spatial arrangement + colors differ. index.html
# embeds all four and swaps them at runtime against the SAME engine workbook
# (the live theme+layout switcher), which is why the light-theme .msl — dead
# code until now, rendered by no demo — finally ships.
#
#   variant   theme   ->  build/FormulaBar.<desktop|touch>.<dark|light>.html
for variant in desktop touch; do
  for theme in dark light; do
    echo "Compiling FormulaBar (HTML, $variant / $theme)..."
    "$MOSAIC_COMPILE" --backend html \
      --interface "$SRC/FormulaBar.mil" \
      --layout    "$SRC"   --variant "$variant" \
      --style     "$SRC/FormulaBar.$theme.msl" \
      -o "$OUT_DIR/FormulaBar.$variant.$theme.html"
  done
done

# Backwards-compatible aliases: the pre-switcher filenames some docs/tools still
# reference. Desktop-dark was `FormulaBar.html`; touch-dark was
# `FormulaBar.touch.html`.
cp "$OUT_DIR/FormulaBar.desktop.dark.html" "$OUT_DIR/FormulaBar.html"
cp "$OUT_DIR/FormulaBar.touch.dark.html"   "$OUT_DIR/FormulaBar.touch.html"

echo "Compiling Grid (HTML, dark + light)..."
# UI34 PR — the demo's Grid is now generated by mosaic-compile from
# the shared visicalc/mosaic/Grid.{mil,desktop.mll,dark.msl} triple
# (the same source the React demo consumes).  Grid.desktop.mll
# itself collapses to a one-line `pkg::mosaic-pkg-grid::Grid (...)`
# reference per UI34 §5, so we pass --package-search-path so the
# resolver locates the package, recursively compiles its
# Grid + Cell + Column triple, and substitutes the resolved sub-tree
# into the demo's layout before the HTML emitter runs.
#
# The output is a STATIC TEMPLATE — mosaic-for / mosaic-if / mosaic-
# else comment markers surround the loop / branch bodies and `{{x}}`
# mustache placeholders sit in slot-bound positions.  The visicalc-
# html shell ships a small inline JS template-expander that hydrates
# the template with hard-coded sample data so the demo opens
# directly from disk without a server.
# Grid is generated per THEME (dark + light). The Grid layout doesn't diverge
# desktop-vs-touch in v0.2.0 (Grid.touch.mll is isomorphic to desktop — the real
# touch divergence is the stacked FormulaBar), so only the theme axis matters
# here; the switcher reuses the same Grid template for both layouts and picks the
# theme-matched one.
for theme in dark light; do
  echo "Compiling Grid (HTML, $theme)..."
  "$MOSAIC_COMPILE" --backend html \
    --interface           "$SRC/Grid.mil" \
    --layout              "$SRC/Grid.desktop.mll" \
    --style               "$SRC/Grid.$theme.msl" \
    --package-search-path "$REPO_ROOT/code/packages" \
    -o "$OUT_DIR/Grid.$theme.html"
done
# Back-compat alias for the pre-switcher filename.
cp "$OUT_DIR/Grid.dark.html" "$OUT_DIR/Grid.html"

echo "Done. Generated:"
ls -la "$OUT_DIR"
echo
echo "Open $DEMO_DIR/index.html in a browser to view."
