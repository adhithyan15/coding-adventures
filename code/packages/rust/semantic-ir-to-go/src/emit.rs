thread_local! {
    static FN_ARITY: RefCell<HashMap<String, usize>> = RefCell::new(HashMap::new());
}

// ---------------------------------------------------------------------------
// Lexical helpers
// ---------------------------------------------------------------------------

fn indent_str(level: usize) -> String {
    "\t".repeat(level)
}

/// Sanitize a SIR identifier for Go.
///
/// Go identifiers match `[A-Za-z_][A-Za-z0-9_]*`.  Keywords get an
/// underscore suffix.  Invalid characters get `_<hex>` encoding.
/// Empty → `_sir_empty`.
pub fn sanitize_ident(s: &str) -> String {
    if s.is_empty() {
        return "_sir_empty".to_string();
    }
    if is_valid_go_ident(s) && !is_go_keyword(s) && !is_go_builtin(s) {
        return s.to_string();
    }
    if is_go_keyword(s) || is_go_builtin(s) {
        return format!("{}_", s);
    }
    let mut out = String::with_capacity(s.len() + 4);
    out.push('_');
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            out.push(ch);
        } else {
            let _ = write!(out, "_{:x}", ch as u32);
        }
    }
    out
}

fn is_valid_go_ident(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }
    let mut chars = s.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    for ch in chars {
        if !(ch.is_ascii_alphanumeric() || ch == '_') {
            return false;
        }
    }
    true
}

fn is_go_keyword(s: &str) -> bool {
    matches!(
        s,
        "break" | "case" | "chan" | "const" | "continue" | "default"
            | "defer" | "else" | "fallthrough" | "for" | "func"
            | "go" | "goto" | "if" | "import" | "interface"
            | "map" | "package" | "range" | "return" | "select"
            | "struct" | "switch" | "type" | "var"
    )
}

/// Predeclared identifiers that are not keywords but conflict at
/// the lexer level.  We rewrite to avoid surprising shadowing.
fn is_go_builtin(s: &str) -> bool {
    matches!(
        s,
        "bool" | "byte" | "complex64" | "complex128" | "error"
            | "float32" | "float64" | "int" | "int8" | "int16"
            | "int32" | "int64" | "rune" | "string" | "uint"
            | "uint8" | "uint16" | "uint32" | "uint64" | "uintptr"
            | "true" | "false" | "iota" | "nil"
            | "append" | "cap" | "close" | "complex" | "copy"
            | "delete" | "imag" | "len" | "make" | "new" | "panic"
            | "print" | "println" | "real" | "recover"
    )
}

fn sanitize_comment(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\n' | '\r' | '\u{0085}' | '\u{2028}' | '\u{2029}' => out.push(' '),
            _ => out.push(ch),
        }
    }
    out
}

fn quote_go_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\x{:02x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use semantic_ir::{
        EffectSet, FeatureManifest, Metadata, Param, Span,
    };

    fn s() -> Span {
        Span::synthetic()
    }

    #[test]
    fn sanitize_idents() {
        assert_eq!(sanitize_ident("hello"), "hello");
        assert_eq!(sanitize_ident(""), "_sir_empty");
        assert_eq!(sanitize_ident("func"), "func_");
        assert_eq!(sanitize_ident("type"), "type_");
        assert_eq!(sanitize_ident("int"), "int_"); // builtin predeclared
        assert_eq!(sanitize_ident("print"), "print_"); // predeclared
        let r = sanitize_ident("null?");
        assert!(r.starts_with('_'));
        assert!(r.contains("null"));
    }

    #[test]
    fn quote_go_string_escapes() {
        assert_eq!(quote_go_string("hi"), r#""hi""#);
        assert_eq!(quote_go_string(r#"a"b\c"#), r#""a\"b\\c""#);
    }

    #[test]
    fn quote_go_string_control_chars() {
        let q = quote_go_string("\u{0001}");
        assert!(q.contains(r"\x01"), "got: {}", q);
    }

    #[test]
    fn sanitize_comment_strips_terminators() {
        let r = sanitize_comment("a\nb");
        assert!(!r.contains('\n'));
    }

    #[test]
    fn function_emit_name_renames_main() {
        assert_eq!(function_emit_name("main"), "_sir_user_main");
        assert_eq!(function_emit_name("id"), "id");
    }

    #[test]
    fn emit_int_literal() {
        let mut out = String::new();
        emit_expr(&mut out, &Expr::IntLit { value: 42, span: s() }, 0);
        assert_eq!(out, "Value(int64(42))");
    }

    #[test]
    fn emit_bool_and_nil() {
        let mut a = String::new();
        let mut b = String::new();
        let mut c = String::new();
        emit_expr(&mut a, &Expr::BoolLit { value: true, span: s() }, 0);
        emit_expr(&mut b, &Expr::BoolLit { value: false, span: s() }, 0);
        emit_expr(&mut c, &Expr::NilLit { span: s() }, 0);
        assert_eq!(a, "Value(true)");
        assert_eq!(b, "Value(false)");
        assert_eq!(c, "Value(nil)");
    }

    #[test]
    fn emit_simple_function() {
        let body = Block {
            stmts: vec![],
            value: Expr::VarRef {
                name: "x".into(),
                scope: Scope::Param,
                span: s(),
            },
            span: s(),
        };
        let f = Function {
            name: "id".into(),
            params: vec![Param { name: "x".into(), sir_type: None, span: s() }],
            return_type: None,
            captures: vec![],
            body,
            effects: EffectSet::PURE,
            metadata: Metadata::new(),
            span: s(),
        };
        let mut out = String::new();
        emit_function(&mut out, &f);
        assert!(out.contains("func id(x Value) Value"));
        assert!(out.contains("return x"));
    }

    #[test]
    fn emit_minimal_module() {
        let m = Module {
            name: "demo".into(),
            manifest: FeatureManifest::new(),
            imports: vec![],
            exports: vec![],
            functions: vec![Function {
                name: "main".into(),
                params: vec![],
                return_type: None,
                captures: vec![],
                body: Block {
                    stmts: vec![],
                    value: Expr::IntLit { value: 42, span: s() },
                    span: s(),
                },
                effects: EffectSet::PURE,
                metadata: Metadata::new(),
                span: s(),
            }],
            globals: vec![],
            metadata: Metadata::new()
                .with_source_language("twig")
                .with_sir_version(semantic_ir::CURRENT_SIR_VERSION),
            span: s(),
        };
        let out = emit_module(&m);
        assert!(out.contains("package main"));
        assert!(out.contains("import ("));
        assert!(out.contains("\"fmt\""));
        assert!(out.contains("\"strconv\""));
        assert!(out.contains("func _sir_user_main() Value"));
        assert!(out.contains("func main()"));
        assert!(out.contains("_sir_user_main()"));
    }
}
