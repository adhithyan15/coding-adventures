<!-- hl-knowledge: introduces=[]; assesses=[ES-LEX-SER, ES-GRAMMAR-SER-PRESENT-SINGULAR, ES-GRAMMAR-SER-IDENTITY, ES-GRAMMAR-SER-ESTAR-CONTRAST, ES-LEX-DONDE] -->

