#!/usr/bin/env python3
"""contraindications_build.py — generate the CONTRAINDICATION RULEBOOK as ADJ `rule`s.

WHY THIS EXISTS (the ADJ-native refactor).  Until now, "which drugs are contraindicated
for this patient" lived in a Python dict inside `chart_to_cop.py`:

    _PREGNANCY_CONTRAINDICATED = {"moxifloxacin", "tmp_smx"}   # <- the reasoning, in Python

That is exactly the "Python rule layer in the middle" we are removing. A contraindication
is *conditional knowledge* — "a fluoroquinolone is contraindicated IN pregnancy" — which is
precisely what the adj-lang `rule { head: … when: … }` clause (the rulebook keystone) was
built to express. So the knowledge moves OUT of Python and INTO an ADJ rulebook the engine
reasons over; Python is left only translating chart facts into the patient's active
*contexts* and reading the engine's derived answer.

    grounding/treatment-constraints-grounding.json   (spider byte-quotes, already grounded)
            │
            ▼  THIS GENERATOR
    contraindications.adj          a rulebook of GROUNDED relate-facts + two GENERIC,
                                   context-scoped derivation rules
            │
            ▼  contraindications.derive_contraindications(cli, active_contexts)
    ? contraindicated($D, $C)      the ENGINE derives the excluded drugs (0 model calls)

THE GENERIC SHAPE (this is the point — it is NOT medicine-specific).  A contraindication is
"term/drug D is excluded IN context C", McCarthy's `ist(c, φ)`.  The patient's *contexts*
(pregnancy, QT prolongation, …) are per-case facts; the universal grounded knowledge
(fluoroquinolones are contraindicated in pregnancy) is a rulebook fact; the engine joins
them.  The very same shape encodes "term T MEANS m in context (jurisdiction) J" — so the
machinery built here is the substrate for any context-scoped rule corpus (see the memory
`project_adj_universal_rule_substrate`).  We deliberately use the domain-neutral word
**context** (relation `active_context`), not "pregnancy-specific" predicates.

GROUNDING / TRUST.  Each contraindication fact carries the spider's verbatim byte-quote as
its `source` + the fetched URL as `locator`.  A contraindication is DIRECTIONAL (a binary
exclusion, not a magnitude), so a grounding whose verdict confirms the DIRECTION of harm
("may cause fetal harm") is sufficient to ground it at `trust authoritative`; a record with
no usable quote stays `trust consensus` and is tagged `% [FLAG: …]` so the authored-debt is
visible (mirrors recall/iem_edge_ground.py).  With no grounding JSON present the file is
regenerated byte-identically from the authored fallbacks, so `--check` is meaningful before
any web pass and the harness is testable offline.

Usage:  python3 contraindications_build.py            # regenerate .adj + manifest
        python3 contraindications_build.py --check    # verify the .adj matches the manifest
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MYCIN = HERE.parents[1]  # .../mycin-2026 (antibiotics → treatment → mycin-2026)
ADJ = HERE / "contraindications.adj"
GROUNDING = MYCIN / "grounding" / "treatment-constraints-grounding.json"
MANIFEST = HERE / "contraindication-manifest.json"


def _esc(s: str) -> str:
    """Escape an untrusted spider-derived string for an adj-lang `source "..."` literal.
    Backslash FIRST (a trailing `\\` would escape the closing quote and corrupt the parse of
    every following clause), then the double-quote, then collapse control chars to spaces."""
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return re.sub(r"[\r\n\t]", " ", s)


# ---------------------------------------------------------------------------
# The contraindication knowledge, as data.  Each row names the grounding record that backs
# it (an id in treatment-constraints-grounding.json) and the structural fact it produces.
#
#   class-level:  a whole drug CLASS is contraindicated in a context.  Needs a `has_class`
#                 membership fact too, so the engine can map a concrete drug → its class.
#   drug-level:   a specific drug is contraindicated in a context (no class abstraction).
#
# The drug tokens (moxifloxacin, tmp_smx) are the SAME tokens the set-cover uses, so the
# derived exclusions key straight into `forced_zero`.  Class membership is definitional
# (moxifloxacin IS a fluoroquinolone) — not a clinical claim — so it needs no grounding.
# ---------------------------------------------------------------------------

# (drug token, class token) — definitional class membership.
DRUG_CLASSES: list[tuple[str, str]] = [
    ("moxifloxacin", "fluoroquinolone"),
]

# Class-level contraindications: (grounding_id, class, context, authored_fallback_quote).
CLASS_CONTRA: list[tuple[str, str, str, str]] = [
    ("ci_moxifloxacin_pregnancy", "fluoroquinolone", "pregnancy",
     "Fluoroquinolones (e.g. moxifloxacin) are generally avoided in pregnancy due to "
     "potential fetal harm shown in animal studies."),
    # Genericity demonstration (GROUNDED, but gated on a context no current chart asserts):
    # the SAME generic rule excludes fluoroquinolones in QT prolongation.  This adds no
    # behaviour change to the existing charts — it only fires if a chart carries
    # active_context(qt_prolongation) — but shows the context mechanism is not pregnancy-bound.
    ("ci_fluoroquinolone_qt", "fluoroquinolone", "qt_prolongation",
     "Fluoroquinolones (e.g. moxifloxacin) prolong the QT interval and should be avoided in "
     "patients with known QT prolongation."),
]

# Drug-level contraindications: (grounding_id, drug, context, authored_fallback_quote).
DRUG_CONTRA: list[tuple[str, str, str, str]] = [
    ("ci_tmpsmx_pregnancy", "tmp_smx", "pregnancy",
     "Trimethoprim-sulfamethoxazole is avoided in pregnancy (folate antagonism / risk of "
     "neural tube defects)."),
]


def _gate(rec: dict | None) -> tuple[str, str]:
    """Map a grounding record to (verdict, trust).  A contraindication is directional, so a
    `grounded` OR `direction_only` verdict WITH a byte-quote grounds it authoritatively; any
    other state is authored-debt at consensus trust."""
    if not rec:
        return "FLAG:pending", "consensus"
    g = rec.get("grounded") or {}
    verdict = g.get("verdict")
    if verdict in ("grounded", "direction_only") and g.get("byte_quote"):
        return "ACCEPT", "authoritative"
    return f"FLAG:{re.sub(r'[^a-z_]', '', (verdict or 'pending').lower())[:24] or 'pending'}", "consensus"


def _contra_block(rel: str, subj: str, ctx: str, gid: str, authored: str,
                  rec: dict | None) -> tuple[str, dict]:
    """Render one grounded `relate <rel>(<subj>, <ctx>)` clause + its manifest entry."""
    verdict, trust = _gate(rec)
    g = (rec or {}).get("grounded") or {}
    if verdict == "ACCEPT":
        source = g.get("byte_quote") or authored
        url = g.get("resolved_url")
        lines = [f"    relate {rel}({subj}, {ctx})",
                 f'        source "{_esc(source)}"']
        if url:
            lines.append(f'        locator "{_esc(url)}"')
        lines.append("        trust authoritative")
    else:
        source, url = authored, None
        lines = [f"    relate {rel}({subj}, {ctx})",
                 f'        source "{_esc(authored)}"',
                 f"        trust consensus   % [{verdict}]"]
    entry = {"relation": rel, "subject": subj, "context": ctx, "grounding_id": gid,
             "verdict": verdict, "trust": trust, "source": source, "url": url}
    return "\n".join(lines), entry


HEADER = """\
% ============================================================================
% contraindications — drug exclusions as CONTEXT-SCOPED derivation rules (ADJ-native).
% ============================================================================
% MYCIN-2026 (therapy layer).  A drug is contraindicated IN a clinical CONTEXT
% (pregnancy, QT prolongation, …): McCarthy's ist(c, φ).  The patient's active
% contexts are per-case facts; the universal, grounded contraindication knowledge
% lives HERE; the engine joins them and DERIVES the excluded drugs:
%
%     ? contraindicated($Drug, $Context)
%
% This replaces a hand-written Python set (_PREGNANCY_CONTRAINDICATED) — the
% reasoning now lives in the language, not the compiler.  The SAME generic shape
% encodes any context-scoped rule corpus (e.g. "a term MEANS m in jurisdiction J"),
% which is the whole point: a domain-neutral substrate (project_adj_universal_rule_substrate).
%
% GENERATED by treatment/antibiotics/contraindications_build.py from
% grounding/treatment-constraints-grounding.json (the spider's byte-provenanced
% output).  Do not hand-edit — re-ground and regenerate.  A grounded fact carries
% its byte-quote as `source` + `trust authoritative` (+ the fetched URL as
% `locator`); an ungrounded one stays `trust consensus` tagged `% [FLAG: …]` so the
% authored-debt is visible and drives to zero (feedback_nothing_human_authored).
% ============================================================================

dictionary contraindication_vocab {
    define drug             : entity   surface "drug", "antibiotic", "agent"
    define drug_class       : entity   surface "drug class", "antibiotic class"
    define clinical_context : entity   surface "clinical context", "patient context"

    % drug → its pharmacologic class (definitional membership).
    define has_class                : relation from drug to drug_class
    % a CLASS is contraindicated in a context (the grounded clinical claim).
    define class_contraindicated_in : relation from drug_class to clinical_context
    % a specific DRUG is contraindicated in a context (no class abstraction).
    define drug_contraindicated_in  : relation from drug to clinical_context
    % the patient's currently-active contexts (asserted per case from the chart).
    define active_context           : relation from clinical_context to clinical_context
    % DERIVED: drug D is contraindicated under active context C (the query target).
    define contraindicated          : relation from drug to clinical_context
}
"""

# The two generic derivation rules.  These are STRUCTURAL (the logical form of "a drug is
# contraindicated when one of its contexts is active") — the clinical grounding lives on the
# facts they join, whose byte-quotes flow into each answer's citations.  $Var binds across
# head and body (clause scope); both rules share the `active_context($C)` gate so a drug is
# only excluded for a context the patient is actually in.
RULES = """\

    % --- the GENERIC, context-scoped derivation rules ------------------------
    % class route: D is contraindicated in C if D's class is contraindicated in C
    % and C is one of the patient's active contexts.
    rule {
        head: contraindicated($D, $C)
        when: active_context($C), class_contraindicated_in($Class, $C), has_class($D, $Class)
    }
    % drug route: D is directly contraindicated in an active context C.
    rule {
        head: contraindicated($D, $C)
        when: active_context($C), drug_contraindicated_in($D, $C)
    }
"""


def build(check: bool = False) -> int:
    recs: dict[str, dict] = {}
    if GROUNDING.exists():
        recs = {r["id"]: r for r in json.loads(GROUNDING.read_text()).get("records", [])}

    body = [HEADER, "rulebook contraindications {", "    use contraindication_vocab"]
    clauses: dict[str, dict] = {}

    body.append("")
    body.append("    % --- drug → class membership (definitional) " + "-" * 28)
    for drug, klass in DRUG_CLASSES:
        body.append(f"    relate has_class({drug}, {klass})")
        clauses[f"has_class__{drug}"] = {"relation": "has_class", "subject": drug,
                                         "context": klass, "verdict": "DEFINITIONAL",
                                         "trust": "definitional", "grounding_id": None}

    body.append("")
    body.append("    % --- grounded CLASS-level contraindications " + "-" * 29)
    for gid, klass, ctx, authored in CLASS_CONTRA:
        block, entry = _contra_block("class_contraindicated_in", klass, ctx, gid, authored, recs.get(gid))
        body.append(block)
        clauses[f"class_contraindicated_in__{klass}__{ctx}"] = entry

    body.append("")
    body.append("    % --- grounded DRUG-level contraindications " + "-" * 30)
    for gid, drug, ctx, authored in DRUG_CONTRA:
        block, entry = _contra_block("drug_contraindicated_in", drug, ctx, gid, authored, recs.get(gid))
        body.append(block)
        clauses[f"drug_contraindicated_in__{drug}__{ctx}"] = entry

    body.append(RULES.rstrip("\n"))
    body.append("}")
    adj_text = "\n".join(body) + "\n"

    accepted = sum(1 for c in clauses.values() if c["verdict"] == "ACCEPT")
    flagged = sum(1 for c in clauses.values() if str(c["verdict"]).startswith("FLAG"))
    manifest = {"kind": "contraindication", "clauses": clauses,
                "hash": hashlib.sha256(json.dumps(clauses, sort_keys=True).encode()).hexdigest()[:16]}

    if check:
        ok = ADJ.exists() and ADJ.read_text() == adj_text
        mok = MANIFEST.exists() and json.loads(MANIFEST.read_text()).get("hash") == manifest["hash"]
        print("contraindications_build --check:", "up to date" if (ok and mok) else "OUT OF DATE")
        return 0 if (ok and mok) else 1

    ADJ.write_text(adj_text)
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"contraindications_build: regenerated contraindications.adj + manifest "
          f"({accepted} grounded ACCEPT, {flagged} consensus/flagged authored-debt).")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
