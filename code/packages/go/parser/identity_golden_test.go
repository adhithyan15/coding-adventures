package parser

// Identity-aware goldens over seeded RANDOM grammars.
//
// The goldens in golden_test.go pin real grammars, and the frozen-engine
// differential pins small hand-written ones, but the property most easily
// broken by an engine rewrite is node and slice IDENTITY: which *ASTNodes are
// distinct, which Children slices are one backing array, which nodes a memo
// hit hands out. This test generates random grammars (nullable rules, left
// recursion, lookaheads, separated repetitions, duplicate and undefined
// rules, enum-only and disagreeing tokens) and random token streams under
// random limits, and hashes an identity-aware dump of every result:
// every distinct *ASTNode pointer and every distinct Children backing array
// is numbered in first-visit order, so a node that appears twice, or two
// nodes that share a slice, are visible in the text.
//
// The hashes in testdata/golden/identity.golden were generated by the PR 1
// engine (the engine before the flat-array rewrite) using only the public
// API, so the very same test file runs against either engine. A committed
// golden was chosen over a third frozen engine copy: it costs one small file
// instead of 1,200 lines of dead code, and it was produced by the engine that
// shipped. Regenerate (only for an INTENDED output change) with
//
//	GOLDEN_UPDATE=1 go test -run TestIdentityGolden

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"testing"

	grammartools "github.com/adhithyan15/coding-adventures/code/packages/go/grammar-tools"
	"github.com/adhithyan15/coding-adventures/code/packages/go/lexer"
)

var idVocab = []string{"NUM", "X", "Y", "NEWLINE", "EOF", "NUM", "X"}
var idVals = map[string]string{"NUM": "1", "PLUS": "+", "X": "x", "Y": "y", "Z": "z", "LP": "(", "RP": ")", "NEWLINE": "\n", "EOF": "", "NAME": "n", "COMMA": ","}

func idGrammar(rng *rand.Rand, nrules int, allowNL bool) *grammartools.ParserGrammar {
	rn := func(i int) string { return fmt.Sprintf("r%d", i) }
	tokName := func() string {
		for {
			v := idVocab[rng.Intn(len(idVocab))]
			if v == "NEWLINE" && !allowNL {
				continue
			}
			return v
		}
	}
	var gen func(d int) grammartools.GrammarElement
	gen = func(d int) grammartools.GrammarElement {
		k := 16
		if d <= 0 {
			k = 6
		}
		switch rng.Intn(k) {
		case 0, 1, 2:
			return grammartools.RuleReference{Name: rn(rng.Intn(nrules))}
		case 3, 4:
			return grammartools.RuleReference{Name: tokName(), IsToken: true}
		case 5:
			switch rng.Intn(6) {
			case 0:
				return grammartools.Literal{Value: ""}
			case 1:
				return grammartools.RuleReference{Name: "nope"}
			case 2:
				return grammartools.RuleReference{Name: rn(rng.Intn(nrules)), IsToken: true} // token named like a rule
			case 3:
				return grammartools.Literal{Value: "NUM"}
			}
			return grammartools.Literal{Value: idVals[tokName()]}
		case 6, 7, 8:
			els := make([]grammartools.GrammarElement, 1+rng.Intn(3))
			for i := range els {
				els[i] = gen(d - 1)
			}
			return grammartools.Sequence{Elements: els}
		case 9, 10:
			els := make([]grammartools.GrammarElement, 2+rng.Intn(2))
			for i := range els {
				els[i] = gen(d - 1)
			}
			return grammartools.Alternation{Choices: els}
		case 11:
			return grammartools.Optional{Element: gen(d - 1)}
		case 12:
			return grammartools.Repetition{Element: gen(d - 1)}
		case 13:
			if rng.Intn(2) == 0 {
				return grammartools.PositiveLookahead{Element: gen(d - 1)}
			}
			return grammartools.NegativeLookahead{Element: gen(d - 1)}
		case 14:
			if rng.Intn(2) == 0 {
				return grammartools.Group{Element: gen(d - 1)}
			}
			return grammartools.OneOrMoreRepetition{Element: gen(d - 1)}
		default:
			return grammartools.SeparatedRepetition{Element: gen(d - 1), Separator: gen(d - 1), AtLeastOne: rng.Intn(2) == 0}
		}
	}
	pg := &grammartools.ParserGrammar{}
	for i := 0; i < nrules; i++ {
		pg.Rules = append(pg.Rules, grammartools.GrammarRule{Name: rn(i), Body: gen(1 + rng.Intn(4))})
	}
	if rng.Intn(8) == 0 { // duplicate rule name
		pg.Rules = append(pg.Rules, grammartools.GrammarRule{Name: rn(0), Body: gen(2)})
	}
	return pg
}

var idEnum = []lexer.TokenType{lexer.TokenName, lexer.TokenNumber, lexer.TokenPlus, lexer.TokenLParen, lexer.TokenRParen, lexer.TokenComma, lexer.TokenNewline, lexer.TokenEOF}

func idTokens(rng *rand.Rand) []lexer.Token {
	n := rng.Intn(12)
	var toks []lexer.Token
	for i := 0; i < n; i++ {
		v := idVocab[rng.Intn(len(idVocab))]
		if (v == "EOF" || v == "NEWLINE") && rng.Intn(3) != 0 {
			v = "NUM"
		}
		t := lexer.Token{TypeName: v, Value: idVals[v], Line: 1, Column: i + 1}
		switch rng.Intn(40) {
		case 0: // enum-only token
			t = lexer.Token{Type: idEnum[rng.Intn(len(idEnum))], Value: idVals[v], Line: 1, Column: i + 1}
		case 1: // TypeName disagrees with the enum
			t.Type = idEnum[rng.Intn(len(idEnum))]
		case 2: // a real token with an empty value
			t.Value = ""
		case 3:
			t.TypeName = fmt.Sprintf("r%d", rng.Intn(4))
		}
		toks = append(toks, t)
	}
	if rng.Intn(4) != 0 {
		toks = append(toks, lexer.Token{TypeName: "EOF", Line: 1, Column: n + 1})
	}
	return toks
}

type idNumbering struct {
	nodes map[*ASTNode]int
	arrs  map[*interface{}]int
}

// idDump writes n with its node number (#n), its Children backing-array
// number (#c, -1 when empty), positions and nil-ness. A node visited before
// prints "^" and is not descended into again.
func idDump(n *ASTNode, sb *strings.Builder, ids *idNumbering) {
	nid, seen := ids.nodes[n]
	if !seen {
		nid = len(ids.nodes)
		ids.nodes[n] = nid
	}
	aid := -1
	if len(n.Children) > 0 {
		p := &n.Children[0]
		var ok bool
		if aid, ok = ids.arrs[p]; !ok {
			aid = len(ids.arrs)
			ids.arrs[p] = aid
		}
	}
	fmt.Fprintf(sb, "(%s#n%d#c%d@%d:%d-%d:%d nil=%v", n.RuleName, nid, aid, n.StartLine, n.StartColumn, n.EndLine, n.EndColumn, n.Children == nil)
	if seen {
		sb.WriteString(" ^)")
		return
	}
	for _, c := range n.Children {
		switch x := c.(type) {
		case *ASTNode:
			idDump(x, sb, ids)
		case lexer.Token:
			fmt.Fprintf(sb, " %s/%d/%q:%d:%d", x.TypeName, x.Type, x.Value, x.Line, x.Column)
		}
	}
	sb.WriteString(")")
}

func TestIdentityGolden(t *testing.T) {
	grammars, batch := 20000, 2500
	if testing.Short() {
		t.Skip("identity golden covers 200,000 parses")
	}
	rng := rand.New(rand.NewSource(4242))
	var lines []string
	h := sha256.New()
	cases := 0
	for gi := 0; gi < grammars; gi++ {
		nr := 1 + rng.Intn(6)
		c, err := CompileGrammar(idGrammar(rng, nr, rng.Intn(3) == 0))
		if err != nil {
			t.Fatal(err)
		}
		for it := 0; it < 10; it++ {
			toks := idTokens(rng)
			opts := Options{}
			switch rng.Intn(6) {
			case 0:
				opts.MaxDepth = 1 + rng.Intn(14)
			case 1:
				opts.MaxMemoSlots = 1 + rng.Intn(60)
			case 2:
				opts.MaxDepth, opts.MaxMemoSlots = 1+rng.Intn(14), 1+rng.Intn(60)
			case 3:
				opts.MaxTokens = 1 + rng.Intn(8)
			}
			if rng.Intn(2) == 0 {
				opts.StartRule = fmt.Sprintf("r%d", rng.Intn(nr))
			}
			ast, err := c.Parse(toks, opts)
			var sb strings.Builder
			if err != nil {
				sb.WriteString("ERR " + err.Error())
				if ge, ok := err.(*GrammarParseError); ok {
					fmt.Fprintf(&sb, " tok=%v cause=%v nil=%v", ge.Tok, ge.Err, ast == nil)
				}
			} else {
				idDump(ast, &sb, &idNumbering{map[*ASTNode]int{}, map[*interface{}]int{}})
			}
			fmt.Fprintf(h, "%d/%d %s\n", gi, it, sb.String())
			cases++
			if cases%batch == 0 {
				lines = append(lines, fmt.Sprintf("%d\t%s", cases, hex.EncodeToString(h.Sum(nil)[:16])))
				h.Reset()
			}
		}
	}
	got := strings.Join(lines, "\n") + "\n"
	path := filepath.Join("testdata", "golden", "identity.golden")
	if os.Getenv("GOLDEN_UPDATE") != "" {
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (generate with GOLDEN_UPDATE=1)", err)
	}
	wantLines := strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n")
	for i, l := range lines {
		if i >= len(wantLines) || wantLines[i] != l {
			t.Errorf("identity golden batch %d differs (cases up to %s)", i, strings.SplitN(l, "\t", 2)[0])
		}
	}
	if len(wantLines) != len(lines) {
		t.Errorf("golden has %d batches, test produced %d", len(wantLines), len(lines))
	}
}
