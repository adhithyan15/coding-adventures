#[test]
fn expands_multiple_blocks_and_a_partial_final_block() {
    let limits = Mgf1Sha512Limits::new(EXPECTED_MASK.len()).unwrap();
    let mut output = [0u8; EXPECTED_MASK.len()];
    generate_mgf1_sha512_mask(&SEED, &mut output, limits).unwrap();
    assert_eq!(output, EXPECTED_MASK);
}

#[test]
fn every_prefix_matches_the_complete_expansion() {
    let limits = Mgf1Sha512Limits::new(EXPECTED_MASK.len()).unwrap();
    for length in [1, 63, 64, 65, 128, 191] {
        let mut output = vec![0u8; length];
        generate_mgf1_sha512_mask(&SEED, &mut output, limits).unwrap();
        assert_eq!(output, EXPECTED_MASK[..length]);
    }
}

#[test]
fn empty_output_is_valid_under_a_nonzero_policy() {
    let limits = Mgf1Sha512Limits::new(1).unwrap();
    let mut output = [];
    generate_mgf1_sha512_mask(&SEED, &mut output, limits).unwrap();
    assert!(output.is_empty());
}

#[test]
fn policy_failure_leaves_the_complete_output_unchanged() {
    let limits = Mgf1Sha512Limits::new(64).unwrap();
    let mut output = [0xa5; 65];
    let error = generate_mgf1_sha512_mask(&SEED, &mut output, limits).unwrap_err();
    assert_eq!(error.kind(), Mgf1Sha512ErrorKind::MaskTooLongForPolicy);
    assert_eq!(output, [0xa5; 65]);
}

#[test]
fn limit_policy_rejects_zero_and_reports_its_bound() {
    let error = Mgf1Sha512Limits::new(0).unwrap_err();
    assert_eq!(
        error.kind(),
        Mgf1Sha512LimitsErrorKind::ZeroMaximumMaskBytes
    );
    let limits = Mgf1Sha512Limits::new(4096).unwrap();
    assert_eq!(limits.maximum_mask_bytes(), 4096);
}

#[cfg(target_pointer_width = "64")]
#[test]
fn limit_policy_rejects_lengths_beyond_the_rfc_domain() {
    let too_long = usize::try_from(MAXIMUM_MGF1_MASK_LENGTH + 1).unwrap();
    let error = Mgf1Sha512Limits::new(too_long).unwrap_err();
    assert_eq!(error.kind(), Mgf1Sha512LimitsErrorKind::MaximumMaskTooLong);
}

#[test]
fn public_constants_match_rfc_8017_sha512_mgf1() {
    assert_eq!(SHA512_DIGEST_LENGTH, 64);
    assert_eq!(MGF1_COUNTER_LENGTH, 4);
    assert_eq!(MAXIMUM_MGF1_MASK_LENGTH, 274_877_906_944);
}

#[test]
fn errors_are_stable_and_redacted() {
    let limits_error = Mgf1Sha512Limits::new(0).unwrap_err();
    assert_eq!(
        format!("{limits_error:?}"),
        "Mgf1Sha512LimitsError { kind: ZeroMaximumMaskBytes }"
    );
    assert_eq!(
        limits_error.to_string(),
        "SHA-512 MGF1 limits error ZeroMaximumMaskBytes"
    );

    let limits = Mgf1Sha512Limits::new(1).unwrap();
    let mut output = [0x7d; 2];
    let error = generate_mgf1_sha512_mask(&SEED, &mut output, limits).unwrap_err();
    assert_eq!(
        format!("{error:?}"),
        "Mgf1Sha512Error { kind: MaskTooLongForPolicy }"
    );
    assert_eq!(error.to_string(), "SHA-512 MGF1 error MaskTooLongForPolicy");
    assert!(!format!("{error:?}").contains("125"));
    assert!(!error.to_string().contains("125"));
}
