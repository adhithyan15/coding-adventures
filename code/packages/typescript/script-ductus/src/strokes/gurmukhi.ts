// ---------------------------------------------------------------------------
// gurmukhi.ts — the Gurmukhi (Punjabi) owner of cited pen paths
// ---------------------------------------------------------------------------
//
// WHERE THE ORDER COMES FROM. GNPS's children's Punjabi app "Gurmukhi Sikho"
// (GNPS Learning Hub, github.com/codemanxdev/gnps_learning_hub, Apache-2.0) has
// an Alphabet Tracing lesson: for every letter, ordered checkpoints that the
// developer tapped over the Noto Sans Gurmukhi letter, one list per pen-down
// stroke, which the app's trace widget makes a child reach IN ORDER. That is
// one attested teaching order, cited the way the Telugu owner cites a tracing
// app. Only facts are taken from it: the order, where each stroke starts,
// which way it goes and where the pen lifts. No checkpoint coordinate is
// copied. The points below are fitted to the bundled Noto Sans Gurmukhi
// outline instead (font units, y up), and tests/strokes/gurmukhi.test.ts holds
// them to that ink at the default tolerances.
//
// THE HEADLINE. The source draws the headline FIRST, left to right, in every
// letter whose printed headline is one piece. That is its teaching order, and
// each record says so: fluent writers are often described as adding it last
// (as native Devanagari writers do in HP Labs India's pen data). Five letters,
// ਅ ਖ ਘ ਪ ਮ, print a SPLIT headline in Noto; the source draws no separate bar
// for them, and neither does the path: the bar's left part opens the first
// stroke and its right part, drawn right to left, opens the stem stroke.
//
// LIFTS. Omniglot's non-native copyists (Lake et al. 2015, MIT) draw ਛ ਨ ਬ in
// one stroke fewer than the source, and copyist counts are a ceiling on native
// lifts. Those three keep the source's order and join one restart on the ink.
//
// WORDS. A word shares one headline, so it is not these letters side by side:
// `headline-word.ts` composes it from them. Each letter's body is drawn as
// below WITHOUT its first (headline) stroke, the split-bar letters ਅ ਖ ਘ ਪ ਮ
// whole, and then ONE headline last, left to right, along the word's printed
// bar. That word-level order is this book's convention (the order fluent
// writers are described as using, and the one it draws Devanagari words in),
// not something this source records; a letter's own strip keeps the source's
// headline-first order.
//
// Vowel signs, bindi, tippi, addak, halant and the dot below have no source, so
// they are absent, and a word holding one is never composed.
// ---------------------------------------------------------------------------

