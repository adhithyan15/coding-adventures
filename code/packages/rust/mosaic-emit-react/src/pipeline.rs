/// Emit the discriminated-union event type for a component.
///
/// Layout for a component with zero emits (UI24 §6):
///
/// ```tsx
/// type ButtonEvent = never;
/// ```
///
/// Layout for a component with one or more emits (UI24 §3.1):
///
/// ```tsx
/// type GridEvent =
///   | { type: "navigate"; row: number; col: number }
///   | { type: "editCommit"; value: string };
/// ```
fn emit_event_union(component: &str, emits: &[EmitDecl]) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    if emits.is_empty() {
        writeln!(out, "type {component}Event = never;").unwrap();
        return Ok(out);
    }
    writeln!(out, "type {component}Event =").unwrap();
    let last = emits.len() - 1;
    for (i, e) in emits.iter().enumerate() {
        // Strip the leading `on` prefix and camelCase the rest. This is the
        // UI24 §5 conversion rule; the resulting string is the variant's
        // `type` field literal.
        let lowered = strip_on_prefix(&e.name);
        let type_field = to_camel_case_first_lower(&lowered);
        validate_emit_name(&type_field)?;

        let mut variant = format!("  | {{ type: \"{type_field}\"");
        for p in &e.params {
            let field = to_camel_case_first_lower(&p.name);
            validate_slot_or_field_name(&field)
                .map_err(|n| PipelineEmitError::UnsafeSlotName(n))?;
            let ts = emit_payload_to_ts(&p.r#type);
            variant.push_str(&format!("; {field}: {ts}"));
        }
        variant.push_str(" }");
        if i == last {
            variant.push(';');
        }
        writeln!(out, "{variant}").unwrap();
    }
    Ok(out)
}

/// Emit the props interface.
///
/// Slots come first in declaration order; the required `dispatch` prop is
/// always last (UI24 §3.3 invariant #5).
fn emit_props_interface(component: &str, slots: &[SlotDecl]) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "interface {component}Props {{").unwrap();
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_slot_or_field_name(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        let ts = slot_type_to_ts(&s.r#type);
        // `node` and `Component(X)` slots are optional by convention (UI20 §6).
        // Other types follow the source `required` flag.
        let optional = matches!(s.r#type, SlotType::Node | SlotType::Component(_)) || !s.required;
        let q = if optional { "?" } else { "" };
        writeln!(out, "  {field}{q}: {ts};").unwrap();
    }
    writeln!(out, "  dispatch: (event: {component}Event) => void;").unwrap();
    writeln!(out, "}}").unwrap();
    Ok(out)
}

/// Emit the React functional component declaration.
///
/// Slots are destructured in declaration order; `dispatch` is destructured
/// last (so it is trivial to spot in diffs and code reviews — UI24 §3.3).
fn emit_function(
    component: &str,
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
    part_styles: &HashMap<String, String>,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "export function {component}({{").unwrap();
    for s in slots {
        writeln!(out, "  {},", to_camel_case_first_lower(&s.name)).unwrap();
    }
    writeln!(out, "  dispatch,").unwrap();
    writeln!(out, "}}: {component}Props) {{").unwrap();
    writeln!(out, "  return (").unwrap();
    out.push_str(&emit_jsx_tree(layout_root, 4, part_styles)?);
    writeln!(out, "  );").unwrap();
    writeln!(out, "}}").unwrap();
    // Suppress unused-variable warnings the compiler would emit for slots
    // that the simple layout tree does not yet reference. A real layout will
    // reference them through child JSX in follow-up PRs.
    let _ = slots;
    Ok(out)
}

