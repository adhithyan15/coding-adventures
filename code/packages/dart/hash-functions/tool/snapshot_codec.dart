import 'dart:convert';

/// Encodes fixture bytes as base64 chunks in a generated Dart source file.
///
/// The generated data is test-only. Base64 and JSON decoding use
/// `dart:convert`, so the same snapshot can be loaded by the Dart VM and Node
/// without filesystem access in the test process.
String renderFixtureSnapshotSource(
  List<int> bytes, {
  int chunkSize = 32768,
}) {
  if (chunkSize <= 0) {
    throw ArgumentError.value(chunkSize, 'chunkSize', 'Must be positive');
  }
  final encoded = base64Encode(bytes);
  final chunks = <String>[];
  for (var offset = 0; offset < encoded.length; offset += chunkSize) {
    final end = (offset + chunkSize < encoded.length)
        ? offset + chunkSize
        : encoded.length;
    chunks.add(encoded.substring(offset, end));
  }

  final source = StringBuffer()
    ..writeln('// Generated by tool/generate_fixture_snapshot.dart.')
    ..writeln(
        '// Do not edit. The source corpus is hash-functions-v1/cases.json.')
    ..writeln('const List<String> fixtureJsonBase64Chunks = <String>[');
  for (final chunk in chunks) {
    source.writeln("  '$chunk',");
  }
  source.writeln('];');
  return source.toString();
}

/// Decodes generated fixture chunks without using filesystem or host APIs.
List<int> decodeFixtureSnapshot(Iterable<String> chunks) =>
    base64Decode(chunks.join());
