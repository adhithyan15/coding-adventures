<!-- hl-knowledge: introduces=[ML-GRAMMAR-C341-TONNUNNU-01]; assesses=[ML-CONCEPT-C06-DATIVE-SUBJECT-01, ML-LEX-C306-KRIYA306-05, ML-LEX-C256-VASTU256-03, ML-LEX-C146-WANT146-02] -->

