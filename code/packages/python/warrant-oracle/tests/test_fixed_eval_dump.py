def test_the_domain_table_recomputes_from_an_independent_formula():
    """The ``fx_edge`` sets of [D21] and [D25], written here with bit strings and no shared code."""
    leaves = load(DOMAINS)["leaves"]
    for width in (16, 32):
        full = (1 << width) - 1
        unsigned = (
            [*range(256)]
            + [int("1" + "0" * i, 2) for i in range(8, width)]
            + [full]
            + [int("1" * (width - 1 - i) + "0" + "1" * i, 2) for i in range(width)]
        )
        assert [int(v) for v in leaves[f"fx_edge:U{width}"]["values"]] == unsigned
        assert len(unsigned) == {16: 281, 32: 313}[width]
        signed = sorted({v - (full + 1) if v >> (width - 1) else v for v in unsigned} | set(range(-255, 0)))
        assert [int(v) for v in leaves[f"fx_edge:I{width}"]["values"]] == signed
        assert len(signed) == {16: 527, 32: 559}[width]
    full = (1 << 64) - 1
    unsigned = (
        [*range(256)]
        + [1 << i for i in range(8, 64)]
        + [full]
        + [full ^ (1 << i) for i in range(64)]
    )
    assert [int(v) for v in leaves["u64_edge"]["values"]] == unsigned and len(unsigned) == 377
    signed = sorted({v - (1 << 64) if v >> 63 else v for v in unsigned} | set(range(-255, 0)))
    assert [int(v) for v in leaves["fx_edge:I64"]["values"]] == signed and len(signed) == 623
    assert leaves["nat_shift"]["descriptor"] == SHIFT
    assert [int(v) for v in leaves["nat_shift"]["values"]] == [
        *range(65),
        65,
        127,
        128,
        129,
        255,
        256,
        65535,
        65536,
    ]
    for key in ("fx_edge:U16", "fx_edge:I16", "fx_edge:I32", "fx_edge:I64", "nat_shift"):
        assert leaves[key]["label"] == "bounded-set"
        assert leaves[key]["size"] == len(leaves[key]["values"]) == leaves[key]["descriptor"]["size"]


