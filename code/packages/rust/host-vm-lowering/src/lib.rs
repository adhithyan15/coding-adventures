//! Shared lowering facts for LANG host VM backends.
//!
//! The Python ALGOL pipeline discovered a set of details that should not stay
//! trapped in one frontend: explicit activation frames, static links,
//! by-name thunk descriptors, array descriptors, nonlocal goto state, helper
//! signatures, and target-specific backend constraints. This crate ports those
//! facts into Rust so frontends and host VM backends can agree on one ABI.

