#[test]
fn test_eval_value_encoding_and_conversions() {
    let t = EvalValue::Bool(true);
    let f = EvalValue::Bool(false);
    let i = EvalValue::Int(-42);
    let n = EvalValue::Nat(100);
    let u8_val = EvalValue::U8(255);
    let u64_val = EvalValue::U64(18446744073709551615);
    let b = EvalValue::Bytes(vec![0xde, 0xad, 0xbe, 0xef]);
    let l = EvalValue::List(vec![EvalValue::Int(1), EvalValue::Int(2)]);
    let opt_none = EvalValue::Option(None);
    let opt_some = EvalValue::Option(Some(Box::new(EvalValue::Nat(7))));
    let res_ok = EvalValue::Result(Ok(Box::new(EvalValue::Bool(true))));
    let res_err = EvalValue::Result(Err(("MyError".to_string(), "NOT_FOUND".to_string())));

    // encode_tfv
    assert_eq!(t.encode_tfv(), "T");
    assert_eq!(f.encode_tfv(), "F");
    assert_eq!(i.encode_tfv(), "I-42");
    assert_eq!(n.encode_tfv(), "I100");
    assert_eq!(u8_val.encode_tfv(), "I255");
    assert_eq!(u64_val.encode_tfv(), "I18446744073709551615");
    assert_eq!(b.encode_tfv(), "Xdeadbeef");
    assert_eq!(l.encode_tfv(), "L2 I1 I2");
    assert_eq!(opt_none.encode_tfv(), "N");
    assert_eq!(opt_some.encode_tfv(), "I7");
    assert_eq!(res_ok.encode_tfv(), "T");
    assert_eq!(res_err.encode_tfv(), "S4e4f545f464f554e44");

    // as_bool
    assert_eq!(t.as_bool(), Some(true));
    assert_eq!(f.as_bool(), Some(false));
    assert_eq!(i.as_bool(), None);

    // as_bytes
    assert_eq!(b.as_bytes(), Some(&[0xde, 0xad, 0xbe, 0xef][..]));
    assert_eq!(t.as_bytes(), None);

    // as_u64
    assert_eq!(n.as_u64(), Some(100));
    assert_eq!(u64_val.as_u64(), Some(18446744073709551615));
    assert_eq!(u8_val.as_u64(), Some(255));
    assert_eq!(EvalValue::Int(50).as_u64(), Some(50));
    assert_eq!(i.as_u64(), None); // negative
    assert_eq!(t.as_u64(), None);

    // as_i128
    assert_eq!(i.as_i128(), Some(-42));
    assert_eq!(n.as_i128(), Some(100));
    assert_eq!(u8_val.as_i128(), Some(255));
    assert_eq!(t.as_i128(), None);
}

