namespace CodingAdventures.CanonicalCbor.FSharp.Tests

open System
open System.Globalization
open System.IO
open System.Text.Json
open CodingAdventures.CanonicalCbor.FSharp
open Xunit

module PortableConformanceTests =
    let private fromHex (value: string) = Convert.FromHexString(value)

    let private bytesEqual (expected: byte array) (actual: byte array) =
        Assert.True(
            expected.AsSpan().SequenceEqual(actual),
            sprintf "expected %s, got %s" (Convert.ToHexString(expected)) (Convert.ToHexString(actual))
        )

    let private requiredString (element: JsonElement) (property: string) =
        match element.GetProperty(property).GetString() |> Option.ofObj with
        | None -> raise (InvalidDataException(sprintf "fixture property %s is null" property))
        | Some value -> value

    let private nestedArrayWire depth =
        Array.init (depth + 1) (fun index -> if index = depth then 0xf6uy else 0x81uy)

    let private parseNatural (value: string) =
        match Int32.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture) with
        | true, parsed -> parsed
        | _ -> raise (InvalidDataException("generated length is not a bounded decimal natural"))

    let private parseSingleByte value =
        let decoded = fromHex value
        if decoded.Length <> 1 then
            raise (InvalidDataException("generated byte token must decode to exactly one byte"))
        decoded[0]

    let private assertError id (action: unit -> unit) =
        let error = Assert.Throws<CborException>(Action(action))
        Assert.Equal(id, error.Id)
        Assert.StartsWith("canonical-cbor:", error.Message, StringComparison.Ordinal)

    let private mapValue (specification: string) =
        specification.Split(';')
        |> Array.map (fun fragment ->
            let pair = fragment.Split('=', 2)
            CanonicalCbor.decode (fromHex pair[0]), CanonicalCbor.decode (fromHex pair[1]))
        |> Array.toList
        |> CborValue.map

    let private generatedValue (specification: string) =
        if specification.StartsWith("nested-array:", StringComparison.Ordinal) then
            let parts = specification.Split(':')
            if parts.Length <> 2 then
                raise (InvalidDataException("invalid generated nested-array grammar"))
            let depth = parseNatural parts[1]
            [ 1 .. depth ] |> List.fold (fun value _ -> CborValue.array [ value ]) CborValue.nullValue
        else
            if not (specification.StartsWith("bytes-repeat:", StringComparison.Ordinal)) then
                raise (InvalidDataException("unknown generated value grammar"))
            let parts = specification.Split(':')
            if parts.Length <> 3 then
                raise (InvalidDataException("invalid generated byte-string grammar"))
            let length = parseNatural parts[1]
            let repeated = parseSingleByte parts[2]
            CborValue.bytes (Array.create length repeated)

    let private generatedWire (specification: string) =
        if specification.StartsWith("wire:nested-array:", StringComparison.Ordinal) then
            let parts = specification.Split(':')
            if parts.Length <> 3 then
                raise (InvalidDataException("invalid generated nested-array wire grammar"))
            nestedArrayWire (parseNatural parts[2])
        else
            if not (specification.StartsWith("wire:bytes-repeat:", StringComparison.Ordinal)) then
                raise (InvalidDataException("unknown generated wire grammar"))
            let parts = specification.Split(':')
            if parts.Length <> 4 then
                raise (InvalidDataException("invalid generated wire grammar"))
            let length = parseNatural parts[2]
            use output = new MemoryStream(length + 9)
            if length <= 23 then
                output.WriteByte(byte (0x40 ||| length))
            elif length <= int Byte.MaxValue then
                output.WriteByte(0x58uy)
                output.WriteByte(byte length)
            elif length <= int UInt16.MaxValue then
                output.WriteByte(0x59uy)
                output.WriteByte(byte (length >>> 8))
                output.WriteByte(byte length)
            else
                output.WriteByte(0x5auy)
                output.WriteByte(byte (length >>> 24))
                output.WriteByte(byte (length >>> 16))
                output.WriteByte(byte (length >>> 8))
                output.WriteByte(byte length)
            let repeated = parseSingleByte parts[3]
            for _ in 1 .. length do output.WriteByte(repeated)
            output.ToArray()

    let private byteStringWire length repeated =
        let wire = Array.create (length + 5) repeated
        wire[0] <- 0x5auy
        wire[1] <- byte (length >>> 24)
        wire[2] <- byte (length >>> 16)
        wire[3] <- byte (length >>> 8)
        wire[4] <- byte length
        wire

    let private findFixture () =
        let rec search directory =
            match directory with
            | None -> raise (FileNotFoundException("canonical-cbor-v1 fixture not found"))
            | Some (current: DirectoryInfo) ->
                let candidate = Path.Combine(current.FullName, "code", "specs", "fixtures", "canonical-cbor-v1", "cases.json")
                if File.Exists(candidate) then candidate
                else search (current.Parent |> Option.ofObj)
        search (Some(DirectoryInfo(Directory.GetCurrentDirectory())))

    [<Fact>]
    let ``exact portable bytes match shared oracle`` () =
        use document = JsonDocument.Parse(File.ReadAllText(findFixture ()))
        let root = document.RootElement
        Assert.Equal(1, root.GetProperty("schema_version").GetInt32())
        Assert.Equal("rfc8949-section-4.2.3-length-first", root.GetProperty("profile").GetString())
        Assert.Equal(CanonicalCbor.MaxNestingDepth, root.GetProperty("limits").GetProperty("max_nesting_depth").GetInt32())
        Assert.Equal(CanonicalCbor.MaxEncodedBytes, root.GetProperty("limits").GetProperty("max_encoded_bytes").GetInt32())
        Assert.Equal(55, root.GetProperty("cases").GetArrayLength())
        let expectedErrors =
            [| "unexpected-eof"; "trailing-bytes"; "reserved"; "indefinite"
               "non-minimal-integer"; "invalid-utf8"; "non-canonical-map-order"
               "unsupported-simple"; "float-not-supported"; "too-deep"
               "length-too-large"; "duplicate-map-key"; "encode-too-deep"; "encode-too-large" |]
        let actualErrors =
            root.GetProperty("error_ids").EnumerateArray()
            |> Seq.map (fun item ->
                match item.GetString() |> Option.ofObj with
                | Some value -> value
                | None -> raise (InvalidDataException("fixture error identifier is null")))
            |> Seq.toArray
        Assert.True((expectedErrors = actualErrors))

        for testCase in root.GetProperty("cases").EnumerateArray() do
            let id = requiredString testCase "id"
            let operation = requiredString testCase "operation"
            let input = requiredString testCase "input"
            let expected = requiredString testCase "expected"
            match operation with
            | "round-trip" ->
                bytesEqual (fromHex expected) (CanonicalCbor.encodeChecked (CanonicalCbor.decode (fromHex input)))
            | "decode-error" ->
                let wire =
                    if input.StartsWith("nested-array-wire:", StringComparison.Ordinal) then
                        nestedArrayWire (Int32.Parse(input[(input.LastIndexOf(':') + 1)..], CultureInfo.InvariantCulture))
                    else fromHex input
                assertError expected (fun () -> CanonicalCbor.decode wire |> ignore)
            | "encode-map" ->
                bytesEqual (fromHex expected) (CanonicalCbor.encodeChecked (mapValue input))
            | "generated-round-trip" ->
                bytesEqual (generatedWire expected) (CanonicalCbor.encodeChecked (generatedValue input))
            | "encode-error" ->
                let value = if input = "duplicate-map-key" then mapValue "6161=00;6161=01" else generatedValue input
                assertError expected (fun () -> CanonicalCbor.encodeChecked value |> ignore)
                use destination = new MemoryStream()
                destination.WriteByte(0xaauy)
                assertError expected (fun () -> CanonicalCbor.encodeIntoChecked value destination)
                bytesEqual (fromHex "aa") (destination.ToArray())
            | _ -> raise (InvalidDataException(sprintf "%s: unknown operation %s" id operation))

    [<Fact>]
    let ``unsigned maximum uses all eight argument bytes`` () =
        let value = CborValue.unsigned UInt64.MaxValue
        bytesEqual (fromHex "1bffffffffffffffff") (CanonicalCbor.encodeChecked value)
        Assert.Equal(value, CanonicalCbor.decode (fromHex "1bffffffffffffffff"))

    [<Fact>]
    let ``public values defend mutable bytes and checked append is atomic`` () =
        let source = [| 1uy; 2uy; 3uy |]
        let value = CborValue.bytes source
        source[0] <- 9uy
        let exposed = CborValue.tryBytes value |> Option.defaultWith (fun () -> failwith "bytes expected")
        bytesEqual [| 1uy; 2uy; 3uy |] exposed
        exposed[1] <- 9uy
        bytesEqual [| 1uy; 2uy; 3uy |] (CborValue.tryBytes value |> Option.get)
        Assert.Equal(CborValue.bytes [| 1uy; 2uy; 3uy |], value)

        use destination = new MemoryStream()
        destination.WriteByte(0xaauy)
        destination.Position <- 0L
        CanonicalCbor.encodeIntoChecked (CborValue.unsigned 24UL) destination
        bytesEqual (fromHex "aa1818") (destination.ToArray())

    [<Fact>]
    let ``text rejects unpaired surrogates before replacement encoding`` () =
        Assert.Throws<ArgumentException>(fun () -> CborValue.text (String([| char 0xd800 |])) |> ignore) |> ignore
        Assert.Throws<ArgumentException>(fun () -> CborValue.text (String([| char 0xdc00 |])) |> ignore) |> ignore
        let astral = String([| char 0xd83d; char 0xde00 |])
        bytesEqual (fromHex "64f09f9880") (CanonicalCbor.encodeChecked (CborValue.text astral))

    [<Fact>]
    let ``oversized UTF-8 fails before publishing and errors stay payload blind`` () =
        let value = CborValue.text (String('\u0800', 400_000))
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeChecked value |> ignore)
        use destination = new MemoryStream()
        destination.WriteByte(0xaauy)
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeIntoChecked value destination)
        bytesEqual (fromHex "aa") (destination.ToArray())

        let error = Assert.Throws<CborException>(fun () -> CanonicalCbor.decode (fromHex "63e298") |> ignore)
        Assert.Equal("length-too-large", error.Id)
        Assert.StartsWith("canonical-cbor:", error.Message, StringComparison.Ordinal)
        Assert.DoesNotContain("e298", error.Message, StringComparison.OrdinalIgnoreCase)

    [<Fact>]
    let ``full unsigned domains and hostile container lengths are handled`` () =
        bytesEqual (fromHex "3bffffffffffffffff") (CanonicalCbor.encodeChecked (CborValue.negative UInt64.MaxValue))
        bytesEqual
            (fromHex "dbffffffffffffffff00")
            (CanonicalCbor.encodeChecked (CborValue.tag UInt64.MaxValue (CborValue.unsigned 0UL)))

        for wire in [ "5bffffffffffffffff"; "7bffffffffffffffff"; "9bffffffffffffffff"; "bbffffffffffffffff" ] do
            assertError "length-too-large" (fun () -> CanonicalCbor.decode (fromHex wire) |> ignore)

    [<Fact>]
    let ``strict UTF-8 and canonical map ordering cover adversarial edges`` () =
        let highThenNonLow = String([| char 0xd800; 'x' |])
        Assert.Throws<ArgumentException>(fun () -> CborValue.text highThenNonLow |> ignore) |> ignore
        for wire in [ "6180"; "62e298"; "64f4908080" ] do
            assertError "invalid-utf8" (fun () -> CanonicalCbor.decode (fromHex wire) |> ignore)

        let value =
            CborValue.map
                [ CborValue.bytes [| 0x80uy |], CborValue.unsigned 1UL
                  CborValue.bytes [| 0x7fuy |], CborValue.unsigned 0UL ]
        bytesEqual (fromHex "a2417f00418001") (CanonicalCbor.encodeChecked value)
        let duplicate =
            CborValue.map
                [ CborValue.bytes [| 1uy |], CborValue.nullValue
                  CborValue.bytes [| 1uy |], CborValue.nullValue ]
        assertError "duplicate-map-key" (fun () -> CanonicalCbor.encodeChecked duplicate |> ignore)

    [<Fact>]
    let ``collections are values and the exact encoding cap is enforced`` () =
        let source = ResizeArray<CborValue>()
        source.Add(CborValue.unsigned 1UL)
        let value = CborValue.array source
        source.Add(CborValue.unsigned 2UL)
        Assert.Equal(CborValue.array [ CborValue.unsigned 1UL ], value)
        let nullValue = Unchecked.defaultof<CborValue>
        Assert.Throws<ArgumentException>(fun () -> CborValue.array [ nullValue ] |> ignore) |> ignore
        Assert.Throws<ArgumentException>(fun () -> CborValue.map [ nullValue, CborValue.nullValue ] |> ignore) |> ignore
        Assert.Throws<ArgumentNullException>(fun () -> CborValue.tag 0UL nullValue |> ignore) |> ignore
        Assert.Throws<ArgumentNullException>(fun () -> CanonicalCbor.encodeChecked nullValue |> ignore) |> ignore

        let mapValue = CborValue.map [ CborValue.text "a", CborValue.unsigned 1UL ]
        Assert.Equal(CborValue.map [ CborValue.text "a", CborValue.unsigned 1UL ], mapValue)
        Assert.Equal(Some 1UL, CborValue.tryUnsigned (CanonicalCbor.decode (fromHex "01")))
        Assert.Equal(Some UInt64.MaxValue, CborValue.tryNegative (CanonicalCbor.decode (fromHex "3bffffffffffffffff")))
        Assert.Equal(Some "a", CborValue.tryText (CanonicalCbor.decode (fromHex "6161")))
        Assert.Equal(Some true, CborValue.tryBoolean (CanonicalCbor.decode (fromHex "f5")))
        Assert.Equal(Some true, CborValue.tryBoolean (CborValue.boolean true))
        Assert.True(CborValue.isNull (CanonicalCbor.decode (fromHex "f6")))
        Assert.False(CborValue.isNull (CborValue.unsigned 0UL))
        Assert.True(CborValue.tryBytes CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryUnsigned CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryNegative CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryText CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryArray CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryMap CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryTag CborValue.nullValue |> Option.isNone)
        Assert.True(CborValue.tryBoolean CborValue.nullValue |> Option.isNone)
        Assert.Equal(1, CborValue.tryArray (CanonicalCbor.decode (fromHex "8100")) |> Option.get |> List.length)
        Assert.Equal(1, CborValue.tryMap (CanonicalCbor.decode (fromHex "a10001")) |> Option.get |> List.length)
        let tagNumber, tagged = CborValue.tryTag (CanonicalCbor.decode (fromHex "c001")) |> Option.get
        Assert.Equal(0UL, tagNumber)
        Assert.Equal(Some 1UL, CborValue.tryUnsigned tagged)
        bytesEqual (fromHex "6161") (CanonicalCbor.encodeChecked (CborValue.text "a"))
        bytesEqual (fromHex "62c3a9") (CanonicalCbor.encodeChecked (CborValue.text "é"))
        let nestedTag =
            [ 1 .. CanonicalCbor.MaxNestingDepth ]
            |> List.fold (fun value _ -> CborValue.tag 0UL value) CborValue.nullValue
        let nestedTagWire =
            Array.append
                (Array.replicate CanonicalCbor.MaxNestingDepth 0xc0uy)
                [| 0xf6uy |]
        bytesEqual nestedTagWire (CanonicalCbor.encodeChecked nestedTag)
        bytesEqual nestedTagWire (CanonicalCbor.encodeChecked (CanonicalCbor.decode nestedTagWire))
        assertError "encode-too-deep" (fun () -> CanonicalCbor.encodeChecked (CborValue.tag 0UL nestedTag) |> ignore)
        let tooDeepTagWire =
            Array.append
                (Array.replicate (CanonicalCbor.MaxNestingDepth + 1) 0xc0uy)
                [| 0xf6uy |]
        assertError "too-deep" (fun () -> CanonicalCbor.decode tooDeepTagWire |> ignore)
        for count in [ 24; 256; 65_536 ] do
            let encoded =
                Seq.replicate count CborValue.nullValue
                |> CborValue.array
                |> CanonicalCbor.encodeChecked
            bytesEqual encoded (CanonicalCbor.encodeChecked (CanonicalCbor.decode encoded))
        let oversizedArray = Seq.replicate CanonicalCbor.MaxEncodedBytes CborValue.nullValue |> CborValue.array
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeChecked oversizedArray |> ignore)

        let exactText = String(char 0x0800, 349_523) + "aa"
        let exact = CanonicalCbor.encodeChecked (CborValue.text exactText)
        Assert.Equal(CanonicalCbor.MaxEncodedBytes, exact.Length)
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeChecked (CborValue.text (exactText + "a")) |> ignore)

        let oversized = CanonicalCbor.decode (byteStringWire CanonicalCbor.MaxEncodedBytes 0x5auy)
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeChecked oversized |> ignore)

        let firstKey = Array.zeroCreate<byte> 524_284
        let secondKey = Array.zeroCreate<byte> 524_284
        secondKey[secondKey.Length - 1] <- 1uy
        let retainedKeys =
            CborValue.map
                [ CborValue.bytes firstKey, CborValue.nullValue
                  CborValue.bytes secondKey, CborValue.nullValue ]
        assertError "encode-too-large" (fun () -> CanonicalCbor.encodeChecked retainedKeys |> ignore)
