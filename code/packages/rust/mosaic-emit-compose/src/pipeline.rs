fn slot_type_to_kotlin(t: &SlotType) -> String {
    match t {
        SlotType::Text => "String".to_string(),
        SlotType::Number => "Double".to_string(),
        SlotType::Bool => "Boolean".to_string(),
        SlotType::Image => "String".to_string(),
        SlotType::Color => "String".to_string(),
        SlotType::Node => "Any".to_string(),
        SlotType::List(inner) => format!("List<{}>", list_inner_to_kotlin(inner)),
        SlotType::Component(name) => {
            // Same defence in depth as in `from_pipeline` — the
            // upstream grammar should already constrain component
            // names, but re-validate here in case we ever interpolate
            // a hostile name into a Kotlin type position.  On
            // failure, return a Kotlin type that won't compile so
            // the issue surfaces loudly at the next layer rather than
            // silently producing injected code.
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
    }
}

fn list_inner_to_kotlin(t: &ListInnerType) -> String {
    match t {
        ListInnerType::Text => "String".to_string(),
        ListInnerType::Number => "Double".to_string(),
        ListInnerType::Bool => "Boolean".to_string(),
        ListInnerType::Image => "String".to_string(),
        ListInnerType::Color => "String".to_string(),
        ListInnerType::Node => "Any".to_string(),
        ListInnerType::Component(name) => {
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
        ListInnerType::List(inner) => format!("List<{}>", list_inner_to_kotlin(inner)),
    }
}

fn emit_payload_type_to_kotlin(t: &EmitPayloadType) -> String {
    match t {
        EmitPayloadType::Text => "String".to_string(),
        EmitPayloadType::Number => "Double".to_string(),
        EmitPayloadType::Bool => "Boolean".to_string(),
        EmitPayloadType::Color => "String".to_string(),
        EmitPayloadType::Component(name) => {
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
    }
}

// =====================================================================
// Helpers (identifier / case conversions, prop lookups)
// =====================================================================

fn find_prop_value<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a LayoutPropValue> {
    node.props
        .iter()
        .find(|p| p.name == name)
        .map(|p: &LayoutProp| &p.value)
}

fn find_slot_ref_prop<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    match find_prop_value(node, name)? {
        LayoutPropValue::SlotRef(s) => Some(s.as_str()),
        _ => None,
    }
}

fn find_emit_ref_prop<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    match find_prop_value(node, name)? {
        LayoutPropValue::EmitRef(s) => Some(s.as_str()),
        _ => None,
    }
}

/// `onFooBar` → `FooBar`.  Strip the leading `on` if and only if it
/// is followed by an upper-cased letter (so `online` stays `online`).
fn strip_on_prefix(s: &str) -> String {
    if let Some(rest) = s.strip_prefix("on") {
        if rest
            .chars()
            .next()
            .map(|c| c.is_ascii_uppercase())
            .unwrap_or(false)
        {
            return rest.to_string();
        }
    }
    s.to_string()
}

/// `formula-change` → `FormulaChange`.  PascalCase from kebab-case.
fn pascalize(s: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for c in s.chars() {
        if c == '-' || c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// `read-only` → `readOnly`.  camelCase from kebab-case.
fn to_camel_case_first_lower(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for (i, c) in s.chars().enumerate() {
        if c == '-' || c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else if i == 0 {
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Defence-in-depth: reject anything that wouldn't survive being
/// interpolated into a Kotlin identifier position.
fn validate_safe_identifier(s: &str) -> Result<(), String> {
    if s.is_empty() {
        return Err(s.to_string());
    }
    let mut chars = s.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_alphabetic() || first == '_') {
        return Err(s.to_string());
    }
    for c in chars {
        if !(c.is_ascii_alphanumeric() || c == '_') {
            return Err(s.to_string());
        }
    }
    Ok(())
}

/// Escape a Rust string into a Kotlin single-line string literal.
///
/// Beyond the obvious `\` and `"`, this also escapes:
///
/// - `$` — Kotlin's string interpolation sigil.  An unescaped `$` in
///   a literal expression (e.g. `"$dispatch"`) reads the named
///   variable from lexical scope.  Inside our `@Composable` function
///   the `dispatch` lambda *is* in scope, so a `.mll` literal
///   containing `"$dispatch"` would silently dereference it.  Escape
///   to `\$`.
/// - `\n`, `\r`, `\t` — newlines and tabs.  Without escaping, a
///   literal newline in the source would break out of the
///   single-line `"..."` literal.
///
/// Triple-quoted (raw) Kotlin strings are not emitted by this
/// crate, so we don't have to model their separate escape rules.
fn escape_kotlin_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

