<!-- hl-knowledge: introduces=[GU-GRAMMAR-C150-VAANO-Q-01]; assesses=[GU-CONCEPT-C02-SHUN-01, GU-GRAMMAR-C145-PRESENT-O-01, GU-GRAMMAR-C147-E-TIME-01] -->

