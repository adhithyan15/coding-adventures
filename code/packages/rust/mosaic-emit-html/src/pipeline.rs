// Name conversion
// =====================================================================

/// Convert kebab-case to camelCase (first letter lowered). Used to
/// produce the slot-reference identifier inside `{{...}}` placeholders.
/// Matches the React backend's `to_camel_case_first_lower` so the same
/// host code can substitute placeholders against both outputs.
fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut cap_next = false;
    let mut first = true;
    for ch in s.chars() {
        if ch == '-' {
            cap_next = true;
            continue;
        }
        if first {
            out.push(ch.to_ascii_lowercase());
            first = false;
        } else if cap_next {
            out.push(ch.to_ascii_uppercase());
            cap_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// Convert a camelCase or kebab-case name to canonical kebab-case CSS
/// property syntax. mosstyle generally emits kebab-case already, but
/// hand-authored grammars sometimes round-trip a camelCase value (e.g.
/// `backgroundColor`); normalising here makes the output stable.
///
/// Truth table:
///
/// | Input             | Output             |
/// |-------------------|--------------------|
/// | `background`      | `background`       |
/// | `background-color`| `background-color` |
/// | `backgroundColor` | `background-color` |
/// | `fontSize`        | `font-size`        |
fn camel_to_kebab(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for (i, ch) in s.chars().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            out.push('-');
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch.to_ascii_lowercase());
        }
    }
    out
}

