import 'dart:convert';

/// Produces a Node-loadable Dart source snapshot of canonical fixture bytes.
String renderFixtureSnapshotSource(List<int> bytes, {int chunkSize = 32768}) {
  if (chunkSize <= 0) {
    throw ArgumentError.value(chunkSize, 'chunkSize', 'Must be positive');
  }
  final encoded = base64Encode(bytes);
  final chunks = <String>[];
  for (var offset = 0; offset < encoded.length; offset += chunkSize) {
    final end = (offset + chunkSize < encoded.length)
        ? offset + chunkSize
        : encoded.length;
    chunks.add(encoded.substring(offset, end));
  }
  final source = StringBuffer()
    ..writeln('// Generated by tool/generate_fixture_snapshot.dart.')
    ..writeln('// Do not edit. Source: hash-map-v1/cases.json.')
    ..writeln('const List<String> hashMapFixtureJsonBase64Chunks = <String>[');
  for (final chunk in chunks) {
    source.writeln("  '$chunk',");
  }
  source.writeln('];');
  return source.toString();
}

List<int> decodeFixtureSnapshot(Iterable<String> chunks) =>
    base64Decode(chunks.join());
