<!-- hl-knowledge: introduces=[GU-GRAMMAR-C274-NEGATIVE-SHORT-VERBS-01]; assesses=[GU-LEX-JAVU, GU-LEX-LEVU, GU-LEX-KHAAVU, GU-LEX-C147-PAST147-01] -->

