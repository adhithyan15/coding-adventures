<!-- hl-knowledge: introduces=[]; assesses=[ES-LEX-COMER, ES-GRAMMAR-ER-PRESENT-SINGULAR, ES-LEX-VIVIR, ES-GRAMMAR-IR-PRESENT-SINGULAR, ES-LEX-BEBER, ES-GRAMMAR-AR-PRESENT-SINGULAR, ES-GRAMMAR-PRO-DROP] -->

