<!-- hl-knowledge: introduces=[PT-NOTICE-C26-CORPO-04]; assesses=[PT-LEX-C02-PRACTICE-02, PT-NOTICE-C02-PRACTICE-03, PT-LEX-FORMAL-PRACTICE-02] -->

