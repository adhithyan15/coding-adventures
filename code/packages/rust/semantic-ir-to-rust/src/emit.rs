fn indent_str(level: usize) -> String {
    "    ".repeat(level)
}

/// Emit a SIR float literal as a `__sir::Value::Float(<rust-f64>)`.
///
/// Truth table for the spelling we choose:
///
/// | SIR value        | Rust literal emitted        | Why                       |
/// |------------------|-----------------------------|---------------------------|
/// | `3.0`            | `3.0f64`                    | `{:?}` keeps the `.0`     |
/// | `3.14`           | `3.14f64`                   | round-trippable decimal   |
/// | `-7.5`           | `-7.5f64`                   | sign preserved            |
/// | `NaN`            | `f64::NAN`                  | no literal spelling exists |
/// | `+∞`             | `f64::INFINITY`             | ditto                     |
/// | `-∞`             | `f64::NEG_INFINITY`         | ditto                     |
///
/// Using `{:?}` (Debug) rather than `{}` (Display) is deliberate:
/// Display renders `3.0_f64` as `"3"`, which would compile as an
/// `i64` mismatch; Debug renders `"3.0"`, an unambiguous float.
fn emit_float_literal(out: &mut String, value: f64) {
    if value.is_finite() {
        let _ = write!(out, "__sir::Value::Float({:?}f64)", value);
    } else if value.is_nan() {
        out.push_str("__sir::Value::Float(f64::NAN)");
    } else if value > 0.0 {
        out.push_str("__sir::Value::Float(f64::INFINITY)");
    } else {
        out.push_str("__sir::Value::Float(f64::NEG_INFINITY)");
    }
}

/// Sanitize a SIR identifier for Rust.
///
/// SIR names can include `?`, `!`, `-`, `+`, `*`, etc.  Rust
/// identifiers must match `[A-Za-z_][A-Za-z0-9_]*`.  Problematic
/// characters are rewritten to a stable underscore-encoded form;
/// names that are already valid Rust identifiers pass through
/// unchanged (UNLESS they are Rust keywords, in which case we
/// prefix `r#` raw-identifier syntax).
pub fn sanitize_ident(s: &str) -> String {
    if s.is_empty() {
        return "_$empty".to_string();
    }
    if is_valid_rust_ident(s) && !is_rust_keyword(s) {
        return s.to_string();
    }
    if is_rust_keyword(s) {
        // Raw-identifier syntax — keeps the original spelling
        // visible in tooling.
        return format!("r#{}", s);
    }
    let mut out = String::with_capacity(s.len() + 4);
    out.push('_'); // prefix so the result never starts with a digit
    out.push('_');
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            out.push(ch);
        } else {
            let _ = write!(out, "_{:x}", ch as u32);
        }
    }
    out
}

fn is_valid_rust_ident(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }
    let mut chars = s.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    for ch in chars {
        if !(ch.is_ascii_alphanumeric() || ch == '_') {
            return false;
        }
    }
    true
}

fn is_rust_keyword(s: &str) -> bool {
    // 2021-edition keywords + reserved.  `r#` raw-identifier
    // syntax can wrap most of these; some (`crate`, `self`,
    // `super`, `extern`) cannot — for those we fall back to the
    // underscore-encoded form below by ALSO returning `false`
    // here.  In v0 we accept the `r#` form for all common
    // keywords; the few un-raw-able ones get encoded.
    matches!(
        s,
        "as" | "break"
            | "const"
            | "continue"
            | "else"
            | "enum"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "static"
            | "struct"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "async"
            | "await"
            | "dyn"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "macro"
            | "override"
            | "priv"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
            | "try"
            | "union"
    )
}

/// Render `s` safe for inclusion in a Rust `//` line comment.
/// Strips line terminators; same approach as the TS backend.
fn sanitize_comment(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\n' | '\r' | '\u{0085}' | '\u{2028}' | '\u{2029}' => out.push(' '),
            _ => out.push(ch),
        }
    }
    out
}

fn quote_rs_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

