#[test]
fn an_ordinary_part_is_admitted_and_keeps_its_bytes() {
    let text = "  -- a comment\n  claim c:\n    true\n\n  claim d:\n    true\n";
    let p = part(text);
    assert_eq!(p.text(), text);
    assert_eq!(
        p.digest(),
        vos_manifest::digest::sha256_hex(text.as_bytes())
    );
}

