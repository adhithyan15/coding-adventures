// SqlVm.fs — stack-machine bytecode interpreter for the Mini-SQLite Level 1 pipeline.
//
// This module executes Program values produced by sql-codegen, evaluating them
// against a Backend and returning a QueryResult.
//
// ┌─────────────────────────────────────────────────────────────────────────┐
// │  PIPELINE POSITION                                                       │
// │                                                                          │
// │  sql-lexer → sql-parser → sql-planner → sql-optimizer → sql-codegen    │
// │           → [sql-vm] → mini-sqlite                                       │
// │                                                                          │
// │  Input : Program (from sql-codegen)                                      │
// │  Output: QueryResult — columns + rows + rows_affected                   │
// └─────────────────────────────────────────────────────────────────────────┘
//
// ── Execution model ───────────────────────────────────────────────────────
//
// The VM is a classic stack machine:
//   - A mutable stack holds intermediate SqlValue results.
//   - A program counter (pc) walks through the flat instruction array.
//   - Named labels are pre-indexed into a Map<string,int> for O(1) jumps.
//   - Cursors are open iterators over backend rows; multiple can be open at
//     once (supporting JOINs).
//   - Aggregate accumulators are mutable arrays; the VM initialises them
//     before the scan loop and finalises them after.
//
// ── SqlValue encoding ─────────────────────────────────────────────────────
//
// The planner defines SqlValue as a DU (Null | Integer | Real | Text | Bool).
// The backend uses obj (null = SQL NULL, int64, float, string, bool, byte[]).
//
// Inside the VM we work entirely with SqlValue DU so the type system can
// exhaustively check all branches. Only at the backend boundary (Insert/Update)
// do we convert to obj via toObj / fromObj helpers.
//
// ── Three-valued logic ────────────────────────────────────────────────────
//
// SQL has three truth values: TRUE, FALSE, and NULL (unknown).
//   - Comparison with NULL yields NULL (not FALSE).
//   - AND: FALSE AND NULL = FALSE; TRUE AND NULL = NULL.
//   - OR: TRUE OR NULL = TRUE; FALSE OR NULL = NULL.
//
// ── Loop structure ────────────────────────────────────────────────────────
//
// Every table scan follows the pattern generated by sql-codegen:
//
//   OpenScan("t", alias)
//   Label("loop_N")
//   JumpIfExhausted(alias, "end_N")   ← advance OR jump to end
//   AdvanceCursor(alias)              ← advance again (paired with JumpIfExhausted)
//   <body>
//   Jump("loop_N")
//   Label("end_N")
//   CloseScan(alias)
//
// NOTE: the F# codegen emits JumpIfExhausted THEN AdvanceCursor. In the
// Python/Java VMs, JumpIfExhausted is a pure test (no advance) and
// AdvanceCursor does the actual advance. This VM honours that model:
// JumpIfExhausted peeks via a pre-advance stored in a slot, and
// AdvanceCursor advances the iterator after the peek.

// We disable the nullable reference warnings that the project-level <Nullable>enable</Nullable>
// setting produces for legacy interop code (backend Row type).
// The backend's Row extends Dictionary<string,obj> and Next() returns Row|null
// at the .NET level. We handle nulls explicitly via obj.ReferenceEquals checks.
#nowarn "3261" // FS3261 nullness warnings — managed explicitly via ReferenceEquals
#nowarn "3264" // FS3264 nullness downcast warning

