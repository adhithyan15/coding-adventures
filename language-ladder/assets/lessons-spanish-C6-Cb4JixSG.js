<!-- hl-knowledge: introduces=[]; assesses=[ES-LEX-TENER, ES-GRAMMAR-TENER-PRESENT-SINGULAR, ES-LEX-NUMBERS-1-5, ES-LEX-NUMBERS-6-10] -->

