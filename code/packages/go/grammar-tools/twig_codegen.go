package grammartools

// twig_codegen.go — Generate Twig source code from TokenGrammar and ParserGrammar.
//
// Two exported functions produce ready-to-compile .tw files:
//
//   GenerateTwigLexer(grammar *TokenGrammar, sourceFile string) string
//       Generates compiler/lexer module (lexer.tw) from a .tokens file.
//       All tokens in grammar order + skip patterns become a dispatch chain.
//
//   GenerateTwigParser(pg *ParserGrammar, tg *TokenGrammar, sourceFile string) string
//       Generates compiler/cst-parser module (cst-parser.tw) from a .grammar file.
//       Each grammar rule becomes a Twig function returning a CST node or nil.
//
// CST node format
// ---------------
// Non-terminal: (cons "rule-name" (list child ...))
// Terminal:     the Token record as produced by the lexer
// Failure:      nil
// Success:      (cons rest-tokens cst-node)
//
// Token kind mapping
// ------------------
// Grammar token names map to Twig TokenKind constructors in token.tw:
//   LPAREN     → TkLParen
//   RPAREN     → TkRParen
//   QUOTE      → TkQuote
//   COLON      → TkColon
//   ARROW      → TkIdentifier  (no TkArrow in token.tw; "->" lexes as identifier)
//   BOOL_TRUE  → TkBoolean     (lexeme "#t")
//   BOOL_FALSE → TkBoolean     (lexeme "#f")
//   STRING     → TkString
//   INTEGER    → TkInteger
//   NAME       → TkIdentifier
//
// Keyword matching
// ----------------
// Keywords (e.g. "define", "lambda") lex as TkIdentifier.  The generated
// parser uses (cst-match-kw tokens "define") which checks both token kind
// (TkIdentifier?) and lexeme (string=? lex "define").

import (
	"fmt"
	"strings"
	"unicode"
)

// ============================================================================
// Shared helpers
// ============================================================================

// twigKindFor maps a grammar token name to the Twig TokenKind constructor.
func twigKindFor(grammarName string) string {
	switch grammarName {
	case "LPAREN":
		return "TkLParen"
	case "RPAREN":
		return "TkRParen"
	case "QUOTE":
		return "TkQuote"
	case "COLON":
		return "TkColon"
	case "ARROW":
		// ARROW "->" has no dedicated variant in token.tw; it lexes as TkIdentifier.
		return "TkIdentifier"
	case "BOOL_TRUE", "BOOL_FALSE":
		return "TkBoolean"
	case "STRING":
		return "TkString"
	case "INTEGER":
		return "TkInteger"
	case "NAME":
		return "TkIdentifier"
	default:
		// Generic: convert UPPER_SNAKE to PascalCase prefixed with Tk
		return "Tk" + snakeToCamel(grammarName)
	}
}

// snakeToCamel converts UPPER_SNAKE_CASE to PascalCase.
// "BOOL_TRUE" → "BoolTrue"
func snakeToCamel(s string) string {
	parts := strings.Split(strings.ToLower(s), "_")
	var sb strings.Builder
	for _, p := range parts {
		if len(p) > 0 {
			sb.WriteString(strings.ToUpper(p[:1]))
			sb.WriteString(p[1:])
		}
	}
	return sb.String()
}

// kebabCase converts a grammar rule name (snake_case or camelCase) to kebab-case.
// "if_form" → "if-form", "letStarForm" → "let-star-form"
func kebabCase(s string) string {
	// Replace underscores with hyphens first
	s = strings.ReplaceAll(s, "_", "-")
	// Insert hyphens before uppercase letters (for camelCase)
	var sb strings.Builder
	for i, r := range s {
		if i > 0 && unicode.IsUpper(r) {
			sb.WriteRune('-')
		}
		sb.WriteRune(unicode.ToLower(r))
	}
	return sb.String()
}

