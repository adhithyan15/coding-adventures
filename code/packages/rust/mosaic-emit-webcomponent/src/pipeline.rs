//! # Three-file pipeline entry point for the Web Components backend.
//!
//! This module implements **UI24 — emit→dispatch Flux pattern** for the
//! Custom Elements / Web Components output target. The public entry point is
//! [`from_pipeline`], which consumes the three-language pipeline output
//! produced by [`mosmodel-compiler`], [`moslayout-compiler`], and
//! [`mosstyle-compiler`].
//!
//! It exists alongside the legacy [`crate::WebComponentRenderer`] that is
//! driven by [`mosaic_vm::MosaicVM`]; the two code paths share no state. The
//! legacy path continues to compile single-file `.mosaic` source and is left
//! untouched.
//!
//! ## What this module produces
//!
//! For a component named `Button` with slot `label: text` and emit
//! `onClick`, this module produces a `.js` file shaped like this:
//!
//! ```javascript
//! // Auto-generated by mosaic-emit-webcomponent (pipeline path). Do not edit.
//!
//! class MosButton extends HTMLElement {
//!   static get observedAttributes() {
//!     return ["label"];
//!   }
//!
//!   constructor() {
//!     super();
//!     this.attachShadow({ mode: "open" });
//!   }
//!
//!   connectedCallback() { this._render(); }
//!   attributeChangedCallback(_n, _o, _v) { this._render(); }
//!
//!   _render() {
//!     const label = this.getAttribute("label") ?? "";
//!     this.shadowRoot.innerHTML = `<div>${label}</div>`;
//!   }
//!
//!   dispatch(event) {
//!     this.dispatchEvent(new CustomEvent("mosaic:" + event.type, {
//!       detail: event, bubbles: true, composed: true,
//!     }));
//!   }
//!
//!   onClick() { this.dispatch({ type: "click" }); }
//! }
//!
//! customElements.define("mos-button", MosButton);
//! ```
//!
//! Five things to notice in the output:
//!
//! 1. The element class is named `Mos<ComponentName>` — `Button` becomes
//!    `MosButton`. This avoids collisions with built-in DOM types such as
//!    `HTMLButtonElement` (the unprefixed `Button` is already a Java-era
//!    global on some hosts).
//! 2. **`observedAttributes`** returns one entry per declared slot in
//!    kebab-case — the same form the host writes in HTML
//!    (`<mos-button label="OK">`). `attributeChangedCallback` re-renders the
//!    shadow DOM whenever any observed attribute changes.
//! 3. **`_render()`** reads attributes back via `this.getAttribute(...)` and
//!    interpolates them into the shadow tree as `${variable}`. Template
//!    literals (`` ` ` ``) make slot interpolation a syntax-level feature
//!    rather than something we have to escape and re-quote.
//! 4. **`dispatch(event)`** emits a `CustomEvent` named `mosaic:<type>` so
//!    host code can listen with `el.addEventListener("mosaic:click", …)`.
//!    `bubbles: true, composed: true` ensure the event crosses the shadow
//!    DOM boundary into the light tree where the listener typically lives.
//! 5. **Per-emit signal-like methods** (`onClick`, `onNavigate`, …) make it
//!    easy for downstream JS to programmatically fire events the same way
//!    they would be triggered by a primitive's DOM handler. The method name
//!    keeps the source `onFoo` form — distinct from the lowered event
//!    `type` string (`foo`) — so authors can fire `el.onClick()` from JS
//!    and listen with `addEventListener("mosaic:click", …)`.
//!
//! ## Primitive lowering table (first cut)
//!
//! | moslayout tag | HTML template                                           |
//! |---------------|---------------------------------------------------------|
//! | `Box`         | `<div></div>`                                           |
//! | `Row`         | `<div style="display: flex; flex-direction: row;"></div>`    |
//! | `Column`      | `<div style="display: flex; flex-direction: column;"></div>` |
//! | `Text`        | `<span>…</span>` (slot ref interpolated as `${var}`)    |
//! | `Image`       | `<img>` (self-closing void element)                     |
//! | `Spacer`      | `<div style="flex: 1"></div>`                           |
//! | `Divider`     | `<hr>` (self-closing void element)                      |
//! | `Icon`        | `<span class="icon"></span>`                            |
//!
//! ## UI29 kernel primitives (U29-K-webcomp)
//!
//! In addition to the original Box/Row/Column/Text/Image/Spacer/Divider/Icon
//! set above, the WebComponent pipeline now lowers the full UI29 kernel:
//!
//! | Primitive       | Template-literal output                                          |
//! |---|---|
//! | `Stack`         | `<div style="position: relative;">…</div>`                       |
//! | `HostInput`     | `<input type="text" value="${value}" …>` (onchange/onkeydown wired via `this.getRootNode().host.dispatch(...)`) |
//! | `HostButton`    | `<button onclick="this.getRootNode().host.dispatch({type:'…'})">${label}</button>` |
//! | `HostScroll`    | `<div style="overflow: auto;">…</div>`                           |
//! | `HostTable`     | `<table>…</table>` — assembles from sub-tags                     |
//! | `HostTableHead` | `<thead>…</thead>` (children walked as `<tr>` rows of `<th>`)    |
//! | `HostTableBody` | `<tbody>…</tbody>` (children walked as `<tr>` rows of `<td>`)    |
//! | `HostTableFoot` | `<tfoot>…</tfoot>` (children walked as `<tr>` rows of `<td>`)    |
//! | `HostTableColGroup` | `<colgroup><col></colgroup>`                                 |
//! | `HostDialog`    | `<dialog id="mos-dlg-N">…</dialog>` plus a post-`innerHTML` block in `_render()` that calls `showModal()`/`show()`/`close()` and wires `close`/`cancel` events (U29-1) |
//! | `If`            | `${(cond) ? `then-html` : `else-html`}` (Else is consumed from the next sibling) |
//! | `Else`          | element of the surrounding `If` — never reached as a top-level node when paired; standalone `Else` produces an empty interpolation |
//! | `For`           | `${collection.map((item, idx) => `body-html`).join('')}`         |
//!
//! For `HostButton` the inline event handler uses the shadow-DOM-aware form
//! `this.getRootNode().host.dispatch(...)` so dispatch resolves to the
//! Custom Element host rather than the inner `<button>`. The legacy
//! single-arg `onclick="this.dispatch(...)"` wiring on `Box`/`Row`/`Column`
//! (the UI24 connects-style) is kept as-is to avoid breaking existing tests.
//!
//! ## What is NOT in this pass
//!
//! - The mosstyle `StyleDef` is accepted (so callers can build against the
//!   stable signature) but not yet inlined. Per-primitive built-in styles
//!   are emitted; author-declared part styles are deferred.
//! - Payload-carrying emits (`onNavigate(row, col)`) lower to a method
//!   that accepts the same params and forwards them into the dispatch
//!   payload. Mapping HTML event payloads back into typed params
//!   (e.g. extracting `event.target.value` for an `onChange`) is wired
//!   inline for `HostInput` only.

