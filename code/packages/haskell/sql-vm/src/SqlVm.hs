-- ── QueryResult ───────────────────────────────────────────────────────────
--
-- The public result of executing a program. For SELECT queries:
--   - columns: ordered list of output column names.
--   - rows: each row is a list of SqlValues in column order.
-- For DML (INSERT/UPDATE/DELETE):
--   - rowsAffected: number of rows changed.

-- | The result of executing a Program against a Backend.
data QueryResult = QueryResult
    { columns      :: [String]     -- ^ Names of output columns (SELECT order).
    , rows         :: [[SqlValue]] -- ^ Data rows; each row is a list of values.
    , rowsAffected :: Int          -- ^ For DML: number of rows changed.
    } deriving (Show, Eq)

-- ── Cursor state ──────────────────────────────────────────────────────────
--
-- A cursor is an open iterator over backend rows. We wrap the mutable
-- ListRowIterator in an IORef so we can advance it from inside the
-- StateT monad without threading it explicitly.
--
-- cursorPeeked: the row that JumpIfExhausted peeked at (already advanced
-- by iteratorNext). AdvanceCursor uses this instead of calling next again.

data CursorState = CursorState
    { csRef    :: IORef ListRowIterator
      -- ^ The underlying iterator (advanced by JumpIfExhausted peek).
    , csPeeked :: Maybe Row
      -- ^ Row already fetched by the last JumpIfExhausted peek.
    }

-- | Convert a Maybe String alias to a dictionary key.
-- Nothing → "" (the default / only cursor)
-- Just s  → s  (named alias for a specific JOIN leg)
cursorKey :: Maybe String -> String
cursorKey Nothing  = ""
cursorKey (Just s) = s

-- ── Aggregate accumulator ─────────────────────────────────────────────────
--
-- Each aggregate slot holds one AggAccum. Think of it as a running tally:
--
--   CountStar     → count increments on every row
--   Count         → count increments only for non-NULL values
--   CountDistinct → distinct non-NULL values tracked in a Set; final result
--                   is the size of the set
--   Sum        → acc accumulates the sum; SqlNull if no non-NULL seen yet
--   Avg        → acc = sum, count = number of non-NULL values seen
--   Min/Max    → acc tracks the extreme value seen so far

data AggAccum = AggAccum
    { aggCount       :: !Int               -- ^ Non-NULL input count (or all-row count for CountStar).
    , aggAcc         :: !SqlValue          -- ^ Running sum / min / max; SqlNull until first value.
    , aggDistinctSet :: Set.Set SqlValue   -- ^ Distinct values for COUNT(DISTINCT …); empty otherwise.
    } deriving (Show)

-- | The zero state for a fresh accumulator slot.
defaultAccum :: AggAccum
defaultAccum = AggAccum { aggCount = 0, aggAcc = SqlNull, aggDistinctSet = Set.empty }

-- | Feed one SqlValue into an accumulator for the given aggregate function.
updateAccum :: AggFn -> AggAccum -> SqlValue -> AggAccum
updateAccum fn acc val =
    case fn of
        CountStar ->
            -- COUNT(*): count every row, including NULLs.
            acc { aggCount = aggCount acc + 1 }

        Count ->
            -- COUNT(col): skip NULL inputs.
            if val == SqlNull then acc
            else acc { aggCount = aggCount acc + 1 }

        CountDistinct ->
            -- COUNT(DISTINCT col): track unique non-NULL values in a Set.
            -- The Set uses Ord on SqlValue to deduplicate.
            case val of
                SqlNull -> acc
                _       -> acc { aggDistinctSet = Set.insert val (aggDistinctSet acc) }

        Sum ->
            -- SUM: skip NULLs; running sum in acc.
            case val of
                SqlNull -> acc
                _       -> acc { aggAcc = addSqlValues (aggAcc acc) val }

        Avg ->
            -- AVG: sum non-NULLs and track count for the final division.
            case val of
                SqlNull -> acc
                _       -> acc
                    { aggAcc  = addSqlValues (aggAcc acc) val
                    , aggCount = aggCount acc + 1
                    }

        Min ->
            -- MIN: keep the smallest non-NULL value seen so far.
            case val of
                SqlNull -> acc
                _       -> acc { aggAcc = minSqlValue (aggAcc acc) val }

        Max ->
            -- MAX: keep the largest non-NULL value seen so far.
            case val of
                SqlNull -> acc
                _       -> acc { aggAcc = maxSqlValue (aggAcc acc) val }

-- | Compute the final aggregate result after scanning completes.
finalizeAccum :: AggFn -> AggAccum -> SqlValue
finalizeAccum fn acc =
    case fn of
        CountStar     -> SqlInteger (fromIntegral (aggCount acc))
        Count         -> SqlInteger (fromIntegral (aggCount acc))
        CountDistinct -> SqlInteger (fromIntegral (Set.size (aggDistinctSet acc)))
        Sum           -> aggAcc acc   -- SqlNull if no non-NULL input
        Min           -> aggAcc acc   -- SqlNull if no non-NULL input
        Max           -> aggAcc acc   -- SqlNull if no non-NULL input
        Avg       ->
            -- AVG returns NULL if no non-NULL inputs were seen.
            if aggCount acc == 0
                then SqlNull
                else divSqlValues (aggAcc acc) (aggCount acc)

-- | Numeric addition for aggregate accumulation. SqlNull acts as identity.
addSqlValues :: SqlValue -> SqlValue -> SqlValue
addSqlValues SqlNull v = v
addSqlValues v SqlNull = v
addSqlValues (SqlInteger a) (SqlInteger b) = SqlInteger (a + b)
addSqlValues (SqlInteger a) (SqlReal    b) = SqlReal (fromInteger a + b)
addSqlValues (SqlReal    a) (SqlInteger b) = SqlReal (a + fromInteger b)
addSqlValues (SqlReal    a) (SqlReal    b) = SqlReal (a + b)
addSqlValues _ _ = SqlNull

-- | Divide a running sum SqlValue by a count for AVG finalization.
divSqlValues :: SqlValue -> Int -> SqlValue
divSqlValues (SqlInteger s) n = SqlReal (fromInteger s / fromIntegral n)
divSqlValues (SqlReal    s) n = SqlReal (s / fromIntegral n)
divSqlValues _              _ = SqlNull

-- | Return the SQL-order minimum of two values (SqlNull acts as identity).
minSqlValue :: SqlValue -> SqlValue -> SqlValue
minSqlValue SqlNull v = v
minSqlValue v SqlNull = v
minSqlValue a b = if compareSqlValues a b == GT then b else a

-- | Return the SQL-order maximum of two values (SqlNull acts as identity).
maxSqlValue :: SqlValue -> SqlValue -> SqlValue
maxSqlValue SqlNull v = v
maxSqlValue v SqlNull = v
maxSqlValue a b = if compareSqlValues a b == LT then b else a

-- ── VM state ──────────────────────────────────────────────────────────────
--
-- All mutable execution state lives here. The StateT wrapper threads it
-- through every dispatch call without explicit passing.
--
-- vmPostSort / vmPostDistinct / vmPostLimit: set by the corresponding
-- post-processing instructions (SortResult, DistinctResult, LimitResult)
-- and applied at the end when building the QueryResult.

data VmState = VmState
    { vmInstructions :: [Instruction]
      -- ^ The flat instruction list (immutable once set).
    , vmLabelIndex   :: Map.Map String Int
      -- ^ Pre-built label→index map for O(1) jumps.
    , vmPc           :: !Int
      -- ^ Program counter: index of the next instruction to execute.
    , vmStack        :: [SqlValue]
      -- ^ Expression evaluation stack; head = top of stack.
    , vmCursors      :: Map.Map String CursorState
      -- ^ Open cursors keyed by alias (table name when no explicit alias).
    , vmCurrentRow   :: Map.Map String Row
      -- ^ Current row for each open cursor (keyed by alias).
    , vmRowBuffer    :: Map.Map String SqlValue
      -- ^ Accumulates column values during BeginRow..EmitRow.
    , vmColOrder     :: [String]
      -- ^ Column names in the order they were emitted by EmitColumn within
      -- the current BeginRow..EmitRow sequence.  Reset by BeginRow.
      -- This preserves SELECT-list order across the Map (which sorts keys).
    , vmOutputColumns :: [String]
      -- ^ The canonical column order for this query, captured on the first
      -- EmitRow.  Used by buildResult so that output rows respect the
      -- SELECT-list column order rather than alphabetical Map.keys order.
    , vmOutputRows   :: [Map.Map String SqlValue]
      -- ^ Accumulated output rows (in reverse order; reversed at end).
    , vmAggAccums    :: Map.Map Int AggAccum
      -- ^ Aggregate accumulators for non-grouped queries (no GROUP BY).
    , vmGroupAccums  :: Map.Map [SqlValue] (Map.Map Int AggAccum)
      -- ^ Per-group aggregate accumulators for GROUP BY queries.
      -- Key = GROUP BY column values; value = slot-indexed accumulators.
      -- Empty for non-GROUP BY queries.
    , vmCurrentGroup :: [SqlValue]
      -- ^ Current GROUP BY key being accumulated (set by SaveGroupKey) or
      -- the group being emitted (set by AdvanceGroup).
      -- Empty list = not in GROUP BY mode (non-grouped query).
    , vmGroupOrder   :: [[SqlValue]]
      -- ^ Group keys in insertion order (appended by SaveGroupKey).
      -- After the scan this list drives the per-group emit loop.
    , vmGroupIndex   :: !Int
      -- ^ Current position in vmGroupOrder during the emit loop.
      -- Starts at -1; AdvanceGroup increments it before each use.
    , vmRowsAffected :: !Int
      -- ^ DML rows changed.
    , vmBackend      :: IORef InMemoryBackend
      -- ^ The backend (IORef because backend functions return new state).
    , vmPostSort     :: Maybe [SortKey]
      -- ^ Set by SortResult instruction; applied in buildResult.
    , vmPostDistinct :: Bool
      -- ^ Set by DistinctResult instruction; applied in buildResult.
    , vmPostLimit    :: Maybe (Maybe Int64, Maybe Int64)
      -- ^ Set by LimitResult (count, offset); applied in buildResult.
    }

-- | The VM monad: state over IO so we can call IORef-based backend ops.
type VM a = StateT VmState IO a

-- ── Label pre-scan ────────────────────────────────────────────────────────
--
-- Before running, we walk the instruction list once and build a Map from
-- label name to instruction index. This gives O(1) Jump resolution.
--
-- Example: [LoadConst x, Label "foo", Jump "foo"]
--   → buildLabelIndex → Map.fromList [("foo", 1)]

-- | Build a label → instruction-index map from the full instruction list.
buildLabelIndex :: [Instruction] -> Map.Map String Int
buildLabelIndex instrs =
    Map.fromList [(lbl, idx) | (idx, Label lbl) <- zip [0..] instrs]

-- ── Stack helpers ─────────────────────────────────────────────────────────

-- | Push a SqlValue onto the top of the expression stack.
push :: SqlValue -> VM ()
push v = modify (\st -> st { vmStack = v : vmStack st })

-- | Pop a SqlValue from the top of the stack.
-- Returns SqlNull if the stack is empty (defensive; should not happen
-- for well-formed programs produced by sql-codegen).
pop :: VM SqlValue
pop = do
    st <- get
    case vmStack st of
        []     -> return SqlNull
        (x:xs) -> put st { vmStack = xs } >> return x

-- | Pop n values; return them in push order (oldest first).
-- Example: stack = [c, b, a] (c is top), popN 3 → [a, b, c].
-- We call replicateM n pop which yields [c, b, a], then reverse → [a, b, c].
popN :: Int -> VM [SqlValue]
popN 0 = return []
popN n = reverse <$> replicateM n pop

-- ── Label / jump helpers ──────────────────────────────────────────────────

-- | Resolve a label name to its instruction index.
-- Errors if the label is not found (indicates a codegen bug).
resolveLabel :: String -> VM Int
resolveLabel lbl = do
    idx <- gets (Map.lookup lbl . vmLabelIndex)
    case idx of
        Just i  -> return i
        Nothing -> error ("SqlVm: unknown label: " ++ show lbl)

-- | Set the program counter to the instruction at the given label.
jumpTo :: String -> VM ()
jumpTo lbl = do
    i <- resolveLabel lbl
    modify (\st -> st { vmPc = i })

-- ── Column lookup helpers ─────────────────────────────────────────────────

-- | Case-insensitive column lookup in a Row map.
lookupColValue :: String -> Row -> Maybe SqlValue
lookupColValue col row =
    -- Try direct lookup first (fast path).
    case Map.lookup col row of
        Just v  -> Just v
        Nothing ->
            -- Fall back to case-insensitive linear scan.
            let colLower = map toLower col
                pairs = filter (\(k, _) -> map toLower k == colLower) (Map.toList row)
            in case pairs of
                ((_,v):_) -> Just v
                []         -> Nothing

-- | Load a column value from the current row(s).
-- tblOpt = Just alias: look only in that cursor's row.
-- tblOpt = Nothing:    search all open cursor rows.
loadColumnValue :: Maybe String -> String -> VM SqlValue
loadColumnValue tblOpt col = do
    curRows <- gets vmCurrentRow
    case tblOpt of
        Just alias ->
            let row = Map.findWithDefault Map.empty alias curRows
            in return (fromMaybe SqlNull (lookupColValue col row))
        Nothing ->
            let allRows = Map.elems curRows
                values  = mapMaybe (lookupColValue col) allRows
            in return (case values of { (v:_) -> v; [] -> SqlNull })

-- ── LIKE pattern matching ─────────────────────────────────────────────────
--
-- SQL LIKE uses two wildcards:
--   %  →  zero or more characters of any kind
--   _  →  exactly one character
--
-- We use a direct two-pointer recursive approach (NO Regex), which avoids
-- the ReDoS vulnerability that arises from compiling "%" as ".*" in a Regex.
--
-- The matcher is case-insensitive (LIKE is case-insensitive for ASCII text).
--
-- Algorithm for the % wildcard:
--   - We first collapse consecutive % signs (they are equivalent to a single %).
--   - Then we try matching the suffix after % at the current string position,
--     OR we consume one character from the string and try again with ("%":pat).
--   - This gives correct % semantics in O(n*m) without exponential blowup.
--
-- Example patterns:
--   likeMatch "hello" "%llo" = True   (% matches "he")
--   likeMatch "hello" "h_llo" = True  (_ matches "e")
--   likeMatch "hello" "%xyz%" = False (no occurrence of "xyz")

-- | Match a string against a SQL LIKE pattern (case-insensitive, no Regex).
likeMatch :: String -> String -> Bool
likeMatch str pat = go str pat
  where
    -- go s [] : match succeeds iff string is also exhausted.
    go [] []       = True
    go _  []       = False

    -- go [] (p:ps): string exhausted but pattern not.
    -- Only % (matching zero chars) can still succeed.
    go [] ('%':ps) = go [] (dropWhile ('%'==) ps)
    go [] (_:_)    = False

    -- go (c:cs) ('%':ps): the % wildcard.
    -- Collapse consecutive %, then try: match zero chars (skip %) OR
    -- match one char (consume c) and stay on %.
    go (c:cs) ('%':ps) =
        let ps' = dropWhile ('%'==) ps
        in go (c:cs) ps' || go cs ('%':ps')

    -- go (_:cs) ('_':ps): _ matches exactly one character.
    go (_:cs) ('_':ps) = go cs ps

    -- go (c:cs) (p:ps): literal character match (case-insensitive).
    go (c:cs) (p:ps) = toLower c == toLower p && go cs ps

-- ── Three-valued logic ────────────────────────────────────────────────────

-- | A SqlValue is truthy iff it is non-null and non-zero/non-false.
-- This governs JumpIfTrue / JumpIfFalse behaviour.
isTruthy :: SqlValue -> Bool
isTruthy SqlNull         = False
isTruthy (SqlBool b)    = b
isTruthy (SqlInteger 0) = False
isTruthy (SqlInteger _) = True
isTruthy (SqlReal    r) = r /= 0.0
isTruthy (SqlText    _) = True
isTruthy (SqlBlob    _) = True

-- ── Binary operator evaluation ────────────────────────────────────────────
--
-- Three-valued logic applies throughout:
--   - If either operand is NULL, the result is NULL — EXCEPT:
--     - AND: FALSE AND NULL = FALSE
--     - OR:  TRUE  OR  NULL = TRUE
--   - Division by zero → NULL (safe, matches SQLite behaviour).
--   - Concat (||) coerces non-text values to strings.

-- | Apply a binary operator to two SqlValues. NULL propagates per SQL 3VL.
evalBinary :: BinaryOp -> SqlValue -> SqlValue -> SqlValue

-- AND short-circuits on FALSE even with NULL.
evalBinary And lv rv =
    case (lv, rv) of
        (SqlBool False, _)           -> SqlBool False
        (_, SqlBool False)           -> SqlBool False
        (SqlNull, _)                 -> SqlNull
        (_, SqlNull)                 -> SqlNull
        (SqlBool True, SqlBool True) -> SqlBool True
        _                            -> SqlNull

-- OR short-circuits on TRUE even with NULL.
evalBinary Or lv rv =
    case (lv, rv) of
        (SqlBool True, _)            -> SqlBool True
        (_, SqlBool True)            -> SqlBool True
        (SqlNull, _)                 -> SqlNull
        (_, SqlNull)                 -> SqlNull
        (SqlBool False, SqlBool False) -> SqlBool False
        _                              -> SqlNull

-- NULL propagation for all other operators.
evalBinary _ SqlNull _ = SqlNull
evalBinary _ _ SqlNull = SqlNull

-- Comparison operators use compareSqlValues for consistent type coercion.
evalBinary Eq  lv rv = SqlBool (compareSqlValues lv rv == EQ)
evalBinary Neq lv rv = SqlBool (compareSqlValues lv rv /= EQ)
evalBinary Lt  lv rv = SqlBool (compareSqlValues lv rv == LT)
evalBinary Lte lv rv = SqlBool (compareSqlValues lv rv `elem` [LT, EQ])
evalBinary Gt  lv rv = SqlBool (compareSqlValues lv rv == GT)
evalBinary Gte lv rv = SqlBool (compareSqlValues lv rv `elem` [GT, EQ])

-- Arithmetic operators.
evalBinary Add (SqlInteger a) (SqlInteger b) = SqlInteger (a + b)
evalBinary Add (SqlInteger a) (SqlReal    b) = SqlReal (fromInteger a + b)
evalBinary Add (SqlReal    a) (SqlInteger b) = SqlReal (a + fromInteger b)
evalBinary Add (SqlReal    a) (SqlReal    b) = SqlReal (a + b)

evalBinary Sub (SqlInteger a) (SqlInteger b) = SqlInteger (a - b)
evalBinary Sub (SqlInteger a) (SqlReal    b) = SqlReal (fromInteger a - b)
evalBinary Sub (SqlReal    a) (SqlInteger b) = SqlReal (a - fromInteger b)
evalBinary Sub (SqlReal    a) (SqlReal    b) = SqlReal (a - b)

evalBinary Mul (SqlInteger a) (SqlInteger b) = SqlInteger (a * b)
evalBinary Mul (SqlInteger a) (SqlReal    b) = SqlReal (fromInteger a * b)
evalBinary Mul (SqlReal    a) (SqlInteger b) = SqlReal (a * fromInteger b)
evalBinary Mul (SqlReal    a) (SqlReal    b) = SqlReal (a * b)

-- Division by zero → NULL (safe behaviour matching SQLite).
evalBinary Div _ (SqlInteger 0) = SqlNull
evalBinary Div _ (SqlReal    0) = SqlNull
evalBinary Div (SqlInteger a) (SqlInteger b) = SqlInteger (a `div` b)
evalBinary Div (SqlInteger a) (SqlReal    b) = SqlReal (fromInteger a / b)
evalBinary Div (SqlReal    a) (SqlInteger b) = SqlReal (a / fromInteger b)
evalBinary Div (SqlReal    a) (SqlReal    b) = SqlReal (a / b)

evalBinary Mod _ (SqlInteger 0) = SqlNull
evalBinary Mod _ (SqlReal    0) = SqlNull
evalBinary Mod (SqlInteger a) (SqlInteger b) = SqlInteger (a `mod` b)
evalBinary Mod (SqlReal    a) (SqlReal    b) =
    let q = fromIntegral (floor (a / b) :: Integer) :: Double
    in SqlReal (a - q * b)
evalBinary Mod (SqlInteger a) (SqlReal    b) =
    let r = fromInteger a :: Double
        q = fromIntegral (floor (r / b) :: Integer) :: Double
    in SqlReal (r - q * b)
evalBinary Mod (SqlReal    a) (SqlInteger b) =
    let r = fromInteger b :: Double
        q = fromIntegral (floor (a / r) :: Integer) :: Double
    in SqlReal (a - q * r)

-- String concatenation (||): coerce non-text to string.
evalBinary Concat (SqlText a) (SqlText b) = SqlText (a ++ b)
evalBinary Concat (SqlText a) v           = SqlText (a ++ sqlToStr v)
evalBinary Concat v           (SqlText b) = SqlText (sqlToStr v ++ b)

evalBinary _ _ _ = SqlNull   -- Type mismatch → NULL.

-- | Coerce a SqlValue to its string representation (for Concat).
sqlToStr :: SqlValue -> String
sqlToStr SqlNull         = ""
sqlToStr (SqlBool True)  = "1"
sqlToStr (SqlBool False) = "0"
sqlToStr (SqlInteger i)  = show i
sqlToStr (SqlReal    r)  = show r
sqlToStr (SqlText    s)  = s
sqlToStr (SqlBlob    _)  = ""

-- ── Unary operator evaluation ─────────────────────────────────────────────

-- | Apply a unary operator. NULL propagates per SQL 3VL.
evalUnary :: UnaryOp -> SqlValue -> SqlValue
evalUnary Neg SqlNull        = SqlNull
evalUnary Neg (SqlInteger i) = SqlInteger (negate i)
evalUnary Neg (SqlReal    r) = SqlReal (negate r)
evalUnary Neg _              = SqlNull

evalUnary Not SqlNull      = SqlNull
evalUnary Not (SqlBool b)  = SqlBool (not b)
evalUnary Not _            = SqlNull

-- ── Built-in scalar function evaluation ──────────────────────────────────
--
-- This mirrors the mini-sqlite `evalScalarFunc` but lives in the VM so that
-- function calls inside FROM-clause queries (e.g. LOWER(col)) work correctly.
-- The argument list is in left-to-right order (first arg first).

evalBuiltin :: String -> [SqlValue] -> SqlValue
evalBuiltin "length" [SqlNull]   = SqlNull
evalBuiltin "length" [SqlText s] = SqlInteger (fromIntegral (length s))
evalBuiltin "length" _           = SqlNull

evalBuiltin "upper" [SqlNull]   = SqlNull
evalBuiltin "upper" [SqlText s] = SqlText (map toUpper s)
evalBuiltin "upper" _           = SqlNull

evalBuiltin "lower" [SqlNull]   = SqlNull
evalBuiltin "lower" [SqlText s] = SqlText (map toLower s)
evalBuiltin "lower" _           = SqlNull

evalBuiltin "substr" [SqlNull, _] = SqlNull
evalBuiltin "substr" [_, SqlNull] = SqlNull
evalBuiltin "substr" [SqlText s, SqlInteger pos] =
    let start = fromIntegral pos - 1
    in SqlText (drop (max 0 start) s)
evalBuiltin "substr" [SqlText s, SqlInteger pos, SqlInteger len] =
    let start = fromIntegral pos - 1
    in SqlText (take (fromIntegral len) (drop (max 0 start) s))
evalBuiltin "substr" _ = SqlNull

evalBuiltin "trim"  [SqlNull]   = SqlNull
evalBuiltin "trim"  [SqlText s] = SqlText (dropWhileEnd isSpace (dropWhile isSpace s))
evalBuiltin "trim"  _           = SqlNull

evalBuiltin "ltrim" [SqlNull]   = SqlNull
evalBuiltin "ltrim" [SqlText s] = SqlText (dropWhile isSpace s)
evalBuiltin "ltrim" _           = SqlNull

evalBuiltin "rtrim" [SqlNull]   = SqlNull
evalBuiltin "rtrim" [SqlText s] = SqlText (dropWhileEnd isSpace s)
evalBuiltin "rtrim" _           = SqlNull

evalBuiltin "replace" [SqlNull, _, _] = SqlNull
evalBuiltin "replace" [SqlText s, SqlText from, SqlText to] =
    SqlText (replaceAllVm from to s)
evalBuiltin "replace" _ = SqlNull

evalBuiltin "abs" [SqlNull]        = SqlNull
evalBuiltin "abs" [SqlInteger n]   = SqlInteger (abs n)
evalBuiltin "abs" [SqlReal    d]   = SqlReal    (abs d)
evalBuiltin "abs" _                = SqlNull

evalBuiltin "concat" [SqlNull, _]  = SqlNull
evalBuiltin "concat" [_, SqlNull]  = SqlNull
evalBuiltin "concat" [a, b]        = SqlText (sqlToStr a ++ sqlToStr b)
evalBuiltin "concat" _             = SqlNull

evalBuiltin "coalesce" args =
    case filter (/= SqlNull) args of
        (x:_) -> x
        []    -> SqlNull

evalBuiltin "ifnull" [SqlNull, b] = b
evalBuiltin "ifnull" [a, _]       = a
evalBuiltin "ifnull" _            = SqlNull

evalBuiltin "round" [SqlNull]        = SqlNull
evalBuiltin "round" [SqlInteger n]   = SqlReal (fromIntegral n)
evalBuiltin "round" [SqlReal    d]   = SqlReal (roundHalfAwayVm d 0)
evalBuiltin "round" [SqlInteger n, SqlInteger p] =
    SqlReal (roundHalfAwayVm (fromIntegral n) (fromIntegral p))
evalBuiltin "round" [SqlReal    d, SqlInteger p] =
    SqlReal (roundHalfAwayVm d (fromIntegral p))
evalBuiltin "round" _ = SqlNull

evalBuiltin _ _ = SqlNull

-- | Round a Double to `digits` decimal places using half-away-from-zero
-- rounding (SQLite ROUND semantics, not Haskell banker rounding).
--
-- Security notes:
--   1. 'Integer' (arbitrary-precision) is used for intermediate values to
--      prevent silent overflow that would corrupt results.  The original
--      'Int' path overflowed silently for digits >= 19 on 64-bit systems.
--   2. 'digits' is clamped to [-15, 15].  Negative values implement SQLite's
--      "round to tens/hundreds/…" semantics and avoid a "Negative exponent"
--      runtime exception from '(^)'.  The upper clamp of 15 reflects Double
--      precision limits.
roundHalfAwayVm :: Double -> Int -> Double
roundHalfAwayVm x digits
    | digits < 0 =
        let factor = (10 :: Integer) ^ (min 15 (negate digits))
            scaled = x / fromIntegral factor
            rounded :: Integer
            rounded = if x >= 0
                      then floor   (scaled + 0.5)
                      else ceiling (scaled - 0.5)
        in fromIntegral rounded * fromIntegral factor
    | digits == 0 =
        let rounded :: Integer
            rounded = if x >= 0 then floor (x + 0.5) else ceiling (x - 0.5)
        in fromIntegral rounded
    | otherwise =
        let d      = min digits 15
            factor = (10 :: Integer) ^ d
            scaled = x * fromIntegral factor
            truncated :: Integer
            truncated = if x >= 0
                        then floor   (scaled + 0.5)
                        else ceiling (scaled - 0.5)
        in fromIntegral truncated / fromIntegral factor

-- | Replace all non-overlapping occurrences of 'from' with 'to' in 's'.
replaceAllVm :: String -> String -> String -> String
replaceAllVm _ _ [] = []
replaceAllVm from to s@(c:cs)
    | from `isPrefixOf` s = to ++ replaceAllVm from to (drop (length from) s)
    | otherwise           = c : replaceAllVm from to cs

-- ── BETWEEN evaluation ────────────────────────────────────────────────────
--
-- `value BETWEEN lo AND hi` means `lo <= value AND value <= hi`.
-- NULL propagates: any NULL input → NULL result.

evalBetween :: SqlValue -> SqlValue -> SqlValue -> SqlValue
evalBetween SqlNull _ _ = SqlNull
evalBetween _ SqlNull _ = SqlNull
evalBetween _ _ SqlNull = SqlNull
evalBetween val lo hi   = evalBinary And (evalBinary Gte val lo) (evalBinary Lte val hi)

-- ── LiteralVal → SqlValue ─────────────────────────────────────────────────
--
-- The codegen uses SqlPlanner.LiteralVal; the backend uses SqlBackend.SqlValue.

literalToSqlValue :: LiteralVal -> SqlValue
literalToSqlValue (LitInt  i)  = SqlInteger i
literalToSqlValue (LitReal r)  = SqlReal r
literalToSqlValue (LitText s)  = SqlText s
literalToSqlValue (LitBool b)  = SqlBool b
literalToSqlValue (LitBlob bs) = SqlBlob (map fromIntegral bs)

-- ── ColumnDef conversion ──────────────────────────────────────────────────
--
-- SqlCodegen's CreateTableInstr carries SqlPlanner.ColumnDef values (the
-- planner's compile-time column description). The SqlBackend.createTable
-- function accepts SqlBackend.ColumnDef values (the runtime schema type).
-- We convert between the two here; SQL DEFAULT expressions are dropped
-- (evaluated at insert time by the backend).

plannerColToBackendCol :: P.ColumnDef -> SB.ColumnDef
plannerColToBackendCol pc =
    (SB.defaultColumnDef (P.colName pc) (P.colTypeName pc))
        { SB.columnNotNull     = P.colNotNull pc
        , SB.columnPrimaryKey  = P.colPrimaryKey pc
        , SB.columnUnique      = P.colUnique pc
        }

-- ── Cursor operations ─────────────────────────────────────────────────────

-- | Open a read-only scan cursor for the named table.
doOpenScan :: String -> Maybe String -> VM ()
doOpenScan tbl alias = do
    bRef <- gets vmBackend
    backend <- liftIO (readIORef bRef)
    case scan backend tbl of
        Left err -> error ("SqlVm: scan failed: " ++ errorMessage err)
        Right it -> do
            ref <- liftIO (newIORef it)
            let key = cursorKey alias
            modify (\st -> st
                { vmCursors    = Map.insert key (CursorState ref Nothing) (vmCursors st)
                , vmCurrentRow = Map.delete key (vmCurrentRow st)
                })

-- | Test whether the cursor is exhausted WITHOUT consuming the next row.
-- This is the "peek" step used by JumpIfExhausted.
-- If there is a next row, it is stored as vmCurrentRow[alias] so that
-- AdvanceCursor becomes a no-op (row is already available).
isCursorExhausted :: Maybe String -> VM Bool
isCursorExhausted alias = do
    let key = cursorKey alias
    cursors <- gets vmCursors
    case Map.lookup key cursors of
        Nothing -> return True
        Just cs -> do
            -- If we have a peeked row from a previous check, use it.
            case csPeeked cs of
                Just row -> do
                    -- Row is already stored; cursor is not exhausted.
                    modify (\st -> st { vmCurrentRow = Map.insert key row (vmCurrentRow st) })
                    return False
                Nothing -> do
                    -- No peeked row; advance the iterator once to see.
                    it <- liftIO (readIORef (csRef cs))
                    let (mRow, it') = iteratorNext it
                    liftIO (writeIORef (csRef cs) it')
                    case mRow of
                        Nothing ->
                            return True
                        Just row -> do
                            -- Store the peeked row so AdvanceCursor can use it.
                            modify (\st -> st
                                { vmCursors    = Map.insert key cs { csPeeked = Just row } (vmCursors st)
                                , vmCurrentRow = Map.insert key row (vmCurrentRow st)
                                })
                            return False

-- | Advance a cursor to its next row.
-- Since JumpIfExhausted already peeked and stored the next row in vmCurrentRow,
-- AdvanceCursor only needs to clear the peeked row so the NEXT JumpIfExhausted
-- call will actually call iteratorNext again.
doAdvanceCursor :: Maybe String -> VM ()
doAdvanceCursor alias = do
    let key = cursorKey alias
    cursors <- gets vmCursors
    case Map.lookup key cursors of
        Nothing -> return ()
        Just cs ->
            -- Clear the peek so the next JumpIfExhausted advances again.
            modify (\st -> st
                { vmCursors = Map.insert key cs { csPeeked = Nothing } (vmCursors st)
                })

-- | Close a cursor and clear its current row from vmCurrentRow.
doCloseScan :: Maybe String -> VM ()
doCloseScan alias = do
    let key = cursorKey alias
    modify (\st -> st
        { vmCursors    = Map.delete key (vmCursors st)
        , vmCurrentRow = Map.delete key (vmCurrentRow st)
        })

-- ── Post-processing helpers ───────────────────────────────────────────────

-- | Sort rows by the given sort keys using compareSqlValues.
-- The SortKey carries a SqlExpr (typically a Column reference); we evaluate
-- that expression against each row map to get the sort value.
doSort :: [SortKey] -> [Map.Map String SqlValue] -> [Map.Map String SqlValue]
doSort keys rowMaps = sortBy compareRows rowMaps
  where
    compareRows ra rb = foldr combineOrd EQ (map (compareKey ra rb) keys)

    compareKey ra rb sk =
        let dirAsc = sortDir sk == SortAsc
            va     = evalExprOnRow (sortExpr sk) ra
            vb     = evalExprOnRow (sortExpr sk) rb
            ord    = compareSqlValues va vb
        in if dirAsc then ord else flipOrd ord

    flipOrd LT = GT
    flipOrd GT = LT
    flipOrd EQ = EQ

    combineOrd EQ next = next
    combineOrd o  _    = o

-- | Evaluate a SqlExpr against a row map (for sort key extraction).
-- Only handles Column and Literal; anything else returns SqlNull.
--
-- For Column references, we first look up the column by its plain name.
-- If not found (the column was not in the SELECT list), we fall back to the
-- hidden sentinel "__sort_<col>" name emitted by compileSelect when the
-- sort key is not part of the projection.
evalExprOnRow :: SqlExpr -> Map.Map String SqlValue -> SqlValue
evalExprOnRow expr row = case expr of
    P.Column _ col ->
        case lookupColValue col row of
            Just v  -> v
            Nothing -> fromMaybe SqlNull (lookupColValue ("__sort_" ++ col) row)
    P.Literal (Just lit) ->
        literalToSqlValue lit
    P.Literal Nothing ->
        SqlNull
    _ ->
        SqlNull

-- | Apply LIMIT / OFFSET to a list of rows.
doLimit :: Maybe Int64 -> Maybe Int64 -> [a] -> [a]
doLimit cntOpt offOpt xs =
    let start  = maybe 0 fromIntegral offOpt
        sliced = drop start xs
    in case cntOpt of
        Nothing  -> sliced
        Just cnt -> take (fromIntegral cnt) sliced

-- | Remove duplicate rows (by value equality list).
doDistinct :: [[SqlValue]] -> [[SqlValue]]
doDistinct = nub

-- ── Main dispatch loop ────────────────────────────────────────────────────
--
-- runLoop fetches the instruction at vmPc, increments vmPc, and dispatches.
-- Halt (or running past the end) terminates the loop.

-- | Run the VM dispatch loop until Halt or end of instruction list.
runLoop :: VM ()
runLoop = do
    st <- get
    let instrs = vmInstructions st
        pc     = vmPc st
    when (pc < length instrs) $ do
        let instr = instrs !! pc
        modify (\s -> s { vmPc = vmPc s + 1 })
        dispatch instr
        case instr of
            Halt -> return ()   -- Halt terminates the loop immediately.
            _    -> runLoop

-- | Dispatch a single instruction to its handler.
dispatch :: Instruction -> VM ()
dispatch instr = case instr of

    -- ── Stack / constants ─────────────────────────────────────────────────
    -- LoadConst: push a compile-time literal (integer, real, text, bool).
    -- LoadNull: push SQL NULL — the "unknown" value in three-valued logic.
    LoadConst lit ->
        push (literalToSqlValue lit)

    LoadNull ->
        push SqlNull

    LoadColumn tOpt col ->
        loadColumnValue tOpt col >>= push

    LoadParam _ ->
        -- Level 1: runtime parameters not supported; push NULL as placeholder.
        push SqlNull

    -- LoadGroupKey i: push the i-th value from the current group key.
    -- Used in the per-group emit loop to project the GROUP BY column values
    -- into the output row.
    LoadGroupKey i -> do
        grp <- gets vmCurrentGroup
        push (if i < length grp then grp !! i else SqlNull)

    Pop -> do
        _ <- pop
        return ()

    -- ── Arithmetic and comparison ──────────────────────────────────────────
    -- Binary operators pop TWO values (right on top, left below) and push ONE.
    -- This ordering matches how the codegen pushes them:
    --   compileExpr left → compileExpr right → BinaryOpInstr op
    BinaryOpInstr op -> do
        r <- pop   -- right operand (was pushed last, so on top)
        l <- pop   -- left operand
        push (evalBinary op l r)

    -- ── Unary operations ──────────────────────────────────────────────────
    UnaryOpInstr op -> do
        v <- pop
        push (evalUnary op v)

    -- ── Predicate / test instructions ─────────────────────────────────────
    -- IS NULL / IS NOT NULL: unlike `= NULL` (which is NULL), these always
    -- return a boolean.
    IsNullInstr -> do
        v <- pop
        push (SqlBool (v == SqlNull))

    IsNotNullInstr -> do
        v <- pop
        push (SqlBool (v /= SqlNull))

    BetweenInstr _ -> do
        -- Stack (top → bottom): hi, lo, value.
        hi  <- pop
        lo  <- pop
        val <- pop
        push (evalBetween val lo hi)

    LikeInstr -> do
        -- Stack (top → bottom): pattern, value.
        -- Codegen emits: compileExpr value, LoadConst pattern, LikeInstr.
        pat <- pop
        val <- pop
        case (val, pat) of
            (SqlNull, _) -> push SqlNull
            (_, SqlNull) -> push SqlNull
            (SqlText v, SqlText p) -> push (SqlBool (likeMatch v p))
            _ -> push SqlNull

    InList n -> do
        -- Stack (top → bottom): item_n, item_{n-1}, …, item_1, needle.
        -- popN n returns them in push order (oldest first = item_1 first).
        items  <- popN n
        needle <- pop
        case needle of
            SqlNull -> push SqlNull
            _ ->
                let found   = any (\item -> item /= SqlNull && compareSqlValues item needle == EQ) items
                    hasNull = SqlNull `elem` items
                in if found
                    then push (SqlBool True)
                    else if hasNull
                        then push SqlNull
                        else push (SqlBool False)

    -- ── Scan / cursor control ─────────────────────────────────────────────
    OpenScan tbl alias ->
        doOpenScan tbl alias

    AdvanceCursor alias ->
        -- JumpIfExhausted has already peeked the next row and stored it in
        -- vmCurrentRow. AdvanceCursor clears the peek so the NEXT
        -- JumpIfExhausted will advance the iterator again.
        doAdvanceCursor alias

    JumpIfExhausted alias lbl -> do
        exhausted <- isCursorExhausted alias
        when exhausted (jumpTo lbl)

    CloseScan alias ->
        doCloseScan alias

    -- ── Row construction ──────────────────────────────────────────────────
    -- Output rows are assembled column by column between BeginRow and EmitRow.
    --
    -- vmColOrder tracks the order in which EmitColumn was called.  This
    -- preserves SELECT-list column order because Data.Map.Strict sorts keys
    -- alphabetically, which would otherwise reorder columns (e.g. SELECT
    -- id, name, age → Map.keys gives ["age","id","name"]).
    BeginRow ->
        modify (\st -> st { vmRowBuffer = Map.empty, vmColOrder = [] })

    EmitColumn name -> do
        v <- pop
        modify (\st -> st
            { vmRowBuffer = Map.insert name v (vmRowBuffer st)
            , vmColOrder  = vmColOrder st ++ [name]
            })

    EmitRow -> do
        rowBuf   <- gets vmRowBuffer
        colOrder <- gets vmColOrder
        traceM ("[DBG] EmitRow colOrder=" ++ show colOrder)
        -- SELECT * support: if no EmitColumn was called (colOrder is empty)
        -- and the top of stack is SqlText "*" (emitted by compileOutputCols for
        -- OutputStar), expand the current cursor row into the output buffer.
        -- This is how `SELECT * FROM t` works without knowing column names at
        -- compile time.
        (finalBuf, finalOrder) <-
            if null colOrder
            then do
                topMaybe <- gets (\s -> case vmStack s of { (v:_) -> Just v; [] -> Nothing })
                case topMaybe of
                    Just (SqlText "*") -> do
                        -- Pop the wildcard marker from the stack.
                        _ <- pop
                        -- Collect all columns from all open cursors in alias order.
                        curRows <- gets vmCurrentRow
                        let allPairs = concatMap Map.toAscList (Map.elems curRows)
                        let buf  = Map.fromList allPairs
                        let ord  = map fst allPairs
                        return (buf, ord)
                    _ -> return (rowBuf, colOrder)
            else return (rowBuf, colOrder)
        modify (\st -> st
            { vmOutputRows    = finalBuf : vmOutputRows st
              -- Capture column order on first EmitRow; all rows share the same
              -- schema so we only need to do this once.
            , vmOutputColumns = if null (vmOutputColumns st)
                                    then finalOrder
                                    else vmOutputColumns st
            })

    -- ── Aggregation ───────────────────────────────────────────────────────
    -- InitAgg n: initialise n accumulator slots to their zero state.
    -- For non-GROUP BY queries this populates vmAggAccums.
    -- For GROUP BY queries the per-group accumulators in vmGroupAccums are
    -- created lazily by SaveGroupKey / UpdateAgg, so this is a no-op.
    InitAgg n ->
        forM_ [0..n-1] $ \idx ->
            modify (\st -> st
                { vmAggAccums = Map.insertWith (\_ old -> old) idx defaultAccum (vmAggAccums st)
                })

    -- UpdateAgg: feed a value into an aggregate accumulator.
    --
    -- COUNT(*) (CountStar) does not consume any expression value — it simply
    -- increments a counter for every row.  All other aggregate functions pop
    -- the top-of-stack value and feed it into the running accumulator.
    --
    -- In GROUP BY mode (vmCurrentGroup non-empty) update the per-group slot;
    -- otherwise update the global accumulator.
    UpdateAgg idx fn -> do
        -- Pop a value only when the function actually needs it.
        -- CountStar ignores the value, so we avoid a stack-underflow crash.
        v <- if fn == CountStar then return SqlNull else pop
        grp <- gets vmCurrentGroup
        traceM ("[DBG] UpdateAgg idx=" ++ show idx ++ " fn=" ++ show fn ++ " grp=" ++ show grp)
        if null grp
            -- Non-GROUP BY: update the global accumulator.
            then modify (\st -> st
                { vmAggAccums = Map.alter
                    (\mAcc -> Just (updateAccum fn (fromMaybe defaultAccum mAcc) v))
                    idx
                    (vmAggAccums st)
                })
            -- GROUP BY: update the per-group accumulator.
            else modify (\st ->
                let grpMap  = Map.findWithDefault Map.empty grp (vmGroupAccums st)
                    grpMap' = Map.alter
                                (\mAcc -> Just (updateAccum fn (fromMaybe defaultAccum mAcc) v))
                                idx grpMap
                in st { vmGroupAccums = Map.insert grp grpMap' (vmGroupAccums st) })

    -- FinalizeAgg: compute and push the final aggregate value.
    -- In GROUP BY mode read from the current group's accumulator map;
    -- otherwise read from the global accumulator map.
    FinalizeAgg idx fn -> do
        grp <- gets vmCurrentGroup
        acc <- if null grp
                then do
                    accums <- gets vmAggAccums
                    return (Map.findWithDefault defaultAccum idx accums)
                else do
                    grpAccums <- gets vmGroupAccums
                    let grpMap = Map.findWithDefault Map.empty grp grpAccums
                    return (Map.findWithDefault defaultAccum idx grpMap)
        let result = finalizeAccum fn acc
        traceM ("[DBG] FinalizeAgg idx=" ++ show idx ++ " fn=" ++ show fn
                ++ " grp=" ++ show grp ++ " aggCount=" ++ show (aggCount acc)
                ++ " result=" ++ show result)
        push result

    -- SaveGroupKey: pop the GROUP BY expression values from the stack,
    -- record the current group key, and add it to the ordered group list.
    -- The codegen emits the GROUP BY expressions onto the stack (leftmost
    -- first, so the top-of-stack holds the LAST key column).
    SaveGroupKey names -> do
        -- Pop one value per GROUP BY column in reverse order, then reverse
        -- the list to recover the natural left-to-right key tuple.
        vals <- replicateM (length names) pop
        let key = reverse vals
        traceM ("[DBG] SaveGroupKey names=" ++ show names ++ " key=" ++ show key)
        modify (\st ->
            let order = vmGroupOrder st
                -- Append to group order if this key has not been seen yet.
                order' = if key `elem` order then order else order ++ [key]
            in st { vmCurrentGroup = key
                  , vmGroupOrder   = order'
                  })

    -- AdvanceGroup: step to the next group during the emit loop.
    -- Increments vmGroupIndex and updates vmCurrentGroup.
    AdvanceGroup -> do
        modify (\st ->
            let i      = vmGroupIndex st + 1
                order  = vmGroupOrder st
                newGrp = if i < length order then order !! i else []
            in st { vmGroupIndex   = i
                  , vmCurrentGroup = newGrp
                  })
        i <- gets vmGroupIndex
        order <- gets vmGroupOrder
        grp <- gets vmCurrentGroup
        traceM ("[DBG] AdvanceGroup idx=" ++ show i ++ " orderLen=" ++ show (length order) ++ " currentGrp=" ++ show grp)

    -- JumpIfGroupsDone: jump when all groups have been emitted.
    JumpIfGroupsDone lbl -> do
        i     <- gets vmGroupIndex
        order <- gets vmGroupOrder
        traceM ("[DBG] JumpIfGroupsDone lbl=" ++ lbl ++ " i=" ++ show i ++ " orderLen=" ++ show (length order) ++ " jumps=" ++ show (i >= length order))
        when (i >= length order) (jumpTo lbl)

    -- ── Control flow ──────────────────────────────────────────────────────
    Label _ ->
        -- No-op at runtime: labels are already indexed in vmLabelIndex.
        return ()

    Jump lbl ->
        jumpTo lbl

    JumpIfTrue lbl -> do
        v <- pop
        when (isTruthy v) (jumpTo lbl)

    JumpIfFalse lbl -> do
        v <- pop
        traceM ("[DBG] JumpIfFalse lbl=" ++ lbl ++ " val=" ++ show v ++ " jumps=" ++ show (not (isTruthy v)))
        unless (isTruthy v) (jumpTo lbl)

    Halt ->
        -- The main loop checks for Halt and terminates; this arm is defensive.
        return ()

    -- ── DDL ───────────────────────────────────────────────────────────────
    -- CreateTableInstr carries SqlPlanner.ColumnDef values; convert them to
    -- SqlBackend.ColumnDef before calling the backend.
    CreateTableInstr name ifne plannerColDefs -> do
        bRef <- gets vmBackend
        backend <- liftIO (readIORef bRef)
        let backendColDefs = map plannerColToBackendCol plannerColDefs
        case createTable backend name backendColDefs ifne of
            Left err -> error ("SqlVm: createTable failed: " ++ errorMessage err)
            Right b' -> liftIO (writeIORef bRef b')

    DropTableInstr name ife -> do
        bRef <- gets vmBackend
        backend <- liftIO (readIORef bRef)
        case dropTable backend name ife of
            Left err -> error ("SqlVm: dropTable failed: " ++ errorMessage err)
            Right b' -> liftIO (writeIORef bRef b')

    -- ── DML ───────────────────────────────────────────────────────────────
    -- InsertRow: values were pushed onto the stack by compileInsert (one push
    -- per column expression, left-to-right).  We pop them in push order
    -- (popN reverses the LIFO stack so the oldest/leftmost value comes first),
    -- zip with the column names, build a Row map, and hand it to the backend.
    --
    -- When colsOpt is Nothing (INSERT INTO t VALUES (...) with no explicit
    -- column list) we query the backend schema to get the canonical column
    -- order.
    InsertRow tbl colsOpt -> do
        bRef <- gets vmBackend
        backend <- liftIO (readIORef bRef)
        -- Resolve column names: explicit list takes priority; fall back to schema.
        colNames <- case colsOpt of
            Just cs -> return cs
            Nothing ->
                case SB.columns backend tbl of
                    Left  err -> liftIO (throwIO (userError ("insert: schema lookup failed: " ++ errorMessage err)))
                    Right defs -> return (map SB.columnName defs)
        -- Pop exactly as many values as columns; popN returns them in push order.
        vals <- popN (length colNames)
        let rowBuf = Map.fromList (zip colNames vals)
        case insert backend tbl rowBuf of
            Left err ->
                -- Use throwIO (a proper IO exception) rather than 'error'
                -- (an impure exception).  The caller's IO-level catch in
                -- MiniSqlite.runPipeline will intercept this and convert it
                -- to a Left MiniSqliteError.  Internal error message details
                -- are intentionally included only in the error value returned
                -- to the application layer, not logged to stderr.
                liftIO (throwIO (userError ("insert failed: " ++ errorMessage err)))
            Right b' -> do
                liftIO (writeIORef bRef b')
                modify (\st -> st { vmRowsAffected = vmRowsAffected st + 1 })

    UpdateRows _ ->
        -- Level 1: placeholder; mark one row affected.
        modify (\st -> st { vmRowsAffected = vmRowsAffected st + 1 })

    DeleteRows _ ->
        -- Level 1: placeholder; mark one row affected.
        modify (\st -> st { vmRowsAffected = vmRowsAffected st + 1 })

    -- ── Transaction control ───────────────────────────────────────────────
    BeginTransaction    -> return ()   -- Level 1: no-op.
    CommitTransaction   -> return ()
    RollbackTransaction -> return ()

    -- ── Result post-processing ────────────────────────────────────────────
    -- These record directives that are applied in buildResult after the loop.
    SortResult keys ->
        modify (\st -> st { vmPostSort = Just keys })

    DistinctResult ->
        modify (\st -> st { vmPostDistinct = True })

    LimitResult cnt off ->
        modify (\st -> st { vmPostLimit = Just (cnt, off) })

    -- ── Built-in scalar function calls ────────────────────────────────────
    -- CallBuiltin pops `arity` arguments (rightmost was pushed last), applies
    -- the named function, and pushes the result.  NULL propagates for most
    -- functions (except COALESCE and IFNULL which are null-specific).
    CallBuiltin name arity -> do
        -- replicateM n pop yields [last-arg, ..., first-arg].
        -- Reverse to get first-arg first, matching LEFT-TO-RIGHT argument order.
        argVals <- replicateM arity pop
        let args = reverse argVals
        push (evalBuiltin (map toLower name) args)

-- ── Public execute function ───────────────────────────────────────────────
--
-- This is the single public entry point. It:
--   1. Wraps the backend in an IORef so backend functions can mutate state.
--   2. Builds the label index (pre-scan, O(n)).
--   3. Creates the initial VmState.
--   4. Runs the dispatch loop in IO.
--   5. Packages the result.

-- | Execute a Program against an InMemoryBackend and return the QueryResult.
execute :: Program -> InMemoryBackend -> IO QueryResult
execute prog backend = do
    bRef <- newIORef backend
    fst <$> executeWithRef prog bRef

-- | Execute a Program using a caller-supplied IORef for the backend.
-- On return the IORef holds the post-execution (possibly mutated) backend.
-- This is the low-level entry point used by callers that need to persist
-- DML/DDL side-effects (e.g. the mini-sqlite connection layer).
executeWithRef :: Program -> IORef InMemoryBackend -> IO (QueryResult, InMemoryBackend)
executeWithRef prog bRef = do
    let instrs   = instructions prog
        lblIdx   = buildLabelIndex instrs
        initSt   = mkInitState instrs lblIdx bRef
    finalSt <- execStateT runLoop initSt
    finalBe <- readIORef bRef
    return (buildResult finalSt, finalBe)

-- | Build the initial VmState for a fresh execution.
mkInitState :: [Instruction] -> Map.Map String Int -> IORef InMemoryBackend -> VmState
mkInitState instrs lblIdx bRef =
    VmState
        { vmInstructions  = instrs
        , vmLabelIndex    = lblIdx
        , vmPc            = 0
        , vmStack         = []
        , vmCursors       = Map.empty
        , vmCurrentRow    = Map.empty
        , vmRowBuffer     = Map.empty
        , vmColOrder      = []
        , vmOutputColumns = []
        , vmOutputRows    = []
        , vmAggAccums     = Map.empty
        , vmGroupAccums   = Map.empty
        , vmCurrentGroup  = []
        , vmGroupOrder    = []
        , vmGroupIndex    = (-1)
        , vmRowsAffected  = 0
        , vmBackend       = bRef
        , vmPostSort      = Nothing
        , vmPostDistinct  = False
        , vmPostLimit     = Nothing
        }

-- | Build the final QueryResult from the finished VmState.
-- Applies Sort → Distinct → Limit in that order (same as Python vm).
buildResult :: VmState -> QueryResult
buildResult st =
    let rawRows  = reverse (vmOutputRows st)

        -- Use the column order captured during EmitColumn/EmitRow execution.
        -- This preserves SELECT-list order (e.g. SELECT id, name, age)
        -- rather than Map.keys alphabetical order (e.g. age, id, name).
        -- If no rows were emitted (DML or empty result), colNames is [].
        --
        -- Strip hidden sort-key columns (prefixed "__sort_") from the
        -- output column list.  These were emitted by compileSelect so that
        -- doSort can look up sort-key values for columns not in the SELECT
        -- list.  They must not appear in the user-visible query result.
        allCols  = vmOutputColumns st
        colNames = filter (not . ("__sort_" `isPrefixOf`)) allCols

        -- Convert row maps to value lists in column order.
        -- Only include the user-visible columns (not the hidden sort cols).
        toValueList rowMap = map (\col -> Map.findWithDefault SqlNull col rowMap) colNames

        -- Apply Sort on the full row maps (including hidden sort-key cols
        -- so that evalExprOnRow can find them via the "__sort_" fallback).
        sorted = case vmPostSort st of
            Nothing   -> rawRows
            Just keys -> doSort keys rawRows

        -- Project to value lists (hidden cols are excluded by colNames).
        sortedVals = map toValueList sorted

        -- Apply Distinct on value lists.
        distincted = if vmPostDistinct st
            then doDistinct sortedVals
            else sortedVals

        -- Apply Limit.
        limited = case vmPostLimit st of
            Nothing          -> distincted
            Just (cnt, off)  -> doLimit cnt off distincted

    in QueryResult
        { columns      = colNames
        , rows         = limited
        , rowsAffected = vmRowsAffected st
        }
