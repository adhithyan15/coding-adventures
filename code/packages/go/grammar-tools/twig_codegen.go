// GenerateTwigLexer generates the content of lexer.tw from a TokenGrammar.
//
// The generated module is compiler/lexer, exporting lex-source.
// It handles tokens in the order they appear in the .tokens file, plus skip
// patterns at the end of the chain.
//
// Architecture: a dispatch chain of functions lex-dispatch-N (one per token
// or token group).  Each function tests one condition and tails into the next
// on no-match.  Skip patterns restart the main lex-loop silently.
func GenerateTwigLexer(grammar *TokenGrammar, sourceFile string) string {
	var w strings.Builder

	wl := func(s string) { w.WriteString(s); w.WriteString("\n") }
	wf := func(f string, args ...interface{}) { w.WriteString(fmt.Sprintf(f, args...)) }

	// ── Module header ────────────────────────────────────────────────────────
	wl("; Generated by grammar-tools from " + sourceFile + " — DO NOT EDIT")
	wl(";")
	wl("; Twig lexer: converts a source string into a flat list of Token records.")
	wl("; Regenerate with:")
	wl(";   grammar-tools compile-tokens-twig " + sourceFile + " -o lexer.tw")
	wl("")
	wl("(module compiler/lexer")
	wl("  (typed lenient)")
	wl("  (export lex-source)")
	wl("  (import compiler/span compiler/token))")
	wl("")

	// ── Character predicates ─────────────────────────────────────────────────
	wl("; ─── Character predicates (derived from token patterns) ──────────────────────────")
	wl("")
	wl("(define (lex-digit? c)")
	wl("  ; INTEGER pattern: /[0-9]/ — ASCII 48 ('0') through 57 ('9')")
	wl("  (and (>= c 48) (<= c 57)))")
	wl("")
	wl("(define (lex-whitespace? c)")
	wl("  ; WHITESPACE skip: /[ \\t\\r\\n]+/ — 32=space 9=tab 13=cr 10=newline")
	wl("  (or (= c 32) (= c 9) (= c 13) (= c 10)))")
	wl("")
	wl("(define (lex-name-start? c)")
	wf("  ; NAME pattern first-char class: /[A-Za-z+\\-*/=<>!?_$]/\n")
	wl("  (or (and (>= c 65) (<= c 90))    ; A–Z")
	wl("      (and (>= c 97) (<= c 122))   ; a–z")
	wl("      (= c 43)                      ; +")
	wl("      (= c 45)                      ; - (also ARROW first char; ARROW checked first)")
	wl("      (= c 42)                      ; *")
	wl("      (= c 47)                      ; /")
	wl("      (= c 61)                      ; =")
	wl("      (= c 60)                      ; <")
	wl("      (= c 62)                      ; >")
	wl("      (= c 33)                      ; !")
	wl("      (= c 63)                      ; ?")
	wl("      (= c 95)                      ; _")
	wl("      (= c 36)))                    ; $")
	wl("")
	wl("(define (lex-name-continue? c)")
	wl("  ; NAME continuation class: name-start chars plus digits")
	wl("  (or (lex-name-start? c) (lex-digit? c)))")
	wl("")

	// ── Scan functions ───────────────────────────────────────────────────────
	wl("; ─── Scan helpers — advance pos, return (cons new-pos lexeme) ────────────────────")
	wl("")
	wl("(define (lex-scan-name src pos len start)")
	wl("  ; NAME pattern: advance while lex-name-continue?")
	wl("  (if (>= pos len)")
	wl("      (cons pos (substring src start pos))")
	wl("      (if (lex-name-continue? (char->integer (string-ref src pos)))")
	wl("          (lex-scan-name src (+ pos 1) len start)")
	wl("          (cons pos (substring src start pos)))))")
	wl("")
	wl("(define (lex-scan-digits src pos len start)")
	wl("  ; INTEGER pattern: /[0-9]+/ continuation after the leading digit or '-'")
	wl("  (if (>= pos len)")
	wl("      (cons pos (substring src start pos))")
	wl("      (if (lex-digit? (char->integer (string-ref src pos)))")
	wl("          (lex-scan-digits src (+ pos 1) len start)")
	wl("          (cons pos (substring src start pos)))))")
	wl("")
	wl("(define (lex-scan-string src pos len start)")
	wl(`  ; STRING pattern: /"([^"\\]|\\.)*"/`)
	wl("  ; Called after consuming the opening '\"'.  Returns (cons pos-after-close-quote content).")
	wl("  ; 34='\"'  92='\\\\'")
	wl("  (if (>= pos len)")
	wl("      (cons pos (substring src start pos))")
	wl("      (let* ((c (char->integer (string-ref src pos))))")
	wl("        (if (= c 34)")
	wl("            (cons (+ pos 1) (substring src start pos))")
	wl("            (if (and (= c 92) (< (+ pos 1) len))")
	wl("                (lex-scan-string src (+ pos 2) len start)")
	wl("                (lex-scan-string src (+ pos 1) len start))))))")
	wl("")
	wl("(define (lex-skip-whitespace src pos len)")
	wl("  ; WHITESPACE skip: advance past spaces/tabs/crs/newlines")
	wl("  (if (>= pos len)")
	wl("      pos")
	wl("      (if (lex-whitespace? (char->integer (string-ref src pos)))")
	wl("          (lex-skip-whitespace src (+ pos 1) len)")
	wl("          pos)))")
	wl("")
	wl("(define (lex-skip-comment src pos len)")
	wl("  ; COMMENT skip: advance from after ';' to end of line")
	wl("  ; 10 = '\\n'")
	wl("  (if (>= pos len)")
	wl("      pos")
	wl("      (if (= (char->integer (string-ref src pos)) 10)")
	wl("          (+ pos 1)")
	wl("          (lex-skip-comment src (+ pos 1) len))))")
	wl("")

	// ── Main loop ────────────────────────────────────────────────────────────
	wl("; ─── Main lex loop ─────────────────────────────────────────────────────────────")
	wl("")
	wl("(define (lex-emit src next-pos len acc tok)")
	wl("  (lex-loop src next-pos len (cons tok acc)))")
	wl("")
	wl("(define (lex-loop src pos len acc)")
	wl("  (if (>= pos len)")
	wl("      (reverse (cons (Token (TkEOF) \"\" (make-span 0 pos pos)) acc))")
	wl("      (let* ((c (char->integer (string-ref src pos))))")
	wl("        (lex-dispatch-0 src pos len acc c))))")
	wl("")

	// ── Dispatch chain ───────────────────────────────────────────────────────
	wl("; ─── Token dispatch chain (grammar-file order) ─────────────────────────────────")
	wl("; One function per token or token group.  Each tests one condition;")
	wl("; on no-match it tails into the next function (lex-dispatch-N+1).")
	wl("")

	// Build dispatch steps: one per token definition + skip patterns
	type dispatchStep struct {
		comment string
		code    string // Twig body (uses __NEXT__ for the next function name)
	}

	var steps []dispatchStep

	for _, td := range grammar.Definitions {
		comment := fmt.Sprintf("; %s = %s", td.Name, describeTokenDef(td))
		code := genLexDispatchBody(td)
		steps = append(steps, dispatchStep{comment, code})
	}

	// Add skip patterns after main tokens
	for _, sd := range grammar.SkipDefinitions {
		var comment, code string
		switch sd.Name {
		case "WHITESPACE":
			comment = "; WHITESPACE skip (from skip: section)"
			code = "  (if (lex-whitespace? c)\n" +
				"      (lex-loop src (lex-skip-whitespace src pos len) len acc)\n" +
				"      (__NEXT__ src pos len acc c))"
		case "COMMENT":
			comment = "; COMMENT skip (from skip: section)"
			code = "  (if (= c 59)  ; ';'\n" +
				"      (lex-loop src (lex-skip-comment src (+ pos 1) len) len acc)\n" +
				"      (__NEXT__ src pos len acc c))"
		default:
			continue
		}
		steps = append(steps, dispatchStep{comment, code})
	}

	// Emit dispatch functions
	total := len(steps)
	for i, step := range steps {
		nextFn := fmt.Sprintf("lex-dispatch-%d", i+1)
		if i+1 >= total {
			nextFn = "lex-unknown"
		}
		body := strings.ReplaceAll(step.code, "__NEXT__", nextFn)
		wl(step.comment)
		wf("(define (lex-dispatch-%d src pos len acc c)\n", i)
		wl(body + ")")
		wl("")
	}

	// Error fallback
	wl("; Unrecognized character: skip byte and continue.")
	wl("(define (lex-unknown src pos len acc c)")
	wl("  (lex-loop src (+ pos 1) len acc))")
	wl("")

	// ── Public API ───────────────────────────────────────────────────────────
	wl("; ─── Public API ─────────────────────────────────────────────────────────────────")
	wl("")
	wl("(define (lex-source src)")
	wl("  (lex-loop src 0 (string-length src) (list)))")

	return w.String()
}

// describeTokenDef returns a short human-readable description of a token definition.
func describeTokenDef(td TokenDefinition) string {
	if td.IsRegex {
		return "/" + td.Pattern + "/"
	}
	return `"` + td.Pattern + `"`
}

// genLexDispatchBody generates the Twig dispatch body for one token definition.
// Uses __NEXT__ as a placeholder for the next dispatch function name.
func genLexDispatchBody(td TokenDefinition) string {
	if !td.IsRegex {
		return genExactLiteralBody(td)
	}
	switch td.Name {
	case "STRING":
		return genStringBody(td)
	case "INTEGER":
		return genIntegerBody(td)
	case "NAME":
		return genNameBody(td)
	default:
		// Unknown regex pattern: skip and continue
		return "  (__NEXT__ src pos len acc c)"
	}
}

// genExactLiteralBody generates dispatch code for a single exact literal token.
func genExactLiteralBody(td TokenDefinition) string {
	pattern := td.Pattern
	kind := twigKindFor(td.Name)

	switch len(pattern) {
	case 1:
		ascii := int(pattern[0])
		return fmt.Sprintf(
			"  (if (= c %d)  ; %q\n"+
				"      (lex-emit src (+ pos 1) len acc\n"+
				"                (Token (%s) %q (make-span 0 pos (+ pos 1))))\n"+
				"      (__NEXT__ src pos len acc c))",
			ascii, rune(ascii), kind, pattern)

	case 2:
		ascii0 := int(pattern[0])
		ascii1 := int(pattern[1])
		// For BOOL_TRUE "#t" and BOOL_FALSE "#f": same first char '#' (35)
		// The dispatch chain handles them sequentially: if #t doesn't match,
		// we fall through to check #f.
		return fmt.Sprintf(
			"  (if (and (= c %d)  ; %q\n"+
				"           (< (+ pos 1) len)\n"+
				"           (= (char->integer (string-ref src (+ pos 1))) %d))  ; %q\n"+
				"      (lex-emit src (+ pos 2) len acc\n"+
				"                (Token (%s) %q (make-span 0 pos (+ pos 2))))\n"+
				"      (__NEXT__ src pos len acc c))",
			ascii0, rune(ascii0), ascii1, rune(ascii1), kind, pattern)

	default:
		// N-char literal: check N characters via substring comparison
		return fmt.Sprintf(
			"  (if (and (>= (- len pos) %d)\n"+
				"           (string=? (substring src pos (+ pos %d)) %q))\n"+
				"      (lex-emit src (+ pos %d) len acc\n"+
				"                (Token (%s) %q (make-span 0 pos (+ pos %d))))\n"+
				"      (__NEXT__ src pos len acc c))",
			len(pattern), len(pattern), pattern, len(pattern), kind, pattern, len(pattern))
	}
}

// genStringBody generates dispatch for the STRING regex token.
func genStringBody(_ TokenDefinition) string {
	return "  ; 34 = '\"'\n" +
		"  (if (= c 34)\n" +
		"      (let* ((r   (lex-scan-string src (+ pos 1) len (+ pos 1)))\n" +
		"             (ep  (car r))\n" +
		"             (lex (cdr r)))\n" +
		"        (lex-emit src ep len acc\n" +
		"                  (Token (TkString) lex (make-span 0 pos ep))))\n" +
		"      (__NEXT__ src pos len acc c))"
}

// genIntegerBody generates dispatch for the INTEGER regex token.
// INTEGER = /-?[0-9]+/ which covers both positive and negative integers.
// ARROW "->" must appear before INTEGER in the grammar (otherwise the `-`
// in "->xxx" would be consumed here).  By this point in the chain, any
// `-` we see is either a negative integer or a bare name-start `-`.
func genIntegerBody(_ TokenDefinition) string {
	return "  ; INTEGER = /-?[0-9]+/\n" +
		"  ; Positive integer: first char is a digit.\n" +
		"  (if (lex-digit? c)\n" +
		"      (let* ((r   (lex-scan-digits src (+ pos 1) len pos))\n" +
		"             (ep  (car r))\n" +
		"             (lex (cdr r)))\n" +
		"        (lex-emit src ep len acc\n" +
		"                  (Token (TkInteger) lex (make-span 0 pos ep))))\n" +
		"  ; Negative integer: '-' followed by a digit.\n" +
		"  (if (and (= c 45)  ; '-'\n" +
		"           (< (+ pos 1) len)\n" +
		"           (lex-digit? (char->integer (string-ref src (+ pos 1)))))\n" +
		"      (let* ((r   (lex-scan-digits src (+ pos 2) len pos))\n" +
		"             (ep  (car r))\n" +
		"             (lex (cdr r)))\n" +
		"        (lex-emit src ep len acc\n" +
		"                  (Token (TkInteger) lex (make-span 0 pos ep))))\n" +
		"  (__NEXT__ src pos len acc c)))"
}

// genNameBody generates dispatch for the NAME regex token.
// By this point in the dispatch chain, ARROW and INTEGER have already consumed
// the '->' and '-digit' cases, so any lex-name-start? character here starts a
// genuine identifier.
func genNameBody(_ TokenDefinition) string {
	return "  ; NAME = /[A-Za-z+\\-*/=<>!?_$][A-Za-z+\\-*/=<>!?_$0-9]*/\n" +
		"  (if (lex-name-start? c)\n" +
		"      (let* ((r   (lex-scan-name src (+ pos 1) len pos))\n" +
		"             (ep  (car r))\n" +
		"             (lex (cdr r)))\n" +
		"        (lex-emit src ep len acc\n" +
		"                  (Token (TkIdentifier) lex (make-span 0 pos ep))))\n" +
		"      (__NEXT__ src pos len acc c))"
}

