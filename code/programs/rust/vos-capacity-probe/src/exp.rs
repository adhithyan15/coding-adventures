//! # `exp`: the experiment plan and the row runners
//!
//! This module turns the table of VOS30 section 9.7 into rows.  [`plan`] lists every
//! `(experiment, knob, mode, seed)` of a tier; [`run_row`] executes one of them *in this
//! process* (the runner starts one child process per row, section 9.2) and fills in a
//! [`Row`] with the measurements of section 9.5 and the guards of section 9.4.
//!
//! ```text
//!   monolithic row   build -> G1/G2 -> CNF -> solve with DRAT -> check (default limits)
//!                                   -> control (mutated instance, must be SAT and replay)
//!   chain row        the same per segment, each segment its own CNF (certified) or all
//!                    segments in one solver under assumptions (incremental)
//!   enumeration row  `enumx`: the generated by-value harness, and the budget refusals
//! ```
//!
//! The row never decides `green`: the parent computes it from the other fields once the
//! child's peak resident memory is known (`results::green`).

