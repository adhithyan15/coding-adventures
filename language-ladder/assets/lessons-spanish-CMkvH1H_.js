<!-- hl-knowledge: introduces=[ES-GRAMMAR-ESTAR-PRESENT-COMPLETE]; assesses=[ES-GRAMMAR-SER-PRESENT-COMPLETE, ES-GRAMMAR-ESTAR-ESTA-ESTAS, ES-GRAMMAR-ESTAR-PRESENT-1PL, ES-GRAMMAR-ESTAR-PRESENT-2PL, ES-GRAMMAR-ESTAR-PRESENT-3PL, ES-ETYMON-STARE] -->

