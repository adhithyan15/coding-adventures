/// Convert `kebab-case` (and `lowerCamelCase` / `PascalCase`) to
/// `lowerCamelCase`. The first character of the output is lowered so
/// PascalCase inputs still produce a JS-style identifier.
fn to_camel_case_first_lower(s: &str) -> String {
    let mut out = String::new();
    let mut cap_next = false;
    let mut first = true;
    for ch in s.chars() {
        if ch == '-' {
            cap_next = true;
            continue;
        }
        if first {
            out.push(ch.to_ascii_lowercase());
            first = false;
        } else if cap_next {
            out.push(ch.to_ascii_uppercase());
            cap_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// Convert `PascalCase` / `camelCase` to `kebab-case` for the custom
/// element tag name. `ProfileCard` → `profile-card`.
///
/// HTML custom element tag names *must* contain a `-` (per the Custom
/// Elements spec). We always prepend `mos-` at the call site to
/// satisfy that rule, but the inner conversion still produces a
/// hyphenated form so multi-word component names look natural in HTML.
fn to_kebab_case(s: &str) -> String {
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i != 0 {
                out.push('-');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

/// Strip a leading `on` prefix from an emit name, if present.
/// `onClick` → `Click`; `onEditCommit` → `EditCommit`. The caller then
/// runs `to_camel_case_first_lower` to lowercase the first letter.
fn strip_on_prefix(s: &str) -> String {
    if let Some(rest) = s.strip_prefix("on") {
        if let Some(first) = rest.chars().next() {
            if first.is_ascii_uppercase() {
                return rest.to_string();
            }
        }
    }
    s.to_string()
}

/// `true` iff `s` matches `[_$a-zA-Z][_$a-zA-Z0-9]*` — the safe
/// shape for embedding verbatim in JavaScript source.
fn is_safe_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

/// Result-style wrapper around [`is_safe_identifier`] so callers can
/// use the `?` operator with `map_err`.
fn validate_safe_identifier(s: &str) -> Result<(), String> {
    if is_safe_identifier(s) {
        Ok(())
    } else {
        Err(s.to_string())
    }
}

/// Escape a string literal for safe embedding inside an HTML text
/// node that itself lives inside a JavaScript template literal.
///
/// Two layers of escaping apply because `_render()` builds the shadow
/// HTML as a template literal:
///
/// ```javascript
/// this.shadowRoot.innerHTML = `<span>${text}</span>`;
/// ```
///
/// 1. **HTML layer**: `&`, `<`, `>` are escaped to entity references
///    so an author-supplied string cannot inject HTML tags or
///    attributes into the rendered tree.
/// 2. **Template-literal layer**: backticks (`` ` ``) and the
///    interpolation opener (`${`) are escaped with `\\\`` / `\\${`
///    so author-supplied content cannot break out of the template
///    literal in `_render()` and execute arbitrary JS.
///
/// The two layers are independent: a `<` in source needs HTML
/// escaping (`&lt;`); a backtick needs JS escaping (`` \\` ``).
///
/// **Threat model.** `.mil` / `.mll` source files are author-controlled
/// in the same sense `.tsx` or `.rs` files are, but downstream tooling
/// (mosaic-package-manifest, etc.) may load layout fragments from
/// caches and registries. Treating literal string content as
/// untrusted-by-default is cheap and removes a foot-gun class.
fn escape_html_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            // Backtick would close the surrounding template literal.
            '`' => out.push_str("\\`"),
            // Backslash must be doubled so the subsequent escapes
            // (e.g. `\\\``) stay distinct from a source-literal `\`.
            '\\' => out.push_str("\\\\"),
            // `${` opens a template-literal interpolation; break the
            // sequence by escaping the dollar. A bare `$` not followed
            // by `{` passes through (the spec only treats `${` as the
            // interpolation opener).
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            _ => out.push(ch),
        }
    }
    out
}

/// `true` iff `s` is a valid mosmodel kebab-case identifier:
/// `[a-z][a-z0-9]*(-[a-z][a-z0-9]*)*`. This matches what the mosmodel
/// grammar enforces on slot and emit names, and is what we expect
/// before embedding the raw name into an HTML attribute string or
/// `getAttribute(...)` argument.
///
/// Used as a defense-in-depth guard: the grammar should already
/// reject anything else, but a direct IR construction that bypasses
/// the lexer (a fuzzer, an LSP that hand-builds nodes, …) could
/// still produce ill-formed names.
fn is_kebab_identifier(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }
    let mut prev_dash = false;
    for (i, ch) in s.chars().enumerate() {
        match ch {
            'a'..='z' => prev_dash = false,
            '0'..='9' if i > 0 && !prev_dash => prev_dash = false,
            '-' if i > 0 && !prev_dash => prev_dash = true,
            _ => return false,
        }
    }
    !prev_dash
}

