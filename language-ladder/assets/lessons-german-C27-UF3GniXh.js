<!-- hl-knowledge: introduces=[GE-ETYMON-MILCH-04]; assesses=[GE-LEX-MILCH-02, GE-LEX-TEE-02, GE-ETYMON-TEE-04, GE-SOUND-TEE-03, GE-SOUND-KAFFEE-03] -->

