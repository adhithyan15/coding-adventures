param(
    [string]$RegistryPath,
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"

$packageRoot = Split-Path -Parent $PSScriptRoot
if (-not $RegistryPath) {
    $RegistryPath = Join-Path $packageRoot "../../../specs/fixtures/build-tool-v1/language-source-input-registry.json"
}
if (-not $OutputPath) {
    $OutputPath = Join-Path $packageRoot "internal/hasher/language_source_input_registry_generated.go"
}

$registryBytes = [System.IO.File]::ReadAllBytes($RegistryPath)
if ($registryBytes.Length -eq 0 -or $registryBytes.Length -gt 1MB) {
    throw "language source-input registry exceeds the byte limit"
}
$registry = [System.Text.UTF8Encoding]::new($false, $true).GetString($registryBytes)
$depth = 0
$inString = $false
$escaped = $false
foreach ($character in $registry.ToCharArray()) {
    if ($inString) {
        if ($escaped) {
            $escaped = $false
        } elseif ($character -eq '\') {
            $escaped = $true
        } elseif ($character -eq '"') {
            $inString = $false
        }
        continue
    }
    if ($character -eq '"') {
        $inString = $true
    } elseif ($character -eq '{' -or $character -eq '[') {
        $depth += 1
        if ($depth -gt 64) {
            throw "language source-input registry exceeds the depth limit"
        }
    } elseif ($character -eq '}' -or $character -eq ']') {
        $depth -= 1
        if ($depth -lt 0) {
            throw "language source-input registry is unbalanced"
        }
    }
}
if ($inString -or $depth -ne 0) {
    throw "language source-input registry is unbalanced"
}

function Assert-NoDuplicateJsonKeys {
    param([System.Text.Json.JsonElement]$Element)

    if ($Element.ValueKind -eq [System.Text.Json.JsonValueKind]::Object) {
        $keys = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
        foreach ($property in $Element.EnumerateObject()) {
            if (-not $keys.Add($property.Name)) {
                throw "language source-input registry contains a duplicate object key"
            }
            Assert-NoDuplicateJsonKeys $property.Value
        }
    } elseif ($Element.ValueKind -eq [System.Text.Json.JsonValueKind]::Array) {
        foreach ($item in $Element.EnumerateArray()) {
            Assert-NoDuplicateJsonKeys $item
        }
    }
}

$jsonDocument = [System.Text.Json.JsonDocument]::Parse($registry)
try {
    Assert-NoDuplicateJsonKeys $jsonDocument.RootElement
} finally {
    $jsonDocument.Dispose()
}
$parsedRegistry = $registry | ConvertFrom-Json
if ($registry.Contains('`')) {
    throw "language source-input registry cannot contain a Go raw-string delimiter"
}

function ConvertTo-CanonicalJson {
    param([AllowNull()]$Value)

    if ($null -eq $Value) {
        return "null"
    }
    if ($Value -is [string]) {
        return ConvertTo-Json -InputObject $Value -Compress
    }
    if ($Value -is [bool]) {
        if ($Value) { return "true" }
        return "false"
    }
    if ($Value -is [System.Collections.IEnumerable] -and $Value -isnot [System.Management.Automation.PSCustomObject]) {
        $items = @($Value | ForEach-Object { ConvertTo-CanonicalJson $_ })
        return "[" + ($items -join ",") + "]"
    }
    if ($Value -is [System.Management.Automation.PSCustomObject]) {
        $members = @(
            $Value.PSObject.Properties |
                Sort-Object -Property Name -CaseSensitive |
                ForEach-Object {
                    (ConvertTo-Json -InputObject $_.Name -Compress) + ":" +
                        (ConvertTo-CanonicalJson $_.Value)
                }
        )
        return "{" + ($members -join ",") + "}"
    }
    return [System.Convert]::ToString($Value, [System.Globalization.CultureInfo]::InvariantCulture)
}

$canonical = ConvertTo-CanonicalJson $parsedRegistry
$utf8 = [System.Text.UTF8Encoding]::new($false)
$domain = $utf8.GetBytes("coding-adventures/build-tool-language-source-input-registry/v1`0")
$canonicalBytes = $utf8.GetBytes($canonical)
$length = [System.BitConverter]::GetBytes([uint64]$canonicalBytes.Length)
if ([System.BitConverter]::IsLittleEndian) {
    [System.Array]::Reverse($length)
}
$framed = [byte[]]::new($domain.Length + 8 + $canonicalBytes.Length)
[System.Array]::Copy($domain, 0, $framed, 0, $domain.Length)
[System.Array]::Copy($length, 0, $framed, $domain.Length, 8)
[System.Array]::Copy($canonicalBytes, 0, $framed, $domain.Length + 8, $canonicalBytes.Length)
$sha256 = [System.Security.Cryptography.SHA256]::Create()
try {
    $digest = -join ($sha256.ComputeHash($framed) | ForEach-Object { $_.ToString("x2") })
} finally {
    $sha256.Dispose()
}

$header = @'
// Code generated by tools/generate-language-source-input-registry.ps1; DO NOT EDIT.
//
// The neutral JSON is embedded so production hashing never reads a repository
// fixture. Regenerate this file whenever the checked registry changes.

package hasher

const languageSourceInputRegistryJSON = `
'@

$footer = @'
`

const languageSourceInputRegistryDigest = "__REGISTRY_DIGEST__"
'@

$normalizedRegistry = $registry.Replace("`r`n", "`n").TrimEnd("`r", "`n")
$content = $header + "`n" + $normalizedRegistry + "`n" +
    $footer.TrimStart("`r", "`n").Replace("__REGISTRY_DIGEST__", $digest) + "`n"
$outputDirectory = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
[System.IO.File]::WriteAllText(
    $OutputPath,
    $content.Replace("`r`n", "`n"),
    [System.Text.UTF8Encoding]::new($false)
)
