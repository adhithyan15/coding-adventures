//! End-to-end test for the earth-science ATMOSPHERE-LAYERS facts library
//! (`adj-facts-stdlib/earth-science/atmosphere-layers.adj`) driven through the
//! built CLI: a native `table` of atmosphere layer → distinctive feature
//! resolves a binding-query recall carrying the NASA "Earth's Atmosphere: A
//! Multi-layered Cake" citation, runs the relation backward (feature → layer),
//! and abstains on a word that is not one of the five layers (the `mantle`, a
//! layer of the solid Earth) — 0 model calls.

use std::path::{Path, PathBuf};
use std::process::Command;

fn facts_stdlib() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../specs/data/adj-facts-stdlib")
        .canonicalize()
        .expect("shipped adj-facts-stdlib must exist")
}

fn scratch(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("adjcli_factsk_{tag}_{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn run(program: &Path) -> (bool, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_adj-lang-cli"))
        .arg(program)
        .output()
        .expect("run adj-lang-cli");
    (out.status.success(), String::from_utf8(out.stdout).unwrap())
}

#[test]
fn earth_science_atmosphere_layer_recall_binds_feature_with_citation() {
    let dir = scratch("atmospherelayers");
    // Copy the shipped atmosphere-layers table beside the entry program and import it.
    let src = facts_stdlib().join("earth-science/atmosphere-layers.adj");
    std::fs::copy(&src, dir.join("atmosphere-layers.adj"))
        .expect("copy shipped atmosphere-layers.adj");
    std::fs::write(
        dir.join("case.adj"),
        "import \"atmosphere-layers.adj\"\n\
         ? atmosphere_layer_feature(troposphere, $Feature)\n\
         ? atmosphere_layer_feature(stratosphere, $Feature)\n\
         ? atmosphere_layer_feature(exosphere, $Feature)\n\
         ? atmosphere_layer_feature($Layer, auroras)\n\
         ? atmosphere_layer_feature(mantle, $Feature)\n",
    )
    .unwrap();

    let (ok, out) = run(&dir.join("case.adj"));
    assert!(ok, "cli should succeed: {out}");
    // THE WHOLE CITATION, anchored on its JSON key and closed by the
    // terminating quote. This sentence carries a qualifier, so a
    // truncation would silently drop meaning -- the defect issue #13916
    // shipped. Pinning a fragment narrows that hole rather than closing
    // it, because `contains` on a fragment cannot see what precedes or
    // follows it. See issue #13918.
    //
    // #14986 WIDENED this span at the FRONT as well: the weather sentence
    // says "happens here" and names no layer, so quoted alone it warranted
    // nothing. It now opens on the sentence that names the troposphere.
    assert!(
        out.contains("\"source\":\"The troposphere is the densest atmospheric layer, compressed by the weight of the rest of the atmosphere above it. Most of Earth’s weather happens here, and almost all clouds that are generated by weather are found here, with the exception of cumulonimbus thunder clouds, whose tops can rise into the lowest parts of the neighboring stratosphere.\""),
        "the citation is the whole widened span, exactly: {out}"
    );
    assert!(out.contains("\"recall\""), "has a recall section: {out}");
    // Forward lookups bind each layer to the distinctive feature NASA states.
    assert!(
        out.contains("\"Feature\":\"weather\""),
        "troposphere → weather: {out}"
    );
    assert!(
        out.contains("\"Feature\":\"ozone_layer\""),
        "stratosphere → ozone_layer: {out}"
    );
    assert!(
        out.contains("\"Feature\":\"highest\""),
        "exosphere → highest: {out}"
    );
    // The relation runs BACKWARD: the feature `auroras` recalls the thermosphere.
    assert!(
        out.contains("\"Layer\":\"thermosphere\""),
        "auroras → thermosphere (reverse recall): {out}"
    );
    // The answer carries the NASA (science.nasa.gov) citation as its proof, at
    // the authoritative trust tier of a primary U.S. government source.
    assert!(
        out.contains("science.nasa.gov") && out.contains("\"trust\":\"authoritative\""),
        "carries the source citation: {out}"
    );
    // The `mantle` is a layer of the solid Earth, not the atmosphere — it is not
    // a row, so the recall abstains honestly, never a fabricated feature.
    assert!(
        out.contains("\"abstained\":true"),
        "ungrounded layer (mantle) abstains: {out}"
    );
}

const LOCATOR: &str =
    "https://science.nasa.gov/earth/earth-atmosphere/earths-atmosphere-a-multi-layered-cake/";

/// Assert one row carries a SELF-CONTAINED span — one that names its own
/// layer AND states its feature — as a whole `source`/`locator`/`trust`
/// object, in a program returning only that row.
///
/// `feature` is pinned too. Review found `mesosphere -> meteors` entirely
/// unpinned: its value could be changed to anything and every test stayed
/// green, because the span assertion never read the binding. That is the same
/// gap the `planets` entry found and declared closed two entries earlier.
fn assert_layer(tag: &str, layer: &str, feature: &str, span: &str) -> String {
    let dir = scratch(tag);
    std::fs::copy(
        facts_stdlib().join("earth-science/atmosphere-layers.adj"),
        dir.join("atmosphere-layers.adj"),
    )
    .expect("copy shipped atmosphere-layers.adj");
    std::fs::write(
        dir.join("case.adj"),
        format!(
            "import \"atmosphere-layers.adj\"\n? atmosphere_layer_feature({layer}, $Feature)\n"
        ),
    )
    .unwrap();
    let (ok, out) = run(&dir.join("case.adj"));
    assert!(ok, "cli should succeed: {out}");
    assert_eq!(
        out.matches("\"citations\":[").count(),
        1,
        "exactly one answer, so every needle below belongs to {layer}: {out}"
    );
    assert!(
        out.contains(&format!("\"Feature\":\"{feature}\"")),
        "{layer} binds {feature}: {out}"
    );
    assert!(
        out.contains(&format!(
            "\"source\":\"{span}\",\"locator\":\"{LOCATOR}\",\"trust\":\"authoritative\""
        )),
        "{layer} carries a span that names it and states its feature: {out}"
    );
    // No row needs a second span any more. Twice, not once: each answer emits
    // its provenance under "citations" and again under "steps".
    assert_eq!(
        out.matches("\"corroborations\":[]").count(),
        2,
        "the widened span is self-contained, so no corroboration: {out}"
    );
    out
}

/// #14986: this table had one envelope — the TROPOSPHERE row's weather
/// sentence — so a recall of the exosphere was warranted by a sentence about
/// clouds.
///
/// THE SPANS ARE WIDENED, not paired. Three of the five features are carried
/// by a sentence naming its subject only as "here" or "this atmospheric
/// layer". A first draft gave those rows a naming `source` plus a feature
/// `cites`; review caught that this violates the shipped README rule
/// ("A citation must name its own subject … widen the quote until it is
/// self-contained") AND left the row's warrant — the field that carries the
/// tier — a sentence about altitude that never mentions the feature.
///
/// Widened minimally instead: each span starts at the last sentence naming
/// the layer before the feature sentence. 346 / 269 / 358 characters, each
/// occurring exactly once on the page, all inside the 702-character
/// precedent this stdlib already set.
#[test]
fn atmosphere_rows_carry_a_span_that_names_their_own_layer() {
    assert_layer(
        "atmostropo",
        "troposphere",
        "weather",
        "The troposphere is the densest atmospheric layer, compressed by the weight of the rest of the atmosphere above it. Most of Earth’s weather happens here, and almost all clouds that are generated by weather are found here, with the exception of cumulonimbus thunder clouds, whose tops can rise into the lowest parts of the neighboring stratosphere.",
    );
    assert_layer(
        "atmosmeso",
        "mesosphere",
        "meteors",
        "The very scarce water vapor present at the top of the mesosphere forms noctilucent clouds, the highest clouds in Earth’s atmosphere, which can be seen by the naked eye under certain conditions and at certain times of day. Most meteors burn up in this atmospheric layer.",
    );
    assert_layer(
        "atmostherm",
        "thermosphere",
        "auroras",
        "Located between about 80 and 700 kilometers (50 and 440 miles) above Earth’s surface is the thermosphere, whose lowest part contains the ionosphere. In this layer, temperatures increase with altitude due to the very low density of molecules found here. It is both cloud- and water vapor-free. The aurora borealis and aurora australis are sometimes seen here.",
    );
    assert_layer(
        "atmosstrat",
        "stratosphere",
        "ozone_layer",
        "Located between approximately 12 and 50 kilometers (7.5 and 31 miles) above Earth’s surface, the stratosphere is perhaps best known as home to Earth’s ozone layer, which protects us from the Sun’s harmful ultraviolet radiation.",
    );
}

/// `exosphere -> highest` was flagged by the bounding-language audit as a
/// superlative with no bounding language in its provenance. The page states
/// it outright. A false alarm, and the second in this cascade after
/// `biology/rainforest-layer` — two of that audit's flags have now resolved
/// this way.
#[test]
fn atmosphere_exosphere_carries_the_bound_the_page_states() {
    let out = assert_layer(
        "atmosexo",
        "exosphere",
        "highest",
        "Located between about 700 and 10,000 kilometers (440 and 6,200 miles) above Earth’s surface, the exosphere is the highest layer of Earth’s atmosphere and, at its top, merges with the solar wind.",
    );
    assert!(
        out.contains("is the highest layer of Earth’s atmosphere"),
        "the bound itself reaches the answer: {out}"
    );
}

/// The envelope is unreachable by construction — every row overrides
/// `source`. Its wording cannot be pinned by any output test (fabricating it
/// leaves this suite green, disclosed rather than implied); the PROPERTY can
/// be, and a leak back into an answer is what would redden.
#[test]
fn atmosphere_envelope_never_reaches_an_answer() {
    let dir = scratch("atmosenvelope");
    std::fs::copy(
        facts_stdlib().join("earth-science/atmosphere-layers.adj"),
        dir.join("atmosphere-layers.adj"),
    )
    .expect("copy shipped atmosphere-layers.adj");
    std::fs::write(
        dir.join("case.adj"),
        "import \"atmosphere-layers.adj\"\n? atmosphere_layer_feature($L, $F)\n",
    )
    .unwrap();
    let (ok, out) = run(&dir.join("case.adj"));
    assert!(ok, "cli should succeed: {out}");
    assert_eq!(
        out.matches("\"citations\":[").count(),
        5,
        "all five layers answer: {out}"
    );
    assert!(
        !out.contains("From lowest to highest, the major layers are"),
        "the framing span warrants no row: {out}"
    );
}
