//! # MUS05: Naive Instrument Models, Timbre, and Note Rendering
//!
//! MUS00 maps note names to frequencies. MUS01 turns one frequency into a simple
//! sine tone. MUS04 introduces named instruments and multiple tracks.
//!
//! This crate implements the first naive musical instrument timbre model:
//!
//! ```text
//! note frequency + harmonic profile + ADSR envelope -> shaped waveform -> PCM audio
//! ```
//!
//! The goal is not realism yet. The goal is to make virtual instruments, virtual
//! keyboards, and virtual orchestras possible with an inspectable, deterministic model:
//!
//! - The same note keeps the same fundamental frequency across instruments.
//! - Instruments differ by harmonic content, envelope shape, gain, and subtle variation.
//! - Every layer remains inspectable and deterministic by default.
//! - Seeded variation is generated by a deterministic [`SplitMix64`] PRNG engine.
//! - Strict security bounds (**CWE-400 / CWE-190 / CWE-20**) are enforced before allocation.
//! - All synthesis routines are strictly iterative, provably eliminating recursion (**CWE-674**).
//!
//! ## Verification & Security Guarantees
//!
//! - **Safety**: `#![forbid(unsafe_code)]`, zero third-party dependencies (only `std`, `oscillator`, and `pcm-audio`).
//! - **CWE-400 (Resource Exhaustion)**:
//!   - `MAX_PARTIALS = 64`
//!   - `MAX_NOTE_DURATION_SECONDS = 60.0`
//!   - `MAX_SAMPLE_RATE_HZ = 192_000.0`
//!   - `MAX_SAMPLE_COUNT = 16_777_216` (2^24)
//! - **CWE-20 (Improper Input Validation)**: Finite float checks on all numeric inputs; `NaN` and `±Inf` fail closed.
//! - **CWE-674 (Uncontrolled Recursion)**: Zero recursive function calls.

