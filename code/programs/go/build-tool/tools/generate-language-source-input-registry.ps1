param(
    [string]$RegistryPath,
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"

$packageRoot = Split-Path -Parent $PSScriptRoot
if (-not $RegistryPath) {
    $RegistryPath = Join-Path $packageRoot "../../../specs/fixtures/build-tool-v1/language-source-input-registry.json"
}
if (-not $OutputPath) {
    $OutputPath = Join-Path $packageRoot "internal/hasher/language_source_input_registry_generated.go"
}

$registry = Get-Content -LiteralPath $RegistryPath -Raw
$null = $registry | ConvertFrom-Json
if ($registry.Contains('`')) {
    throw "language source-input registry cannot contain a Go raw-string delimiter"
}

$header = @'
// Code generated by tools/generate-language-source-input-registry.ps1; DO NOT EDIT.
//
// The neutral JSON is embedded so production hashing never reads a repository
// fixture. Regenerate this file whenever the checked registry changes.

package hasher

const languageSourceInputRegistryJSON = `
'@

$footer = @'
`

const languageSourceInputRegistryDigest = "f49bfe8c7c9c0fb9b534ecc9ca4a614f3684abe32bdb0edac82d99bdc806fb70"
'@

$normalizedRegistry = $registry.Replace("`r`n", "`n").TrimEnd("`r", "`n")
$content = $header + "`n" + $normalizedRegistry + "`n" + $footer.TrimStart("`r", "`n") + "`n"
$outputDirectory = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
[System.IO.File]::WriteAllText(
    $OutputPath,
    $content.Replace("`r`n", "`n"),
    [System.Text.UTF8Encoding]::new($false)
)
