import { createHash } from "node:crypto";
import { readFile, readdir, rm } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, "dist");
const reportPath = resolve(dist, ".forme-build-report.json");
const report = JSON.parse(await readFile(reportPath, "utf8")) as BuildReport;
const site = report.outputs.site;
if (report.schemaVersion !== 1 || report.outcome !== "success" || site?.kind !== "DeployArtifact") {
  throw new Error("Landing Forme build report is missing its successful site artifact");
}
if (site.manifest.assets.length !== 1 || site.manifest.assets[0] === undefined) {
  throw new Error("Landing manifest must contain exactly one asset");
}
if (site.manifest.routes.length !== 1 || site.manifest.routes[0]?.pattern !== "/index.html") {
  throw new Error(`Landing routes differ: ${JSON.stringify(site.manifest.routes)}`);
}
const manifestAsset = site.manifest.assets[0];
if (
  manifestAsset.id !== "01952c0d-7e63-7000-8000-000000000302" ||
  manifestAsset.mime !== "image/jpeg"
) {
  throw new Error(`Landing manifest asset differs: ${JSON.stringify(manifestAsset)}`);
}
const assetFiles = (await readdir(resolve(dist, "assets")))
  .filter(path => /^og\.[0-9a-f]{64}\.jpg$/.test(path));
if (assetFiles.length !== 1 || assetFiles[0] === undefined) {
  throw new Error(`Landing must emit exactly one fingerprinted social image: ${JSON.stringify(assetFiles)}`);
}
const assetPath = `assets/${assetFiles[0]}`;
const assetBytes = await readFile(resolve(dist, assetPath));
const htmlBytes = await readFile(resolve(dist, "index.html"));
const reportFiles = new Map(site.files.map(file => [file.path, file]));
if (reportFiles.size !== 2 || manifestAsset.path !== assetPath) {
  throw new Error("Landing report routes, asset path, or file count differ");
}
const html = htmlBytes.toString("utf8");
const expectedAssetUrl = `/coding-adventures/${assetPath}`;
const requiredFragments = [
  '<meta name="generator" content="Forme">',
  "Generated by Forme",
  expectedAssetUrl,
  'id="paths"',
  'id="labs"',
  'id="forme"',
  "5,003",
  "1,498",
  "62",
  "Preview and watch mode",
];
for (const fragment of requiredFragments) {
  if (!html.includes(fragment)) throw new Error(`Landing HTML is missing ${JSON.stringify(fragment)}`);
}
if (html.includes("forme-asset:") || html.includes("<script")) {
  throw new Error("Landing HTML contains an unresolved asset or unexpected script");
}
const sha256 = createHash("sha256").update(assetBytes).digest("hex");
const htmlSha256 = createHash("sha256").update(htmlBytes).digest("hex");
if (
  !assetPath.includes(sha256) ||
  manifestAsset.sha256 !== sha256 ||
  reportFiles.get(assetPath)?.sha256 !== sha256 ||
  reportFiles.get("index.html")?.sha256 !== htmlSha256
) {
  throw new Error("Landing manifest, report, filenames, and on-disk bytes differ");
}

await rm(reportPath);
console.log(`landing verification: index.html + ${assetPath}`);

interface BuildReport {
  readonly schemaVersion: number;
  readonly outcome: string;
  readonly outputs: {
    readonly site?: {
      readonly kind: string;
      readonly manifest: {
        readonly routes: readonly { readonly pattern: string }[];
        readonly assets: readonly {
          readonly id: string;
          readonly path: string;
          readonly mime: string;
          readonly sha256: string;
        }[];
      };
      readonly files: readonly { readonly path: string; readonly sha256: string | null }[];
    };
  };
}
