<!-- hl-knowledge: introduces=[]; assesses=[ES-LEX-QUERER, ES-GRAMMAR-QUERER-PRESENT-SINGULAR, ES-LEX-HABLAR, ES-LEX-COMER, ES-LEX-VIVIR] -->

