<!-- hl-knowledge: introduces=[RU-GRAMMAR-LI-01]; assesses=[RU-LEX-ILI-01, RU-ETYMON-ILI-I-PLUS-LI, RU-GRAMMAR-ZNAYU-CHTO-01, RU-LEX-ZNAT, RU-LEX-PONIMAT, RU-PUNCT-ZAPYATAYA-01, RU-PUNCT-VOPROS-01, RU-GRAMMAR-NE-NEGATION] -->

