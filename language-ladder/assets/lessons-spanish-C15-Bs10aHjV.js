<!-- hl-knowledge: introduces=[ES-GRAMMAR-IR-PRETERITE-SINGULAR]; assesses=[ES-LEX-VIVIR, ES-GRAMMAR-IR-PRESENT-SINGULAR, ES-LEX-EN] -->

