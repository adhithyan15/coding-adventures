//! Jetpack Compose backend pipeline emitter.

use std::collections::HashMap;
use std::fmt::Write;

use moslayout_compiler::{LayoutDef, LayoutNode, LayoutProp, LayoutPropValue};
use mosmodel_compiler::{
    EmitDecl, EmitPayloadType, ListInnerType, MosmodelComponent, SlotDecl, SlotType,
};
use mosstyle_compiler::{StyleDef, StyleProp};

/// Errors the Compose pipeline emitter can return.
#[derive(Debug)]
pub enum PipelineEmitError {
    UnknownPrimitive(String),
    UnsafeSlotName(String),
    UnsafeEmitName(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the Compose emitter"
            ),
            Self::UnsafeSlotName(n) => write!(f, "unsafe slot name '{n}' (post conversion)"),
            Self::UnsafeEmitName(n) => write!(f, "unsafe emit name '{n}' (post conversion)"),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

/// The result of a successful emission.
#[derive(Debug, Clone)]
pub struct PipelineEmitResult {
    pub output: String,
    pub component_name: String,
}

#[derive(Clone, Copy)]
struct ForPayloadScope<'a> {
    item: &'a str,
    index: Option<&'a str>,
}

/// Emit one Composable function for the three-file triple.
///
/// The `style` argument's `part` blocks are inlined as Jetpack Compose
/// `Modifier` chains attached to layout nodes whose `part_name`
/// matches.  See [`compose_box_style`] for the property→Modifier
/// table.  State blocks (`state X { ... }`) are folded into the chain
/// as nested `if/else` expressions when the matching node carries a
/// `state-when-X: ( expr )` prop — see [`collect_state_layers`] for the
/// predicate-extraction rules.  HostTable column-widths thread into
/// each cell's `.width(columnWidths[_kotlinIdx<idx>].dp)` via
/// [`TableContext`].
pub fn from_pipeline(
    component: &MosmodelComponent,
    layout: &LayoutDef,
    style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    let name = component.component.clone();
    // Defence in depth: validate the component name before we
    // interpolate it into Kotlin identifier positions (sealed class
    // name, function name, event union member, etc.).  The mosmodel
    // grammar already restricts component names to PascalCase ASCII,
    // but re-validating here protects against:
    //   - a grammar regression that admits surprising characters
    //   - a hand-built `MosmodelComponent` struct fed in by test or
    //     fuzz harness code with a hostile name
    validate_safe_identifier(&name).map_err(PipelineEmitError::UnsafeSlotName)?;
    let mut out = String::new();

    writeln!(
        out,
        "// Auto-generated by mosaic-emit-compose. Do not edit."
    )
    .unwrap();
    writeln!(out).unwrap();
    // We don't know the host's package; emit the standard
    // `androidx.compose.*` imports and leave a TODO for the host
    // to add its own package declaration.  In practice the host's
    // build script can prepend `package com.example.foo` before
    // wiring the file into the source set.
    // Build the part-style map ONCE per emission and thread it through
    // the layout walker.  Empty when the `.msl` declares no parts — the
    // no-op path, where every Modifier-chain lookup returns nothing and
    // emission proceeds identically to a styleless pipeline.
    let part_styles = build_part_style_map(style);

    writeln!(out, "import androidx.compose.foundation.background").unwrap();
    writeln!(out, "import androidx.compose.foundation.border").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Box").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Column").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Row").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Spacer").unwrap();
    writeln!(
        out,
        "import androidx.compose.foundation.layout.fillMaxWidth"
    )
    .unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.height").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.padding").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.width").unwrap();
    writeln!(
        out,
        "import androidx.compose.foundation.text.BasicTextField"
    )
    .unwrap();
    writeln!(
        out,
        "import androidx.compose.foundation.text.KeyboardActions"
    )
    .unwrap();
    writeln!(
        out,
        "import androidx.compose.foundation.text.KeyboardOptions"
    )
    .unwrap();
    writeln!(out, "import androidx.compose.material.Button").unwrap();
    writeln!(out, "import androidx.compose.material.Checkbox").unwrap();
    writeln!(out, "import androidx.compose.material.RadioButton").unwrap();
    writeln!(out, "import androidx.compose.material.Text").unwrap();
    writeln!(out, "import androidx.compose.material.TextField").unwrap();
    writeln!(out, "import androidx.compose.runtime.Composable").unwrap();
    writeln!(out, "import androidx.compose.ui.Alignment").unwrap();
    writeln!(out, "import androidx.compose.ui.Modifier").unwrap();
    writeln!(out, "import androidx.compose.ui.graphics.Color").unwrap();
    writeln!(out, "import androidx.compose.ui.text.TextStyle").unwrap();
    writeln!(out, "import androidx.compose.ui.text.font.FontFamily").unwrap();
    writeln!(out, "import androidx.compose.ui.text.input.ImeAction").unwrap();
    writeln!(out, "import androidx.compose.ui.text.input.KeyboardType").unwrap();
    writeln!(out, "import androidx.compose.ui.unit.dp").unwrap();
    writeln!(out, "import androidx.compose.ui.unit.sp").unwrap();
    writeln!(out).unwrap();

    out.push_str(&emit_event_sealed_class(&name, &component.emits)?);
    writeln!(out).unwrap();
    out.push_str(&emit_composable_function(
        &name,
        &component.slots,
        &layout.root,
        &component.emits,
        &part_styles,
    )?);

    Ok(PipelineEmitResult {
        output: out,
        component_name: name,
    })
}

// =====================================================================
// Event sealed class
// =====================================================================

fn emit_event_sealed_class(
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "sealed class {component_name}Event {{").unwrap();
    writeln!(out, "    abstract val mosaicName: String").unwrap();
    writeln!(
        out,
        "    open val mosaicPayload: Map<String, Any?> = emptyMap()"
    )
    .unwrap();
    writeln!(
        out,
        "    val mosaicEnvelope: Map<String, Any?> get() = mapOf(\"event\" to mosaicName) + mosaicPayload"
    )
    .unwrap();
    for e in emits {
        let case = pascalize(&strip_on_prefix(&e.name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        if e.params.is_empty() {
            // Parameterless events are singletons in Kotlin — `data object`
            // is the idiomatic shape and exposes `equals` / `hashCode`
            // automatically.
            writeln!(out, "    data object {case} : {component_name}Event() {{").unwrap();
            writeln!(
                out,
                "        override val mosaicName: String = \"{}\"",
                escape_kotlin_string(&e.name)
            )
            .unwrap();
            writeln!(out, "    }}").unwrap();
        } else {
            let params: Vec<String> = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    let ty = emit_payload_type_to_kotlin(&p.r#type);
                    format!("val {field}: {ty}")
                })
                .collect();
            writeln!(
                out,
                "    data class {case}({params}) : {component_name}Event() {{",
                params = params.join(", ")
            )
            .unwrap();
            writeln!(
                out,
                "        override val mosaicName: String = \"{}\"",
                escape_kotlin_string(&e.name)
            )
            .unwrap();
            let payload_entries = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    format!("\"{}\" to {field}", escape_kotlin_string(&field))
                })
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "        override val mosaicPayload: Map<String, Any?> get() = mapOf({payload_entries})"
            )
            .unwrap();
            writeln!(out, "    }}").unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    Ok(out)
}

// =====================================================================
// Composable function
// =====================================================================

fn emit_composable_function(
    component_name: &str,
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
) -> Result<String, PipelineEmitError> {
    if should_split_root_sections(layout_root) {
        return emit_split_composable_function(
            component_name,
            slots,
            layout_root,
            emits,
            part_styles,
        );
    }

    let mut out = String::new();
    writeln!(out, "@Composable").unwrap();
    writeln!(out, "fun {component_name}(").unwrap();
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        let ty = slot_type_to_kotlin(&s.r#type);
        // Optional slots in the IR become nullable Kotlin types.
        let suffix = if s.required { "" } else { "?" };
        writeln!(out, "    {field}: {ty}{suffix},").unwrap();
    }
    writeln!(out, "    dispatch: ({component_name}Event) -> Unit,").unwrap();
    writeln!(out, ") {{").unwrap();
    out.push_str(&emit_compose_tree(
        layout_root,
        1,
        component_name,
        emits,
        part_styles,
        None,
        None,
        None,
        None,
    )?);
    writeln!(out, "}}").unwrap();
    Ok(out)
}

fn should_split_root_sections(layout_root: &LayoutNode) -> bool {
    matches!(
        layout_root.tag.as_str(),
        "Box"
            | "Row"
            | "Column"
            | "HostTable"
            | "HostTableHead"
            | "HostTableBody"
            | "HostTableFoot"
    ) && layout_root.children.len() > 1
}

fn emit_split_composable_function(
    component_name: &str,
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    let (root_composable, table_context, root_text) =
        root_container_context(layout_root, part_styles);

    writeln!(out, "@Composable").unwrap();
    writeln!(out, "fun {component_name}(").unwrap();
    emit_composable_parameters(&mut out, slots, component_name)?;
    writeln!(out, ") {{").unwrap();

    let frame = emit_container_frame(
        layout_root,
        root_composable,
        1,
        part_styles,
        root_text.as_ref(),
        None,
    );
    out.push_str(&frame.opener);
    let ranges = child_section_ranges(&layout_root.children);
    for (index, _) in ranges.iter().enumerate() {
        write_section_call(&mut out, component_name, index, slots, 2)?;
    }
    out.push_str(&frame.closer);
    writeln!(out, "}}").unwrap();

    for (index, range) in ranges.into_iter().enumerate() {
        writeln!(out).unwrap();
        writeln!(out, "@Composable").unwrap();
        writeln!(out, "private fun {component_name}Section{index}(").unwrap();
        emit_composable_parameters(&mut out, slots, component_name)?;
        writeln!(out, ") {{").unwrap();
        out.push_str(&emit_children_compose(
            &layout_root.children[range],
            1,
            component_name,
            emits,
            part_styles,
            table_context.as_ref(),
            frame.child_text.as_ref(),
            None,
            None,
        )?);
        writeln!(out, "}}").unwrap();
    }

    Ok(out)
}

fn root_container_context<'a>(
    layout_root: &'a LayoutNode,
    part_styles: &'a PartStyleMap,
) -> (&'static str, Option<TableContext>, Option<TextStyleCtx>) {
    match layout_root.tag.as_str() {
        "HostTable" => {
            let ctx = extract_table_context(layout_root);
            let sheet_text = layout_root
                .part_name
                .as_deref()
                .map(|p| sheet_text_style(part_styles, p))
                .unwrap_or_default();
            ("Column", Some(ctx), Some(sheet_text))
        }
        "HostTableHead" | "HostTableBody" | "HostTableFoot" => ("Column", None, None),
        other => match other {
            "Box" => ("Box", None, None),
            "Row" => ("Row", None, None),
            _ => ("Column", None, None),
        },
    }
}

fn child_section_ranges(children: &[LayoutNode]) -> Vec<std::ops::Range<usize>> {
    let mut ranges = Vec::new();
    let mut i = 0;
    while i < children.len() {
        let end = if children[i].tag == "If" && children.get(i + 1).is_some_and(|n| n.tag == "Else")
        {
            i + 2
        } else {
            i + 1
        };
        ranges.push(i..end);
        i = end;
    }
    ranges
}

fn emit_composable_parameters(
    out: &mut String,
    slots: &[SlotDecl],
    component_name: &str,
) -> Result<(), PipelineEmitError> {
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        let ty = slot_type_to_kotlin(&s.r#type);
        // Optional slots in the IR become nullable Kotlin types.
        let suffix = if s.required { "" } else { "?" };
        writeln!(out, "    {field}: {ty}{suffix},").unwrap();
    }
    writeln!(out, "    dispatch: ({component_name}Event) -> Unit,").unwrap();
    Ok(())
}

fn write_section_call(
    out: &mut String,
    component_name: &str,
    index: usize,
    slots: &[SlotDecl],
    depth: usize,
) -> Result<(), PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    writeln!(out, "{pad}{component_name}Section{index}(").unwrap();
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        writeln!(out, "{inner}{field},").unwrap();
    }
    writeln!(out, "{inner}dispatch,").unwrap();
    writeln!(out, "{pad})").unwrap();
    Ok(())
}

// =====================================================================
// Part-style lowering — `.msl` `part` blocks → Compose `Modifier`.
//
// Covers BASE styles AND state-block lowering (`state selected {...}`,
// `state editing {...}`).  When a layout node carries one or more
// `state-when-<name>: ( expr )` props (UI28-1 / Task #35), each state
// block's overriding properties fold into the Modifier chain as nested
// `if (cond) ... else ...` expressions.  Author surface mirrors the
// React + SwiftUI emitters' `state-when-X` mechanism.
//
// The map shape is identical to the SwiftUI emitter's
// `build_part_style_map` (`HashMap<String, Vec<StyleProp>>` keyed by
// part name OR a composite `{part}:{state}` key) so the backends can
// share downstream tooling that walks "which parts have author-declared
// styles?".
// =====================================================================

/// Map from `part` name (or composite `{part}:{state}` key) to its
/// style props.  Built once in [`from_pipeline`] and threaded through
/// the walker.  Base-state entries are keyed by the part name verbatim
/// (`cell`, `header-cell`, `sheet`).  State-block entries are keyed
/// under a composite `{part}:{state}` key (`cell:selected`,
/// `cell:editing`).  Empty when the `.msl` declares no parts — every
/// lookup returns `None` and emission proceeds unchanged.
type PartStyleMap = HashMap<String, Vec<StyleProp>>;

/// Build a `part_name → props` map from a [`StyleDef`].  Mirrors the
/// SwiftUI emitter's `build_part_style_map` — keeps props as
/// `Vec<StyleProp>` (not a pre-rendered string) so we can re-lower per
/// node with the right indentation.
fn build_part_style_map(style: &StyleDef) -> PartStyleMap {
    let mut out = PartStyleMap::with_capacity(style.parts.len());
    for part in &style.parts {
        if !part.base.is_empty() {
            out.insert(part.name.clone(), part.base.clone());
        }
        // State blocks surface under a composite `{part}:{state}` key so
        // [`collect_state_layers`] can look up the matching state-when
        // prop without re-walking `style.parts`.
        for state in &part.states {
            if !state.props.is_empty() {
                let key = format!("{}:{}", part.name, state.state);
                out.insert(key, state.props.clone());
            }
        }
    }
    out
}

