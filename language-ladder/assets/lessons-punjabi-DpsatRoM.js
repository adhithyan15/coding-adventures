<!-- hl-knowledge: introduces=[PA-ETYMON-BHAIN-BHAGA]; assesses=[PA-LEX-BHARA, PA-ETYMON-BHARA-BROTHER, PA-LEX-DOST, PA-LEX-PARIVAR] -->

