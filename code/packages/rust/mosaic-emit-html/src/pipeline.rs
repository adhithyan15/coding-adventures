/// The pieces needed to format a single HTML element of a given primitive.
///
/// Split out so that author-declared part styles (from mosstyle) can be
/// merged with the primitive's built-in inline style before the opening
/// tag is formed.
struct HtmlTag {
    /// The element name without `<>`, e.g. `div`, `span`, `img`.
    tag_name: &'static str,
    /// The built-in inline-style fragment for this primitive — already in
    /// CSS shorthand form, e.g. `display: flex; flex-direction: row`. Empty
    /// for primitives that have no defaults (`Box`, `Text`, `Image`).
    builtin_style: &'static str,
    /// Extra non-style attributes the primitive wants on every element,
    /// e.g. ` class="icon"` for `Icon`. Includes the leading space when
    /// non-empty.
    extra_attrs: &'static str,
    /// `true` for HTML void elements (`<hr>`, `<img>`) which take no
    /// closing tag.
    void: bool,
}

/// Map a moslayout primitive tag to its HTML element + built-in style.
///
/// This table only covers the "trivial container / leaf" primitives —
/// the ones whose entire lowering is *open tag → children → close tag*
/// with no per-prop logic. The primitives that need prop-aware emission
/// (`Image`'s `source`, `HostInput`'s `value` / `placeholder` /
/// `read-only`, `HostButton`'s `label` / `disabled`) are intercepted by
/// `emit_html_tree` before this function is called. The meta-primitives
/// (`If`, `Else`, `For`) and the table sub-tags
/// (`HostTable*`) are likewise handled in `emit_html_tree`.
///
/// Unknown tags return `PipelineEmitError::UnknownPrimitive` — silently
/// rendering `<div>` for an unknown tag would be worse than a clear error.
fn primitive_to_html_tag(tag: &str) -> Result<HtmlTag, PipelineEmitError> {
    Ok(match tag {
        "Box" => HtmlTag {
            tag_name: "div",
            builtin_style: "",
            extra_attrs: "",
            void: false,
        },
        "Row" => HtmlTag {
            tag_name: "div",
            builtin_style: "display: flex; flex-direction: row",
            extra_attrs: "",
            void: false,
        },
        "Column" => HtmlTag {
            tag_name: "div",
            builtin_style: "display: flex; flex-direction: column",
            extra_attrs: "",
            void: false,
        },
        "Text" => HtmlTag {
            tag_name: "span",
            builtin_style: "",
            extra_attrs: "",
            void: false,
        },
        "Image" => HtmlTag {
            tag_name: "img",
            builtin_style: "",
            extra_attrs: "",
            void: true,
        },
        "Spacer" => HtmlTag {
            tag_name: "div",
            builtin_style: "flex: 1",
            extra_attrs: "",
            void: false,
        },
        "Divider" => HtmlTag {
            tag_name: "hr",
            builtin_style: "",
            extra_attrs: "",
            void: true,
        },
        "Icon" => HtmlTag {
            tag_name: "span",
            builtin_style: "",
            extra_attrs: " class=\"icon\"",
            void: false,
        },
        // UI29 §2.1 — `Stack` is the z-axis / overlay container. Children
        // are layered front-to-back at the same flow position; we rely on
        // `position: relative` here so a child's `position: absolute` /
        // `top`/`left` (declared in mosstyle) resolves against the stack.
        "Stack" => HtmlTag {
            tag_name: "div",
            builtin_style: "position: relative",
            extra_attrs: "",
            void: false,
        },
        // UI29 §2.1 — `HostScroll` is the kernel-canonical scroll container.
        // `overflow: auto` lets the browser decide whether to surface
        // scrollbars; the React backend ships the same default.
        "HostScroll" => HtmlTag {
            tag_name: "div",
            builtin_style: "overflow: auto",
            extra_attrs: "",
            void: false,
        },
        // UI31 §3.2 / UI28-1 / U29-D1 — `Col` is the cell-definition
        // sub-tag inside HostTableColGroup. The colgroup walker
        // (above) handles direct Col children specially, but when Col
        // is wrapped in a For (e.g. mosaic-pkg-grid v0.2.0's `For
        // (each: slot: column-widths, as: w) { Col [col] (width: ( w
        // )) }`), the generic walker recurses into the For body and
        // hits Col here as a standalone primitive. `<col>` is HTML's
        // canonical void column-definition element — emit it as a
        // void tag with no built-in style; per-column width comes
        // from the part-style merge if the author bound one.
        "Col" => HtmlTag {
            tag_name: "col",
            builtin_style: "",
            extra_attrs: "",
            void: true,
        },
        other => return Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    })
}

/// Walk a `LayoutNode` and produce the corresponding indented HTML string.
///
/// Behaviour summary:
///
/// - The primitive's built-in style is merged with any author-declared
///   `part` style (looked up by `node.part_name`) into a single
///   `style="..."` attribute. Author wins on collisions — `style="a; b;"`
///   in HTML uses last-property-wins, mirroring CSS specificity.
/// - **Image** primitives read a `source` prop (string literal or slot
///   ref) and emit it as `src="..."`. A slot ref becomes `src="{{slot}}"`.
/// - **Text** primitives read a `content` prop. A slot ref becomes the
///   element's text content as `{{slot}}`; a literal string becomes the
///   element's escaped text content.
/// - **Emit refs** in props produce no attribute but emit a
///   `<!-- emit "<name>" dropped: HTML is static -->` comment immediately
///   before the element.
fn emit_html_tree(
    node: &LayoutNode,
    indent: usize,
    part_styles: &HashMap<String, String>,
) -> Result<String, PipelineEmitError> {
    let pad = " ".repeat(indent);
    let mut out = String::new();

    // Surface dropped emit refs as a comment so the generated HTML is
    // self-documenting — a reviewer can grep for them and see at a glance
    // what the React backend would have wired up.
    for prop in &node.props {
        if let LayoutPropValue::EmitRef(name) = &prop.value {
            writeln!(out, "{pad}<!-- emit \"{name}\" dropped: HTML is static -->").unwrap();
        }
    }

    if node.tag == "HostSurface" {
        out.push_str(&emit_host_surface_html(node, indent, part_styles));
        return Ok(out);
    }

    // ----------------------------------------------------------------
    // Specialised primitives — dispatched before the generic
    // `primitive_to_html_tag` lookup because each carries prop-aware or
    // structural logic that the simple HtmlTag table cannot express.
    // ----------------------------------------------------------------

    // UI29 §3.1 — `For ( each: <list>, as: <name>, index: <name>? )`. The
    // host's template engine resolves the loop at render time.
    if node.tag == "For" {
        out.push_str(&emit_for_node(node, indent, part_styles)?);
        return Ok(out);
    }

    // UI29 §3.2 — `If ( when: <expr> ) { ... } Else { ... }`.
    //
    // The parent walker `emit_children` is the authoritative entry
    // point for If/Else because it has the sibling context — it
    // peeks ahead for a paired `Else` and passes both branches
    // together.  Reaching `emit_html_tree` here means the caller
    // walked a single `If` without going through `emit_children`
    // (a test fixture, for example).  We emit the If branch only
    // and pass `None` for the else branch so the resulting markup
    // is structurally valid.  The intra-sibling case is handled by
    // `emit_children` directly.
    if node.tag == "If" {
        out.push_str(&emit_if_node(node, None, indent, part_styles)?);
        return Ok(out);
    }

    // UI29 §2.1 — `HostTable` and its four structural sub-tags
    // (`HostTableHead`, `HostTableBody`, `HostTableFoot`,
    // `HostTableColGroup`) lower to a semantically correct HTML
    // `<table>`. `HostTable` is the canonical entry point; the sub-tags
    // can also be lowered standalone (e.g. when a future pkg renders a
    // bare `<tbody>` fragment), so we expose them as first-class cases.
    if matches!(
        node.tag.as_str(),
        "HostTable" | "HostTableColGroup" | "HostTableHead" | "HostTableBody" | "HostTableFoot"
    ) {
        out.push_str(&emit_table_node(node, indent, part_styles)?);
        return Ok(out);
    }

    // UI29 §2.1 — `HostInput` and `HostButton`. Both have custom prop
    // shapes (value/placeholder/read-only for input, label/disabled for
    // button) that the simple HtmlTag table cannot express.
    if node.tag == "HostInput" {
        out.push_str(&emit_host_input(node, indent, part_styles));
        return Ok(out);
    }
    if node.tag == "HostButton" {
        out.push_str(&emit_host_button(node, indent, part_styles)?);
        return Ok(out);
    }

    // UI29-2 — `HostCheckbox` and `HostRadio` lower to native
    // `<input type="checkbox|radio">` form controls, optionally wrapped
    // in a `<label>` when a `label:` slot is supplied. Static HTML
    // can't wire `onChange`-style emit handlers (no JS runtime), so
    // emit-typed props become `data-on-*` markers the host's template
    // engine can use to attach handlers after-the-fact. Mirrors how
    // `read-only` and `disabled` are surfaced on `HostInput`/
    // `HostButton`.
    if node.tag == "HostCheckbox" {
        out.push_str(&emit_host_checkbox(node, indent, part_styles));
        return Ok(out);
    }
    if node.tag == "HostRadio" {
        out.push_str(&emit_host_radio(node, indent, part_styles));
        return Ok(out);
    }

    // UI29-4 — `HostLink` lowers to `<a href ...>label</a>`.
    // `target="_blank"` always pairs with `rel="noopener
    // noreferrer"` as a security default (HTML5 living-standard
    // recommendation; same shape the React backend emits).
    if node.tag == "HostLink" {
        out.push_str(&emit_host_link(node, indent, part_styles));
        return Ok(out);
    }
    // UI29-4 — `HostTooltip` wraps its single child in `<span
    // title={text}>...</span>`. The DOM's `title=` attribute is the
    // simplest cross-browser tooltip; rich content is v2.
    if node.tag == "HostTooltip" {
        out.push_str(&emit_host_tooltip(node, indent, part_styles)?);
        return Ok(out);
    }
    // UI29-4 — `HostNumberInput` lowers to `<input type="number"
    // inputmode="numeric" ...>`. The inputmode triggers the mobile
    // numeric keyboard (one of the "what composition loses" items
    // from the UI29-4 survey).
    if node.tag == "HostNumberInput" {
        out.push_str(&emit_host_number_input(node, indent, part_styles));
        return Ok(out);
    }

    // UI29-1 §3.5 — `HostDialog` lowers to HTML's native `<dialog>`
    // element. The browser provides modal blocking, focus trap,
    // top-layer rendering, and Esc-to-close for free; we only need a
    // tiny inline script for `modal: true` (since the bare `open`
    // attribute alone triggers non-modal `show()`) and another for
    // `dismiss-on-backdrop: false` (to swallow the `cancel` event).
    if node.tag == "HostDialog" {
        out.push_str(&emit_host_dialog(node, indent, part_styles)?);
        return Ok(out);
    }

    // UI35 — the drag-and-drop family.
    if node.tag == "HostDraggable" {
        out.push_str(&emit_host_draggable(node, indent, part_styles)?);
        return Ok(out);
    }
    if node.tag == "HostDropTarget" {
        out.push_str(&emit_host_drop_target(node, indent, part_styles)?);
        return Ok(out);
    }

    // `Else` is consumed by its sibling `If`. Reaching it through the
    // tree walk means the moslayout-compiler accepted an orphan `Else`
    // (or a caller invoked `emit_html_tree` on one directly, e.g. in a
    // test). Surface it as an HTML comment rather than erroring, so the
    // generated output stays diagnosable.
    if node.tag == "Else" {
        writeln!(out, "{pad}<!-- mosaic-else (orphan — no preceding If) -->").unwrap();
        return Ok(out);
    }

    let HtmlTag {
        tag_name,
        builtin_style,
        extra_attrs,
        void,
    } = primitive_to_html_tag(&node.tag)?;

    // Merge the built-in style with the author-declared part style. The
    // author's declarations come second so they override on collision.
    let part_style = node
        .part_name
        .as_deref()
        .and_then(|n| part_styles.get(n).map(String::as_str))
        .unwrap_or("");
    let merged_style = merge_styles(builtin_style, part_style);
    let style_attr = if merged_style.is_empty() {
        String::new()
    } else {
        format!(" style=\"{merged_style}\"")
    };

    // Image: source becomes the src attribute.
    let src_attr = if node.tag == "Image" {
        match find_prop(node, "source") {
            Some(LayoutPropValue::SlotRef(s)) => format!(" src=\"{{{{{}}}}}\"", camel(s)),
            Some(LayoutPropValue::String(lit)) => {
                format!(" src=\"{}\"", escape_html_attr(lit))
            }
            _ => String::new(),
        }
    } else {
        String::new()
    };

    if void {
        // HTML5-style void elements (`<hr>`, `<img>`) — no closing tag.
        // We use the unslashed form (HTML5, not XHTML).
        writeln!(out, "{pad}<{tag_name}{extra_attrs}{src_attr}{style_attr}>").unwrap();
        return Ok(out);
    }

    // Text node with a `content: …` prop.  Lowers depending on the
    // prop-value shape:
    //
    //   * `SlotRef(x)`  → `<span>{{x}}</span>` — host's template
    //     engine (or the demo's JS shim) substitutes the camelCased
    //     slot name.
    //   * `String(lit)` → `<span>escaped-literal</span>`.
    //   * `Expr(e)`     → `<span>{{e}}</span>` — same mustache shape
    //     as the slot-ref path so the runtime template engine can
    //     evaluate the expression against the current loop / slot
    //     scope.  Without this case, layouts like the visicalc grid
    //     (which use `Text ( content: ( v ) )` to render a `For`-
    //     loop binding) would lower to an empty `<span></span>` and
    //     the demo would show empty cells.
    //
    //     The expression text passes through `escape_html_text` AND
    //     `escape_mustache_braces` — the second pass turns any
    //     literal `{` / `}` inside the expression into the HTML
    //     entity sequence `&#123;` / `&#125;`.  Without that step, a
    //     STRING literal inside the parsed expression (e.g.
    //     `Text ( content: ( "}}…{{" ) )` — `reconstruct_expr_text`
    //     keeps the STRING's body in the Expr text) could close the
    //     mustache placeholder early and confuse the runtime
    //     template engine.  The HTML browser decodes the entities
    //     back to `{` / `}` after parsing, so the rendered DOM is
    //     visually unchanged on legitimate inputs (which contain
    //     neither brace); the template engine sees the entities in
    //     the raw HTML string and treats them as opaque.
    //   * `Keyword(k)`  → `<span>{{k}}</span>` — a bare NAME in
    //     prop-value position is typically a loop binding or
    //     value keyword; emit the same mustache so the runtime
    //     resolves it.  This was previously dropped to an empty
    //     `<span>` for the same reason as Expr.
    if node.tag == "Text" && node.children.is_empty() {
        match find_prop(node, "content") {
            Some(LayoutPropValue::SlotRef(s)) => {
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{{{{{slot}}}}}</{tag_name}>",
                    slot = camel(s)
                )
                .unwrap();
                return Ok(out);
            }
            Some(LayoutPropValue::String(lit)) => {
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{esc}</{tag_name}>",
                    esc = escape_html_text(lit)
                )
                .unwrap();
                return Ok(out);
            }
            Some(LayoutPropValue::Expr(e)) => {
                // Strip whitespace + outer parens so `( v )` reduces
                // to `v` in the mustache — the runtime expander
                // then resolves the bare identifier in the active
                // loop scope.  Complex expressions (`row.cells`,
                // `r == editRow`) survive the strip and reach the
                // expander as the original text.
                let trimmed = strip_outer_parens(e.trim());
                let safe = escape_mustache_braces(&escape_html_text(trimmed));
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{{{{{e}}}}}</{tag_name}>",
                    e = safe,
                )
                .unwrap();
                return Ok(out);
            }
            Some(LayoutPropValue::Keyword(k)) => {
                // Symmetry with the Expr path — even though the
                // moslayout NAME grammar admits only
                // `[a-zA-Z][a-zA-Z0-9-]*` today (so no braces can
                // sneak in), routing through the same escape
                // discipline keeps the contract identical and
                // future-proofs against grammar widening or
                // programmatically constructed nodes.
                let safe = escape_mustache_braces(&escape_html_text(k));
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{{{{{k}}}}}</{tag_name}>",
                    k = safe
                )
                .unwrap();
                return Ok(out);
            }
            _ => {}
        }
    }

    // Container or empty leaf: emit open + children + close.
    if node.children.is_empty() {
        writeln!(
            out,
            "{pad}<{tag_name}{extra_attrs}{style_attr}></{tag_name}>"
        )
        .unwrap();
        return Ok(out);
    }

    writeln!(out, "{pad}<{tag_name}{extra_attrs}{style_attr}>").unwrap();
    out.push_str(&emit_children(&node.children, indent + 2, part_styles)?);
    writeln!(out, "{pad}</{tag_name}>").unwrap();
    Ok(out)
}

/// Walk a list of sibling children with explicit If/Else pairing.
///
/// When the walker encounters an `If`, it peeks at the next sibling.
/// If that sibling is `Else`, both branches are handed to
/// [`emit_if_node`] (the `else_node` argument), which emits a
/// `<!-- mosaic-if … --> … <!-- mosaic-else --> … <!-- /mosaic-if -->`
/// triple.  Previously the `Else` branch was silently dropped —
/// `emit_if_node` only knew about the `If`, and the parent walker
/// "consumed" the `Else` after it had already been lost.  That made
/// the HTML emitter's static-template output unusable for layouts
/// like the spreadsheet grid (UI28-1), where the `If/Else` carries
/// the "edit vs display" Cell branch.
///
/// Orphan `Else` (an `Else` not preceded by an `If`) flows through
/// `emit_html_tree`, which emits a `<!-- mosaic-else (orphan) -->`
/// diagnostic marker.
fn emit_children(
    children: &[LayoutNode],
    indent: usize,
    part_styles: &HashMap<String, String>,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    let mut i = 0;
    while i < children.len() {
        let child = &children[i];
        if child.tag == "If" {
            // Look ahead for a sibling Else.  If present, hand both
            // branches to `emit_if_node` and advance past both.
            let next_is_else = children
                .get(i + 1)
                .map(|n| n.tag == "Else")
                .unwrap_or(false);
            let else_node = if next_is_else {
                Some(&children[i + 1])
            } else {
                None
            };
            out.push_str(&emit_if_node(child, else_node, indent, part_styles)?);
            i += if next_is_else { 2 } else { 1 };
            continue;
        }
        // Bare Else (no preceding If sibling) falls through to
        // `emit_html_tree`'s orphan-diagnostic path.
        out.push_str(&emit_html_tree(child, indent, part_styles)?);
        i += 1;
    }
    Ok(out)
}

