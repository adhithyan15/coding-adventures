<!-- hl-knowledge: introduces=[ES-GRAMMAR-ORIGIN-WITH-SER]; assesses=[ES-LEX-DE, ES-LEX-DONDE, ES-GRAMMAR-SER-PRESENT-SINGULAR, ES-ORTHOGRAPHY-PUNCTUATION-SPAN] -->

