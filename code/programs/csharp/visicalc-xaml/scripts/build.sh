#!/usr/bin/env bash
#
# build.sh — regenerate the FormulaBar AND Grid XAML triples from
# the Mosaic pipeline and drop them into Generated/.
#
# Per the VisiCalc cross-backend demo plan (Phase 2 / VC2-xaml):
# this is the WinUI 3 / XAML cross-backend demo. The output is two
# triples:
#   - FormulaBar.xaml + FormulaBar.xaml.cs + FormulaBar.Event.cs
#   - Grid.xaml + Grid.xaml.cs + Grid.Event.cs + Grid_*Vm.cs
#     + BoolToVisibilityConverter.cs
# MainWindow.xaml mounts BOTH generated controls — there is no
# hand-written grid anymore. The XAML emitter now lowers the Grid
# from mosaic-pkg-grid (HostTable + nested For + Cell) into valid
# WinUI 3 markup (px-stripped lengths, TextAlignment/FontWeight
# enum values, per-column Width bindings).
#
# Why not --emit-project? The full --emit-project mode generates a
# stand-alone single-component WinUI 3 shell, but we need a multi-
# component layout (FormulaBar + Grid). Plan item [M] (Phase 3 —
# multi-component artifact-builder shells) will extend the
# generator to handle this case; until then, the host shell here
# is hand-authored.
#
# Usage:
#   cd code/programs/csharp/visicalc-xaml
#   bash scripts/build.sh
#
# Then to actually run the app (WinUI 3 SDK / .NET 9 required;
# Windows-only):
#   winget install Microsoft.WindowsAppRuntime.1.7
#   dotnet build
#   dotnet run

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$DEMO_DIR/../../../.." && pwd)"

MOSAIC_COMPILE="$REPO_ROOT/code/packages/rust/target/debug/mosaic-compile"

# Always (re)build mosaic-compile so emitter fixes reach the generated code.
# cargo is incremental, so this is ~free when nothing changed. The old
# `if [ ! -x "$MOSAIC_COMPILE" ]` guard skipped the build whenever ANY stale
# binary already existed, silently serving pre-fix output (this is what hid the
# Compose formula-bar textStyle fix — the demo kept using an old mosaic-compile).
echo "Building mosaic-compile..."
(cd "$REPO_ROOT/code/packages/rust" && cargo build -p mosaic-compile)

SRC="$REPO_ROOT/code/programs/mosaic/visicalc"
OUT_DIR="$DEMO_DIR/Generated"
mkdir -p "$OUT_DIR"

echo "Compiling FormulaBar (XAML)..."
"$MOSAIC_COMPILE" --backend xaml \
  --interface "$SRC/FormulaBar.mil" \
  --layout    "$SRC/FormulaBar.desktop.mll" \
  --style     "$SRC/FormulaBar.dark.msl" \
  -o "$OUT_DIR/FormulaBar"

# Grid — now generated by the XAML emitter. The Grid.desktop.mll
# references `pkg::mosaic-pkg-grid::Grid`, so we must give the
# compiler a `--package-search-path` rooted at code/packages so it
# can locate and inline the package's Grid + Cell + Column triple.
echo "Compiling Grid (XAML)..."
"$MOSAIC_COMPILE" --backend xaml \
  --interface "$SRC/Grid.mil" \
  --layout    "$SRC/Grid.desktop.mll" \
  --style     "$SRC/Grid.dark.msl" \
  --package-search-path "$REPO_ROOT/code/packages" \
  -o "$OUT_DIR/Grid"

echo "Building the spreadsheet engine (Rust → dynamic lib) and vendoring it..."
# The C ABI dynamic library the .NET host P/Invokes (see Engine.cs), built from
# the spreadsheet-capi crate (cdylib) and copied into native/ (git-ignored). On
# Windows the WinUI app needs spreadsheet_capi.dll; on this macOS/Linux checkout
# we vendor the host slice so the cross-platform console test (test/) can run.
RUST="$REPO_ROOT/code/packages/rust"
(cd "$RUST" && cargo build -p spreadsheet-capi --release)
mkdir -p "$DEMO_DIR/native"
case "$(uname -s)" in
  Darwin) LIB="libspreadsheet_capi.dylib" ;;
  *)      LIB="libspreadsheet_capi.so" ;;
esac
cp "$RUST/target/release/$LIB" "$DEMO_DIR/native/$LIB"

echo "Done. Generated controls + vendored engine:"
ls -la "$OUT_DIR"
ls -la "$DEMO_DIR/native"
echo
echo "Verify the engine path (cross-platform, runs on macOS/Linux/Windows):"
echo "  cd $DEMO_DIR && bash scripts/verify.sh"
echo "Run the WinUI app (Windows + .NET 9 + WindowsAppRuntime 1.7 only):"
echo "  cd $DEMO_DIR && dotnet build && dotnet run"
