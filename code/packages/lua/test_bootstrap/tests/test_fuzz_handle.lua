-- The per-execution handle, sentinels and the edge map (VER06p sections 4 and 5.2).
package.path = "../src/?.lua;../src/?/init.lua;" .. package.path
local H = require("helper")
local tb = H.tb
local Fuzz = tb.Fuzz
local Handle, Bitmap, Int = Fuzz.Handle, Fuzz.Bitmap, tb.Int
local I = Int.parse

local function sentinel_of(fn, ...)
  local ok, err = pcall(fn, ...)
  assert.is_false(ok)
  return err
end

local function which_of(sentinel)
  local rec = Handle.sentinel_record(sentinel)
  return rec and rec.which
end

describe("Handle.edge", function()
  it("records reduced edge ids and counts every call", function()
    local h, st = Handle.new(10, 10)
    h:edge(5)
    Handle.edge(h, 5)
    Handle.edge(h, 65536 + 7)
    Handle.edge(h, -1)
    Handle.edge(h, I("18446744073709551621")) -- 2^64 + 5
    assert.are.same({ 5, 7, 65535 }, Handle.edge_list(st))
    assert.are.equal(5, st.edge_calls)
  end)

  it("edge_id is the stable FNV-1a of the label", function()
    assert.is_true(Int.eq(tb.Prng.fnv1a64("entered"), Handle.edge_id("entered")))
    assert.is_false(Int.eq(Handle.edge_id("a"), Handle.edge_id("b")))
    assert.has_error(function() Handle.edge_id(5) end)
  end)

  it("refuses a float or a string id on a live handle", function()
    local h = Handle.new(10, 10)
    assert.has_error(function() h:edge(1.5) end)
    assert.has_error(function() h:edge("1") end)
    assert.has_error(function() h:edge(nil) end)
  end)

  it("a retired, a forged and a retained handle record NO edge (asserted with a valid id, before any bad one)", function()
    local h, st = Handle.new(10, 10)
    h:edge(1)
    Handle.retire(st)
    h:edge(42) -- retired
    Handle.edge(h, 43) -- retained use of the same dead handle
    Handle.edge({}, 44) -- forged
    Handle.edge(setmetatable({}, { __index = h }), 45) -- look-alike
    Handle.edge(nil, 46)
    assert.are.same({ 1 }, Handle.edge_list(st))
    assert.are.equal(1, st.edge_calls)
    -- a second, live handle is untouched by all of it
    local h2, st2 = Handle.new(10, 10)
    h:edge(47)
    assert.are.same({}, Handle.edge_list(st2))
    h2:edge(48)
    assert.are.same({ 48 }, Handle.edge_list(st2))
  end)

  it("the shared metatable is locked and the module is checked and repaired (M2)", function()
    local h = Handle.new(10, 10)
    assert.is_false(getmetatable(h))
    assert.has_error(function() getmetatable(h).__index = {} end)
    assert.is_true(Handle.intact())
    local saved = Handle.tick
    Handle.tick = function() end
    assert.is_false(Handle.intact())
    Handle.repair()
    assert.are.equal(saved, Handle.tick)
    Handle.extra = 1
    assert.is_false(Handle.intact())
    Handle.repair()
    assert.is_nil(Handle.extra)
    assert.is_true(Handle.intact())
  end)

  it("is a no-op on a retired, a forged and a retained handle, whatever the argument", function()
    local h, st = Handle.new(10, 10)
    h:edge(1)
    Handle.retire(st)
    h:edge(2)
    h:edge(1.5) -- not even validated: it is inert
    Handle.edge({}, 3)
    Handle.edge(nil, 3)
    Handle.edge(setmetatable({}, { __index = h }), 3)
    assert.are.same({ 1 }, Handle.edge_list(st))
    assert.are.equal(1, st.edge_calls)
  end)

  it("a handle is an empty table: its state cannot be read through it", function()
    local h = Handle.new(10, 10)
    assert.is_nil(next(h))
    assert.are.equal("#<Fuzz.Handle>", tostring(h))
    assert.is_nil(h.steps)
    assert.is_nil(h.step_budget)
  end)
end)

describe("Handle.tick and Handle.reserve", function()
  it("tick counts one unit by default, n units on request, and n <= 0 counts nothing", function()
    local h, st = Handle.new(10, 10)
    h:tick()
    Handle.tick(h, 3)
    Handle.tick(h, 0)
    Handle.tick(h, -5)
    assert.are.equal(4, st.steps)
  end)

  it("the first breach of the step budget raises a registered sentinel, and keeps raising THE SAME one", function()
    local h, st = Handle.new(2, 100)
    h:tick()
    h:tick()
    local s1 = sentinel_of(Handle.tick, h)
    assert.are.equal("steps", which_of(s1))
    assert.are.equal("steps", Handle.exhausted_which(st))
    assert.is_true(rawequal(s1, sentinel_of(Handle.tick, h)))
    assert.is_true(rawequal(s1, sentinel_of(Handle.tick, h, 0)))
  end)

  it("sticky in BOTH directions: after steps, reserve(0) and reserve(1) raise it", function()
    local h = Handle.new(1, 100)
    h:tick()
    local s = sentinel_of(Handle.tick, h)
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, h, 0)))
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, h, 1)))
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, h, -1)))
  end)

  it("sticky in BOTH directions: after memory, tick(0) and tick(1) raise it", function()
    local h, st = Handle.new(100, 10)
    local s = sentinel_of(Handle.reserve, h, 11)
    assert.are.equal("memory", which_of(s))
    assert.are.equal("memory", Handle.exhausted_which(st))
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, h, 0)))
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, h)))
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, h, 0)))
  end)

  it("the first breach wins: a later breach of the other budget does not replace it", function()
    local h, st = Handle.new(1, 10)
    h:tick()
    local s = sentinel_of(Handle.tick, h)
    assert.is_true(rawequal(s, Handle.breach(st, "memory")))
    assert.are.equal("steps", Handle.exhausted_which(st))
  end)

  it("reserve accumulates up to the budget exactly, ignores non-positive and refuses over", function()
    local h, st = Handle.new(10, 10)
    Handle.reserve(h, 4)
    Handle.reserve(h, 0)
    Handle.reserve(h, -9)
    Handle.reserve(h, 6)
    assert.are.equal(10, st.reserved)
    assert.are.equal("memory", which_of(sentinel_of(Handle.reserve, h, 1)))
  end)

  it("reserve treats a Big as over any budget, and a negative Big as nothing", function()
    local h, st = Handle.new(10, 10)
    Handle.reserve(h, I("-100000000000000000000"))
    assert.are.equal(0, st.reserved)
    assert.are.equal("memory", which_of(sentinel_of(Handle.reserve, h, I("100000000000000000000"))))
  end)

  it("tick(n) over the remaining budget is a breach and leaves the counter alone", function()
    local h, st = Handle.new(5, 10)
    Handle.tick(h, 3)
    assert.are.equal("steps", which_of(sentinel_of(Handle.tick, h, 3)))
    assert.are.equal(3, st.steps)
    -- n = maxinteger cannot overflow the comparison
    local h2 = Handle.new(5, 10)
    assert.are.equal("steps", which_of(sentinel_of(Handle.tick, h2, math.maxinteger)))
  end)

  it("refuse arguments of the wrong type (an ordinary error, never a sentinel)", function()
    local h = Handle.new(5, 5)
    for _, bad in ipairs({ 1.5, "1", true, {} }) do
      local err = sentinel_of(Handle.tick, h, bad)
      assert.is_nil(Handle.sentinel_record(err))
    end
    assert.is_nil(Handle.sentinel_record(sentinel_of(Handle.tick, h, I("100000000000000000000"))))
    for _, bad in ipairs({ 1.5, "1", true, {} }) do
      assert.is_nil(Handle.sentinel_record(sentinel_of(Handle.reserve, h, bad)))
    end
  end)

  it("a zero budget breaches on the first tick and the first positive reserve", function()
    local h = Handle.new(0, 0)
    h:tick(0)
    h:reserve(0)
    assert.are.equal("steps", which_of(sentinel_of(Handle.tick, h)))
    local h2 = Handle.new(0, 0)
    assert.are.equal("memory", which_of(sentinel_of(Handle.reserve, h2, 1)))
  end)
end)

describe("retired, retained and forged handles", function()
  it("tick and reserve on a retired handle raise ONE memoised retired sentinel", function()
    local h, st = Handle.new(10, 10)
    Handle.retire(st)
    local s = sentinel_of(Handle.tick, h)
    assert.are.equal("retired", which_of(s))
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, h, 0)))
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, h, 0)))
    -- and retirement is not an exhaustion
    assert.is_nil(Handle.exhausted_which(st))
  end)

  it("a retired handle is retired even after a budget breach", function()
    local h, st = Handle.new(1, 1)
    h:tick()
    local steps = sentinel_of(Handle.tick, h)
    Handle.retire(st)
    local s = sentinel_of(Handle.tick, h)
    assert.are.equal("retired", which_of(s))
    assert.is_false(rawequal(s, steps))
  end)

  it("a forged handle gets the one process-wide retired sentinel", function()
    local forged = { "not", "a", "handle" }
    local s = sentinel_of(Handle.tick, forged)
    assert.are.equal("retired", which_of(s))
    assert.is_true(rawequal(s, sentinel_of(Handle.reserve, {}, 1)))
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, nil)))
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, 5)))
    -- copying a real handle's metatable does not make a handle
    local h = Handle.new(10, 10)
    local copy = setmetatable({}, { __index = h })
    assert.is_true(rawequal(s, sentinel_of(Handle.tick, copy)))
  end)

  it("a retained handle touches only its own dead state, never a later execution's", function()
    local h1, st1 = Handle.new(10, 10)
    local h2, st2 = Handle.new(10, 10)
    Handle.retire(st1)
    h1:edge(77)
    pcall(h1.tick, h1)
    h2:edge(5)
    assert.are.same({ 5 }, Handle.edge_list(st2))
    assert.are.equal(0, st2.steps)
    assert.is_nil(Handle.exhausted_which(st2))
  end)

  it("sentinels are unique tables recognised by identity: a copy or a look-alike is not one", function()
    local h = Handle.new(1, 1)
    h:tick()
    local s = sentinel_of(Handle.tick, h)
    assert.is_nil(next(s)) -- no fields at all
    assert.is_nil(Handle.sentinel_record({}))
    local copy = setmetatable({}, getmetatable(s))
    assert.is_nil(Handle.sentinel_record(copy))
    assert.is_nil(Handle.sentinel_record("steps"))
    assert.is_nil(Handle.sentinel_record(nil))
    assert.is_nil(Handle.sentinel_record(5))
    assert.is_not_nil(Handle.sentinel_record(s))
  end)

  it("the counters cross-check: a counter over its budget is a breach even with no marker", function()
    local _, st = Handle.new(5, 5)
    assert.is_nil(Handle.over_budget(st))
    st.steps = 6
    assert.are.equal("steps", Handle.over_budget(st))
    st.steps = 0
    st.reserved = 6
    assert.are.equal("memory", Handle.over_budget(st))
  end)

  it("minting a retired sentinel in a loop allocates nothing new", function()
    local h, st = Handle.new(1, 1)
    Handle.retire(st)
    local first = sentinel_of(Handle.tick, h)
    for _ = 1, 100 do
      assert.is_true(rawequal(first, sentinel_of(Handle.tick, h)))
    end
  end)
end)

describe("Bitmap", function()
  it("reduces edge ids with floored mod 65536", function()
    assert.are.equal(0, Bitmap.reduce(0))
    assert.are.equal(65535, Bitmap.reduce(-1))
    assert.are.equal(0, Bitmap.reduce(65536))
    assert.are.equal(5, Bitmap.reduce(I("18446744073709551621")))
    assert.are.equal(65531, Bitmap.reduce(I("-18446744073709551621")))
    assert.are.equal(Int.mod(I("1000000000000000000000000007"), 65536), Bitmap.reduce(I("1000000000000000000000000007")))
    assert.has_error(function() Bitmap.reduce(1.5) end)
    assert.has_error(function() Bitmap.reduce("1") end)
  end)

  it("records, tests, counts, lists ascending, resets", function()
    local b = Bitmap.new()
    b:record(9)
    b:record(3)
    b:record(9 + 65536)
    assert.are.equal(2, b:count())
    assert.is_true(b:has(3))
    assert.is_true(b:has(9 + 65536))
    assert.is_false(b:has(4))
    assert.are.same({ 3, 9 }, b:covered_edges())
    assert.is_truthy(tostring(b):find("edges=2", 1, true))
    b:reset()
    assert.are.equal(0, b:count())
    assert.are.same({}, b:covered_edges())
  end)

  it("admit ORs a trace and reports the novel count", function()
    local b = Bitmap.new()
    local has_new, n = b:admit({ 1, 2, 2, 3 })
    assert.is_true(has_new)
    assert.are.equal(3, n)
    has_new, n = b:admit({ 1, 4 })
    assert.is_true(has_new)
    assert.are.equal(1, n)
    has_new, n = b:admit({ 1, 2 })
    assert.is_false(has_new)
    assert.are.equal(0, n)
    has_new, n = b:admit({})
    assert.is_false(has_new)
  end)

  it("corpus_admit counts UNIQUE novel edges over the UNREDUCED ids", function()
    local a, n = Bitmap.corpus_admit({ 1, 2, 3 }, { 2, 4 })
    assert.is_true(a)
    assert.are.equal(1, n)
    a, n = Bitmap.corpus_admit({ 1, 2, 3 }, { 1, 2 })
    assert.is_false(a)
    assert.are.equal(0, n)
    a, n = Bitmap.corpus_admit({}, { 7, 7, 7, 8 })
    assert.are.equal(2, n)
    -- 1 and 65537 collide in the map but are different edges here
    a, n = Bitmap.corpus_admit({ 1 }, { 65537 })
    assert.is_true(a)
    assert.are.equal(1, n)
    -- a Big edge is keyed by its text and never collides with a native
    local big = I("18446744073709551615")
    a, n = Bitmap.corpus_admit({ big }, { big, -1 })
    assert.are.equal(1, n)
    a, n = Bitmap.corpus_admit({}, { big, I("18446744073709551615") })
    assert.are.equal(1, n)
    assert.has_error(function() Bitmap.corpus_admit({ 1.5 }, {}) end)
    assert.has_error(function() Bitmap.corpus_admit({}, { "x" }) end)
  end)
end)
