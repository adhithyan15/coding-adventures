/// Compile a three-file Mosaic pipeline triple to a static HTML fragment.
///
/// This is the new (UI24-aligned, three-language) HTML entry point.  It
/// supersedes the legacy [`crate::HtmlRenderer`] + [`mosaic_vm::MosaicVM`]
/// flow for components authored in the three-language form.  The legacy
/// path is left untouched.
///
/// The `style` argument is consumed eagerly: the mosstyle parts are
/// flattened into a `part_name -> "css: value; ..."` lookup and inlined
/// onto the matching elements during the tree walk.
pub fn from_pipeline(
    interface: &MosmodelComponent,
    layout: &LayoutDef,
    style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    // Reset the per-call HostDialog id counter so two emits of the same
    // input produce byte-identical output.
    reset_dialog_id_counter();

    // 1. Sanity check: the mosmodel and moslayout files must agree on the
    //    component name. The mosstyle file's name is allowed to differ
    //    (UI23 §4 — styles can target a layout variant).
    if interface.component != layout.component_name {
        return Err(PipelineEmitError::ComponentNameMismatch {
            mosmodel: interface.component.clone(),
            moslayout: layout.component_name.clone(),
        });
    }

    let name = &interface.component;
    let part_styles = build_part_style_map(style);

    // 2. Emit the banner + component-tagged root wrapper. The wrapper
    //    carries `data-mosaic-component="<Name>"` so a hydrator (or a
    //    devtools query) can find every instance of the component on a
    //    page without resorting to class names.
    let mut out = String::new();
    writeln!(
        out,
        "<!-- Auto-generated by mosaic-emit-html (pipeline path). Do not edit. -->"
    )
    .unwrap();
    writeln!(out, "<div data-mosaic-component=\"{name}\">").unwrap();
    out.push_str(&emit_html_tree(&layout.root, 2, &part_styles)?);
    writeln!(out, "</div>").unwrap();

    // The mosmodel `interface` is otherwise unused at this layer — slot
    // values become `{{slotName}}` template tokens during the tree walk,
    // and emits are dropped entirely. Silence the unused warning.
    let _ = interface;

    Ok(PipelineEmitResult {
        output: out,
        component_name: name.clone(),
    })
}

