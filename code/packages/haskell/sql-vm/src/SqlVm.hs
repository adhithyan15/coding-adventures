-- SqlVm.hs — stack-machine bytecode interpreter for the Mini-SQLite Level 1 pipeline.
--
-- This module executes Program values produced by sql-codegen, evaluating them
-- against an InMemoryBackend and returning a QueryResult.
--
-- ┌─────────────────────────────────────────────────────────────────────────┐
-- │  PIPELINE POSITION                                                      │
-- │                                                                         │
-- │  sql-lexer → sql-parser → sql-planner → sql-optimizer → sql-codegen   │
-- │           → [sql-vm] → mini-sqlite                                      │
-- │                                                                         │
-- │  Input : Program (from sql-codegen)                                     │
-- │  Output: QueryResult — columns + rows + rowsAffected                   │
-- └─────────────────────────────────────────────────────────────────────────┘
--
-- ── Execution model ───────────────────────────────────────────────────────
--
-- The VM is a classic stack machine:
--   - A stack holds intermediate SqlValue results.
--   - A program counter (pc) walks through the flat instruction list.
--   - Named labels are pre-indexed into a Map String Int for O(1) jumps.
--   - Cursors are open iterators over backend rows; multiple can be open
--     simultaneously (supporting JOINs).
--   - Aggregate accumulators are indexed maps; the VM initialises them
--     before the scan loop and finalises them after.
--
-- ── Three-valued logic ────────────────────────────────────────────────────
--
-- SQL has three truth values: TRUE, FALSE, and NULL (unknown).
--   - Comparison with NULL yields NULL (not FALSE).
--   - AND: FALSE AND NULL = FALSE; TRUE AND NULL = NULL.
--   - OR:  TRUE  OR  NULL = TRUE;  FALSE OR  NULL = NULL.
--
-- ── State monad ──────────────────────────────────────────────────────────
--
-- We use StateT VmState IO (called VM) so that:
--   - Pure dispatch is written as get/put/modify calls.
--   - IO effects (backend calls, IORef mutation) are embedded via liftIO.
--   - The program counter and stack are part of VmState.
--
-- ── Loop structure ────────────────────────────────────────────────────────
--
-- Every table scan follows the pattern generated by sql-codegen:
--
--   OpenScan "t" alias
--   Label "loop_N"
--   JumpIfExhausted alias "end_N"  ← test exhaustion; jump if done
--   AdvanceCursor alias            ← move to next row
--   <body>
--   Jump "loop_N"
--   Label "end_N"
--   CloseScan alias
--
-- Note: JumpIfExhausted peeks at the next row by calling iteratorNext.
-- The peeked row is immediately stored as the current row so that
-- AdvanceCursor becomes a logical no-op (the row is already available).
-- This matches the F# and Python VM conventions.

