<!-- hl-knowledge: introduces=[]; assesses=[GU-LEX-VICHARVU, GU-LEX-JAANVU, GU-LEX-NUMBERS-ONE-TO-FIVE, GU-ETYMON-TRAN-R-RESTORATION, GU-HISTORY-LEARNED-RESTORATION] -->

