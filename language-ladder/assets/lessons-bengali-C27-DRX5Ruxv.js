<!-- hl-knowledge: introduces=[]; assesses=[BN-LEX-C27-CHOTURTHO-01, BN-GRAMMAR-C27-ORDINAL-TIYO-01, BN-GRAMMAR-C27-ORDINAL-TATSAMA-01, BN-LEX-C27-DITIYO-01, BN-LEX-C27-TRITIYO-01] -->

