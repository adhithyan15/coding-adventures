<!-- hl-knowledge: introduces=[GE-LEX-WIE-VIEL-01, GE-LEX-WIE-VIELE-01]; assesses=[GE-LEX-WIE-02, GE-LEX-MILCH-02, GE-LEX-UHR-01] -->

