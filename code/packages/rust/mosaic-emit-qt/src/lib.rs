//! # mosaic-emit-qt — Qt/QML backend for the Mosaic compiler.
//!
//! This crate is the **Qt** backend for the Mosaic three-language pipeline.
//! It consumes the IR produced by [`mosmodel-compiler`], [`moslayout-compiler`],
//! and [`mosstyle-compiler`] and emits a `.qml` source string describing the
//! component as a tree of Qt Quick elements.
//!
//! ## Why QML (and not C++)
//!
//! Qt has two surface layers a Mosaic backend could target:
//!
//! 1. **QML** — Qt Quick's declarative UI language. Very close in shape to
//!    React/JSX or SwiftUI: a tree of elements with `property` declarations
//!    and `signal` declarations. The QML engine (loaded by `QQmlApplicationEngine`)
//!    handles layout, redraw, and event dispatch.
//! 2. **C++ widgets** — `QWidget` subclasses, `QStyledItemDelegate`, etc.
//!    Imperative, far more boilerplate per primitive, and the layout system
//!    differs sharply from the moslayout flexbox model. UI28 §4.5 sketches
//!    this path for the `Cell`/`Column`/`Grid v3` primitives in a follow-up
//!    PR; this first cut deliberately stays in QML where the surface area
//!    matches the rest of the Mosaic backends.
//!
//! Targeting QML first means the structural translation looks like the
//! React/SwiftUI emitters and the same idea (`for each moslayout node,
//! emit one element`) carries through.
//!
//! ## Output file structure
//!
//! For a component named `ProfileCard` with slots `display-name: text` and
//! `avatar-url: image`, and an emit `onAvatarClick`, this crate produces:
//!
//! ```qml
//! // Auto-generated by mosaic-emit-qt. Do not edit.
//! pragma ComponentBehavior: Bound
//! import QtQuick
//! import QtQuick.Layouts
//!
//! Item {
//!     property string displayName: ""
//!     property url avatarUrl: ""
//!
//!     signal avatarClick()
//!
//!     ColumnLayout {
//!         Text { text: displayName }
//!         Image { source: avatarUrl }
//!     }
//! }
//! ```
//!
//! Three things to notice:
//!
//! 1. The **imports** are versionless Qt 6 modules; generated projects pin the
//!    supported framework floor in CMake.
//! 2. The **root element is always `Item`**. QML files declare exactly one
//!    top-level element, and `Item` is the lightest container that can host
//!    arbitrary properties and signals plus the moslayout root underneath.
//! 3. **Slots become `property` declarations** and **emits become `signal`
//!    declarations.** This is QML's analogue of React's `props` and event
//!    dispatch: a host application that loads the QML file sets the
//!    properties and connects handlers to the signals.
//!
//! ## What is NOT in this first pass
//!
//! - **No `Cell` / `Column` (data) / `Grid v3` lowering** — UI28 §2 introduces
//!   a richer Grid model. The Qt mapping per UI28 §4.5 uses `QStyledItemDelegate`
//!   / `QAbstractTableModel` / `QTableView`, all of which are C++. The QML
//!   equivalent is `TableView` from `QtQuick.Controls`, which is a different
//!   shape. Both are deferred to a follow-up PR that explicitly chooses
//!   between them; see the README for the planned approach.
//! - **No `connects` wiring** — the moslayout `EmitRef` shape is parsed but
//!   not yet attached to JSX-style event handlers in QML. Today a `signal`
//!   is declared but never emitted from the layout tree.
//! - **No style inlining** — the mosstyle `StyleDef` is accepted now so the
//!   public signature is stable, but its properties are not yet inlined into
//!   QML element attributes.
//!
//! Each is a focused, additive follow-up.

