# -- the value table, row by row against the independent reference ---------------------------------------------------


def parse_value(text: str):
    if text == "true":
        return True
    if text == "false":
        return False
    if text == "none":
        return ("none",)
    if text.startswith("some "):
        return ("some", parse_value(text[5:]))
    if text.startswith("x"):
        return bytes.fromhex(text[1:])
    return int(text)


def split_row(row: str):
    left, result = row.split(" = ")
    parts = left.split(" ")
    return parts[0], parts[1], [parse_value(p) for p in parts[2:]], parse_value(result)


def test_the_value_table_has_every_built_in_at_every_width():
    rows = load(VALUES)["rows"]
    seen = {(r.split(" ")[0], r.split(" ")[1].split("->")[0]) for r in rows}
    unsigned = [t for t in ALL if t.startswith("U")]
    signed = [t for t in ALL if t.startswith("I")]
    every = [
        "bit_and", "bit_or", "bit_xor", "bit_not", "shl", "shr", "rotl", "rotr", "bit", "popcount",
        "clz", "ctz", "be_bytes", "le_bytes", "from_be", "from_le", "to_int", "max_value", "min_value",
        "checked_add", "checked_sub", "checked_mul", "wrap", "try", "unwrap_or_checked_add",
    ]  # fmt: skip
    for tag in every:
        for t in ALL:
            assert (tag, t) in seen, (tag, t)
    for tag in ("sar", "div_trunc", "rem_trunc"):
        for t in signed:
            assert (tag, t) in seen and not any((tag, u) in seen for u in unsigned)
    for tag in ("to_nat", "div", "rem"):
        for t in unsigned:
            assert (tag, t) in seen
    for tag in ("div", "rem", "imin", "imax"):
        assert {(tag, f"{a},{b}") for a in ("Nat", "Int") for b in ("Nat", "Int")} <= seen
    assert ("at", "Bytes,Int") in seen and ("at", "Bytes,Nat") in seen
    # widen only where the range is inside the target
    for r in rows:
        if r.startswith("widen "):
            src, dst = r.split(" ")[1].split("->")
            assert span(dst)[0] <= span(src)[0] and span(src)[1] <= span(dst)[1]
