<!-- hl-knowledge: introduces=[]; assesses=[FR-LEX-BONNE-NUIT-11, FR-CULTURE-MERCI-03, FR-LEX-DERIEN-04, FR-GRAM-REGISTER-09, FR-CULTURE-SHRUG-12, FR-LEX-COMMECI-11, FR-LEX-APLUSTARD-03, FR-LEX-ABIENTOT-04, FR-GRAM-A-FAREWELLS-06, FR-LEX-ADEMAIN-05] -->

