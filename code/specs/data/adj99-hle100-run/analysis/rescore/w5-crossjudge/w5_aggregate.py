#!/usr/bin/env python3
"""W5 — cross-judge robustness: Sonnet vs Opus on the SAME 395 normalized traces.

Tests the single-judge caveat from the ADJ99 rescore (#5261): the corrected
defensibility result rested on one Opus judge. Here a second, non-Opus judge
(Sonnet) scores the identical format-normalized, arm-blind traces under the
identical counterfactual rubric. Only the judge model differs, so any
difference is attributable to the judge.

The question: does the corrected headline — fw beats plain at both scales, and
the Opus sign-flip (fw-opus − plain-opus: −0.11 under the old rubric → +0.45
under the new) — REPRODUCE under a different judge?

Reads:
  ../verdicts.json            (Opus, committed on main)
  verdicts_sonnet.json        (Sonnet, this run)
  ../cell_map.json            (join; regenerated by rescore_prep.py)
Run:  python3 w5_aggregate.py
"""
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RESCORE = os.path.abspath(os.path.join(HERE, ".."))
ARMS = ["plain-haiku", "plain-opus", "fw-haiku", "fw-opus"]

cell_map = {c["idx"]: c for c in json.load(open(os.path.join(RESCORE, "cell_map.json")))}
opus = {v["idx"]: v for v in json.load(open(os.path.join(RESCORE, "verdicts.json")))}
sonnet = {v["idx"]: v for v in json.load(open(os.path.join(HERE, "verdicts_sonnet.json")))}

# Only cells both judges scored.
both = sorted(set(opus) & set(sonnet))


def mean(xs):
    xs = [x for x in xs if x is not None]
    return round(sum(xs) / len(xs), 3) if xs else None


# ---- per-arm means under each judge -------------------------------------
rows_by_arm = defaultdict(list)
for idx in both:
    rows_by_arm[cell_map[idx]["arm"]].append(idx)

per_arm = {}
for arm in ARMS:
    idxs = rows_by_arm[arm]
    per_arm[arm] = {
        "n": len(idxs),
        "opus_mean_def": mean([opus[i]["defensibility"] for i in idxs]),
        "sonnet_mean_def": mean([sonnet[i]["defensibility"] for i in idxs]),
        "sonnet_pct_named": round(sum(sonnet[i]["premise_named_by_solution"] for i in idxs) / len(idxs), 3),
        "sonnet_pct_flagged": round(sum(sonnet[i]["premise_flagged_fallible"] for i in idxs) / len(idxs), 3),
        "sonnet_pct_flip": round(sum(sonnet[i]["states_what_would_flip_answer"] for i in idxs) / len(idxs), 3),
    }


def gap(judge_key):
    return {
        "haiku_fw_minus_plain": round(per_arm["fw-haiku"][judge_key] - per_arm["plain-haiku"][judge_key], 3),
        "opus_fw_minus_plain": round(per_arm["fw-opus"][judge_key] - per_arm["plain-opus"][judge_key], 3),
    }


# ---- inter-judge agreement (cell-level) ---------------------------------
diffs = [sonnet[i]["defensibility"] - opus[i]["defensibility"] for i in both]
abs_diffs = [abs(d) for d in diffs]
exact = sum(1 for d in diffs if d == 0)
within1 = sum(1 for d in abs_diffs if d <= 1)

# Pearson correlation of the two 0-5 score vectors.
ov = [opus[i]["defensibility"] for i in both]
sv = [sonnet[i]["defensibility"] for i in both]
n = len(both)
mo, ms = sum(ov) / n, sum(sv) / n
cov = sum((o - mo) * (s - ms) for o, s in zip(ov, sv))
vo = sum((o - mo) ** 2 for o in ov) ** 0.5
vs = sum((s - ms) ** 2 for s in sv) ** 0.5
pearson = round(cov / (vo * vs), 3) if vo and vs else None

# Boolean-field agreement (the mechanism signals).
def bool_agree(field):
    return round(sum(1 for i in both if opus[i][field] == sonnet[i][field]) / n, 3)


summary = {
    "n_cells_both_judges": n,
    "per_arm": per_arm,
    "fw_minus_plain_gap": {
        "opus_judge": gap("opus_mean_def"),
        "sonnet_judge": gap("sonnet_mean_def"),
    },
    "inter_judge_agreement": {
        "exact_match_rate": round(exact / n, 3),
        "within_1_rate": round(within1 / n, 3),
        "mean_abs_diff": round(sum(abs_diffs) / n, 3),
        "mean_signed_diff_sonnet_minus_opus": round(sum(diffs) / n, 3),
        "pearson_r": pearson,
        "bool_agree_premise_named": bool_agree("premise_named_by_solution"),
        "bool_agree_flagged_fallible": bool_agree("premise_flagged_fallible"),
        "bool_agree_would_flip": bool_agree("states_what_would_flip_answer"),
    },
    # The headline robustness verdict, computed mechanically.
    "reproduces": {
        "fw_beats_plain_haiku_both_judges":
            gap("opus_mean_def")["haiku_fw_minus_plain"] > 0 and gap("sonnet_mean_def")["haiku_fw_minus_plain"] > 0,
        "fw_beats_plain_opus_both_judges":
            gap("opus_mean_def")["opus_fw_minus_plain"] > 0 and gap("sonnet_mean_def")["opus_fw_minus_plain"] > 0,
    },
}

with open(os.path.join(HERE, "w5_summary.json"), "w") as f:
    json.dump(summary, f, ensure_ascii=False, indent=2)

print("\n=== W5 cross-judge: Sonnet vs Opus on the same normalized traces ===\n")
hdr = "{:<13} {:>4} {:>10} {:>11} {:>9} {:>8} {:>8}".format(
    "arm", "n", "opus_def", "sonnet_def", "named%", "flag%", "flip%")
print(hdr); print("-" * len(hdr))
for arm in ARMS:
    t = per_arm[arm]
    print("{:<13} {:>4} {:>10} {:>11} {:>9} {:>8} {:>8}".format(
        arm, t["n"], t["opus_mean_def"], t["sonnet_mean_def"],
        t["sonnet_pct_named"], t["sonnet_pct_flagged"], t["sonnet_pct_flip"]))
g = summary["fw_minus_plain_gap"]
print("\nfw - plain gap  OPUS judge : haiku {} / opus {}".format(
    g["opus_judge"]["haiku_fw_minus_plain"], g["opus_judge"]["opus_fw_minus_plain"]))
print("fw - plain gap  SONNET judge: haiku {} / opus {}".format(
    g["sonnet_judge"]["haiku_fw_minus_plain"], g["sonnet_judge"]["opus_fw_minus_plain"]))
a = summary["inter_judge_agreement"]
print("\ninter-judge: exact {} | within-1 {} | mean|d| {} | r {}".format(
    a["exact_match_rate"], a["within_1_rate"], a["mean_abs_diff"], a["pearson_r"]))
print("reproduces fw>plain  haiku:", summary["reproduces"]["fw_beats_plain_haiku_both_judges"],
      "| opus:", summary["reproduces"]["fw_beats_plain_opus_both_judges"])
print("n cells:", n)
