#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProcedureSignaturePlan {
    pub label: String,
    pub param_types: Vec<AlgolType>,
    pub return_type: Option<AlgolType>,
}

impl ProcedureSignaturePlan {
    pub fn param_count(&self) -> usize {
        self.param_types.len()
    }

    pub fn algol_direct(
        label: impl Into<String>,
        parameters: &[ProcedureParameterPlan],
        return_type: Option<AlgolType>,
    ) -> Self {
        let mut param_types = vec![AlgolType::Integer, AlgolType::Integer];
        param_types.extend(parameters.iter().map(|parameter| {
            if parameter.mode == ParameterMode::Name || parameter.kind != ParameterKind::Scalar {
                AlgolType::Integer
            } else {
                parameter.type_name
            }
        }));
        Self {
            label: label.into(),
            param_types,
            return_type,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProcedureDispatcherPlan {
    pub label: String,
    pub signature: ProcedureSignaturePlan,
}

pub fn procedure_parameter_dispatch_label(
    argument_kinds: &[ParameterKind],
    argument_types: &[AlgolType],
    return_type: Option<AlgolType>,
) -> Result<ProcedureDispatcherPlan, LoweringError> {
    if argument_kinds.len() != argument_types.len() {
        return Err(LoweringError::new(
            "procedure parameter dispatch shape is inconsistent",
        ));
    }

    if argument_types.is_empty() && return_type.is_none() {
        return Ok(ProcedureDispatcherPlan {
            label: PROCEDURE_CALL_LABEL.to_string(),
            signature: ProcedureSignaturePlan {
                label: PROCEDURE_CALL_LABEL.to_string(),
                param_types: vec![AlgolType::Integer, AlgolType::Integer],
                return_type: Some(AlgolType::Integer),
            },
        });
    }

    let suffix = argument_kinds
        .iter()
        .copied()
        .zip(argument_types.iter().copied())
        .map(|(kind, type_name)| procedure_parameter_dispatch_type_tag(type_name, kind))
        .collect::<Result<Vec<_>, _>>()?
        .join("_");

    let label = if let Some(return_type) = return_type {
        let return_tag = procedure_parameter_dispatch_type_tag(return_type, ParameterKind::Scalar)?;
        if suffix.is_empty() {
            format!("{PROCEDURE_CALL_LABEL}_{return_tag}_result")
        } else {
            format!("{PROCEDURE_CALL_LABEL}_{return_tag}_result_{suffix}")
        }
    } else {
        format!("{PROCEDURE_CALL_LABEL}_{suffix}")
    };

    let mut param_types = vec![AlgolType::Integer, AlgolType::Integer];
    param_types.extend(argument_types.iter().map(|_| AlgolType::Integer));
    Ok(ProcedureDispatcherPlan {
        signature: ProcedureSignaturePlan {
            label: label.clone(),
            param_types,
            return_type: Some(return_type.unwrap_or(AlgolType::Integer)),
        },
        label,
    })
}

pub fn procedure_parameter_dispatch_type_tag(
    type_name: AlgolType,
    kind: ParameterKind,
) -> Result<&'static str, LoweringError> {
    match kind {
        ParameterKind::Label => Ok("label"),
        ParameterKind::Switch => Ok("switch"),
        ParameterKind::Procedure => {
            if type_name == AlgolType::Procedure {
                Ok("procedure")
            } else {
                Ok(match type_name {
                    AlgolType::Integer => "procedure_i32",
                    AlgolType::Boolean => "procedure_bool",
                    AlgolType::Real => "procedure_f64",
                    AlgolType::String => "procedure_str",
                    AlgolType::Procedure => unreachable!(),
                })
            }
        }
        ParameterKind::Array => Ok(match type_name {
            AlgolType::Integer => "array_i32",
            AlgolType::Boolean => "array_bool",
            AlgolType::Real => "array_f64",
            AlgolType::String => "array_str",
            AlgolType::Procedure => {
                return Err(LoweringError::new(
                    "procedure arrays are not an ALGOL dispatch shape",
                ))
            }
        }),
        ParameterKind::Scalar => type_name.scalar_dispatch_tag(),
    }
}

pub fn procedure_return_type_satisfies(
    expected_type: AlgolType,
    actual_type: Option<AlgolType>,
) -> bool {
    match actual_type {
        None => false,
        Some(AlgolType::Integer) if expected_type == AlgolType::Real => true,
        Some(actual) => expected_type == actual,
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AlgolHelper {
    EvalThunk,
    StoreThunk,
    EvalRealThunk,
    StoreRealThunk,
    EvalLabel,
    EvalSwitch,
    ResolveSwitch,
    CallProcedure,
}

impl AlgolHelper {
    pub fn label(self) -> &'static str {
        match self {
            AlgolHelper::EvalThunk => THUNK_EVAL_LABEL,
            AlgolHelper::StoreThunk => THUNK_STORE_LABEL,
            AlgolHelper::EvalRealThunk => THUNK_EVAL_REAL_LABEL,
            AlgolHelper::StoreRealThunk => THUNK_STORE_REAL_LABEL,
            AlgolHelper::EvalLabel => LABEL_EVAL_LABEL,
            AlgolHelper::EvalSwitch => SWITCH_EVAL_LABEL,
            AlgolHelper::ResolveSwitch => SWITCH_RESOLVE_LABEL,
            AlgolHelper::CallProcedure => PROCEDURE_CALL_LABEL,
        }
    }

    pub fn signature(self) -> ProcedureSignaturePlan {
        let int = AlgolType::Integer;
        match self {
            AlgolHelper::EvalThunk => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int],
                return_type: Some(int),
            },
            AlgolHelper::StoreThunk => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int, int],
                return_type: Some(int),
            },
            AlgolHelper::EvalRealThunk => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int],
                return_type: Some(AlgolType::Real),
            },
            AlgolHelper::StoreRealThunk => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int, AlgolType::Real],
                return_type: Some(int),
            },
            AlgolHelper::EvalLabel => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int],
                return_type: Some(int),
            },
            AlgolHelper::EvalSwitch | AlgolHelper::ResolveSwitch => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int, int],
                return_type: Some(int),
            },
            AlgolHelper::CallProcedure => ProcedureSignaturePlan {
                label: self.label().to_string(),
                param_types: vec![int, int],
                return_type: Some(int),
            },
        }
    }
}

