# frozen_string_literal: true

# extconf.rb — RubyGems install-time hook for the matrix_rust_ruby_native ext
# =============================================================================
#
# When a user runs `gem install coding_adventures_matrix_rust_ruby`, RubyGems
# runs this file from inside `ext/matrix_rust_ruby_native/`, expecting it to
# generate a `Makefile`.  We comply by writing a tiny Makefile that shells
# out to `cargo build -p matrix-rust-ruby-native --release` and then copies
# the resulting shared library into the gem's lib/ directory under the
# name Ruby will `require`.
#
# Differences from conduit_native's extconf.rb:
#
#   * The Rust crate lives at the workspace root
#     (code/packages/rust/matrix-rust-ruby-native/), NOT inside this gem's
#     ext/ directory.  We invoke cargo with `-p matrix-rust-ruby-native`
#     so it picks up the workspace's Cargo.toml automatically.
#   * Target output therefore lives in
#     code/packages/rust/target/release/, not in a gem-local target/.

require "rbconfig"
require_relative "build_config"

# Pick the cargo-side basename (libfoo.dylib / libfoo.so / foo.dll).
dlext = RbConfig::CONFIG["DLEXT"]
cargo_lib = case RbConfig::CONFIG["host_os"]
            when /darwin/
              "libmatrix_rust_ruby_native.dylib"
            when /mingw|mswin|cygwin/
              "matrix_rust_ruby_native.dll"
            else
              "libmatrix_rust_ruby_native.so"
            end

# Ruby will `require "matrix_rust_ruby_native"` — that resolves to
# `matrix_rust_ruby_native.<DLEXT>` on disk.
target = "matrix_rust_ruby_native.#{dlext}"

# `lib_dir`: where the loaded extension lives once installed.  The gem
# `require_relative "matrix_rust_ruby/native_loader"` looks for it next to
# version.rb, so we install it into
# lib/coding_adventures/matrix_rust_ruby/.
lib_dir       = File.expand_path("../../lib/coding_adventures/matrix_rust_ruby", __dir__)
target_dir    = MatrixRustRubyNativeBuildConfig.target_release_dir(File.expand_path(__dir__))
cargo_command = MatrixRustRubyNativeBuildConfig.cargo_make_command

# Cargo's working directory.  Cargo walks up looking for the workspace root,
# so any directory inside the workspace works.  Use the workspace's rust
# package dir for determinism.
cargo_workdir = File.expand_path("../../../../rust", __dir__)

File.write("Makefile", <<~MAKEFILE)
  # Auto-generated by extconf.rb.  Do not edit by hand.
  CARGO_WORKDIR = #{cargo_workdir}
  TARGET_DIR    = #{target_dir}
  CARGO         = #{cargo_command}
  CARGO_LIB     = $(TARGET_DIR)/#{cargo_lib}
  INSTALL_DIR   = #{lib_dir}
  TARGET        = $(INSTALL_DIR)/#{target}

  all: $(TARGET)

  $(TARGET): $(CARGO_LIB)
  \t@mkdir -p $(INSTALL_DIR)
  \tcp $(CARGO_LIB) $(TARGET)

  $(CARGO_LIB):
  \tcd $(CARGO_WORKDIR) && $(CARGO)

  clean:
  \tcd $(CARGO_WORKDIR) && #{MatrixRustRubyNativeBuildConfig.cargo_clean_command.join(" ")}
  \trm -f $(TARGET)

  install: $(TARGET)

  .PHONY: all clean install
MAKEFILE

puts "Makefile generated; will build via `#{cargo_command}`"
