<!-- hl-knowledge: introduces=[]; assesses=[JA-LEX-ANCHOR-KURUMA, JA-LEX-C132-SOTO, JA-SCRIPT-RO-01, JA-LEX-C119-THINGS119-01, JA-LEX-C130-QUAL130-04] -->

