package.path = "../src/?.lua;../src/?/init.lua;" .. package.path

local module = require("coding_adventures.binary_tree")
local BinaryTree = module.BinaryTree
local BinaryTreeNode = module.BinaryTreeNode
local NULL = module.NULL

describe("BinaryTree construction", function()
    it("exposes the package version and empty-tree state", function()
        assert.equals("0.1.0", module.VERSION)
        local tree = BinaryTree.new()
        assert.is_nil(tree.root)
        assert.equals(-1, tree:height())
        assert.equals(0, tree:size())
        assert.is_true(tree:is_full())
        assert.is_true(tree:is_complete())
        assert.is_true(tree:is_perfect())
        assert.are.same({}, tree:inorder())
        assert.are.same({}, tree:level_order())
        assert.are.same({}, tree:to_array())
        assert.equals("", tree:to_ascii())
        assert.equals("BinaryTree(root=nil, size=0)", tostring(tree))
    end)

    it("constructs singleton and explicit-root trees", function()
        local singleton = BinaryTree.singleton("only")
        assert.equals("only", singleton.root.value)

        local root = BinaryTreeNode.new(
            "root",
            BinaryTreeNode.new("left"),
            BinaryTreeNode.new("right")
        )
        local tree = BinaryTree.with_root(root)
        assert.equals(root, tree.root)
        assert.equals("left", tree:left_child("root").value)
        assert.equals("right", tree:right_child("root").value)
    end)

    it("rejects invalid roots, children, and sentinel node values", function()
        assert.has_error(function() BinaryTree.new("root") end, "root must be a BinaryTreeNode or nil")
        assert.has_error(function() BinaryTreeNode.new(nil) end, "node value must not be nil or NULL")
        assert.has_error(function() BinaryTreeNode.new(NULL) end, "node value must not be nil or NULL")
        assert.has_error(function() BinaryTreeNode.new(1, "left") end, "left must be a BinaryTreeNode or nil")
        assert.has_error(function() BinaryTree.from_level_order("nope") end, "values must be a table")
    end)
end)

describe("BinaryTree traversals and lookup", function()
    it("matches the shared traversal vectors", function()
        local tree = BinaryTree.from_level_order({1, 2, 3, 4, NULL, 5, NULL})
        assert.are.same({1, 2, 3, 4, 5}, tree:level_order())
        assert.are.same({1, 2, 4, 3, 5}, tree:preorder())
        assert.are.same({4, 2, 1, 5, 3}, tree:inorder())
        assert.are.same({4, 2, 5, 3, 1}, tree:postorder())
        assert.are.same({1, 2, 3, 4, NULL, 5, NULL}, tree:to_array())
        assert.equals(5, tree:find(5).value)
        assert.is_nil(tree:find(999))
    end)

    it("round-trips a perfect level-order tree", function()
        local values = {1, 2, 3, 4, 5, 6, 7}
        local tree = BinaryTree.from_level_order(values)
        assert.are.same(values, tree:to_array())
        assert.are.same(values, tree:level_order())
    end)

    it("exports the reference helpers", function()
        local root = BinaryTree.from_level_order({1, 2, 3}).root
        assert.equals(2, module.find(root, 2).value)
        assert.equals(1, module.height(root))
        assert.equals(3, module.size(root))
        assert.is_true(module.is_full(root))
        assert.is_true(module.is_complete(root))
        assert.is_true(module.is_perfect(root))
    end)
end)

describe("BinaryTree shape predicates", function()
    it("distinguishes full, complete, and perfect trees", function()
        local tree = BinaryTree.from_level_order({1, 2, NULL})
        assert.is_false(tree:is_full())
        assert.is_true(tree:is_complete())
        assert.is_false(tree:is_perfect())
        assert.equals(1, tree:height())
        assert.equals(2, tree:size())
        assert.equals(2, tree:left_child(1).value)
        assert.is_nil(tree:right_child(1))
    end)

    it("detects an incomplete tree", function()
        local tree = BinaryTree.from_level_order({1, NULL, 3})
        assert.is_false(tree:is_complete())
        assert.is_false(tree:is_full())
    end)

    it("recognizes a perfect tree", function()
        local tree = BinaryTree.from_level_order({"A", "B", "C", "D", "E", "F", "G"})
        assert.is_true(tree:is_full())
        assert.is_true(tree:is_complete())
        assert.is_true(tree:is_perfect())
    end)
end)

describe("BinaryTree rendering", function()
    it("includes every value and structural connector", function()
        local tree = BinaryTree.from_level_order({"root", "left", "right"})
        local rendered = tree:to_ascii()
        assert.is_truthy(rendered:match("`%-%- root"))
        assert.is_truthy(rendered:match("left"))
        assert.is_truthy(rendered:match("right"))
        assert.equals("BinaryTree(root=root, size=3)", tostring(tree))
    end)
end)
