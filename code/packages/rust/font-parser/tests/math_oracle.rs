//! The `MATH` table reader, checked against a real font and an independent
//! implementation.
//!
//! Every expected value below was produced by **fontTools** reading STIX Two
//! Math — not by our parser. That distinction is the whole point. Transcribing
//! ~56 signed values out of a packed binary layout is exactly where a
//! transposition or a wrong stride passes every self-consistent test: a
//! hand-built fixture and a hand-written reader share their author's
//! understanding, so both are wrong together and agree perfectly.
//!
//! This repository has hit that shape four times now — the zstd encoder
//! agreeing with its own decoder, an emitted Vite project asserted as text and
//! never built, Anki fixtures generated by the code they tested, and a PDF
//! writer whose `FlateDecode` was raw deflate. The fixture here is real bytes
//! from a real maths font, and the expectations come from someone else's
//! implementation.
//!
//! See `tests/fixtures/PROVENANCE.md` for the font's origin and licence, and
//! for the command that regenerates these numbers.

/// The raw `MATH` table extracted from STIX Two Math (OFL 1.1).
const STIX_MATH: &[u8] = include_bytes!("fixtures/stix-two-math.MATH");

/// Wrap the bare table in a minimal but genuine OpenType container.
///
/// The public API takes a whole font, and building one here means the table
/// *directory* lookup is exercised too rather than assumed — the offset
/// arithmetic that finds `MATH` is as much a part of this feature as reading it.
///
/// `head` carries the magic number `load` validates; `hhea`, `maxp`, `cmap` and
/// `hmtx` are required by the loader and can be minimal, since nothing here
/// reads them.
fn font_with_math_table() -> Vec<u8> {
    let tags: [&[u8; 4]; 6] = [b"MATH", b"cmap", b"head", b"hhea", b"hmtx", b"maxp"];
    let num_tables = tags.len() as u16;

    // head: 54 bytes, with magicNumber at offset 12 and unitsPerEm at 18.
    let mut head = vec![0u8; 54];
    head[12..16].copy_from_slice(&0x5F0F_3CF5u32.to_be_bytes());
    head[18..20].copy_from_slice(&1000u16.to_be_bytes());
    // indexToLocFormat at 50; 0 = short.
    let hhea = vec![0u8; 36];
    let mut maxp = vec![0u8; 6];
    maxp[4..6].copy_from_slice(&5000u16.to_be_bytes()); // numGlyphs
    let cmap = vec![0u8; 4];
    let hmtx = vec![0u8; 4];

    let bodies: [&[u8]; 6] = [STIX_MATH, &cmap, &head, &hhea, &hmtx, &maxp];

    let directory_len = 12 + 16 * tags.len();
    let mut out = Vec::new();
    out.extend_from_slice(&0x0001_0000u32.to_be_bytes()); // sfntVersion
    out.extend_from_slice(&num_tables.to_be_bytes());
    out.extend_from_slice(&[0u8; 6]); // searchRange, entrySelector, rangeShift

    // Lay the bodies out after the directory, recording each offset as we go —
    // the same discipline the PDF writer uses, and for the same reason.
    let mut offset = directory_len;
    let mut records = Vec::new();
    for body in bodies.iter() {
        records.push((offset as u32, body.len() as u32));
        offset += body.len();
        while !offset.is_multiple_of(4) {
            offset += 1;
        }
    }
    for (index, tag) in tags.iter().enumerate() {
        out.extend_from_slice(*tag);
        out.extend_from_slice(&0u32.to_be_bytes()); // checksum, unchecked
        out.extend_from_slice(&records[index].0.to_be_bytes());
        out.extend_from_slice(&records[index].1.to_be_bytes());
    }
    for body in bodies.iter() {
        out.extend_from_slice(body);
        while !out.len().is_multiple_of(4) {
            out.push(0);
        }
    }
    out
}

#[test]
fn math_constants_match_an_independent_implementation() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).expect("the synthetic container should load");
    assert!(font_parser::has_math_table(&font));

    let c = font_parser::math_constants(&font)
        .expect("MATH table should parse")
        .expect("the font has a MATH table");

    // Every number here came from fontTools, not from us.
    assert_eq!(c.script_percent_scale_down, 70);
    assert_eq!(c.script_script_percent_scale_down, 55);
    assert_eq!(c.delimited_sub_formula_min_height, 1325);
    assert_eq!(c.display_operator_min_height, 1800);
    assert_eq!(c.math_leading, 150);
    assert_eq!(c.axis_height, 258);
    assert_eq!(c.accent_base_height, 480);
    assert_eq!(c.subscript_shift_down, 210);
    assert_eq!(c.superscript_shift_up, 360);
    assert_eq!(c.fraction_numerator_shift_up, 585);
    assert_eq!(c.fraction_denominator_shift_down, 585);
    assert_eq!(c.fraction_rule_thickness, 68);
    assert_eq!(c.radical_vertical_gap, 85);
    assert_eq!(c.radical_rule_thickness, 68);
}

#[test]
fn the_math_value_stride_is_four_bytes_not_two() {
    // The specific bug this whole fixture exists to catch, stated as a test.
    //
    // Almost every MathConstants entry is a MathValue: an int16 followed by an
    // Offset16 device table. Reading them as bare int16 *appears* to work,
    // because the first field really is the value — but it halves the stride,
    // so everything after the first constant is wrong.
    //
    // With a two-byte stride, AxisHeight would read whatever sits at the
    // MathLeading device offset. Asserting the correct values are NOT what a
    // halved stride produces makes the test fail loudly if someone "simplifies"
    // the reader.
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();
    let c = font_parser::math_constants(&font).unwrap().unwrap();

    assert_ne!(
        c.axis_height, c.math_leading,
        "distinct constants collapsing to one value is the signature of a \
         wrong stride"
    );
    assert_eq!(
        c.axis_height, 258,
        "the axis is what every construction centres on"
    );
}

#[test]
fn italic_corrections_match_the_oracle() {
    // fontTools: glyph 1229 (U+2113, script small l) -> 25
    //            glyph 3331 (U+1D453, italic f)      -> 20
    //
    // Italic correction is the gap a slanted glyph needs after it. Without it a
    // subscript set after an italic f collides with the descender — visible, but
    // hard to name, which is why it needs pinning rather than eyeballing.
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();

    assert_eq!(
        font_parser::italic_correction(&font, 1229).unwrap(),
        Some(25)
    );
    assert_eq!(
        font_parser::italic_correction(&font, 3331).unwrap(),
        Some(20)
    );
}

#[test]
fn a_glyph_with_no_entry_reports_none_rather_than_zero() {
    // `None` and `Some(0)` mean the same thing to a typesetter, but they mean
    // different things to a reader debugging one: `None` says the coverage
    // table had no entry, `Some(0)` says it did and the value was zero.
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();
    assert_eq!(font_parser::italic_correction(&font, 0).unwrap(), None);
}

#[test]
fn a_font_without_a_math_table_reports_absence_not_failure() {
    // Most fonts have no MATH table. That is an ordinary property, so the API
    // must distinguish it from a corrupt one — a caller that conflates them
    // silently typesets with default constants and produces output that looks
    // almost right.
    let inter = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../fixtures/fonts/Inter-Regular.ttf");
    if let Ok(bytes) = std::fs::read(&inter) {
        let font = font_parser::load(&bytes).expect("Inter should load");
        assert!(!font_parser::has_math_table(&font));
        assert_eq!(font_parser::math_constants(&font).unwrap(), None);
        assert_eq!(font_parser::italic_correction(&font, 1).unwrap(), None);
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// MathVariants — how a delimiter grows
// ─────────────────────────────────────────────────────────────────────────────
//
// Every value below was read out of STIX Two Math by **fontTools**, the same
// way the constants above were. This is the part TEX-3 needs to make `\left(`
// wrap a tall fraction instead of staying the size of an ordinary parenthesis.
//
// Glyph ids are STIX Two Math's own: 1064 is `parenleft`, 1068 is `braceleft`.

/// A parenthesis has pre-drawn larger glyphs AND an assembly.
///
/// The variants cover the common sizes; the assembly is what builds one taller
/// than the designer drew. A reader that finds only one of the two silently
/// caps how far a delimiter can grow.
#[test]
fn a_parenthesis_has_both_variants_and_an_assembly() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();

    let construction =
        font_parser::glyph_construction(&font, 1064, font_parser::StretchAxis::Vertical)
            .expect("read")
            .expect("parenleft stretches vertically");

    assert_eq!(
        construction.variants.len(),
        13,
        "fontTools reports 13 variants"
    );
    // The first variant is the glyph itself, at its natural height.
    assert_eq!(construction.variants[0].glyph_id, 1064);
    assert_eq!(construction.variants[0].advance, 933);
    assert_eq!(construction.variants[1].glyph_id, 1301);
    assert_eq!(construction.variants[1].advance, 1187);
    // Variants are ordered by increasing size; a renderer picks the first that
    // is big enough, so an unsorted read would pick the wrong one.
    let sizes: Vec<u16> = construction.variants.iter().map(|v| v.advance).collect();
    assert!(
        sizes.windows(2).all(|pair| pair[0] <= pair[1]),
        "variants should increase in size: {sizes:?}"
    );

    // Top piece, repeatable extender, bottom piece.
    assert_eq!(construction.assembly.len(), 3);
    assert_eq!(construction.assembly[0].glyph_id, 4862);
    assert_eq!(construction.assembly[0].start_connector, 0);
    assert_eq!(construction.assembly[0].end_connector, 250);
    assert_eq!(construction.assembly[0].full_advance, 1273);
    assert!(!construction.assembly[0].is_extender);

    assert_eq!(construction.assembly[1].glyph_id, 4861);
    assert!(
        construction.assembly[1].is_extender,
        "the middle piece is what repeats to reach any height"
    );

    assert_eq!(construction.assembly[2].glyph_id, 4860);
    assert_eq!(construction.assembly[2].end_connector, 0);
    assert!(!construction.assembly[2].is_extender);
}

/// A brace assembles from five pieces, not three.
///
/// It has a middle cusp, so the shape is top / extender / middle / extender /
/// bottom. A reader that assumed three parts would draw a brace with no cusp —
/// recognisably wrong, and only for braces.
#[test]
fn a_brace_assembles_from_five_pieces_with_two_extenders() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();

    let construction =
        font_parser::glyph_construction(&font, 1068, font_parser::StretchAxis::Vertical)
            .expect("read")
            .expect("braceleft stretches vertically");

    let ids: Vec<u16> = construction.assembly.iter().map(|p| p.glyph_id).collect();
    assert_eq!(
        ids,
        vec![4874, 4875, 4873, 4875, 4872],
        "top/ext/middle/ext/bottom"
    );

    let extenders: Vec<bool> = construction
        .assembly
        .iter()
        .map(|p| p.is_extender)
        .collect();
    assert_eq!(
        extenders,
        vec![false, true, false, true, false],
        "only the two repeating pieces are extenders"
    );
    assert_eq!(construction.assembly[2].full_advance, 1947, "the cusp");
}

/// Parts must overlap by at least this much, or the seams show.
#[test]
fn the_minimum_connector_overlap_is_read() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();
    assert_eq!(
        font_parser::min_connector_overlap(&font).unwrap(),
        Some(100)
    );
}

/// Asking on the wrong axis returns nothing rather than the wrong construction.
///
/// A `MATH` table keeps the two independently, and `parenleft` grows only
/// vertically. Reading the horizontal array with a vertical index would return
/// a plausible construction for an unrelated glyph.
#[test]
fn a_vertical_only_glyph_has_no_horizontal_construction() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();
    assert_eq!(
        font_parser::glyph_construction(&font, 1064, font_parser::StretchAxis::Horizontal).unwrap(),
        None,
        "parenleft does not stretch sideways"
    );
}

/// An ordinary letter stretches on neither axis.
#[test]
fn a_glyph_with_no_construction_reports_absence() {
    let bytes = font_with_math_table();
    let font = font_parser::load(&bytes).unwrap();
    for axis in [
        font_parser::StretchAxis::Vertical,
        font_parser::StretchAxis::Horizontal,
    ] {
        assert_eq!(
            font_parser::glyph_construction(&font, 1, axis).unwrap(),
            None
        );
    }
}
