<!-- hl-knowledge: introduces=[PA-GRAM-NU-DATIVE]; assesses=[PA-LEX-JI-AAIAN-NU, PA-LEX-AUNA, PA-ETYMON-AUNA-GAM, PA-ETYMON-JI-JIVA, PA-ETYMON-SALAAM-SLM] -->

