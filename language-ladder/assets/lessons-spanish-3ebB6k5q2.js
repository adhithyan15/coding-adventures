<!-- hl-knowledge: introduces=[ES-LEX-NOS-OBJECT, ES-GRAMMAR-NOS-DIRECT-OBJECT]; assesses=[ES-GRAMMAR-QUERER-PRESENT-PLURAL, ES-LEX-QUERER, ES-GRAMMAR-ME-DIRECT-OBJECT] -->

