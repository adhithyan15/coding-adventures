//! Rust emitter — walks a SIR module and produces Rust source code.
//!
//! Layout (per SIR13):
//!
//! ```text
//! // banner
//! #![allow(...)]
//! mod __sir { ... }                              // inlined runtime
//! fn <user_fn>(...) -> __sir::Value { ... }
//! fn main() {
//!     let _ = _init();
//!     let _ = __sir_user_main();
//! }
//! ```
//!
//! Lowering: each SIR node maps to one Rust construct.  See SIR13
//! §"Per-node lowering rules" for the table.

use std::cell::{Cell, RefCell};
use std::collections::HashSet;
use std::fmt::Write;

use semantic_ir::{
    Block, Expr, Function, Global, Module, Scope, Stmt,
};

use crate::runtime::RUNTIME;

thread_local! {
    /// Monotonic per-module loop counter.  `ForRange` caches its `stop`
    /// and `step` into block-scoped temporaries; a fresh id per loop
    /// keeps those temp names unique (and nested loops collision-free).
    /// Reset at the start of every `emit_module` so output stays
    /// deterministic.
    static LOOP_COUNTER: Cell<usize> = const { Cell::new(0) };

    /// Names that are the target of an `Assign` somewhere in the current
    /// function.  A `LetBinding` for such a name must emit `let mut`
    /// (not plain `let`) so the later reassignment compiles.  Populated
    /// per function in `emit_function`; immutable bindings stay `let`.
    static MUTABLE_NAMES: RefCell<HashSet<String>> = RefCell::new(HashSet::new());
}

fn fresh_loop_id() -> usize {
    LOOP_COUNTER.with(|c| {
        let n = c.get();
        c.set(n + 1);
        n
    })
}

/// Emit a SIR module as Rust source.  Caller is responsible for
/// prior validation; this function assumes the module is valid.
pub fn emit_module(m: &Module) -> String {
    LOOP_COUNTER.with(|c| c.set(0));
    let mut out = String::new();
    emit_banner(&mut out, m);
    emit_allows(&mut out);
    out.push_str(RUNTIME);
    emit_globals(&mut out, &m.globals);
    for f in &m.functions {
        out.push('\n');
        emit_function(&mut out, f);
    }
    emit_main(&mut out, m);
    out
}

fn emit_banner(out: &mut String, m: &Module) {
    let _ = writeln!(
        out,
        "// Generated by semantic-ir-to-rust v0.1 from SIR module `{}`.",
        sanitize_comment(&m.name)
    );
    if let Some(lang) = &m.metadata.source_language {
        let _ = writeln!(out, "// Source language: {}", sanitize_comment(lang));
    }
    let _ = writeln!(out, "// Do not edit by hand.");
    out.push('\n');
}

fn emit_allows(out: &mut String) {
    out.push_str("#![allow(non_snake_case, unused_imports, unused_parens, dead_code, unused_variables, unreachable_code, clippy::all)]\n\n");
}

fn emit_globals(out: &mut String, globals: &[Global]) {
    if globals.is_empty() {
        return;
    }
    // Globals are stored in __sir::GLOBALS at runtime.  At Rust
    // module scope we don't declare them statically (no const ctor
    // for our value model); declarations show up as initialisation
    // assignments in _init.  The Global list is informational —
    // backend uses it to know what globals exist for VarRef Global
    // emission.  Nothing to emit here in v0; left as a comment for
    // readers.
    out.push_str("\n// Globals (initialised in _init): ");
    let mut first = true;
    for g in globals {
        if !first {
            out.push_str(", ");
        }
        first = false;
        out.push_str(&sanitize_comment(&g.name));
    }
    out.push('\n');
}

fn emit_main(out: &mut String, m: &Module) {
    out.push('\n');
    out.push_str("fn main() {\n");
    if m.functions.iter().any(|f| f.name == "_init") {
        out.push_str("    let _ = _init();\n");
    }
    if m.functions.iter().any(|f| f.name == "main") {
        // SIR's `main` was renamed to `__sir_user_main` during
        // function emission (Rust's `main` is reserved for the
        // process entry point).  Call it here.
        out.push_str("    let _ = __sir_user_main();\n");
    }
    out.push_str("}\n");
}

// ---------------------------------------------------------------------------
// Functions
// ---------------------------------------------------------------------------

fn emit_function(out: &mut String, f: &Function) {
    let _ = writeln!(out, "// SIR span: {}", sanitize_comment(&f.span.to_string()));
    let _ = write!(out, "fn {}(", function_emit_name(&f.name));

    let mut first = true;
    for c in &f.captures {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{}: __sir::Value", sanitize_ident(&c.name));
    }
    for p in &f.params {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{}: __sir::Value", sanitize_ident(&p.name));
    }
    out.push_str(") -> __sir::Value {\n");

    // Pre-pass: any local that is later reassigned must bind with
    // `let mut`.  Scope is per-function — clear, populate, emit, clear.
    MUTABLE_NAMES.with(|m| {
        let mut set = m.borrow_mut();
        set.clear();
        collect_assigned_locals(&f.body, &mut set);
    });

    emit_function_body(out, &f.body, 1);

    MUTABLE_NAMES.with(|m| m.borrow_mut().clear());
    out.push_str("}\n");
}

/// Walk a block (recursing through nested blocks, loop bodies, and
/// block-bearing expressions) collecting the names targeted by an
/// `Assign` with `Local` scope.  These need `let mut` rather than
/// plain `let`.  Mirrors the TypeScript backend's `const`/`let`
/// tracking pass.
fn collect_assigned_locals(b: &Block, out: &mut HashSet<String>) {
    for s in &b.stmts {
        collect_stmt_assigned(s, out);
    }
    collect_expr_assigned(&b.value, out);
}

fn collect_stmt_assigned(s: &Stmt, out: &mut HashSet<String>) {
    match s {
        Stmt::Assign { name, scope: Scope::Local, value, .. } => {
            out.insert(name.clone());
            collect_expr_assigned(value, out);
        }
        Stmt::Assign { value, .. } => collect_expr_assigned(value, out),
        Stmt::LetBinding { value, .. } | Stmt::LetStarBinding { value, .. } => {
            collect_expr_assigned(value, out);
        }
        Stmt::ExprStmt { expr, .. } => collect_expr_assigned(expr, out),
        Stmt::While { cond, body, .. } => {
            collect_expr_assigned(cond, out);
            collect_assigned_locals(body, out);
        }
        Stmt::ForRange { start, stop, step, body, .. } => {
            collect_expr_assigned(start, out);
            collect_expr_assigned(stop, out);
            collect_expr_assigned(step, out);
            collect_assigned_locals(body, out);
        }
        Stmt::ForEach { iter, body, .. } => {
            collect_expr_assigned(iter, out);
            collect_assigned_locals(body, out);
        }
        // SIR16 Seq/Map indexed assignment: the target, index/key, and
        // value sub-expressions can each hold a nested `Assign` (e.g.
        // `xs[i] = (foo := 1)`), so recurse into all three.
        Stmt::SeqSet { seq, index, value, .. } => {
            collect_expr_assigned(seq, out);
            collect_expr_assigned(index, out);
            collect_expr_assigned(value, out);
        }
        Stmt::MapSet { map, key, value, .. } => {
            collect_expr_assigned(map, out);
            collect_expr_assigned(key, out);
            collect_expr_assigned(value, out);
        }
        // SIR17 nodes are rejected at the capability check for this
        // backend; nothing reachable to collect.
        Stmt::ClassDef { .. }
        | Stmt::ModuleDef { .. }
        | Stmt::SingletonClassDef { .. }
        | Stmt::TryCatch { .. } => {}
    }
}

fn collect_expr_assigned(e: &Expr, out: &mut HashSet<String>) {
    match e {
        Expr::If { cond, then_branch, else_branch, .. } => {
            collect_expr_assigned(cond, out);
            collect_assigned_locals(then_branch, out);
            collect_assigned_locals(else_branch, out);
        }
        Expr::Block(b) => collect_assigned_locals(b, out),
        Expr::DirectCall { args, .. } | Expr::BuiltinCall { args, .. } => {
            for a in args {
                collect_expr_assigned(a, out);
            }
        }
        Expr::IndirectCall { target, args, .. } => {
            collect_expr_assigned(target, out);
            for a in args {
                collect_expr_assigned(a, out);
            }
        }
        Expr::MakeClosure { captures, .. } => {
            for c in captures {
                collect_expr_assigned(&c.value, out);
            }
        }
        Expr::LogicalAnd { lhs, rhs, .. } | Expr::LogicalOr { lhs, rhs, .. } => {
            collect_expr_assigned(lhs, out);
            collect_expr_assigned(rhs, out);
        }
        // SIR16 Seq/Map expressions: recurse into their sub-expressions,
        // any of which could nest an `Assign`.
        Expr::SeqLit { items, .. } => {
            for item in items {
                collect_expr_assigned(item, out);
            }
        }
        Expr::SeqIndex { seq, index, .. } => {
            collect_expr_assigned(seq, out);
            collect_expr_assigned(index, out);
        }
        Expr::SeqLen { seq, .. } => collect_expr_assigned(seq, out),
        Expr::MapLit { entries, .. } => {
            for entry in entries {
                collect_expr_assigned(&entry.key, out);
                collect_expr_assigned(&entry.value, out);
            }
        }
        Expr::MapGet { map, key, .. } => {
            collect_expr_assigned(map, out);
            collect_expr_assigned(key, out);
        }
        // Leaves, and the SIR18 `StrConcat` node (rejected before emit) —
        // nothing nested that could hold a reachable `Assign`.
        Expr::IntLit { .. }
        | Expr::FloatLit { .. }
        | Expr::BoolLit { .. }
        | Expr::NilLit { .. }
        | Expr::SymLit { .. }
        | Expr::StrLit { .. }
        | Expr::VarRef { .. }
        | Expr::Intrinsic { .. }
        | Expr::StrConcat { .. } => {}
    }
}

/// Map a SIR function name to the name it's emitted under in Rust.
///
/// SIR's synthesised `main` clashes with Rust's process-entry
/// `main` — we rename it to `__sir_user_main`.  All other names go
/// through `sanitize_ident`.
fn function_emit_name(name: &str) -> String {
    if name == "main" {
        "__sir_user_main".to_string()
    } else {
        sanitize_ident(name)
    }
}

fn emit_function_body(out: &mut String, b: &Block, indent: usize) {
    let pad = indent_str(indent);
    for s in &b.stmts {
        emit_stmt(out, s, indent);
    }
    let _ = write!(out, "{}", pad);
    emit_expr(out, &b.value, indent);
    out.push('\n');
}

// ---------------------------------------------------------------------------
// Statements
// ---------------------------------------------------------------------------

fn emit_stmt(out: &mut String, s: &Stmt, indent: usize) {
    let pad = indent_str(indent);
    match s {
        Stmt::LetBinding { name, value, .. } | Stmt::LetStarBinding { name, value, .. } => {
            // Parallel-let semantics are already preserved by the
            // frontend (each RHS was lowered in the outer scope);
            // sequential let* is naturally honored by top-down
            // let emission.  A name later re-bound by an `Assign`
            // (SIR16 MutableBindings) must be declared `let mut` so
            // the reassignment compiles; immutable bindings stay `let`.
            let _ = write!(out, "{}{} {}: __sir::Value = ", pad, let_keyword(name), sanitize_ident(name));
            emit_expr(out, value, indent);
            out.push_str(";\n");
        }
        Stmt::ExprStmt { expr, .. } => {
            // Recognise the synthesised _init global_set pattern
            // and lower to a direct __sir::global_set call.
            let _ = write!(out, "{}let _ = ", pad);
            emit_expr(out, expr, indent);
            out.push_str(";\n");
        }
        // ── SIR16 mutation ──────────────────────────────────────────
        // `Assign` re-binds an already-declared name.  Local/Param/
        // Capture all resolve to a bare Rust identifier (the matching
        // `LetBinding`/param was declared `let mut`), so a plain
        // reassignment is faithful.  `Global` writes through the runtime
        // global store rather than a Rust binding.  Instance/ClassVar/
        // Const/Builtin are not in this backend's accepted features, so
        // they fall through to the panic guard below.
        Stmt::Assign {
            name,
            scope: Scope::Local | Scope::Param | Scope::Capture,
            value,
            ..
        } => {
            let _ = write!(out, "{}{} = ", pad, sanitize_ident(name));
            emit_expr(out, value, indent);
            out.push_str(";\n");
        }
        Stmt::Assign { name, scope: Scope::Global, value, .. } => {
            let _ = write!(out, "{}let _ = __sir::global_set(&__sir::intern({}), ", pad, quote_rs_string(name));
            emit_expr(out, value, indent);
            out.push_str(");\n");
        }
        // ── SIR16 loops ─────────────────────────────────────────────
        Stmt::While { cond, body, .. } => emit_while(out, cond, body, indent),
        Stmt::ForRange { var, start, stop, step, body, .. } => {
            emit_for_range(out, var, start, stop, step, body, indent)
        }
        Stmt::ForEach { var, iter, body, .. } => {
            emit_for_each(out, var, iter, body, indent)
        }
        // ── SIR16 indexed assignment (Sequences/Maps) ───────────────
        // `seq[index] = value` mutates the shared backing vector in place
        // via `seq_set`; the returned value is discarded (`let _ = …`).
        Stmt::SeqSet { seq, index, value, .. } => {
            let _ = write!(out, "{}let _ = __sir::seq_set(&(", pad);
            emit_expr(out, seq, indent);
            out.push_str("), &(");
            emit_expr(out, index, indent);
            out.push_str("), ");
            emit_expr(out, value, indent);
            out.push_str(");\n");
        }
        // `map[key] = value` inserts/overwrites via `map_set`.
        Stmt::MapSet { map, key, value, .. } => {
            let _ = write!(out, "{}let _ = __sir::map_set(&(", pad);
            emit_expr(out, map, indent);
            out.push_str("), ");
            emit_expr(out, key, indent);
            out.push_str(", ");
            emit_expr(out, value, indent);
            out.push_str(");\n");
        }
        // An `Assign` to an Instance/ClassVar/Const/Builtin scope: those
        // scopes belong to SIR17 features this backend does not accept
        // (or, for Builtin, are never produced by any frontend), so a
        // validated module never reaches here.
        Stmt::Assign { span, .. } => {
            panic!("rust backend reached an Assign to an unsupported scope at {} — capability check should have rejected it", span);
        }
        // SIR17 (classes) — `Feature::Classes` is not accepted by
        // this backend, so a class-using module is rejected by the
        // capability check before emit.  Reaching this arm is a bug.
        Stmt::ClassDef { span, .. } => {
            panic!("rust backend reached SIR17 class-def statement at {} — capability check should have rejected it", span);
        }
        Stmt::ModuleDef { span, .. } => {
            panic!("rust backend reached SIR17 module-def statement at {} — capability check should have rejected it", span);
        }
        Stmt::SingletonClassDef { span, .. } => {
            panic!("rust backend reached SIR17 singleton-class-def statement at {} — capability check should have rejected it", span);
        }
        Stmt::TryCatch { span, .. } => {
            panic!("rust backend reached SIR17 try-catch statement at {} — capability check should have rejected it", span);
        }
    }
}

// ---------------------------------------------------------------------------
// Expressions
// ---------------------------------------------------------------------------

fn emit_expr(out: &mut String, e: &Expr, indent: usize) {
    match e {
        Expr::IntLit { value, .. } => {
            let _ = write!(out, "__sir::Value::Int({}i64)", value);
        }
        Expr::BoolLit { value, .. } => {
            let _ = write!(out, "__sir::Value::Bool({})", value);
        }
        Expr::NilLit { .. } => out.push_str("__sir::Value::Nil"),
        Expr::SymLit { name, .. } => {
            let _ = write!(out, "__sir::intern({})", quote_rs_string(name));
        }
        Expr::StrLit { value, .. } => {
            let _ = write!(out, "__sir::Value::Str(::std::rc::Rc::from({}))", quote_rs_string(value));
        }
        Expr::VarRef { name, scope, .. } => emit_var_ref(out, name, *scope),
        Expr::If { cond, then_branch, else_branch, .. } => {
            out.push_str("(if __sir::truthy(&(");
            emit_expr(out, cond, indent);
            out.push_str(")) { ");
            emit_block_as_expr(out, then_branch, indent);
            out.push_str(" } else { ");
            emit_block_as_expr(out, else_branch, indent);
            out.push_str(" })");
        }
        Expr::Block(b) => emit_block_as_expr(out, b, indent),
        Expr::DirectCall { fn_name, args, .. } => {
            let _ = write!(out, "{}(", function_emit_name(fn_name));
            emit_args(out, args, indent);
            out.push(')');
        }
        Expr::IndirectCall { target, args, .. } => {
            out.push_str("__sir::apply_closure(&(");
            emit_expr(out, target, indent);
            out.push_str("), vec![");
            emit_args(out, args, indent);
            out.push_str("])");
        }
        Expr::BuiltinCall { name, args, .. } => emit_builtin_call(out, name, args, indent),
        Expr::MakeClosure { fn_name, captures, .. } => {
            emit_make_closure(out, fn_name, captures, indent);
        }
        Expr::Intrinsic { name, span, .. } => {
            // v0 backend accepts no intrinsics; check_module
            // rejects them before reaching emit.  Defensive panic
            // covers internal bugs only (emit::* is crate-private).
            panic!(
                "emit reached an Intrinsic `{}` at {} — backend should have rejected it",
                name, span
            );
        }
        // ── SIR16: floats ──────────────────────────────────────────
        // Emit a `Value::Float` constructor.  `{:?}` renders an f64 as
        // a round-trippable decimal that is *also* a valid Rust float
        // literal — crucially it keeps the trailing `.0` on integral
        // values (`3.0`, not `3`), so the literal can never be mistaken
        // for an `i64`.  Non-finite values have no literal spelling, so
        // we route them through the `f64::` associated constants.
        Expr::FloatLit { value, .. } => emit_float_literal(out, *value),
        // ── SIR16: short-circuit logical ───────────────────────────
        // A block with a fresh `__l` binding evaluates `lhs` exactly
        // once, then decides whether to evaluate `rhs` — routing the
        // test through SIR truthiness (only `false`/`nil` are falsy).
        // `and` yields `rhs` when `lhs` is truthy else `lhs`; `or` is
        // the mirror.  The `__l` binding is block-scoped, so nested
        // `&&`/`||` shadow cleanly and never collide.  Matches the
        // TypeScript backend's truthy-guarded arrow IIFE semantics.
        Expr::LogicalAnd { lhs, rhs, .. } => {
            out.push_str("({ let __l = (");
            emit_expr(out, lhs, indent);
            out.push_str("); if __sir::truthy(&__l) { (");
            emit_expr(out, rhs, indent);
            out.push_str(") } else { __l } })");
        }
        Expr::LogicalOr { lhs, rhs, .. } => {
            out.push_str("({ let __l = (");
            emit_expr(out, lhs, indent);
            out.push_str("); if __sir::truthy(&__l) { __l } else { (");
            emit_expr(out, rhs, indent);
            out.push_str(") } })");
        }
        // ── SIR16: sequences ───────────────────────────────────────
        // `SeqLit` builds a fresh shared sequence from its items via the
        // runtime `seq_lit` helper; `SeqIndex`/`SeqLen` read through
        // `seq_index`/`seq_len`.  All keep the `Value` model — the seq is
        // boxed, so a `VarRef` to it clones the shared `Rc` handle.
        Expr::SeqLit { items, .. } => {
            out.push_str("__sir::seq_lit(vec![");
            emit_args(out, items, indent);
            out.push_str("])");
        }
        Expr::SeqIndex { seq, index, .. } => {
            out.push_str("__sir::seq_index(&(");
            emit_expr(out, seq, indent);
            out.push_str("), &(");
            emit_expr(out, index, indent);
            out.push_str("))");
        }
        Expr::SeqLen { seq, .. } => {
            out.push_str("__sir::seq_len(&(");
            emit_expr(out, seq, indent);
            out.push_str("))");
        }
        // ── SIR16: maps ────────────────────────────────────────────
        // `MapLit` builds an insertion-ordered map from `(key, value)`
        // pairs; `MapGet` reads through `map_get` (missing key ⇒ `Nil`).
        Expr::MapLit { entries, .. } => {
            out.push_str("__sir::map_lit(vec![");
            for (i, entry) in entries.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                out.push('(');
                emit_expr(out, &entry.key, indent);
                out.push_str(", ");
                emit_expr(out, &entry.value, indent);
                out.push(')');
            }
            out.push_str("])");
        }
        Expr::MapGet { map, key, .. } => {
            out.push_str("__sir::map_get(&(");
            emit_expr(out, map, indent);
            out.push_str("), &(");
            emit_expr(out, key, indent);
            out.push_str("))");
        }
        // The only remaining unsupported expression is `StrConcat`
        // (SIR18 string interpolation).  Its feature is undeclared, so
        // the capability check rejects such modules before emit; reaching
        // this arm is an internal bug.
        Expr::StrConcat { span, .. } => {
            panic!("rust backend reached SIR18 str-concat expression at {} — capability check should have rejected it", span);
        }
    }
}

fn emit_var_ref(out: &mut String, name: &str, scope: Scope) {
    match scope {
        Scope::Local | Scope::Param | Scope::Capture => {
            let _ = write!(out, "{}.clone()", sanitize_ident(name));
        }
        Scope::Global => {
            let _ = write!(out, "__sir::global_get_static({})", quote_rs_string(name));
        }
        Scope::Builtin => {
            let _ = write!(out, "__sir::builtin_closure({})", quote_rs_string(name));
        }
        Scope::Instance => {
            // SIR17 Phase 15a — `Feature::InstanceVars` is not accepted
            // by this backend; instance-var-using modules are rejected
            // at the capability check before emit.  Unreachable.
            panic!("rust backend reached SIR17 instance-var ref `{}` — capability check should have rejected it", name);
        }
        Scope::ClassVar => {
            // SIR17 Phase 15b — `Feature::ClassVars` likewise unaccepted;
            // class-var modules are rejected before emit.  Unreachable.
            panic!("rust backend reached SIR17 class-var ref `{}` — capability check should have rejected it", name);
        }
        Scope::Const => {
            // SIR17 Phase 15c — `Feature::Constants` likewise unaccepted;
            // constant-using modules are rejected before emit.  Unreachable.
            panic!("rust backend reached SIR17 const ref `{}` — capability check should have rejected it", name);
        }
    }
}

fn emit_args(out: &mut String, args: &[Expr], indent: usize) {
    for (i, a) in args.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        emit_expr(out, a, indent);
    }
}

fn emit_builtin_call(out: &mut String, name: &str, args: &[Expr], indent: usize) {
    // Variadic helpers take a Vec<Value>; fixed-arity helpers take
    // positional Value arguments.  This matches the inlined runtime
    // signatures.
    let (helper, variadic) = match name {
        "+" => ("__sir::plus", true),
        "-" => ("__sir::minus", true),
        "*" => ("__sir::times", true),
        "/" => ("__sir::divide", true),
        "=" => ("__sir::eq", false),
        "<" => ("__sir::lt", false),
        ">" => ("__sir::gt", false),
        "cons" => ("__sir::cons", false),
        "car" => ("__sir::car", false),
        "cdr" => ("__sir::cdr", false),
        "null?" => ("__sir::is_null", false),
        "pair?" => ("__sir::is_pair", false),
        "number?" => ("__sir::is_number", false),
        "symbol?" => ("__sir::is_symbol", false),
        "print" => ("__sir::print", false),
        "global_set" => ("__sir::global_set_call", false),
        "global_get" => ("__sir::global_get_call", false),
        _ => {
            // Unknown name → dispatch by name (forward-compat).
            let _ = write!(out, "__sir::call_builtin_by_name({}, vec![", quote_rs_string(name));
            emit_args(out, args, indent);
            out.push_str("])");
            return;
        }
    };
    if name == "global_set" {
        // Two args; pass first by reference, second by value.
        out.push_str("(__sir::global_set(&(");
        if args.len() >= 1 {
            emit_expr(out, &args[0], indent);
        }
        out.push_str("), ");
        if args.len() >= 2 {
            emit_expr(out, &args[1], indent);
        } else {
            out.push_str("__sir::Value::Nil");
        }
        out.push_str("))");
        return;
    }
    if name == "global_get" {
        out.push_str("__sir::global_get(&(");
        if !args.is_empty() {
            emit_expr(out, &args[0], indent);
        }
        out.push_str("))");
        return;
    }
    if variadic {
        let _ = write!(out, "{}(vec![", helper);
        emit_args(out, args, indent);
        out.push_str("])");
    } else {
        let _ = write!(out, "{}(", helper);
        emit_args(out, args, indent);
        out.push(')');
    }
}

fn emit_make_closure(
    out: &mut String,
    fn_name: &str,
    captures: &[semantic_ir::CaptureValue],
    indent: usize,
) {
    // Lower:
    //   let __cap_<n0>: __sir::Value = <v0>;
    //   let __cap_<n1>: __sir::Value = <v1>;
    //   __sir::Value::Closure(Rc::new(__sir::Closure {
    //     fun: Box::new(move |__args: Vec<__sir::Value>| {
    //         let mut __it = __args.into_iter();
    //         <fn_name>(__cap_<n0>.clone(), __cap_<n1>.clone(),
    //                   __it.next().unwrap_or(__sir::Value::Nil),
    //                   ... )
    //     })
    //   }))
    //
    // The capture *bindings* live in an outer block; the closure
    // body sees them via move-capture so they survive after the
    // outer block ends.
    out.push_str("{\n");
    let pad = indent_str(indent + 1);
    let mut cap_names: Vec<String> = Vec::with_capacity(captures.len());
    for c in captures {
        let bind = format!("__cap_{}", sanitize_ident(&c.name));
        cap_names.push(bind.clone());
        let _ = write!(out, "{}let {}: __sir::Value = ", pad, bind);
        emit_expr(out, &c.value, indent + 1);
        out.push_str(";\n");
    }
    let _ = write!(
        out,
        "{}__sir::Value::Closure(::std::rc::Rc::new(__sir::Closure {{ fun: Box::new(move |__args: Vec<__sir::Value>| {{\n",
        pad
    );
    let inner_pad = indent_str(indent + 2);
    let _ = write!(out, "{}let mut __it = __args.into_iter();\n", inner_pad);
    let _ = write!(out, "{}{}(", inner_pad, function_emit_name(fn_name));
    let mut first = true;
    for n in &cap_names {
        if !first {
            out.push_str(", ");
        }
        first = false;
        let _ = write!(out, "{}.clone()", n);
    }
    // Then the runtime args (param count is unknown at emit-time
    // here without looking up the function, so we drain the
    // iterator via `unwrap_or(Nil)` for *each known param*.
    // Since the lowerer pairs MakeClosure with a Function in the
    // module, the emitter could fetch param count from the
    // module — but emit_expr doesn't currently have that handle.
    // For v0 we conservatively emit ".collect()" and pass the
    // full Vec as the variadic tail — but our generated functions
    // are not variadic.
    //
    // Pragmatic alternative: emit args.len()-many `unwrap_or` calls
    // by querying the function's params via a separate pass.  For
    // now, we rely on the assumption that closures' params match
    // the lambda's params and pass them through positional pops.
    //
    // To support this without plumbing the module reference
    // through, we encode the param count in the closure body
    // dynamically using a fallback: each arg is fetched via
    // `__it.next().unwrap_or(__sir::Value::Nil)` and we emit
    // as many as the runtime captures vec.  But MakeClosure does
    // NOT carry the function's param count.
    //
    // Solution: emit a single splat — convert __args into a Vec
    // and call the function with captures-first + args-spread via
    // a helper.  But Rust doesn't support runtime function arg
    // spread for ordinary fns; functions have fixed arity.
    //
    // Therefore the emitter MUST know the param count.  We pass
    // it through by querying the module-level function table at
    // higher level.  See emit_module for the wiring.
    //
    // Fallback for the case where we can't resolve: emit one
    // unwrap_or per arg up to a fixed cap.  Twig closures
    // realistically have ≤ 8 params; we pad with Nil and call
    // the function which will ignore the unused ones... no, Rust
    // requires exact arity.
    //
    // We thread the param count through via a side channel: the
    // module-level function table is built before emit_module
    // iterates, and the MakeClosure emitter consults it.

    // The actual implementation below uses a TLS to thread the
    // param count.  See the wrapper `emit_module_with_fn_arity`.
    let arity = FN_ARITY.with(|t| t.borrow().get(fn_name).copied().unwrap_or(0));
    for _ in 0..arity {
        if !first {
            out.push_str(", ");
        }
        first = false;
        out.push_str("__it.next().unwrap_or(__sir::Value::Nil)");
    }
    out.push_str(")\n");
    let _ = write!(out, "{}}}) }}))\n", pad);
    let _ = write!(out, "{}}}", indent_str(indent));
}

// Thread-local function arity table.  Populated by
// emit_module_with_arity_table before walking expressions so that
// MakeClosure can emit the right number of positional arg drains
// in the closure body.
thread_local! {
    static FN_ARITY: std::cell::RefCell<std::collections::HashMap<String, usize>> =
        std::cell::RefCell::new(std::collections::HashMap::new());
}

/// Wrap a call to `emit_module` so that `MakeClosure` can resolve
/// each lambda's parameter count.  Public for direct use; the
/// crate-level `compile` entry point routes through here.
pub fn emit_module_with_arity_table(m: &Module) -> String {
    FN_ARITY.with(|t| {
        let mut t = t.borrow_mut();
        t.clear();
        for f in &m.functions {
            t.insert(f.name.clone(), f.params.len());
        }
    });
    let out = emit_module(m);
    FN_ARITY.with(|t| t.borrow_mut().clear());
    out
}

fn emit_block_as_expr(out: &mut String, b: &Block, indent: usize) {
    if b.stmts.is_empty() {
        emit_expr(out, &b.value, indent);
        return;
    }
    out.push_str("{ ");
    for s in &b.stmts {
        emit_stmt_inline(out, s, indent + 1);
    }
    emit_expr(out, &b.value, indent + 1);
    out.push_str(" }");
}

