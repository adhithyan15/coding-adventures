<!-- hl-knowledge: introduces=[JA-SCRIPT-SMALL-YU-01]; assesses=[JA-SCRIPT-YU-01, JA-SCRIPT-SMALL-TSU-01, JA-SCRIPT-SHI-01, JA-SCRIPT-DAKUTEN-01] -->

