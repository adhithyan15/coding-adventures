/// The result of compiling a three-file pipeline triple to React TSX.
///
/// Mirrors the legacy [`mosaic_vm::EmitResult`] so downstream code can treat
/// both paths uniformly.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PipelineEmitResult {
    /// The complete TSX source.
    pub output: String,
    /// The component's PascalCase name (matches the source `.mil` /`.mll` files).
    pub component_name: String,
}

/// Errors the pipeline emitter can return.
///
/// These are diagnostic strings rather than rich values; the calling CLI is
/// expected to print them verbatim, so embedding context (slot name, etc.)
/// directly in the message is the simplest interface.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PipelineEmitError {
    /// The mosmodel component name and the moslayout component name disagree.
    /// This is almost always a manifest authoring error.
    ComponentNameMismatch {
        mosmodel: String,
        moslayout: String,
    },
    /// A slot name fails the safe-JS-identifier check after camelCase conversion.
    /// Should never happen in practice because mosmodel grammar restricts slot
    /// names to kebab-case `[a-z][a-z0-9]*(-[a-z][a-z0-9]*)*`, but we double
    /// check at lowering time as a defense-in-depth measure (UI24 §8).
    UnsafeSlotName(String),
    /// An emit name fails the same safe-JS-identifier check.
    UnsafeEmitName(String),
    /// An emit's lowered `type` literal collides with a reserved React prop
    /// name. Per UI24 §5.1, these are `dispatch`, `children`, and `key`.
    ReservedEmitName(String),
    /// A moslayout primitive tag is not recognised by the React backend.
    /// First-pass limitations: see the module-level "What is NOT in this
    /// first pass" section.
    UnknownPrimitive(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PipelineEmitError::ComponentNameMismatch { mosmodel, moslayout } => write!(
                f,
                "component name mismatch: mosmodel says '{mosmodel}', moslayout says '{moslayout}'"
            ),
            PipelineEmitError::UnsafeSlotName(n) => {
                write!(f, "unsafe slot name '{n}' (post camelCase conversion)")
            }
            PipelineEmitError::UnsafeEmitName(n) => {
                write!(f, "unsafe emit name '{n}' (post conversion)")
            }
            PipelineEmitError::ReservedEmitName(n) => write!(
                f,
                "emit '{n}' lowers to a reserved React prop name (dispatch/children/key)"
            ),
            PipelineEmitError::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the pipeline React emitter"
            ),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

/// Compile a three-file Mosaic pipeline triple to a React TSX file.
///
/// This is the new (UI24-compliant) React backend entry point. It supersedes
/// the [`crate::ReactRenderer`] + [`mosaic_vm::MosaicVM`] flow for code paths
/// that author components in the three-language form.
///
/// The `style` argument is accepted now (rather than added later) so that
/// downstream callers can build against the stable signature. It is not yet
/// inlined into the JSX; see the module-level "What is NOT in this first
/// pass" section.
pub fn from_pipeline(
    interface: &MosmodelComponent,
    layout: &LayoutDef,
    style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    // 1. Sanity check: the three IRs must agree on the component name.
    if interface.component != layout.component_name {
        return Err(PipelineEmitError::ComponentNameMismatch {
            mosmodel: interface.component.clone(),
            moslayout: layout.component_name.clone(),
        });
    }
    // The style IR's name is allowed to differ when the style targets a
    // specific layout variant (UI23 §4) — there is no constraint to enforce
    // here yet, so we accept it and reference it via `_` to silence the
    // unused-variable warning.
    let _ = style;

    let name = &interface.component;
    let mut out = String::new();

    // 2. File header.
    writeln!(out, "// Auto-generated by mosaic-emit-react. Do not edit.").unwrap();
    writeln!(out, "import React from \"react\";").unwrap();
    writeln!(out).unwrap();

    // 3. Event union (UI24 §3.1).
    out.push_str(&emit_event_union(name, &interface.emits)?);
    writeln!(out).unwrap();

    // 4. Props interface with the required `dispatch` prop (UI24 §3.2).
    out.push_str(&emit_props_interface(name, &interface.slots)?);
    writeln!(out).unwrap();

    // 5. Function declaration (UI24 §3.3).
    out.push_str(&emit_function(name, &interface.slots, &layout.root)?);

    // 6. Reference the unused `React` import via a comment block so that the
    // simplest emitted file (e.g., a zero-emit zero-primitive component)
    // does not produce a TS6133 "React is declared but not used" warning.
    // Real components reference React via JSX implicitly; this placeholder
    // is a no-op for the common case.

    Ok(PipelineEmitResult {
        output: out,
        component_name: name.clone(),
    })
}

