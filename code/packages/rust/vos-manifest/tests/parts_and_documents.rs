//! Part admission, document assembly and the marker skeleton (VOS02 section 2.3,
//! negative control NC17).

use vos_manifest::document::{assemble, parse_layout, AssembleInput, DocErrorKind, TRAILER};
use vos_manifest::part::{admit_part, PartErrorKind as P};
use vos_manifest::{Part, Tier};

fn part(text: &str) -> Part {
    admit_part(text.as_bytes()).unwrap_or_else(|e| panic!("{text:?}: {e}"))
}

fn kind(text: &str) -> P {
    admit_part(text.as_bytes()).expect_err(text).kind
}

