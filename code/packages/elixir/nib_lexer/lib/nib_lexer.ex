defmodule CodingAdventures.NibLexer do
  @moduledoc """
  Nib lexer backed by the shared grammar-driven lexer engine.
  """

  alias CodingAdventures.GrammarTools.TokenGrammar
  alias CodingAdventures.Lexer.GrammarLexer
  alias CodingAdventures.NibLexer.Grammar

  @doc """
  Return the pre-compiled Nib `TokenGrammar`.

  The grammar is embedded as pre-compiled Elixir data in
  `CodingAdventures.NibLexer.Grammar` (generated by `grammar-tools
  compile-tokens` from `code/grammars/nib/nib.tokens`) — this module no
  longer reads the `.tokens` file from disk at runtime.
  """
  @spec create_nib_lexer() :: {:ok, TokenGrammar.t()}
  def create_nib_lexer do
    {:ok, Grammar.token_grammar()}
  end

  @spec tokenize_nib(String.t()) ::
          {:ok, [CodingAdventures.Lexer.Token.t()]} | {:error, String.t()}
  def tokenize_nib(source) do
    grammar = get_grammar()
    GrammarLexer.tokenize(source, grammar)
  end

  defp get_grammar do
    case :persistent_term.get({__MODULE__, :grammar}, nil) do
      nil ->
        {:ok, grammar} = create_nib_lexer()
        :persistent_term.put({__MODULE__, :grammar}, grammar)
        grammar

      grammar ->
        grammar
    end
  end
end
