<!-- hl-knowledge: introduces=[]; assesses=[LA-LEX-MEDIUS-DIES-NOX-01, LA-PRAGMATICS-MEDIUS-DIES-NOX-02, LA-LEX-DIES-01, LA-ETYMON-DIES-02] -->

