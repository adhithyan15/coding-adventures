//! Jetpack Compose backend pipeline emitter.

use std::fmt::Write;

use moslayout_compiler::{LayoutDef, LayoutNode, LayoutProp, LayoutPropValue};
use mosmodel_compiler::{
    EmitDecl, EmitPayloadType, ListInnerType, MosmodelComponent, SlotDecl, SlotType,
};
use mosstyle_compiler::StyleDef;

/// Errors the Compose pipeline emitter can return.
#[derive(Debug)]
pub enum PipelineEmitError {
    UnknownPrimitive(String),
    UnsafeSlotName(String),
    UnsafeEmitName(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the Compose emitter"
            ),
            Self::UnsafeSlotName(n) => write!(f, "unsafe slot name '{n}' (post conversion)"),
            Self::UnsafeEmitName(n) => write!(f, "unsafe emit name '{n}' (post conversion)"),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

/// The result of a successful emission.
#[derive(Debug, Clone)]
pub struct PipelineEmitResult {
    pub output: String,
    pub component_name: String,
}

/// Emit one Composable function for the three-file triple.
///
/// `_style` is accepted but not yet consumed — Compose styling lands
/// on `Modifier` chains, which v0.1.0 does not yet emit.  Future
/// versions will lower mosstyle blocks to `Modifier.background(...)`
/// / `Modifier.padding(...)` / etc.
pub fn from_pipeline(
    component: &MosmodelComponent,
    layout: &LayoutDef,
    _style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    let name = component.component.clone();
    // Defence in depth: validate the component name before we
    // interpolate it into Kotlin identifier positions (sealed class
    // name, function name, event union member, etc.).  The mosmodel
    // grammar already restricts component names to PascalCase ASCII,
    // but re-validating here protects against:
    //   - a grammar regression that admits surprising characters
    //   - a hand-built `MosmodelComponent` struct fed in by test or
    //     fuzz harness code with a hostile name
    validate_safe_identifier(&name).map_err(PipelineEmitError::UnsafeSlotName)?;
    let mut out = String::new();

    writeln!(out, "// Auto-generated by mosaic-emit-compose. Do not edit.").unwrap();
    writeln!(out).unwrap();
    // We don't know the host's package; emit the standard
    // `androidx.compose.*` imports and leave a TODO for the host
    // to add its own package declaration.  In practice the host's
    // build script can prepend `package com.example.foo` before
    // wiring the file into the source set.
    writeln!(out, "import androidx.compose.foundation.layout.Box").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Column").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Row").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.Spacer").unwrap();
    writeln!(out, "import androidx.compose.foundation.layout.fillMaxWidth").unwrap();
    writeln!(out, "import androidx.compose.foundation.text.BasicTextField").unwrap();
    writeln!(out, "import androidx.compose.material.Button").unwrap();
    writeln!(out, "import androidx.compose.material.Text").unwrap();
    writeln!(out, "import androidx.compose.runtime.Composable").unwrap();
    writeln!(out, "import androidx.compose.ui.Modifier").unwrap();
    writeln!(out).unwrap();

    out.push_str(&emit_event_sealed_class(&name, &component.emits)?);
    writeln!(out).unwrap();
    out.push_str(&emit_composable_function(
        &name,
        &component.slots,
        &layout.root,
        &component.emits,
    )?);

    Ok(PipelineEmitResult {
        output: out,
        component_name: name,
    })
}

// =====================================================================
// Event sealed class
// =====================================================================

fn emit_event_sealed_class(
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "sealed class {component_name}Event {{").unwrap();
    for e in emits {
        let case = pascalize(&strip_on_prefix(&e.name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        if e.params.is_empty() {
            // Parameterless events are singletons in Kotlin — `data object`
            // is the idiomatic shape and exposes `equals` / `hashCode`
            // automatically.
            writeln!(
                out,
                "    data object {case} : {component_name}Event()"
            )
            .unwrap();
        } else {
            let params: Vec<String> = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    let ty = emit_payload_type_to_kotlin(&p.r#type);
                    format!("val {field}: {ty}")
                })
                .collect();
            writeln!(
                out,
                "    data class {case}({params}) : {component_name}Event()",
                params = params.join(", ")
            )
            .unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    Ok(out)
}

// =====================================================================
// Composable function
// =====================================================================

fn emit_composable_function(
    component_name: &str,
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "@Composable").unwrap();
    writeln!(out, "fun {component_name}(").unwrap();
    for s in slots {
        let field = to_camel_case_first_lower(&s.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        let ty = slot_type_to_kotlin(&s.r#type);
        // Optional slots in the IR become nullable Kotlin types.
        let suffix = if s.required { "" } else { "?" };
        writeln!(out, "    {field}: {ty}{suffix},").unwrap();
    }
    writeln!(
        out,
        "    dispatch: ({component_name}Event) -> Unit,"
    )
    .unwrap();
    writeln!(out, ") {{").unwrap();
    out.push_str(&emit_compose_tree(layout_root, 1, component_name, emits)?);
    writeln!(out, "}}").unwrap();
    Ok(out)
}

// =====================================================================
// Layout tree walker
// =====================================================================

fn emit_compose_tree(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    match node.tag.as_str() {
        "Box" => emit_container(node, "Box", depth, component_name, emits),
        "Row" => emit_container(node, "Row", depth, component_name, emits),
        "Column" => emit_container(node, "Column", depth, component_name, emits),
        // UI29 §2.1 — `HostTable` and its four structural sub-tags.
        // Compose UI has no native `<table>` primitive, so we lower
        // every variant to a vertical `Column`: the row order of the
        // sub-tags (`HostTableHead` then `HostTableBody`, etc.) maps
        // straight onto Compose's child-order vertical layout.  The
        // moslayout-author's `Row` / `Box` children then place
        // header/data cells inside each.  `HostTableColGroup` is a
        // semantic hint with no visual analog in Compose; we emit it
        // as a `Column` so its children still iterate, but the
        // generated comment documents the no-op nature.
        "HostTable" | "HostTableHead" | "HostTableBody" | "HostTableFoot" => {
            emit_container(node, "Column", depth, component_name, emits)
        }
        "HostTableColGroup" => {
            writeln!(
                String::new(),
                "{pad}// HostTableColGroup — no visual analog in Compose"
            )
            .unwrap();
            // Fall through to a Column so any `Col` children iterate
            // (they too are colgroup-only; emit as zero-size markers).
            emit_container(node, "Column", depth, component_name, emits)
        }
        "Col" => {
            // `Col` is a column-width hint inside `HostTableColGroup`.
            // It has no Compose analog and never renders visually.
            // Emit an empty `Spacer(Modifier.width(0.dp))` placeholder
            // so the generated file still type-checks; downstream
            // Compose Grid lowerings can refine this once a real
            // width-binding flows.
            Ok(format!(
                "{pad}// Col (column-width hint — no Compose analog)\n"
            ))
        }
        "Text" => emit_text(node, depth),
        "Spacer" => Ok(format!(
            "{pad}Spacer(modifier = Modifier.weight(1f))\n"
        )),
        "HostInput" => emit_host_input(node, depth, component_name, emits),
        "HostButton" => emit_host_button(node, depth, component_name, emits),
        // UI29 §3.1 / §3.2 — meta-primitives.
        "For" => emit_for_compose(node, depth, component_name, emits),
        "If" => emit_if_compose(node, None, depth, component_name, emits),
        // An orphan `Else` (one that did not immediately follow an
        // `If`) renders as a documenting Kotlin comment so the file
        // still compiles.  Paired `If`/`Else` is handled by the
        // sibling walker (`emit_children`); this match arm only
        // fires when an `Else` is reached through `emit_compose_tree`
        // directly (e.g. a hand-built test fixture).
        "Else" => Ok(format!("{pad}// orphan Else — ignored\n")),
        other => Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    }
}

fn emit_container(
    node: &LayoutNode,
    composable: &str,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let mut out = String::new();
    if node.children.is_empty() {
        writeln!(out, "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{ }}").unwrap();
        return Ok(out);
    }
    writeln!(out, "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{").unwrap();
    out.push_str(&emit_children_compose(&node.children, depth + 1, component_name, emits)?);
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Walk a list of sibling children with explicit If/Else pairing
/// (mirrors the equivalent helpers in `mosaic-emit-html` and
/// `mosaic-emit-swiftui`).  When the walker sees an `If`, it peeks
/// the next sibling; if it's `Else`, both branches are handed to
/// [`emit_if_compose`] together and the walker advances past both.
/// All other nodes flow through [`emit_compose_tree`] unchanged.
fn emit_children_compose(
    children: &[LayoutNode],
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    let mut i = 0;
    while i < children.len() {
        let child = &children[i];
        if child.tag == "If" {
            let else_node = children.get(i + 1).filter(|n| n.tag == "Else");
            out.push_str(&emit_if_compose(
                child,
                else_node,
                depth,
                component_name,
                emits,
            )?);
            i += if else_node.is_some() { 2 } else { 1 };
            continue;
        }
        out.push_str(&emit_compose_tree(child, depth, component_name, emits)?);
        i += 1;
    }
    Ok(out)
}

/// Lower a `For ( each: <coll>, as: <name>, index: <name>? )` to a
/// Kotlin `forEachIndexed { idx, item -> ... }` (when `index:` is
/// present) or `forEach { item -> ... }` (when it isn't).
///
/// Compose's preferred iteration shape is plain Kotlin collection
/// extensions inside a layout container — `Column { rows.forEach { … } }`
/// composes naturally because the trailing lambda is a `@Composable`
/// content block.  The `forEachIndexed` form drops the `Int` index
/// directly into scope; moslayout's `index:` binding is a number-
/// typed slot in the runtime's expression-language scope, and Kotlin
/// accepts `Int == Double` via its `Number` coercion in `==` calls,
/// so verbatim Expr text like `( r == editRow && c == editCol )`
/// compiles without further widening.
fn emit_for_compose(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner_depth = depth + 1;

    let coll = match node.props.iter().find(|p| p.name == "each") {
        Some(p) => match &p.value {
            LayoutPropValue::SlotRef(s) => to_camel_case_first_lower(s),
            LayoutPropValue::Expr(text) => text.trim().to_string(),
            // UI29 §3.4 — a bare `Keyword` names an enclosing For's
            // `as:` binding (nested For over the outer's element).
            LayoutPropValue::Keyword(name) => to_camel_case_first_lower(name),
            _ => "emptyList<Any>()".to_string(),
        },
        None => "emptyList<Any>()".to_string(),
    };

    let as_name = find_keyword_prop(node, "as")
        .as_deref()
        .map(to_camel_case_first_lower)
        .unwrap_or_else(|| "item".to_string());
    let index_name = find_keyword_prop(node, "index")
        .as_deref()
        .map(to_camel_case_first_lower);

    let header = match &index_name {
        Some(idx) => {
            // The closure parameter binds the offset as an `Int`
            // under a `_kotlinIdx<idx>` shadow name, and we
            // immediately re-bind `<idx>` to a `Double` so the
            // moslayout author's verbatim expression text (e.g.
            // `( r == editRow && c == editCol )`) compiles cleanly
            // against `number`-typed slots that lower to `Double`.
            //
            // Kotlin's `==` operator does NOT allow `Int == Double`
            // (it desugars to a strict-type `.equals` call), so
            // without this cast the visicalc Grid's per-cell
            // `is-editing` predicate would fail to compile.
            //
            // The moslayout NAME grammar
            // `[a-zA-Z][a-zA-Z0-9]*(-...)*` can never produce a
            // leading underscore, so `_kotlinIdx<idx>` is
            // collision-free against any author-supplied name.  The
            // pattern mirrors `mosaic-emit-swiftui`'s
            // `_swiftIdx<idx>` rename for the same reason.
            let inner_pad = "    ".repeat(inner_depth);
            format!(
                "{pad}{coll}.forEachIndexed {{ _kotlinIdx{idx}, {as_name} ->\n\
                 {inner_pad}val {idx}: Double = _kotlinIdx{idx}.toDouble()\n",
                coll = coll,
                idx = idx,
                as_name = as_name,
            )
        }
        None => format!(
            "{pad}{coll}.forEach {{ {as_name} ->\n",
            coll = coll,
            as_name = as_name,
        ),
    };

    let mut out = header;
    if node.children.is_empty() {
        // Compose's content lambda is fine with no children — the
        // forEach loop just runs zero times' worth of layout.  Still
        // we emit a comment so the generated body is greppable.
        out.push_str(&format!(
            "{}// (empty For body)\n",
            "    ".repeat(inner_depth)
        ));
    } else {
        out.push_str(&emit_children_compose(
            &node.children,
            inner_depth,
            component_name,
            emits,
        )?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Lower an `If ( when: <expr> ) { ... } Else { ... }` pair to a
/// Kotlin `if (cond) { ... } else { ... }` block.  The condition is
/// the `when:` prop's expression text verbatim (moslayout's
/// expression grammar is a strict subset of Kotlin's so identifiers,
/// member access, indexing, `==`, `!=`, `<`, `<=`, `>`, `>=`, `&&`,
/// `||`, `!` all carry across unchanged).  Literal `when: true` /
/// `when: false` fold at compile time so the generated file omits
/// the dead branch entirely.
///
/// The `else_node` parameter is `None` when the parent walker found
/// no sibling `Else` after the `If`.  In that case we emit just the
/// then-branch — Compose accepts a bare `if (cond) { … }` inside a
/// layout block because the trailing-else type is `Unit?`.
fn emit_if_compose(
    node: &LayoutNode,
    else_node: Option<&LayoutNode>,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner_depth = depth + 1;

    let when = find_prop_value(node, "when");

    // Compile-time fold for `when: true` / `when: false`.
    if let Some(LayoutPropValue::Keyword(k)) = when {
        match k.as_str() {
            "true" => {
                return emit_children_compose(
                    &node.children,
                    depth,
                    component_name,
                    emits,
                );
            }
            "false" => {
                if let Some(e) = else_node {
                    return emit_children_compose(
                        &e.children,
                        depth,
                        component_name,
                        emits,
                    );
                }
                return Ok(String::new());
            }
            _ => {}
        }
    }

    let cond_expr = match when {
        Some(LayoutPropValue::SlotRef(s)) => to_camel_case_first_lower(s),
        Some(LayoutPropValue::Expr(e)) => e.trim().to_string(),
        Some(LayoutPropValue::Keyword(k)) => to_camel_case_first_lower(k),
        Some(LayoutPropValue::String(s)) => format!("\"{s}\""),
        Some(LayoutPropValue::Number(n)) => format!("{n}"),
        Some(LayoutPropValue::EmitRef(name)) => name.clone(),
        None => "false".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}if ({cond_expr}) {{").unwrap();
    out.push_str(&emit_children_compose(
        &node.children,
        inner_depth,
        component_name,
        emits,
    )?);
    if let Some(e) = else_node {
        writeln!(out, "{pad}}} else {{").unwrap();
        out.push_str(&emit_children_compose(
            &e.children,
            inner_depth,
            component_name,
            emits,
        )?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Find a prop whose value is a `Keyword` and return its NAME text.
/// Used by `emit_for_compose` for the `as:` / `index:` props.
fn find_keyword_prop(node: &LayoutNode, prop_name: &str) -> Option<String> {
    node.props.iter().find_map(|p| {
        if p.name == prop_name {
            if let LayoutPropValue::Keyword(s) = &p.value {
                return Some(s.clone());
            }
        }
        None
    })
}

fn emit_text(node: &LayoutNode, depth: usize) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let value_expr = match find_prop_value(node, "content") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Expr(text)) => text.clone(),
        _ => "\"\"".to_string(),
    };
    Ok(format!("{pad}Text(text = {value_expr})\n"))
}

fn emit_host_input(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);

    let value_expr = match find_prop_value(node, "value") {
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Expr(text)) => text.clone(),
        _ => "\"\"".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}BasicTextField(").unwrap();
    writeln!(out, "{inner}value = {value_expr},").unwrap();

    // onChange — wraps the new value in a dispatched event whose
    // case mirrors the .mil declaration.  The strict-Flux contract
    // matches mosaic-emit-flutter's `dispatch(<Component>Event<Case>(value:
    // value))` shape — same naming, same arity, same idiomatic shape
    // adapted to Kotlin's `data class` / `data object`.
    if let Some(emit_name) = find_emit_ref_prop(node, "onChange") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        let dispatch_call = if arity == 0 {
            format!("{component_name}Event.{case}")
        } else {
            format!("{component_name}Event.{case}(v)")
        };
        writeln!(
            out,
            "{inner}onValueChange = {{ v -> dispatch({dispatch_call}) }},"
        )
        .unwrap();
    } else {
        // Without an onChange we still need an onValueChange to
        // satisfy BasicTextField's required parameter — emit a
        // no-op closure.
        writeln!(out, "{inner}onValueChange = {{ }},").unwrap();
    }

    // read-only -> enabled = !readOnly (Compose negates the polarity)
    if let Some(slot) = find_slot_ref_prop(node, "read-only") {
        let camel = to_camel_case_first_lower(slot);
        validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
        writeln!(out, "{inner}enabled = !{camel},").unwrap();
    }

    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

fn emit_host_button(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);

    // onTap → onClick dispatch
    let on_click = if let Some(emit_name) = find_emit_ref_prop(node, "onTap") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        // Buttons have no inherent payload; only emit the dispatch
        // call if the signal is parameterless.  A button wired to a
        // payload-carrying signal won't know what to pass; surface
        // that as `(/* TODO: ... */)` deliberately so the codegen
        // is visibly incomplete rather than silently lying.
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!(
                "dispatch({component_name}Event.{case}(/* TODO: payload */))"
            )
        }
    } else {
        "/* no onTap bound */".to_string()
    };

    let label = match find_prop_value(node, "label") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        _ => "\"\"".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}Button(onClick = {{ {on_click} }}) {{").unwrap();
    writeln!(out, "{inner}Text(text = {label})").unwrap();
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

// =====================================================================
// Type lowerings
// =====================================================================

fn slot_type_to_kotlin(t: &SlotType) -> String {
    match t {
        SlotType::Text => "String".to_string(),
        SlotType::Number => "Double".to_string(),
        SlotType::Bool => "Boolean".to_string(),
        SlotType::Image => "String".to_string(),
        SlotType::Color => "String".to_string(),
        SlotType::Node => "Any".to_string(),
        SlotType::List(inner) => format!("List<{}>", list_inner_to_kotlin(inner)),
        SlotType::Component(name) => {
            // Same defence in depth as in `from_pipeline` — the
            // upstream grammar should already constrain component
            // names, but re-validate here in case we ever interpolate
            // a hostile name into a Kotlin type position.  On
            // failure, return a Kotlin type that won't compile so
            // the issue surfaces loudly at the next layer rather than
            // silently producing injected code.
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
    }
}

fn list_inner_to_kotlin(t: &ListInnerType) -> String {
    match t {
        ListInnerType::Text => "String".to_string(),
        ListInnerType::Number => "Double".to_string(),
        ListInnerType::Bool => "Boolean".to_string(),
        ListInnerType::Image => "String".to_string(),
        ListInnerType::Color => "String".to_string(),
        ListInnerType::Node => "Any".to_string(),
        ListInnerType::Component(name) => {
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
        ListInnerType::List(inner) => format!("List<{}>", list_inner_to_kotlin(inner)),
    }
}

fn emit_payload_type_to_kotlin(t: &EmitPayloadType) -> String {
    match t {
        EmitPayloadType::Text => "String".to_string(),
        EmitPayloadType::Number => "Double".to_string(),
        EmitPayloadType::Bool => "Boolean".to_string(),
        EmitPayloadType::Color => "String".to_string(),
        EmitPayloadType::Component(name) => {
            if validate_safe_identifier(name).is_ok() {
                name.clone()
            } else {
                "/*UNSAFE_COMPONENT_NAME*/Any".to_string()
            }
        }
    }
}

