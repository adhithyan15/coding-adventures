<!-- hl-knowledge: introduces=[GU-ETYMON-LABH-GAIN]; assesses=[GU-ETYMON-JOVU-UNSETTLED, GU-ETYMON-KHAAVU-NO-ENGLISH-COUSIN, GU-LEX-JAANVU, GU-ETYMON-JAANVU-KNOW] -->

