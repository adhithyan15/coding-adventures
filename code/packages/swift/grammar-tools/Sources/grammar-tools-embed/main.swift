// ============================================================================
// grammar-tools-embed — generate `_Grammar.swift` for a lexer/parser package
// ============================================================================
//
// Reads one or more canonical grammar files from `code/grammars/**`, parses
// each with GrammarTools' own parser, and writes a Swift source file whose
// constants reconstruct those grammars as native `TokenGrammar` /
// `ParserGrammar` values. The lexer/parser package then imports the generated
// file instead of reading the grammar off disk at run time.
//
// Usage:
//
//   grammar-tools-embed <kind> <output.swift> <enumName> <label>=<file> [<label>=<file> ...]
//
//     kind      "tokens" (→ TokenGrammar) or "grammar" (→ ParserGrammar)
//     output    path of the .swift file to write
//     enumName  the generated enum's name (e.g. "EmbeddedGrammar")
//     label     a Swift identifier that is BOTH the lookup key the package's
//               loadGrammar() passes AND the generated constant's name
//               (e.g. "algol60", "es1", "dartmouthBasic")
//     file      path to the .tokens / .grammar file to embed under that label
//
// The generated enum exposes a `[String: …Grammar]` dictionary keyed by label
// plus one `static let` per label, so single- and multi-version packages share
// the same shape.
// ============================================================================

import Foundation
import GrammarTools

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data(("grammar-tools-embed: " + message + "\n").utf8))
    exit(1)
}

let arguments = Array(CommandLine.arguments.dropFirst())
guard arguments.count >= 4 else {
    fail("usage: grammar-tools-embed <tokens|grammar> <output.swift> <enumName> <label>=<file> ...")
}

let kind = arguments[0]
let outputPath = arguments[1]
let enumName = arguments[2]
let labelledFiles = arguments.dropFirst(3)

guard kind == "tokens" || kind == "grammar" else {
    fail("kind must be 'tokens' or 'grammar', got '\(kind)'")
}

// Parse `label=file` pairs, preserving argument order for deterministic output.
var pairs: [(label: String, file: String)] = []
for argument in labelledFiles {
    guard let equals = argument.firstIndex(of: "=") else {
        fail("expected <label>=<file>, got '\(argument)'")
    }
    let label = String(argument[argument.startIndex..<equals])
    let file = String(argument[argument.index(after: equals)...])
    if label.isEmpty || file.isEmpty {
        fail("empty label or file in '\(argument)'")
    }
    pairs.append((label, file))
}

// Render the source path deterministically: forward slashes, and relative to
// the repo's `code/` root so the comment is identical on every machine (the
// CI sync-check diffs the generated file byte-for-byte).
func displaySource(_ path: String) -> String {
    let unix = path.replacingOccurrences(of: "\\", with: "/")
    if let range = unix.range(of: "code/grammars/") {
        return String(unix[range.lowerBound...])
    }
    return unix
}
let sourceList = pairs.map { displaySource($0.file) }.joined(separator: "; ")

// Render one `static let <label>: <Type> = <expr>` plus the dictionary entry.
var constants: [String] = []
var dictionaryEntries: [String] = []
let grammarType = kind == "tokens" ? "TokenGrammar" : "ParserGrammar"

for (label, file) in pairs {
    let text: String
    do {
        text = try String(contentsOfFile: file, encoding: .utf8)
    } catch {
        fail("cannot read '\(file)': \(error.localizedDescription)")
    }

    let expression: String
    do {
        if kind == "tokens" {
            expression = compileTokenGrammarExpression(try parseTokenGrammar(source: text))
        } else {
            expression = compileParserGrammarExpression(try parseParserGrammar(source: text))
        }
    } catch {
        fail("failed to parse '\(file)': \(error)")
    }

    constants.append("    static let \(label): \(grammarType) = \(expression)")
    dictionaryEntries.append("        \(swiftStringLiteral(label)): \(label),")
}

let dictionaryName = kind == "tokens" ? "tokenGrammars" : "parserGrammars"
let header = """
// Code generated by grammar-tools. DO NOT EDIT.
// Source: \(sourceList.replacingOccurrences(of: "\n", with: "_"))
//
// Embeds the grammar(s) as native Swift so the lexer/parser never reads
// code/grammars/** at run time. Regenerate from swift/grammar-tools with:
//   swift run grammar-tools-embed \(kind) <output> \(enumName) <label>=<file> ...

import GrammarTools

enum \(enumName) {
    /// Embedded grammars keyed by the version label the loader passes.
    static let \(dictionaryName): [String: \(grammarType)] = [
\(dictionaryEntries.joined(separator: "\n"))
    ]

\(constants.joined(separator: "\n\n"))
}

"""

do {
    try header.write(toFile: outputPath, atomically: true, encoding: .utf8)
} catch {
    fail("cannot write '\(outputPath)': \(error.localizedDescription)")
}

FileHandle.standardError.write(Data("grammar-tools-embed: wrote \(outputPath) (\(pairs.count) grammar(s))\n".utf8))
