// ── QueryResult ───────────────────────────────────────────────────────────
//
// The public result of executing a program. For SELECT queries:
//   - Columns: ordered list of output column names.
//   - Rows: each row is a list of SqlValues in column order.
// For DML (INSERT/UPDATE/DELETE):
//   - RowsAffected: number of rows changed.
//   - Columns and Rows may be empty.

/// The result of executing a Program.
type QueryResult =
    { /// Names of the output columns, in SELECT order.
      Columns: string list
      /// Data rows; each row is a list of values in column order.
      Rows: SqlValue list list
      /// For INSERT/UPDATE/DELETE: number of rows affected.
      RowsAffected: int }

// ── Value conversion helpers ──────────────────────────────────────────────
//
// The backend's Row type is Dictionary<string, obj> where:
//   null    → SQL NULL
//   int64   → INTEGER
//   float   → REAL
//   string  → TEXT
//   bool    → BOOLEAN
//   byte[]  → BLOB
//
// These helpers convert between the planner's SqlValue DU and the backend's
// raw obj representation. We use box/unbox carefully and guard nulls with
// obj.ReferenceEquals so the nullable checker is satisfied.

[<AutoOpen>]
module private Conversions =

    /// Convert a SqlValue to its backend obj representation.
    /// SqlValue.Null maps to .NET null (the backend convention).
    let toObj (v: SqlValue) : obj =
        match v with
        | SqlValue.Null      -> box (null: string)  // null as obj
        | SqlValue.Integer i -> box i
        | SqlValue.Real    r -> box r
        | SqlValue.Text    s -> box s
        | SqlValue.Bool    b -> box b

    /// Convert a backend obj to a SqlValue.
    /// Handles null and the common numeric types the backend may produce.
    let fromObj (o: obj) : SqlValue =
        if obj.ReferenceEquals(o, null) then SqlValue.Null
        else
            match o with
            | :? bool   as b -> SqlValue.Bool b
            | :? int64  as i -> SqlValue.Integer i
            | :? int    as i -> SqlValue.Integer (int64 i)
            | :? double as d -> SqlValue.Real d
            | :? single as f -> SqlValue.Real (float f)
            | :? string as s -> SqlValue.Text s
            | _              -> SqlValue.Text (string o)

// ── Cursor key ────────────────────────────────────────────────────────────
//
// The codegen assigns each scan an optional string alias:
//   None      → the default (only) cursor, e.g. single-table SELECT
//   Some "u"  → the cursor for a table aliased as "u" in a JOIN
//
// We represent cursor keys as plain strings in a Dictionary, using the
// empty string "" to represent the None (default) cursor. This avoids
// any nullable-key issues that Dictionary<string option, …> would cause
// under F# nullable-reference-type analysis.

[<AutoOpen>]
module private CursorKey =
    /// Convert an optional alias to a dictionary key.
    /// None → ""   (the default / only cursor)
    /// Some s → s  (named alias)
    let inline cursorKey (alias: string option) : string =
        match alias with
        | None   -> ""
        | Some s -> s

// ── Aggregate accumulator ─────────────────────────────────────────────────
//
// Each aggregate slot holds one of these. Think of it as a running tally:
//
//   COUNT(*)    → count increments on every row
//   COUNT(col)  → count increments only for non-NULL col values
//   SUM(col)    → acc accumulates the sum; Null if no non-NULL seen
//   AVG(col)    → acc = sum, count = number of non-NULL values
//   MIN/MAX     → acc tracks the extreme value seen so far

[<AutoOpen>]
module private Aggregates =

    type AggSlot =
        { mutable Count: int64
          mutable Acc:   SqlValue  // sum / min / max carrier; Null = nothing seen
          mutable Func:  AggFn }

    let private makeSlot fn =
        { Count = 0L; Acc = SqlValue.Null; Func = fn }

    let initSlots (n: int) : AggSlot[] =
        // Allocate n slots with default CountStar function; the actual
        // function is baked in by UpdateAgg when it is first called.
        Array.init n (fun _ -> makeSlot AggFn.CountStar)

    /// Feed one value into an accumulator slot.
    let updateSlot (slot: AggSlot) (value: SqlValue) =
        match slot.Func with
        | AggFn.CountStar ->
            // COUNT(*): count every row, including NULLs.
            slot.Count <- slot.Count + 1L

        | AggFn.Count ->
            // COUNT(col): count only non-NULL values.
            if value <> SqlValue.Null then
                slot.Count <- slot.Count + 1L

        | AggFn.Sum ->
            // SUM: skip NULLs; accumulate into Acc which starts as Null.
            match value with
            | SqlValue.Null -> ()
            | SqlValue.Integer i ->
                match slot.Acc with
                | SqlValue.Null       -> slot.Acc <- SqlValue.Integer i
                | SqlValue.Integer s  -> slot.Acc <- SqlValue.Integer (s + i)
                | SqlValue.Real    s  -> slot.Acc <- SqlValue.Real (s + float i)
                | _                   -> ()
            | SqlValue.Real r ->
                match slot.Acc with
                | SqlValue.Null       -> slot.Acc <- SqlValue.Real r
                | SqlValue.Integer s  -> slot.Acc <- SqlValue.Real (float s + r)
                | SqlValue.Real    s  -> slot.Acc <- SqlValue.Real (s + r)
                | _                   -> ()
            | _ -> ()

        | AggFn.Avg ->
            // AVG: sum non-NULLs into Acc, keep count for division later.
            match value with
            | SqlValue.Null -> ()
            | SqlValue.Integer i ->
                slot.Count <- slot.Count + 1L
                match slot.Acc with
                | SqlValue.Null       -> slot.Acc <- SqlValue.Integer i
                | SqlValue.Integer s  -> slot.Acc <- SqlValue.Integer (s + i)
                | SqlValue.Real    s  -> slot.Acc <- SqlValue.Real (s + float i)
                | _                   -> ()
            | SqlValue.Real r ->
                slot.Count <- slot.Count + 1L
                match slot.Acc with
                | SqlValue.Null       -> slot.Acc <- SqlValue.Real r
                | SqlValue.Integer s  -> slot.Acc <- SqlValue.Real (float s + r)
                | SqlValue.Real    s  -> slot.Acc <- SqlValue.Real (s + r)
                | _                   -> ()
            | _ -> ()

        | AggFn.Min ->
            // MIN: keep the smallest non-NULL value.
            match value with
            | SqlValue.Null -> ()
            | v ->
                match slot.Acc with
                | SqlValue.Null -> slot.Acc <- v
                | current ->
                    let cmp = SqlValues.compareValues (toObj v) (toObj current)
                    if cmp < 0 then slot.Acc <- v

        | AggFn.Max ->
            // MAX: keep the largest non-NULL value.
            match value with
            | SqlValue.Null -> ()
            | v ->
                match slot.Acc with
                | SqlValue.Null -> slot.Acc <- v
                | current ->
                    let cmp = SqlValues.compareValues (toObj v) (toObj current)
                    if cmp > 0 then slot.Acc <- v

    /// Compute the final result of a slot after the scan loop completes.
    let finalizeSlot (slot: AggSlot) : SqlValue =
        match slot.Func with
        | AggFn.CountStar | AggFn.Count ->
            SqlValue.Integer slot.Count
        | AggFn.Sum ->
            slot.Acc  // Null if no non-NULL input
        | AggFn.Avg ->
            if slot.Count = 0L then SqlValue.Null
            else
                match slot.Acc with
                | SqlValue.Integer s -> SqlValue.Real (float s / float slot.Count)
                | SqlValue.Real    s -> SqlValue.Real (s / float slot.Count)
                | _                  -> SqlValue.Null
        | AggFn.Min | AggFn.Max ->
            slot.Acc  // Null if no non-NULL input

// ── LIKE pattern matching ─────────────────────────────────────────────────
//
// SQL LIKE uses two wildcard characters:
//   %  →  zero or more characters (any)
//   _  →  exactly one character
//
// We use a direct recursive iterative matcher rather than compiling a Regex.
// The Regex approach has two problems:
//   1. It compiles a new Regex on every LIKE evaluation (expensive).
//   2. Translating % to .* can trigger catastrophic backtracking (ReDoS) on
//      pathological patterns like "a%b%c%d%…" against long strings.
//
// The iterative matcher handles % by trying to match the rest of the pattern
// starting at every suffix of the string — O(n*m) worst case but with no
// exponential blowup and no heap allocation beyond the call stack.
//
// Matching is case-insensitive via Char.ToUpperInvariant, matching SQL LIKE
// semantics. The _ wildcard matches exactly one character of any kind.
//
// Example patterns:
//   "hello%"  → matches "hello", "hello world", …
//   "a_c"     → matches "abc", "axc", …
//   "a[b]c"   → matches "a[b]c" literally (no special regex metacharacters)

[<AutoOpen>]
module private LikeMatch =

    /// Recursive helper: returns true if s[si..] matches p[pi..].
    ///
    /// When p[pi] = '%', skip consecutive % wildcards (they collapse to one),
    /// then try to anchor the rest of the pattern at every position in s[si..].
    /// When p[pi] = '_', consume exactly one character from s.
    /// Otherwise, require a case-insensitive literal character match.
    let rec private likeMatchRec (s: string) (si: int) (p: string) (pi: int) : bool =
        if pi = p.Length then
            // Pattern fully consumed: match only if string also fully consumed.
            si = s.Length
        elif p.[pi] = '%' then
            // Consume consecutive % signs — they are equivalent to a single %.
            let mutable pi' = pi + 1
            while pi' < p.Length && p.[pi'] = '%' do
                pi' <- pi' + 1
            if pi' = p.Length then
                // Trailing % matches any suffix — always succeeds.
                true
            else
                // Try matching the tail pattern at every position from si onward.
                let mutable i = si
                let mutable found = false
                while i <= s.Length && not found do
                    found <- likeMatchRec s i p pi'
                    i <- i + 1
                found
        elif si = s.Length then
            // String exhausted but pattern still has non-% characters — no match.
            false
        elif p.[pi] = '_' || Char.ToUpperInvariant(p.[pi]) = Char.ToUpperInvariant(s.[si]) then
            // Wildcard _ matches any single character; literal characters must
            // match case-insensitively.
            likeMatchRec s (si + 1) p (pi + 1)
        else
            false

    /// Test whether `value` matches a SQL LIKE `pattern` (case-insensitive).
    ///
    /// Example:
    ///   likeMatch "Hello World" "hello%"  = true
    ///   likeMatch "abc"         "a_c"     = true
    ///   likeMatch "abc"         "a[b]c"   = false  (literal bracket)
    let likeMatch (value: string) (pattern: string) : bool =
        likeMatchRec value 0 pattern 0

// ── Three-valued logic helpers ────────────────────────────────────────────
//
// isTruthy decides whether a stack value should cause a conditional jump.
//
//   NULL → false   (unknown = not true in a boolean context)
//   Bool b → b
//   Integer n → n <> 0
//   Real r → r <> 0.0
//   Text → false   (SQL does not coerce text to boolean here)

[<AutoOpen>]
module private Logic =

    let isTruthy (v: SqlValue) =
        match v with
        | SqlValue.Null      -> false
        | SqlValue.Bool   b  -> b
        | SqlValue.Integer i -> i <> 0L
        | SqlValue.Real   r  -> r <> 0.0
        | SqlValue.Text   _  -> false

// ── Binary / unary evaluation ─────────────────────────────────────────────
//
// These functions implement the per-operator semantics for BinaryOpInstr and
// UnaryOpInstr. NULL propagates through all operators except AND and OR, which
// have SQL-standard short-circuit semantics:
//
//   FALSE AND anything → FALSE   (even if anything is NULL)
//   TRUE  OR  anything → TRUE    (even if anything is NULL)
//
// Arithmetic type promotion:
//   Integer op Integer → Integer  (except Div/Mod which keep Integer)
//   Integer op Real    → Real
//   Real    op Real    → Real

[<AutoOpen>]
module private Eval =

    let private sqlCompare (left: SqlValue) (right: SqlValue) : int =
        SqlValues.compareValues (toObj left) (toObj right)

    let evalBinary (op: BinaryOp) (left: SqlValue) (right: SqlValue) : SqlValue =
        match op with
        // AND short-circuits: FALSE AND NULL = FALSE; FALSE AND FALSE = FALSE.
        | BinaryOp.And ->
            match left, right with
            | SqlValue.Bool false, _ | _, SqlValue.Bool false -> SqlValue.Bool false
            | SqlValue.Integer 0L, _ | _, SqlValue.Integer 0L -> SqlValue.Bool false
            | SqlValue.Null, _  | _, SqlValue.Null            -> SqlValue.Null
            | _ -> SqlValue.Bool (isTruthy left && isTruthy right)
        // OR short-circuits: TRUE OR NULL = TRUE; TRUE OR FALSE = TRUE.
        | BinaryOp.Or ->
            match left, right with
            | SqlValue.Bool true,  _ | _, SqlValue.Bool true  -> SqlValue.Bool true
            | SqlValue.Null, _ | _, SqlValue.Null             -> SqlValue.Null
            | _ -> SqlValue.Bool (isTruthy left || isTruthy right)
        | _ ->
            // All remaining operators propagate NULL.
            if left = SqlValue.Null || right = SqlValue.Null then SqlValue.Null
            else
                match op with
                | BinaryOp.Add ->
                    match left, right with
                    | SqlValue.Integer l, SqlValue.Integer r -> SqlValue.Integer (l + r)
                    | SqlValue.Integer l, SqlValue.Real    r -> SqlValue.Real (float l + r)
                    | SqlValue.Real    l, SqlValue.Integer r -> SqlValue.Real (l + float r)
                    | SqlValue.Real    l, SqlValue.Real    r -> SqlValue.Real (l + r)
                    | _ -> SqlValue.Null
                | BinaryOp.Sub ->
                    match left, right with
                    | SqlValue.Integer l, SqlValue.Integer r -> SqlValue.Integer (l - r)
                    | SqlValue.Integer l, SqlValue.Real    r -> SqlValue.Real (float l - r)
                    | SqlValue.Real    l, SqlValue.Integer r -> SqlValue.Real (l - float r)
                    | SqlValue.Real    l, SqlValue.Real    r -> SqlValue.Real (l - r)
                    | _ -> SqlValue.Null
                | BinaryOp.Mul ->
                    match left, right with
                    | SqlValue.Integer l, SqlValue.Integer r -> SqlValue.Integer (l * r)
                    | SqlValue.Integer l, SqlValue.Real    r -> SqlValue.Real (float l * r)
                    | SqlValue.Real    l, SqlValue.Integer r -> SqlValue.Real (l * float r)
                    | SqlValue.Real    l, SqlValue.Real    r -> SqlValue.Real (l * r)
                    | _ -> SqlValue.Null
                | BinaryOp.Div ->
                    // Integer division by zero → NULL, matching SQLite behaviour.
                    match left, right with
                    | SqlValue.Integer l, SqlValue.Integer r ->
                        if r = 0L then SqlValue.Null else SqlValue.Integer (l / r)
                    | SqlValue.Integer l, SqlValue.Real    r ->
                        if r = 0.0 then SqlValue.Null else SqlValue.Real (float l / r)
                    | SqlValue.Real    l, SqlValue.Integer r ->
                        if r = 0L then SqlValue.Null else SqlValue.Real (l / float r)
                    | SqlValue.Real    l, SqlValue.Real    r ->
                        if r = 0.0 then SqlValue.Null else SqlValue.Real (l / r)
                    | _ -> SqlValue.Null
                | BinaryOp.Mod ->
                    match left, right with
                    | SqlValue.Integer l, SqlValue.Integer r ->
                        if r = 0L then SqlValue.Null else SqlValue.Integer (l % r)
                    | _ -> SqlValue.Null
                | BinaryOp.Concat ->
                    // String concatenation (SQL ||). Convert numbers to string.
                    let l = match left  with SqlValue.Text s -> s | SqlValue.Integer i -> string i | SqlValue.Real r -> string r | _ -> ""
                    let r = match right with SqlValue.Text s -> s | SqlValue.Integer i -> string i | SqlValue.Real r -> string r | _ -> ""
                    SqlValue.Text (l + r)
                | BinaryOp.Eq  -> SqlValue.Bool (sqlCompare left right =  0)
                | BinaryOp.Neq -> SqlValue.Bool (sqlCompare left right <> 0)
                | BinaryOp.Lt  -> SqlValue.Bool (sqlCompare left right <  0)
                | BinaryOp.Lte -> SqlValue.Bool (sqlCompare left right <= 0)
                | BinaryOp.Gt  -> SqlValue.Bool (sqlCompare left right >  0)
                | BinaryOp.Gte -> SqlValue.Bool (sqlCompare left right >= 0)
                | BinaryOp.And | BinaryOp.Or ->
                    // Already matched above; compiler requires exhaustiveness.
                    SqlValue.Null

    let evalUnary (op: UnaryOp) (v: SqlValue) : SqlValue =
        match op with
        | UnaryOp.Neg ->
            // Arithmetic negation. Propagates NULL.
            match v with
            | SqlValue.Null      -> SqlValue.Null
            | SqlValue.Integer i -> SqlValue.Integer (-i)
            | SqlValue.Real    r -> SqlValue.Real (-r)
            | _                  -> SqlValue.Null
        | UnaryOp.Not ->
            // Logical negation. NOT NULL = NULL (three-valued logic).
            match v with
            | SqlValue.Null      -> SqlValue.Null
            | SqlValue.Bool    b -> SqlValue.Bool (not b)
            | SqlValue.Integer i -> SqlValue.Bool (i = 0L)
            | _                  -> SqlValue.Null

// ── Label index builder ───────────────────────────────────────────────────
//
// Pre-scan the instruction list once before execution to build a Map from
// label names to instruction indices. This makes every Jump/JumpIfTrue/
// JumpIfFalse O(1) at runtime rather than O(n) linear search.
//
// Example: instruction list [OpenScan…; Label "loop_0"; …; Label "end_0"; …]
// produces Map [ "loop_0" → 1; "end_0" → 5 ] (indices into the flat list).

[<AutoOpen>]
module private LabelIndex =

    let buildLabelIndex (instructions: Instruction list) : Map<string, int> =
        instructions
        |> List.mapi (fun i instr ->
            match instr with
            | Instruction.Label name -> Some (name, i)
            | _                      -> None)
        |> List.choose id
        |> Map.ofList

// ── Cursor state ──────────────────────────────────────────────────────────
//
// CursorState wraps a backend row iterator and tracks:
//   - The current (most recently read) row.
//   - Whether the iterator has been exhausted.
//   - The optional ICursor interface for UPDATE/DELETE positioned operations.
//
// Invariant: Current is null <=> Exhausted = true OR no row has been read yet.

type private CursorState =
    { mutable Current:   Row       // null before first advance or when exhausted
      mutable Exhausted: bool
      Iterator:          IRowIterator
      Cursor:            ICursor option }

// ── VM execution ──────────────────────────────────────────────────────────
//
// The module exposes one public function:
//
//   SqlVm.execute : Program -> Backend -> QueryResult
//
// All mutable state is local to that function; the module itself has no
// mutable state. Multiple concurrent calls are therefore safe.

module SqlVm =

    // ── Helper: resolve a column name across open cursors ──────────────────
    //
    // When LoadColumn carries table=None, the VM searches all open cursors.
    // When table=Some alias, it looks in that specific cursor only.
    // Returns SqlValue.Null when the column is not found (safe default).

    let private resolveColumn
        (cursors: Dictionary<string, CursorState>)
        (tableOpt: string option)
        (col: string)
        : SqlValue =

        let lookup (row: Row) =
            if obj.ReferenceEquals(row, null) then SqlValue.Null
            else
                match row.TryGetValue(col) with
                | true, v -> fromObj v
                | _       -> SqlValue.Null

        match tableOpt with
        | Some alias ->
            // Qualified column: look in the cursor for this alias first,
            // then fall back to the default ("") cursor.
            match cursors.TryGetValue(alias) with
            | true, cs -> lookup cs.Current
            | _        ->
                match cursors.TryGetValue("") with
                | true, cs -> lookup cs.Current
                | _        -> SqlValue.Null
        | None ->
            // Unqualified: check the default cursor first (most common case),
            // then search named cursors.
            match cursors.TryGetValue("") with
            | true, cs ->
                let v = lookup cs.Current
                // Return if found in this cursor (either a real value or the
                // column genuinely exists with a null value).
                if not (obj.ReferenceEquals(cs.Current, null)) && cs.Current.ContainsKey(col) then v
                else
                    // Column not found in default cursor — search others.
                    let mutable found = SqlValue.Null
                    for KeyValue(k, namedCs) in cursors do
                        if k <> "" && not (obj.ReferenceEquals(namedCs.Current, null)) && namedCs.Current.ContainsKey(col) then
                            found <- fromObj namedCs.Current[col]
                    found
            | _ ->
                let mutable found = SqlValue.Null
                for KeyValue(_, cs) in cursors do
                    if not (obj.ReferenceEquals(cs.Current, null)) && cs.Current.ContainsKey(col) then
                        found <- fromObj cs.Current[col]
                found

    // ── Helper: open a cursor on a table ──────────────────────────────────
    //
    // Prefer a positioned cursor (ICursor) for UPDATE/DELETE support — the
    // InMemoryBackend exposes OpenCursor which returns a ListCursor that
    // implements ICursor and supports backend.Update / backend.Delete.
    //
    // We dispatch via a typed pattern match on InMemoryBackend rather than
    // reflection. This is fully type-safe and zero-overhead. Backends that
    // do not extend InMemoryBackend (e.g. read-only adapters) fall back to
    // backend.Scan which returns a plain IRowIterator with Cursor = None;
    // such backends cannot execute UPDATE/DELETE and will silently skip them.

    let private openCursor (backend: Backend) (table: string) : CursorState =
        match backend with
        | :? InMemoryBackend as imb ->
            // InMemoryBackend.OpenCursor returns a ListCursor (implements ICursor)
            // that holds a live reference into the backing ResizeArray, enabling
            // backend.Update and backend.Delete to locate and mutate the row.
            let c = imb.OpenCursor(table) :> ICursor
            { Current   = null
              Exhausted = false
              Iterator  = (c :> IRowIterator)
              Cursor    = Some c }
        | _ ->
            // Generic / read-only backend: use the standard Scan iterator.
            // Cursor = None means UpdateRows / DeleteRows instructions are no-ops.
            let it = backend.Scan(table)
            { Current   = null
              Exhausted = false
              Iterator  = it
              Cursor    = None }

    // ── Helper: build a Row (backend dict) for INSERT ─────────────────────
    //
    // The codegen pushes values left-to-right (first column pushed first,
    // last column on top). We pop them from the stack in reverse order and
    // zip with the column list to build the Row dict.

    let private buildInsertRow
        (stack: Stack<SqlValue>)
        (table: string)
        (colsOpt: string list option)
        (backend: Backend)
        : Row =

        let cols =
            match colsOpt with
            | Some cs -> cs
            | None    ->
                backend.Columns(table)
                |> Seq.map (fun c -> c.Name)
                |> Seq.toList

        // Pop values: the last column's value is on top of the stack.
        let values = Array.init cols.Length (fun _ -> stack.Pop()) |> Array.rev

        let row = Row()
        List.iteri (fun i col -> row[col] <- toObj values.[i]) cols
        row

    // ── Helper: evaluate an Expr against the current cursor row ───────────
    //
    // UpdateRows carries (column, Expr) pairs. The Expr must be evaluated
    // against the current row (pre-update). We implement a small recursive
    // expression evaluator that mirrors compileExpression from sql-codegen.

    let rec private evalExpr
        (expr: Expr)
        (cursors: Dictionary<string, CursorState>)
        : SqlValue =
        match expr with
        | Expr.Literal v ->
            v
        | Expr.Column(tableOpt, col) ->
            resolveColumn cursors tableOpt col
        | Expr.BinaryOp(op, left, right) ->
            let l = evalExpr left  cursors
            let r = evalExpr right cursors
            evalBinary (plannerBinOp op) l r
        | Expr.UnaryOp(op, operand) ->
            evalUnary (plannerUnOp op) (evalExpr operand cursors)
        | Expr.IsNull e ->
            SqlValue.Bool (evalExpr e cursors = SqlValue.Null)
        | Expr.IsNotNull e ->
            SqlValue.Bool (evalExpr e cursors <> SqlValue.Null)
        | Expr.Like(value, pattern) ->
            match evalExpr value cursors with
            | SqlValue.Null -> SqlValue.Null
            | SqlValue.Text s -> SqlValue.Bool (likeMatch s pattern)
            | _ -> SqlValue.Null
        | Expr.Between(value, lo, hi) ->
            let v = evalExpr value cursors
            let l = evalExpr lo    cursors
            let h = evalExpr hi    cursors
            if v = SqlValue.Null || l = SqlValue.Null || h = SqlValue.Null then SqlValue.Null
            else
                SqlValue.Bool (SqlValues.compareValues (toObj v) (toObj l) >= 0 &&
                                SqlValues.compareValues (toObj v) (toObj h) <= 0)
        | _ -> SqlValue.Null

    /// Map planner BinaryOperator → codegen BinaryOp.
    and private plannerBinOp (op: BinaryOperator) : BinaryOp =
        match op with
        | BinaryOperator.Add   -> BinaryOp.Add
        | BinaryOperator.Sub   -> BinaryOp.Sub
        | BinaryOperator.Mul   -> BinaryOp.Mul
        | BinaryOperator.Div   -> BinaryOp.Div
        | BinaryOperator.Mod   -> BinaryOp.Mod
        | BinaryOperator.Eq    -> BinaryOp.Eq
        | BinaryOperator.NotEq -> BinaryOp.Neq
        | BinaryOperator.Lt    -> BinaryOp.Lt
        | BinaryOperator.Lte   -> BinaryOp.Lte
        | BinaryOperator.Gt    -> BinaryOp.Gt
        | BinaryOperator.Gte   -> BinaryOp.Gte
        | BinaryOperator.And   -> BinaryOp.And
        | BinaryOperator.Or    -> BinaryOp.Or

    /// Map planner UnaryOperator → codegen UnaryOp.
    and private plannerUnOp (op: UnaryOperator) : UnaryOp =
        match op with
        | UnaryOperator.Not -> UnaryOp.Not
        | UnaryOperator.Neg -> UnaryOp.Neg

    // ── Helper: sort result rows by SortKey list ──────────────────────────
    //
    // SortResult carries a list of SortKey records. Each key specifies:
    //   KeyExpr   — column expression (we support Expr.Column only for Level 1)
    //   Direction — Asc or Desc
    //   NullOrder — NullsFirst or NullsLast
    //
    // NullsFirst → NULL < everything (NULL sorts before non-null)
    // NullsLast  → NULL > everything (NULL sorts after non-null)

    let private sortRows
        (rows: SqlValue list list)
        (cols: string list)
        (keys: SortKey list)
        : SqlValue list list =

        // Build a name → index map from the output column list.
        let colIdx =
            cols
            |> List.mapi (fun i c -> (c.ToLowerInvariant(), i))
            |> Map.ofList

        let compareRows (a: SqlValue list) (b: SqlValue list) =
            let mutable result = 0
            let mutable ki = 0
            while result = 0 && ki < keys.Length do
                let k = keys.[ki]
                // Extract the column name from the sort key expression.
                let colName =
                    match k.KeyExpr with
                    | Expr.Column(_, c) -> c.ToLowerInvariant()
                    | _                 -> ""
                let idx =
                    match colIdx.TryFind colName with
                    | Some i -> i
                    | None   -> -1
                let av = if idx >= 0 && idx < a.Length then a.[idx] else SqlValue.Null
                let bv = if idx >= 0 && idx < b.Length then b.[idx] else SqlValue.Null
                // Determine the comparison result, respecting NULL ordering.
                // NullOrder specifies where NULLs appear in the FINAL output,
                // independent of sort direction.  Non-null comparisons are flipped
                // for descending order.
                result <-
                    match av, bv with
                    | SqlValue.Null, SqlValue.Null -> 0
                    | SqlValue.Null, _             ->
                        // NullsFirst → NULL comes before non-null in final output → -1
                        // NullsLast  → NULL comes after  non-null in final output →  1
                        match k.NullOrder with NullsFirst -> -1 | NullsLast -> 1
                    | _, SqlValue.Null             ->
                        match k.NullOrder with NullsFirst -> 1  | NullsLast -> -1
                    | l, r ->
                        let rawCmp = SqlValues.compareValues (toObj l) (toObj r)
                        match k.Direction with SortDir.Asc -> rawCmp | SortDir.Desc -> -rawCmp
                ki <- ki + 1
            result

        rows |> List.sortWith compareRows

    // ── Main execute function ─────────────────────────────────────────────
    //
    // Interprets `program` against `backend`. All mutable state lives here;
    // no module-level state is touched, so concurrent execution is safe.

    /// Execute a compiled Program against a Backend and return a QueryResult.
    ///
    /// This is the VM's single public entry point.
    ///
    /// Example:
    ///   let backend = InMemoryBackend()
    ///   backend.CreateTable("t", [| ColumnDef("id","INTEGER") |], false)
    ///   let prog = SqlCodegen.compile (SqlOptimizer.optimize plan)
    ///   let res  = SqlVm.execute prog backend
    ///   // res.Columns = ["id"]; res.Rows = [[Integer 1L]; ...]
    let execute (program: Program) (backend: Backend) : QueryResult =

        // Convert the instruction list to an array for O(1) index access
        // inside the tight dispatch loop.
        let instructions = program.Instructions |> List.toArray
        let n = instructions.Length

        // ── Pre-scan: build label → instruction-index map ──────────────────
        // One linear pass before execution. Labels are no-ops at runtime;
        // this map lets Jump/JumpIfFalse/JumpIfTrue redirect pc directly.
        let labelIndex = buildLabelIndex program.Instructions

        // ── Mutable VM state ───────────────────────────────────────────────
        // All state is local; no shared module state is touched.

        let stack     = Stack<SqlValue>()              // expression operand stack
        let cursors   = Dictionary<string, CursorState>()  // key = cursorKey alias
        let rowBuffer = ResizeArray<string * SqlValue>()    // (colname, value) pairs

        let mutable outputCols    = []   // column names; set on first EmitRow
        let mutable outputRows    = []   // accumulated rows (in reverse order)
        let mutable rowsAffected  = 0
        let mutable pc            = 0    // program counter
        let mutable halt          = false

        // Aggregate state — array grown by InitAgg/UpdateAgg as needed.
        let mutable aggSlots: AggSlot[] = Array.empty

        // Group key state — set by SaveGroupKey, read by LoadGroupKey.
        let mutable savedGroupKey: SqlValue[] = Array.empty

        // Transaction handle — None when no explicit transaction is active.
        let mutable txHandle: TransactionHandle option = None

        // ── Helper: jump to a named label ──────────────────────────────────
        let jumpTo (label: string) =
            match Map.tryFind label labelIndex with
            | Some idx -> pc <- idx
            | None     -> failwithf "SqlVm: unknown label '%s'" label

        // ── Helper: grow the aggSlots array if needed ─────────────────────
        let ensureSlot (index: int) (fn: AggFn) =
            if index >= aggSlots.Length then
                let newSlots = Array.init (index + 1) (fun i ->
                    if i < aggSlots.Length then aggSlots.[i]
                    else { Count = 0L; Acc = SqlValue.Null; Func = fn })
                aggSlots <- newSlots
            aggSlots.[index].Func <- fn

        // ── Main dispatch loop ─────────────────────────────────────────────
        //
        // We advance pc BEFORE dispatching so non-jump instructions naturally
        // proceed to the next instruction. Jump instructions override pc.
        while pc < n && not halt do
            let instr = instructions.[pc]
            pc <- pc + 1

            match instr with

            // ── Constants / columns ────────────────────────────────────────

            | Instruction.LoadConst value ->
                // Push a compile-time constant onto the expression stack.
                stack.Push(value)

            | Instruction.LoadColumn(tableOpt, col) ->
                // Push the named column's value from the current cursor row.
                // When table=None, search all open cursors for the column.
                stack.Push(resolveColumn cursors tableOpt col)

            | Instruction.LoadParam _ ->
                // Bound parameters not supported in Level 1 — push NULL.
                stack.Push(SqlValue.Null)

            | Instruction.LoadGroupKey idx ->
                // Push the i-th saved group-key value (set by SaveGroupKey).
                let v =
                    if idx >= 0 && idx < savedGroupKey.Length
                    then savedGroupKey.[idx]
                    else SqlValue.Null
                stack.Push(v)

            | Instruction.LoadOuterColumn _ ->
                // Correlated subqueries not supported in Level 1 — push NULL.
                stack.Push(SqlValue.Null)

            | Instruction.Pop ->
                // Discard the top-of-stack value (e.g. unused expression result).
                if stack.Count > 0 then stack.Pop() |> ignore

            // ── Arithmetic and comparison ──────────────────────────────────

            | Instruction.BinaryOpInstr op ->
                // Pop right first (it was pushed last), then left.
                let right = stack.Pop()
                let left  = stack.Pop()
                stack.Push(evalBinary op left right)

            | Instruction.UnaryOpInstr op ->
                let v = stack.Pop()
                stack.Push(evalUnary op v)

            // ── NULL tests ─────────────────────────────────────────────────

            | Instruction.IsNull ->
                // IS NULL: push TRUE iff the top value is SQL NULL.
                stack.Push(SqlValue.Bool (stack.Pop() = SqlValue.Null))

            | Instruction.IsNotNull ->
                stack.Push(SqlValue.Bool (stack.Pop() <> SqlValue.Null))

            // ── BETWEEN ───────────────────────────────────────────────────
            //
            // Stack layout when we arrive (top → bottom): hi, lo, value
            // Push TRUE if lo <= value <= hi; NULL if any input is NULL.

            | Instruction.Between _ ->
                let hi    = stack.Pop()
                let lo    = stack.Pop()
                let value = stack.Pop()
                let result =
                    if value = SqlValue.Null || lo = SqlValue.Null || hi = SqlValue.Null then
                        SqlValue.Null
                    else
                        let ge = SqlValues.compareValues (toObj value) (toObj lo)  >= 0
                        let le = SqlValues.compareValues (toObj value) (toObj hi) <= 0
                        SqlValue.Bool (ge && le)
                stack.Push(result)

            // ── LIKE ──────────────────────────────────────────────────────
            //
            // Stack (top → bottom): pattern, value
            // Push TRUE if value LIKE pattern (SQL wildcard matching).

            | Instruction.Like ->
                let pattern = stack.Pop()
                let value   = stack.Pop()
                let result =
                    match value, pattern with
                    | SqlValue.Null, _ | _, SqlValue.Null ->
                        SqlValue.Null
                    | SqlValue.Text s, SqlValue.Text p ->
                        SqlValue.Bool (likeMatch s p)
                    | _ ->
                        SqlValue.Null
                stack.Push(result)

            // ── IN list ───────────────────────────────────────────────────
            //
            // Stack (top → bottom): item_n, …, item_1, needle
            // Pop `count` items then the needle; push TRUE/FALSE/NULL.
            //
            // SQL standard: x IN () = FALSE (even for NULL x).
            // x IN (…NULL…) where x not found = NULL (not FALSE).

            | Instruction.InList count ->
                let items  = Array.init count (fun _ -> stack.Pop())
                let needle = stack.Pop()
                let result =
                    if count = 0 then
                        // Empty list → always FALSE (SQL standard).
                        SqlValue.Bool false
                    elif needle = SqlValue.Null then
                        SqlValue.Null
                    else
                        let mutable found     = false
                        let mutable foundNull = false
                        for item in items do
                            if item = SqlValue.Null then foundNull <- true
                            elif not found &&
                                 SqlValues.compareValues (toObj needle) (toObj item) = 0 then
                                found <- true
                        if found then SqlValue.Bool true
                        elif foundNull then SqlValue.Null
                        else SqlValue.Bool false
                stack.Push(result)

            // ── Scan / cursor control ──────────────────────────────────────

            | Instruction.OpenScan(table, alias) ->
                // Open an iterator over `table` and register under `alias`.
                let cs = openCursor backend table
                cursors.[cursorKey alias] <- cs

            | Instruction.AdvanceCursor alias ->
                // Advance the cursor to the next row.
                //
                // Design note: the codegen emits JumpIfExhausted BEFORE
                // AdvanceCursor. JumpIfExhausted does the actual peek/advance;
                // AdvanceCursor is a no-op if the cursor already advanced.
                // We use the Exhausted flag to track this.
                let key = cursorKey alias
                match cursors.TryGetValue(key) with
                | false, _ -> ()
                | true, cs ->
                    // If JumpIfExhausted already advanced (row in Current), nothing to do.
                    // If not yet advanced (Current is null and not Exhausted), advance now.
                    if obj.ReferenceEquals(cs.Current, null) && not cs.Exhausted then
                        let row = cs.Iterator.Next()
                        if obj.ReferenceEquals(row, null) then
                            cs.Exhausted <- true
                        else
                            cs.Current <- row

            | Instruction.JumpIfExhausted(alias, label) ->
                // Test whether the cursor is exhausted; jump if so.
                //
                // Implementation: advance the iterator here (peek). If null,
                // the cursor is done — jump to `label`. If a row was obtained,
                // store it in Current (AdvanceCursor will see it already set).
                let key = cursorKey alias
                let exhausted =
                    match cursors.TryGetValue(key) with
                    | false, _ -> true  // No cursor → treat as exhausted.
                    | true, cs ->
                        if cs.Exhausted then
                            true
                        else
                            let row = cs.Iterator.Next()
                            if obj.ReferenceEquals(row, null) then
                                cs.Exhausted <- true
                                cs.Current   <- null
                                true
                            else
                                cs.Current <- row
                                false
                if exhausted then jumpTo label

            | Instruction.CloseScan alias ->
                // Release the cursor.
                let key = cursorKey alias
                match cursors.TryGetValue(key) with
                | true, cs ->
                    cs.Iterator.Close()
                    cursors.Remove(key) |> ignore
                | _ -> ()

            // ── Row construction ───────────────────────────────────────────

            | Instruction.BeginRow ->
                // Clear the row buffer; start assembling a new output row.
                rowBuffer.Clear()

            | Instruction.EmitColumn name ->
                // Pop the top value and store it with its column name.
                rowBuffer.Add((name, stack.Pop()))

            | Instruction.EmitRow ->
                // Flush the assembled row buffer to the result set.
                let row = rowBuffer |> Seq.map snd |> Seq.toList
                // Record column names on the first row (idempotent thereafter).
                if List.isEmpty outputCols then
                    outputCols <- rowBuffer |> Seq.map fst |> Seq.toList
                outputRows <- row :: outputRows  // prepend for O(1); reversed at end
                rowBuffer.Clear()

            // ── Aggregation ────────────────────────────────────────────────
            //
            // The codegen emits:
            //   1. InitAgg(n)          — before the scan loop
            //   2. UpdateAgg(i, fn)    — inside the loop body
            //   3. FinalizeAgg(i, fn)  — after the loop

            | Instruction.InitAgg count ->
                // Allocate accumulator slots. Count is the number of aggregate
                // functions in the query. Called once before the scan loop.
                if aggSlots.Length < count then
                    aggSlots <- initSlots count

            | Instruction.UpdateAgg(index, fn) ->
                // COUNT(*) counts every row without examining any column, so
                // no value is pushed onto the stack before this instruction.
                // All other aggregate functions (COUNT(col), SUM, AVG, MIN,
                // MAX) do push their expression value first.
                let value =
                    if fn = AggFn.CountStar then SqlValue.Null
                    else stack.Pop()
                ensureSlot index fn
                updateSlot aggSlots.[index] value

            | Instruction.FinalizeAgg(index, fn) ->
                // Compute the final value of accumulator `index` and push it.
                ensureSlot index fn
                stack.Push(finalizeSlot aggSlots.[index])

            | Instruction.SaveGroupKey keys ->
                // Snapshot the current group-by key values for LoadGroupKey.
                // Values are on the stack with the last key on top; pop in
                // reverse order then reverse to restore natural order.
                let n = keys.Length
                let values = Array.init n (fun _ -> stack.Pop()) |> Array.rev
                savedGroupKey <- values

            | Instruction.AdvanceGroup ->
                // AdvanceGroup is not emitted by the F# codegen in Level 1.
                // If encountered, it is a no-op.
                ()

            // ── Control flow ───────────────────────────────────────────────

            | Instruction.Label _ ->
                // No-op at runtime; the label was recorded during pre-scan.
                ()

            | Instruction.Jump label ->
                jumpTo label

            | Instruction.JumpIfTrue label ->
                if isTruthy (stack.Pop()) then jumpTo label

            | Instruction.JumpIfFalse label ->
                if not (isTruthy (stack.Pop())) then jumpTo label

            | Instruction.Halt ->
                halt <- true

            // ── DDL ────────────────────────────────────────────────────────

            | Instruction.CreateTable(name, ifNotExists, columns) ->
                // Convert planner ColumnDef records to backend ColumnDef objects.
                let backendCols =
                    columns |> List.map (fun c ->
                        let defaultVal =
                            match c.Default with
                            | Some (Expr.Literal v) -> toObj v
                            | _                     -> box (null: string)
                        let hasDefault = c.Default.IsSome
                        if hasDefault then
                            ColumnDef.WithDefault(c.Name, c.TypeName, defaultVal,
                                notNull    = c.NotNull,
                                primaryKey = c.PrimaryKey,
                                unique     = c.Unique)
                        else
                            ColumnDef(c.Name, c.TypeName,
                                notNull    = c.NotNull,
                                primaryKey = c.PrimaryKey,
                                unique     = c.Unique))
                    |> List.toArray
                backend.CreateTable(name, backendCols, ifNotExists)

            | Instruction.DropTable(name, ifExists) ->
                backend.DropTable(name, ifExists)

            // ── DML ────────────────────────────────────────────────────────

            | Instruction.InsertRow(table, colsOpt) ->
                // Build a Row from the stack values and insert it into `table`.
                let row = buildInsertRow stack table colsOpt backend
                backend.Insert(table, row)
                rowsAffected <- rowsAffected + 1

            | Instruction.UpdateRows(table, assignments) ->
                // Update the row currently under the default cursor.
                // Requires a positioned ICursor (InMemoryBackend.OpenCursor).
                match cursors.TryGetValue("") with
                | true, cs when cs.Cursor.IsSome ->
                    let dict = Dictionary<string, obj>()
                    for (col, expr) in assignments do
                        dict[col] <- toObj (evalExpr expr cursors)
                    backend.Update(table, cs.Cursor.Value, dict)
                    rowsAffected <- rowsAffected + 1
                | _ -> ()

            | Instruction.DeleteRows table ->
                // Delete the row currently under the default cursor.
                match cursors.TryGetValue("") with
                | true, cs when cs.Cursor.IsSome ->
                    backend.Delete(table, cs.Cursor.Value)
                    rowsAffected <- rowsAffected + 1
                | _ -> ()

            // ── Transaction control ────────────────────────────────────────

            | Instruction.BeginTransaction ->
                let h = backend.BeginTransaction()
                txHandle <- Some h

            | Instruction.CommitTransaction ->
                match txHandle with
                | Some h -> backend.Commit(h); txHandle <- None
                | None   -> ()

            | Instruction.RollbackTransaction ->
                match txHandle with
                | Some h -> backend.Rollback(h); txHandle <- None
                | None   -> ()

            // ── Post-processing ────────────────────────────────────────────
            //
            // These instructions run AFTER the scan loop has populated
            // outputRows. They operate on the already-collected result buffer.
            // Because we prepend rows (most recent first), we reverse before
            // operating, then reverse back for the final O(1) reversal below.

            | Instruction.SortResult keys ->
                // Sort the result buffer by the given keys.
                // outputRows is currently in reverse emit order; reverse it,
                // sort, then reverse again so the final reversal gives order.
                let ordered = List.rev outputRows |> sortRows <| outputCols <| keys
                outputRows <- List.rev ordered

            | Instruction.DistinctResult ->
                // Deduplicate adjacent-equal rows after sorting.
                let ordered = List.rev outputRows
                let seen    = HashSet<string>()
                let deduped =
                    ordered |> List.filter (fun row ->
                        let key = row |> List.map (sprintf "%A") |> String.concat "|"
                        seen.Add(key))
                outputRows <- List.rev deduped

            | Instruction.LimitResult(countOpt, offsetOpt) ->
                // Clamp int64 LIMIT/OFFSET values to the int32 range before
                // converting. Without clamping, values > Int32.MaxValue wrap
                // negative on .NET (since int is 32-bit), producing incorrect
                // skip/truncate counts. Large positive values are clamped to
                // Int32.MaxValue, which is effectively "unlimited" for any
                // result set that fits in memory.
                let toSafeInt (v: int64) =
                    if v < 0L then 0
                    elif v > int64 Int32.MaxValue then Int32.MaxValue
                    else int v
                let ordered = List.rev outputRows
                let offset  = offsetOpt |> Option.map toSafeInt |> Option.defaultValue 0
                let sliced  = ordered |> List.skip (min offset (List.length ordered))
                let limited =
                    match countOpt with
                    | None   -> sliced
                    | Some c -> sliced |> List.truncate (toSafeInt c)
                outputRows <- List.rev limited

        // ── Finalise result ────────────────────────────────────────────────
        // outputRows was built with O(1) prepend, so it is in reverse order.
        // Reverse once here so the first emitted row is first in the result.
        { Columns      = outputCols
          Rows         = List.rev outputRows
          RowsAffected = rowsAffected }
