#!/usr/bin/env python3
"""Project the independently validated CT01 corpus into TF01's L0 transport.

The JSON remains the authority. Both generated files are checked together so
adding a fixed width cannot quietly exercise slice equality in its place.
Nothing here obtains expected answers from the Rust implementation.
"""

from __future__ import annotations

import argparse

import ct_compare_conformance as oracle
import tfv

TRANSPORT = oracle.DEFAULT_CORPUS.with_suffix(".tfv")
DISPATCH = oracle.ROOT / "code/packages/rust/ct-compare/tests/generated/fixed_widths.rs"


def render(document: dict) -> tuple[str, str]:
    """Validate first, then preserve every case identity and exact value."""
    oracle.validate_document(document)
    records = []
    widths = set()
    for case in document["cases"]:
        fields = [("op", ("text", case["operation"]))]
        for side in ("left", "right"):
            if case["operation"] == "eq_u64":
                fields.append((side + "_u64", ("int", int(case[side + "_u64"], 16))))
            else:
                fields.append((side, ("bytes", bytes.fromhex(case[side + "_hex"]))))
        if "fixed_size_bytes" in case:
            width = case["fixed_size_bytes"]
            widths.add(width)
            fields.append(("width", ("int", width)))
        if "choice" in case:
            fields.append(("choice", ("bool", case["choice"])))
        for key, value in case["expected"].items():
            if key == "output_hex":
                fields.append(("output", ("bytes", bytes.fromhex(value))))
            elif isinstance(value, bool):
                fields.append((key, ("bool", value)))
            else:
                fields.append((key, ("text", value)))
        fields.extend(
            (key, ("int", value)) for key, value in case["expected_work"].items()
        )
        records.append((case["id"], fields))

    dispatch = [
        "// Generated by code/scripts/ct_compare_tfv.py; edit the CT01 JSON corpus.",
        "// Each arm invokes the actual const-generic API, never a slice substitute.",
        "fn fixed_dispatch(width: u64, left: &[u8], right: &[u8]) -> Result<bool, String> {",
        "    match width {",
    ]
    dispatch.extend(
        f"        {width} => fixed::<{width}>(left, right)," for width in sorted(widths)
    )
    dispatch.extend(
        [
            '        _ => Err("fixed width has no generated arm".into()),',
            "    }",
            "}",
        ]
    )
    return tfv.encode_file(records), "\n".join(dispatch) + "\n"


def check_generated(document: dict, transport: str, dispatch: str) -> None:
    """A stale transport or dispatch must fail even when the other is current."""
    want_transport, want_dispatch = render(document)
    if transport != want_transport:
        raise ValueError(
            "cases.tfv is stale; run python code/scripts/ct_compare_tfv.py --write"
        )
    if dispatch != want_dispatch:
        raise ValueError(
            "fixed_widths.rs is stale; run python code/scripts/ct_compare_tfv.py --write"
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    document = oracle.parse_json(oracle.DEFAULT_CORPUS.read_text(encoding="utf-8"))
    if args.write:
        transport, dispatch = render(document)
        DISPATCH.parent.mkdir(parents=True, exist_ok=True)
        for path, contents in ((TRANSPORT, transport), (DISPATCH, dispatch)):
            with path.open("w", encoding="utf-8", newline="\n") as output:
                output.write(contents)
    check_generated(
        document,
        TRANSPORT.read_text(encoding="utf-8"),
        DISPATCH.read_text(encoding="utf-8"),
    )
    print(
        f"ct-compare-v1: {len(document['cases'])} L0 records and fixed-width dispatch current"
    )


if __name__ == "__main__":
    main()
