"""
================================================================
test_end_to_end_training — MX10 acceptance gate (integration)
================================================================

This file is **the broadest correctness test of the MX10 dispatch
work**.  Per-op parity tests (in ``test_rust_backend_parity.py``)
prove each helper produces the right answer in isolation; the
fallback tests prove the pure-Python path is unchanged.  But
those tests don't exercise a real training loop where forward
and backward pass through *many* dispatch decisions in sequence
(matmul → activation → loss → activation backward → matmul
backward → parameter update → repeat).

This test trains a tiny 2-layer MLP for a handful of epochs on
synthetic data and asserts that **loss decreases monotonically**.
If anything in the dispatch chain corrupts a gradient — wrong
shape, swapped operands, an off-by-one in a Broadcast envelope —
training will diverge, NaN out, or stall, and the test will fail.

Two scenarios:

1. ``test_mlp_trains_via_fallback_path`` — always runs.  Uses
   small enough sizes (batch=16, hidden=64) that everything falls
   below the Rust dispatch thresholds.  Validates the unchanged
   pure-Python kernels still wire forward + backward correctly
   for a real training loop.

2. ``test_mlp_trains_via_rust_path`` — skip if the
   ``coding_adventures_matrix_rust_python`` C extension isn't
   installed.  Uses sizes above the matmul (≥4096) and
   activation/reduction (≥100_000) thresholds so the dispatch
   actually fires, and reports wallclock timing.

Both run identical training loops; only the sizes (and therefore
which path is exercised) differ.
"""

from __future__ import annotations

import math
import random
import time
import unittest

from ml_framework_core import Tensor
from ml_framework_core.functions import (
    MatMulFunction,
    MeanFunction,
    ReLUFunction,
    SigmoidFunction,
    SubFunction,
)

try:
    import coding_adventures_matrix_rust_python  # noqa: F401

    EXTENSION_AVAILABLE = True
except ImportError:
    EXTENSION_AVAILABLE = False


def _xavier_init(
    fan_in: int, fan_out: int, *, seed: int
) -> Tensor:
    """Xavier-uniform initialiser for a ``(fan_in, fan_out)`` weight matrix.

    The Xavier initialiser keeps the variance of activations roughly
    constant across layers in a feed-forward network — without it, a
    randomly initialised network with ReLU activations either
    saturates (gradients vanish) or explodes (gradients overflow).

    Bound: ``sqrt(6 / (fan_in + fan_out))``, drawn uniform in
    ``[-bound, bound]``.
    """
    rng = random.Random(seed)
    bound = math.sqrt(6.0 / (fan_in + fan_out))
    data = [rng.uniform(-bound, bound) for _ in range(fan_in * fan_out)]
    return Tensor(data, (fan_in, fan_out), requires_grad=True)


def _synthetic_binary_classification(
    n: int, d: int, *, seed: int
) -> tuple[Tensor, Tensor]:
    """Generate ``n`` samples of ``d``-dim inputs with a sigmoidal target.

    Returns ``(X, y)`` where ``X`` is shape ``(n, d)`` and ``y`` is shape
    ``(n, 1)`` of values in ``[0, 1]``.  The target is generated by
    a fixed linear projection through a sigmoid, so a 2-layer MLP
    can fit it perfectly given enough capacity — making this an
    honest sanity-check problem (loss should approach zero with
    enough training, not bounce around a noisy floor).
    """
    rng = random.Random(seed)
    x_data = [rng.uniform(-1.0, 1.0) for _ in range(n * d)]
    X = Tensor(x_data, (n, d))

    # Fixed teacher weights for the target.  Same seed offset so the
    # targets are deterministic but independent of the model init.
    teacher_rng = random.Random(seed + 1000)
    teacher_weights = [teacher_rng.uniform(-1.0, 1.0) for _ in range(d)]

    # y_i = sigmoid(sum_j(x_ij * w_j))
    y_data = []
    for i in range(n):
        z = sum(x_data[i * d + j] * teacher_weights[j] for j in range(d))
        y_data.append(1.0 / (1.0 + math.exp(-z)))
    y = Tensor(y_data, (n, 1))
    return X, y


def _mse_loss_and_grad(
    pred: Tensor, target: Tensor
) -> tuple[float, Tensor]:
    """Mean squared error loss + grad-output for backward.

    ``loss = mean((pred - target)²)``

    Returns ``(loss_value, grad_output_for_pred)`` where
    ``grad_output = 2 * (pred - target) / n``.  We compute the
    grad analytically rather than going through SumFunction +
    MulFunction so the test exercises pred-going-backward
    independently of the loss-shaping machinery.
    """
    n = pred.numel
    diff_data = [
        p - t
        for p, t in zip(pred.data, target.data, strict=False)
    ]
    loss_val = sum(d * d for d in diff_data) / n
    grad_data = [2.0 * d / n for d in diff_data]
    grad_output = Tensor(grad_data, pred.shape, device=pred.device)
    return loss_val, grad_output


def _sgd_step(params: list[Tensor], lr: float) -> None:
    """In-place SGD update.

    For each ``p`` with a populated ``.grad``, replace ``p.data`` with
    ``p.data - lr * p.grad.data`` and zero the gradient.  We mutate
    ``p.data`` rather than building a new ``Tensor`` so the parameter
    identity (used by autograd) stays stable across steps.
    """
    for p in params:
        if p.grad is None:
            continue
        p.data = [
            v - lr * g for v, g in zip(p.data, p.grad.data, strict=False)
        ]
        # Reset grad to zero (autograd accumulates by default).
        p.grad = None


def _train_one_epoch(
    X: Tensor, y: Tensor, W1: Tensor, W2: Tensor, lr: float
) -> float:
    """One forward + backward + SGD step over the whole batch.

    Architecture: ``X → matmul(W1) → ReLU → matmul(W2) → Sigmoid``.
    Loss: MSE against ``y``.

    The output activation is Sigmoid (not the more typical
    BCE-with-logits) because this lets the parity/timing test
    exercise SigmoidFunction.forward and .backward both end-to-end.
    """
    # Forward
    h = MatMulFunction.apply(X, W1)        # (n, hidden)
    h = ReLUFunction.apply(h)              # (n, hidden)
    z = MatMulFunction.apply(h, W2)        # (n, 1)
    pred = SigmoidFunction.apply(z)        # (n, 1)

    # Loss + analytic grad
    loss_val, grad_pred = _mse_loss_and_grad(pred, y)

    # Backward (autograd chains through Sigmoid → MatMul → ReLU → MatMul)
    pred.backward(grad_pred)

    # Parameter update
    _sgd_step([W1, W2], lr)

    return loss_val


class EndToEndTrainingTests(unittest.TestCase):
    """Train a tiny MLP and assert loss decreases monotonically.

    The strict monotonicity check is conservative — a noisy SGD on
    a small dataset can oscillate epoch-to-epoch, so we instead
    assert that **the final epoch's loss is materially lower than
    the initial epoch's loss** (a halving is plenty of headroom).
    """

    def test_mlp_trains_via_fallback_path(self) -> None:
        """Small MLP, sizes below all Rust thresholds — pure-Python path.

        ``batch=16, d=8, hidden=8`` keeps every op below the Rust
        threshold:
          - matmuls: 16·8·8 = 1024 < 4096
          - elementwise (post-bias): 16·8 = 128 < 100_000
          - activations: 16·8 = 128 < 100_000

        So this test exercises the unchanged pure-Python kernels
        end-to-end.  If the dispatch wiring ever leaks Rust calls
        into the small-tensor path (e.g. broken predicate), this
        test would either error from a missing C extension or
        compute slightly different numbers and break monotonicity.
        """
        n, d, hidden = 16, 8, 8
        X, y = _synthetic_binary_classification(n, d, seed=42)
        W1 = _xavier_init(d, hidden, seed=1)
        W2 = _xavier_init(hidden, 1, seed=2)

        # Track loss across epochs
        losses: list[float] = []
        n_epochs = 200  # small data, more epochs to compensate
        lr = 0.5
        for _ in range(n_epochs):
            loss = _train_one_epoch(X, y, W1, W2, lr)
            losses.append(loss)

        initial_loss = losses[0]
        final_loss = losses[-1]
        self.assertLess(
            final_loss,
            initial_loss * 0.5,
            f"MLP did not learn: initial loss {initial_loss:.4f}, "
            f"final loss {final_loss:.4f} (expected at least 50% reduction)",
        )

    @unittest.skipUnless(
        EXTENSION_AVAILABLE,
        "matrix_rust_python C extension not installed; "
        "this test exercises the Rust dispatch path and is meaningless without it.",
    )
    def test_mlp_trains_via_rust_path(self) -> None:
        """Larger MLP, sizes above all Rust thresholds — Rust dispatch path.

        ``batch=400, d=400, hidden=300`` puts every op above its
        respective threshold:
          - matmul (X @ W1): 400·400·300 = 48,000,000 ≫ 4096
          - matmul (h @ W2): 400·300·1 = 120,000 ≫ 4096
          - elementwise (h post-ReLU): 400·300 = 120,000 ≥ 100_000

        This is the actual end-to-end Rust dispatch test.  Same
        monotonicity assertion as the fallback test; additionally
        reports wallclock per epoch so a future change that
        accidentally slows the dispatch down (e.g. introducing a
        Python loop over cells inside a helper) shows up.
        """
        n, d, hidden = 400, 400, 300
        X, y = _synthetic_binary_classification(n, d, seed=42)
        W1 = _xavier_init(d, hidden, seed=1)
        W2 = _xavier_init(hidden, 1, seed=2)

        losses: list[float] = []
        epoch_times: list[float] = []
        n_epochs = 5  # large data, fewer epochs (each epoch is heavier)
        lr = 0.1
        for _ in range(n_epochs):
            t0 = time.perf_counter()
            loss = _train_one_epoch(X, y, W1, W2, lr)
            t1 = time.perf_counter()
            losses.append(loss)
            epoch_times.append(t1 - t0)

        initial_loss = losses[0]
        final_loss = losses[-1]
        self.assertLess(
            final_loss,
            initial_loss * 0.95,
            f"MLP did not learn via Rust dispatch: initial loss "
            f"{initial_loss:.4f}, final loss {final_loss:.4f} "
            f"(expected at least 5% reduction over {n_epochs} epochs)",
        )

        # Report timing to stderr — not an assertion, just a signal
        # for humans reading test output that the Rust path is engaged.
        avg_epoch_ms = 1000.0 * sum(epoch_times) / len(epoch_times)
        print(
            f"\n[rust-path] {n_epochs} epochs, n={n} batch · d={d} · h={hidden}; "
            f"avg epoch wallclock = {avg_epoch_ms:.1f} ms; "
            f"loss {initial_loss:.4f} → {final_loss:.4f}"
        )


if __name__ == "__main__":
    unittest.main()
