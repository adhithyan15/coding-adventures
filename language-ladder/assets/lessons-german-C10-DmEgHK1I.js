<!-- hl-knowledge: introduces=[]; assesses=[GE-GRAMMAR-HABEN-REGULAR-01, GE-GRAMMAR-HABEN-DU-HAST-01, GE-GRAMMAR-HABEN-ER-HAT-01, GE-GRAMMAR-HABEN-B-DROP-01] -->

