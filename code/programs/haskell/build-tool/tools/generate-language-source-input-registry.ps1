param(
    [string]$RegistryPath = "",
    [string]$OutputPath = ""
)

$ErrorActionPreference = "Stop"

$packageRoot = Split-Path -Parent $PSScriptRoot
if ($RegistryPath -eq "") {
    $RegistryPath = Join-Path $packageRoot "../../../specs/fixtures/build-tool-v1/language-source-input-registry.json"
}
if ($OutputPath -eq "") {
    $OutputPath = Join-Path $packageRoot "src/LanguageSourceInputRegistryData.hs"
}

$lines = [System.IO.File]::ReadAllLines((Resolve-Path -LiteralPath $RegistryPath))
$rendered = foreach ($line in $lines) {
    $escaped = $line.Replace("\", "\\").Replace('"', '\"').Replace("`t", "\t")
    "        `"$escaped`""
}

$source = @(
    "{-# LANGUAGE OverloadedStrings #-}"
    ""
    "-- Generated by tools/generate-language-source-input-registry.ps1."
    "-- Do not edit by hand."
    "module LanguageSourceInputRegistryData (languageSourceInputRegistryJSON) where"
    ""
    "import qualified Data.Text as Text"
    ""
    "languageSourceInputRegistryJSON :: Text.Text"
    "languageSourceInputRegistryJSON ="
    "    Text.unlines"
    "        ["
) + (($rendered -join ",`n") -split "`n") + @(
    "        ]"
    ""
)

[System.IO.File]::WriteAllLines(
    $OutputPath,
    $source,
    [System.Text.UTF8Encoding]::new($false)
)
