<!-- hl-knowledge: introduces=[GE-LEX-NASE-02]; assesses=[GE-LEX-HAND-02, GE-SOUND-AUGE-03, GE-SOUND-OHR-03, GE-ETYMON-OHR-04, GE-SOUND-MUND-03] -->

