<!-- hl-knowledge: introduces=[]; assesses=[TE-LEX-C41-DEIXIS-01, TE-LEX-C41-DEIXIS-02, TE-LEX-C41-DEIXIS-03, TE-LEX-C41-DEIXIS-04, TE-LEX-C41-DEIXIS-05, TE-LEX-C41-DEIXIS-06] -->

