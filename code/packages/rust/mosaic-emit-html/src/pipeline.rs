/// The pieces needed to format a single HTML element of a given primitive.
///
/// Split out so that author-declared part styles (from mosstyle) can be
/// merged with the primitive's built-in inline style before the opening
/// tag is formed.
struct HtmlTag {
    /// The element name without `<>`, e.g. `div`, `span`, `img`.
    tag_name: &'static str,
    /// The built-in inline-style fragment for this primitive — already in
    /// CSS shorthand form, e.g. `display: flex; flex-direction: row`. Empty
    /// for primitives that have no defaults (`Box`, `Text`, `Image`).
    builtin_style: &'static str,
    /// Extra non-style attributes the primitive wants on every element,
    /// e.g. ` class="icon"` for `Icon`. Includes the leading space when
    /// non-empty.
    extra_attrs: &'static str,
    /// `true` for HTML void elements (`<hr>`, `<img>`) which take no
    /// closing tag.
    void: bool,
}

/// Map a moslayout primitive tag to its HTML element + built-in style.
///
/// The eight primitives we cover in this first cut match what the React
/// and Skia backends started with. Unknown tags return
/// `PipelineEmitError::UnknownPrimitive` — silently rendering `<div>` for
/// an unknown tag would be worse than a clear error.
fn primitive_to_html_tag(tag: &str) -> Result<HtmlTag, PipelineEmitError> {
    Ok(match tag {
        "Box" => HtmlTag {
            tag_name: "div",
            builtin_style: "",
            extra_attrs: "",
            void: false,
        },
        "Row" => HtmlTag {
            tag_name: "div",
            builtin_style: "display: flex; flex-direction: row",
            extra_attrs: "",
            void: false,
        },
        "Column" => HtmlTag {
            tag_name: "div",
            builtin_style: "display: flex; flex-direction: column",
            extra_attrs: "",
            void: false,
        },
        "Text" => HtmlTag {
            tag_name: "span",
            builtin_style: "",
            extra_attrs: "",
            void: false,
        },
        "Image" => HtmlTag {
            tag_name: "img",
            builtin_style: "",
            extra_attrs: "",
            void: true,
        },
        "Spacer" => HtmlTag {
            tag_name: "div",
            builtin_style: "flex: 1",
            extra_attrs: "",
            void: false,
        },
        "Divider" => HtmlTag {
            tag_name: "hr",
            builtin_style: "",
            extra_attrs: "",
            void: true,
        },
        "Icon" => HtmlTag {
            tag_name: "span",
            builtin_style: "",
            extra_attrs: " class=\"icon\"",
            void: false,
        },
        other => return Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    })
}

/// Walk a `LayoutNode` and produce the corresponding indented HTML string.
///
/// Behaviour summary:
///
/// - The primitive's built-in style is merged with any author-declared
///   `part` style (looked up by `node.part_name`) into a single
///   `style="..."` attribute. Author wins on collisions — `style="a; b;"`
///   in HTML uses last-property-wins, mirroring CSS specificity.
/// - **Image** primitives read a `source` prop (string literal or slot
///   ref) and emit it as `src="..."`. A slot ref becomes `src="{{slot}}"`.
/// - **Text** primitives read a `content` prop. A slot ref becomes the
///   element's text content as `{{slot}}`; a literal string becomes the
///   element's escaped text content.
/// - **Emit refs** in props produce no attribute but emit a
///   `<!-- emit "<name>" dropped: HTML is static -->` comment immediately
///   before the element.
fn emit_html_tree(
    node: &LayoutNode,
    indent: usize,
    part_styles: &HashMap<String, String>,
) -> Result<String, PipelineEmitError> {
    let pad = " ".repeat(indent);
    let mut out = String::new();

    // Surface dropped emit refs as a comment so the generated HTML is
    // self-documenting — a reviewer can grep for them and see at a glance
    // what the React backend would have wired up.
    for prop in &node.props {
        if let LayoutPropValue::EmitRef(name) = &prop.value {
            writeln!(
                out,
                "{pad}<!-- emit \"{name}\" dropped: HTML is static -->"
            )
            .unwrap();
        }
    }

    let HtmlTag {
        tag_name,
        builtin_style,
        extra_attrs,
        void,
    } = primitive_to_html_tag(&node.tag)?;

    // Merge the built-in style with the author-declared part style. The
    // author's declarations come second so they override on collision.
    let part_style = node
        .part_name
        .as_deref()
        .and_then(|n| part_styles.get(n).map(String::as_str))
        .unwrap_or("");
    let merged_style = merge_styles(builtin_style, part_style);
    let style_attr = if merged_style.is_empty() {
        String::new()
    } else {
        format!(" style=\"{merged_style}\"")
    };

    // Image: source becomes the src attribute.
    let src_attr = if node.tag == "Image" {
        match find_prop(node, "source") {
            Some(LayoutPropValue::SlotRef(s)) => format!(" src=\"{{{{{}}}}}\"", camel(s)),
            Some(LayoutPropValue::String(lit)) => {
                format!(" src=\"{}\"", escape_html_attr(lit))
            }
            _ => String::new(),
        }
    } else {
        String::new()
    };

    if void {
        // HTML5-style void elements (`<hr>`, `<img>`) — no closing tag.
        // We use the unslashed form (HTML5, not XHTML).
        writeln!(out, "{pad}<{tag_name}{extra_attrs}{src_attr}{style_attr}>").unwrap();
        return Ok(out);
    }

    // Text node with a `content: slot: x` prop lowers to a `<span>` whose
    // text is `{{x}}`. A literal-string content becomes escaped text.
    if node.tag == "Text" && node.children.is_empty() {
        match find_prop(node, "content") {
            Some(LayoutPropValue::SlotRef(s)) => {
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{{{{{slot}}}}}</{tag_name}>",
                    slot = camel(s)
                )
                .unwrap();
                return Ok(out);
            }
            Some(LayoutPropValue::String(lit)) => {
                writeln!(
                    out,
                    "{pad}<{tag_name}{extra_attrs}{style_attr}>{esc}</{tag_name}>",
                    esc = escape_html_text(lit)
                )
                .unwrap();
                return Ok(out);
            }
            _ => {}
        }
    }

    // Container or empty leaf: emit open + children + close.
    if node.children.is_empty() {
        writeln!(
            out,
            "{pad}<{tag_name}{extra_attrs}{style_attr}></{tag_name}>"
        )
        .unwrap();
        return Ok(out);
    }

    writeln!(out, "{pad}<{tag_name}{extra_attrs}{style_attr}>").unwrap();
    for child in &node.children {
        out.push_str(&emit_html_tree(child, indent + 2, part_styles)?);
    }
    writeln!(out, "{pad}</{tag_name}>").unwrap();
    Ok(out)
}

