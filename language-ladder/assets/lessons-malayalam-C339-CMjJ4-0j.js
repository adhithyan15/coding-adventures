<!-- hl-knowledge: introduces=[ML-GRAMMAR-C341-THINK-THAT-01]; assesses=[ML-GRAMMAR-C72-ENNU-01, ML-GRAMMAR-C72-ENNU-VERBS-01, ML-GRAMMAR-C89-NOMINAL-01, ML-LEX-SARI-01] -->

