<!-- hl-knowledge: introduces=[GE-ETYMON-HOEREN-10]; assesses=[GE-LEX-HOEREN-09, GE-SOUND-GRIMMS-LAW-04, GE-ETYMON-HUND-03, GE-ETYMON-SITZEN-03] -->

