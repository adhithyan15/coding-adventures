/// Build a `part_name -> "css: value; ..."` lookup table from a mosstyle
/// `StyleDef`.
///
/// The HTML backend speaks CSS shorthand (`background: #eee; padding: 8px`)
/// rather than the React backend's CSS-in-JS form
/// (`background: "#eee", padding: "8px"`). State blocks (`state hover { ... }`)
/// are ignored here — they'd need a `<style>`-block detour with
/// pseudo-class selectors, which is out of scope for this PR.
fn build_part_style_map(style: &StyleDef) -> HashMap<String, String> {
    let mut out = HashMap::with_capacity(style.parts.len());
    for part in &style.parts {
        let frag = build_inline_css_fragment(&part.base);
        if !frag.is_empty() {
            out.insert(part.name.clone(), frag);
        }
    }
    out
}

/// Convert a slice of [`StyleProp`] values into a `key: value; ...` CSS
/// declaration list, suitable for embedding in a `style="..."` attribute.
///
/// kebab-case names pass through verbatim — they are already in valid CSS
/// property syntax. Values are emitted unquoted. We do *not* attempt to
/// validate values: the mosstyle compiler is upstream of us and is
/// trusted to have parsed them. Any embedded `"` is HTML-attr-escaped to
/// keep the attribute well-formed.
fn build_inline_css_fragment(props: &[StyleProp]) -> String {
    let mut parts: Vec<String> = Vec::with_capacity(props.len());
    for p in props {
        // The key is the kebab-case CSS property name — pass through.
        // For an author who wrote `backgroundColor: ...` in source we map
        // that to `background-color` so the resulting HTML attribute is
        // canonical CSS, not mixed-case.
        let key = camel_to_kebab(&p.name);
        let value = escape_html_attr(&p.value);
        parts.push(format!("{key}: {value}"));
    }
    parts.join("; ")
}

/// Concatenate two CSS declaration lists, semicolon-separated, dropping
/// empty inputs. Built-in style comes first so the author's declarations
/// can override defaults (last-property-wins).
fn merge_styles(builtin: &str, author: &str) -> String {
    match (builtin.is_empty(), author.is_empty()) {
        (true, true) => String::new(),
        (false, true) => builtin.to_string(),
        (true, false) => author.to_string(),
        (false, false) => format!("{builtin}; {author}"),
    }
}

