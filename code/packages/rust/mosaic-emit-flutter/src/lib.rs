//! # mosaic-emit-flutter — Flutter (Dart) backend
//!
//! This crate is the Flutter backend for the Mosaic compiler. It
//! consumes the three-IR triple (mosmodel + moslayout + mosstyle) and
//! emits a Dart source file containing a `StatelessWidget` class for
//! the component. The output drops directly into a Flutter `lib/`
//! directory; the host imports it like any other Dart file.
//!
//! ## Why a separate backend
//!
//! Flutter is a first-class cross-platform target (iOS, Android,
//! macOS, Windows, Linux, web). It is *also* the only backend whose
//! widget model is structurally closest to React's: a functional tree
//! of immutable widgets with a single `build` method per component.
//! That makes it a natural fit for Mosaic's React-shaped pipeline —
//! everything that lowers to React's JSX has a near-1-for-1
//! analogue in Flutter widgets.
//!
//! ## Output structure
//!
//! ```dart
//! // Auto-generated by mosaic-emit-flutter. Do not edit.
//! import 'package:flutter/material.dart';
//!
//! // Discriminated event union — one subclass per declared emit.
//! sealed class GridEvent { const GridEvent(); }
//! class GridEventNavigate extends GridEvent {
//!   final int row;
//!   final int col;
//!   const GridEventNavigate({required this.row, required this.col});
//! }
//!
//! class Grid extends StatelessWidget {
//!   final List<String> headers;
//!   final void Function(GridEvent) dispatch;
//!
//!   const Grid({super.key, required this.headers, required this.dispatch});
//!
//!   @override
//!   Widget build(BuildContext context) {
//!     return Container(
//!       child: Row(children: [
//!         Text(headers.first),
//!       ]),
//!     );
//!   }
//! }
//! ```
//!
//! ## Naming conventions
//!
//! - `.mil` component name `Grid`        → Dart class `Grid` (PascalCase, unchanged).
//! - Event union: `<Component>Event` is a sealed base class; each
//!   declared emit becomes `<Component>Event<EventName>` with the
//!   emit's `on` prefix stripped and the rest PascalCased.
//! - Slot `display-name` (kebab-case) → Dart field `displayName`
//!   (camelCase). Same rule as the React backend.
//!
//! ## Style mapping
//!
//! Mosaic style parts lower to Flutter widget properties on a
//! best-effort basis. The most common CSS-shape rules map cleanly:
//!
//! | Mosaic style prop  | Flutter widget property        |
//! |---|---|
//! | `padding`          | `padding: EdgeInsets.all(N)`   |
//! | `background-color` | `color: Color(0xFF…)`          |
//! | `border-radius`    | `BorderRadius.circular(N)`     |
//! | `width` / `height` | `width:` / `height:`           |
//!
//! Properties without a clean Flutter equivalent (`font-family`
//! variants, complex `border-style` cascades) are emitted as
//! `// TODO: <prop>` Dart comments so authors can spot-fill them
//! in the host. A future pass will widen the coverage.
//!
//! See the per-primitive function comments in `pipeline.rs` for the
//! detailed widget-by-widget lowering tables.

