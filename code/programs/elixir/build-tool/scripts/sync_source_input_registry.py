"""Embed the checked neutral source-input registry in generated Elixir source.

The build tool embeds this local snapshot at compile time. Keeping the copy
mechanical makes a missing selector visible in code review and in native tests.
"""

from __future__ import annotations

import argparse
import base64
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
SOURCE = (
    Path(__file__).resolve().parents[4]
    / "specs/fixtures/build-tool-v1/language-source-input-registry.json"
)
TARGET = PACKAGE / "lib/build_tool/source_input_registry_data.ex"


def render_module(checked: bytes) -> bytes:
    encoded = base64.b64encode(checked).decode("ascii")
    chunks = [encoded[i : i + 96] for i in range(0, len(encoded), 96)]
    lines = [
        "# Generated by scripts/sync_source_input_registry.py; do not edit by hand.",
        "defmodule BuildTool.SourceInputRegistryData do",
        "  @moduledoc false",
        "  @encoded [",
        *(f'    "{chunk}",' for chunk in chunks),
        "  ]",
        "  @bytes @encoded |> Enum.join() |> Base.decode64!()",
        "  def bytes, do: @bytes",
        "end",
        "",
    ]
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if generated source differs"
    )
    args = parser.parse_args()
    rendered = render_module(SOURCE.read_bytes())
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != rendered:
            parser.error("Elixir source-input registry snapshot is stale")
        return 0
    TARGET.write_bytes(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
