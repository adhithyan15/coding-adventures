<!-- hl-knowledge: introduces=[AR-LEX-C289-TAJRIBA289-01]; assesses=[AR-LEX-C82-ADJ82-01, AR-LEX-C98-WORLD98-03, AR-LEX-C149-QUAL149-05] -->

