/// **The slice's acceptance criterion.**
#[test]
fn macrooct_and_oct_agree_on_everything_except_instruction_provenance() {
    for pair in PAIRS {
        let a = compile_source(pair.macrooct, "identity")
            .unwrap_or_else(|e| panic!("MacroOct failed to compile ({}): {e}", pair.what));
        let b = oct_iir_compiler::compile_source(pair.oct, "identity")
            .unwrap_or_else(|e| panic!("the hand-expanded Oct failed to compile ({}): {e}", pair.what));
        assert_same_iir(pair.what, &a, &b, false);
    }
    assert!(PAIRS.len() >= 10, "the oracle must keep a real corpus, not one example");
}

/// The same criterion, for `@include`.
#[test]
fn included_macrooct_and_hand_expanded_oct_agree() {
    for pair in INCLUDE_PAIRS {
        let a = compile_source_with_includes(pair.macrooct, "identity", pair.includes)
            .unwrap_or_else(|e| panic!("MacroOct failed to compile ({}): {e}", pair.what));
        let b = oct_iir_compiler::compile_source(pair.oct, "identity")
            .unwrap_or_else(|e| panic!("the hand-expanded Oct failed to compile ({}): {e}", pair.what));
        assert_same_iir(pair.what, &a, &b, false);
    }
}

/// Removes the exclusion: with the line numbers aligned, the IIR matches
/// **including** the provenance side table.
///
/// This is what turns the exclusion in the tests above from a loophole into a
/// measurement. The Oct source here is padded with leading blank lines so that
/// `fn main` lands on the same physical line it occupies in the MacroOct
/// source — the `@if` sits on line 1, so the Oct equivalent starts on line 2.
/// If the preprocessor were doing anything to the program beyond choosing
/// which text reaches the parser, this would fail even with the padding.
#[test]
fn line_aligned_sources_produce_byte_identical_iir_including_provenance() {
    // `@if 1` on line 1; the kept code on line 2.
    let macrooct = "@if 1\nfn main() { out(1, 42); }\n@else\nfn main() { out(1, 7); }\n@end\n";
    // The same code, also on line 2.
    let oct = "\nfn main() { out(1, 42); }\n";

    let a = compile_source(macrooct, "identity").expect("MacroOct compiles");
    let b = oct_iir_compiler::compile_source(oct, "identity").expect("Oct compiles");
    assert_same_iir("line-aligned @if/@else", &a, &b, true);

    // And the padding is load-bearing, not decoration: without it the two
    // source maps really do differ, which is the difference the other tests
    // exclude. Asserting that here means the exclusion is measured rather
    // than assumed.
    let unaligned =
        oct_iir_compiler::compile_source("fn main() { out(1, 42); }\n", "identity").unwrap();
    assert_ne!(
        render(&a, true),
        render(&unaligned, true),
        "if this passes, the source maps were never line-sensitive and the \
         exclusion in the other tests was never needed — simplify them"
    );
    assert_eq!(
        render(&a, false),
        render(&unaligned, false),
        "with provenance excluded, the unaligned Oct program must still match"
    );
}

/// The include-path version of the alignment argument.
///
/// An included file's tokens keep *their own* file's line numbers, which is
/// the correct behaviour (that is what the `SourceMap`'s `FileId` is for) and
/// makes a byte-identical provenance comparison impossible in general: two
/// files both have a line 1. This test states that explicitly rather than
/// leaving a reader to wonder why the include oracle excludes provenance.
#[test]
fn an_included_functions_positions_come_from_the_included_file() {
    let module = compile_source_with_includes(
        "@include \"helper.macrooct\"\nfn main() { out(1, helper()); }\n",
        "identity",
        &[("helper.macrooct", "fn helper() -> u8 { return 42; }\n")],
    )
    .expect("compiles");

    let helper = module
        .functions
        .iter()
        .find(|f| f.name == "helper")
        .expect("the included function is present");
    // `helper` is on line 1 *of helper.macrooct*, even though the `@include`
    // that pulled it in is on line 1 of the primary file and `main` is on
    // line 2 of it.
    assert!(
        helper.source_map.iter().any(|p| p.line == 1),
        "the included function's positions should come from its own file"
    );
}

/// A MacroOct program that uses no directives at all must be, byte for byte,
/// the same compilation as the identical Oct program.
///
/// The degenerate case, and the one that would catch the crudest possible
/// regression: a preprocessor that mangles a stream it should have passed
/// through untouched. Provenance included, because with no directives there is
/// no line shift to excuse.
#[test]
fn a_directive_free_program_compiles_byte_identically_to_oct() {
    for src in [
        "fn main() { out(1, 42); }\n",
        "fn main() { out(1, 200 + 100); }\n",
        "fn main() { if !(1 == 2) { out(1, 42); } else { out(1, 0); } }\n",
        "static counter: u8 = 40;\nfn bump() { counter = counter + 1; }\n\
         fn main() { bump(); bump(); out(1, counter); }\n",
        "fn main() { let n: u8 = 0; loop { n = n + 1; if n == 3 { break; } } out(1, n); }\n",
    ] {
        let a = compile_source(src, "identity").expect("MacroOct compiles");
        let b = oct_iir_compiler::compile_source(src, "identity").expect("Oct compiles");
        assert_same_iir(src, &a, &b, true);
    }
}

/// MacroOct's modules claim `language = "oct"`, and that is correct.
///
/// After preprocessing, the program being lowered *is* Oct — the same tokens
/// Oct's own lexer would have produced from the hand-expanded source. A
/// different string here would be a difference with no semantic content that
/// nevertheless broke every comparison above, so it is pinned deliberately
/// rather than left to be "fixed" by someone who reads it as a bug.
#[test]
fn the_module_identifies_its_language_as_oct() {
    let module = compile_source("@if 1\nfn main() { }\n@end\n", "identity").unwrap();
    assert_eq!(module.language, "oct");
    assert_eq!(module.entry_point.as_deref(), Some("main"));
}

