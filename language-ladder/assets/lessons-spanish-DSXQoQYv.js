<!-- hl-knowledge: introduces=[]; assesses=[ES-GRAMMAR-BACKDROP-AND-EVENT, ES-LEX-CUANDO, ES-GRAMMAR-AR-IMPERFECT-SINGULAR, ES-GRAMMAR-AR-PRETERITE-SINGULAR, ES-LEX-ESTUDIAR, ES-LEX-HABLAR, ES-LEX-TENER, ES-GRAMMAR-TENER-PRETERITE-SINGULAR] -->

