//! HIR → structural Verilog back-writer.
//!
//! Walks an HIR document and emits IEEE 1364-2005 Verilog. The synthesisable
//! subset is the target for v0.1.0; behavioural processes (always blocks) and
//! testbench constructs are documented as v0.2.0.
//!
//! ## Identifier escaping
//!
//! Verilog reserves many keywords (`input`, `output`, `wire`, `assign`, …).
//! When a signal or module name collides with a reserved word, or contains
//! characters not allowed in a simple identifier (`a-z A-Z 0-9 _$`), we
//! emit an *escaped identifier*: `\name ` (backslash-prefix, space-suffix).
//! The space is mandatory in Verilog grammar to terminate the escaped name.
//!
//! ```text
//! module my_buffer (         ← simple identifier, no escaping needed
//!   input  \input_port ,    ← "input_port" collides with keyword "input"? No,
//!                              wait — "input_port" is fine; only "input" alone
//!                              is reserved. Let's show a real case:
//!   input  \and ,           ← "and" is reserved → escaped as \and  (note space)
//!   output y
//! );
//! ```
//!
//! ## Continuous assignments
//!
//! Each HIR `ContAssign { target, rhs }` maps to:
//! ```text
//! assign <target> = <rhs>;
//! ```
//!
//! ## Instance ports
//!
//! ```text
//! cell_type [#(params)] inst_name (connections);
//! ```
//!
//! ## Binary operator map
//!
//! | HIR op  | Verilog |   | HIR op  | Verilog |
//! |---------|---------|---|---------|---------|
//! | `AND`   | `&`     |   | `+`     | `+`     |
//! | `OR`    | `\|`    |   | `-`     | `-`     |
//! | `XOR`   | `^`     |   | `*`     | `*`     |
//! | `NAND`  | `~&`    |   | `<`     | `<`     |
//! | `NOR`   | `~\|`   |   | `<=`    | `<=`    |
//! | `XNOR`  | `~^`    |   | `==`    | `==`    |
//!
//! ## Unary operator map
//!
//! | HIR op      | Verilog |
//! |-------------|---------|
//! | `NOT`       | `~`     |
//! | `NEG`       | `-`     |
//! | `LOGIC_NOT` | `!`     |
//! | `AND_RED`   | `&`     |
//! | `OR_RED`    | `\|`    |

use std::fmt::Write as FmtWrite;
use std::path::Path;

use hdl_ir::expr::{Expr, LitValue};
use hdl_ir::hir::Hir;
use hdl_ir::module::{ContAssign, Direction, Module};
use hdl_ir::types::Ty;

// ---------------------------------------------------------------------------
// Reserved words
// ---------------------------------------------------------------------------

/// Verilog-2005 reserved words.  Any identifier matching these must be emitted
/// as an escaped identifier (`\name `).
const VERILOG_RESERVED: &[&str] = &[
    "always", "and", "assign", "begin", "buf", "case", "casex", "casez",
    "default", "defparam", "else", "end", "endcase", "endfunction",
    "endgenerate", "endmodule", "endtask", "for", "function", "generate",
    "genvar", "if", "initial", "inout", "input", "integer", "localparam",
    "module", "nand", "negedge", "nor", "not", "or", "output", "parameter",
    "posedge", "real", "reg", "signed", "supply0", "supply1", "task",
    "tri", "unsigned", "wire", "xnor", "xor",
];

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/// Write a Verilog file containing every `Module` in `hir`.
pub fn write_verilog(hir: &Hir, path: &Path) -> std::io::Result<()> {
    let text = write_verilog_str(hir);
    std::fs::write(path, text)
}

/// Return the Verilog source for `hir` as a `String`.
pub fn write_verilog_str(hir: &Hir) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by real-fpga-export 0.1.0");
    let _ = writeln!(out, "// HIR top: {}\n", hir.top);
    for module in hir.modules.values() {
        let _ = write!(out, "{}", module_to_verilog(module));
        out.push('\n');
    }
    out
}

// ---------------------------------------------------------------------------
// Module emission
// ---------------------------------------------------------------------------

fn module_to_verilog(module: &Module) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "module {} (", escape_id(&module.name));

    // Port list
    let port_lines: Vec<String> = module.ports.iter().map(|p| {
        let dir_str = match p.direction {
            Direction::In    => "input",
            Direction::Out   => "output",
            Direction::Inout => "inout",
        };
        let range = type_to_range(&p.ty);
        format!("  {dir_str} {range}{}", escape_id(&p.name))
    }).collect();
    out.push_str(&port_lines.join(",\n"));
    out.push_str("\n);\n");

    // Internal wire declarations
    for net in &module.nets {
        let range = type_to_range(&net.ty);
        let _ = writeln!(out, "  wire {range}{};", escape_id(&net.name));
    }

    // Continuous assignments
    for ca in &module.cont_assigns {
        let _ = writeln!(out, "  {};", continuous_assign_to_verilog(ca));
    }

    // Instances
    for inst in &module.instances {
        out.push_str(&instance_to_verilog(inst));
    }

    out.push_str("endmodule\n");
    out
}

// ---------------------------------------------------------------------------
// Type → Verilog range prefix
// ---------------------------------------------------------------------------

/// Return `"[width-1:0] "` for vectors, `""` for 1-bit types.
fn type_to_range(ty: &Ty) -> String {
    match ty {
        Ty::Vec { width } => format!("[{}:0] ", width - 1),
        _ => String::new(),
    }
}

// ---------------------------------------------------------------------------
// Continuous assignment
// ---------------------------------------------------------------------------

fn continuous_assign_to_verilog(ca: &ContAssign) -> String {
    format!("assign {} = {}", expr_to_verilog(&ca.target), expr_to_verilog(&ca.rhs))
}

// ---------------------------------------------------------------------------
// Instance emission
// ---------------------------------------------------------------------------

fn instance_to_verilog(inst: &hdl_ir::module::Instance) -> String {
    let mut parts: Vec<String> = Vec::new();
    parts.push(format!("  {}", escape_id(&inst.module)));

    // Parameters
    if !inst.parameters.is_empty() {
        let mut params: Vec<(String, &hdl_ir::expr::Expr)> =
            inst.parameters.iter().collect::<Vec<_>>()
                .into_iter().map(|(k, v)| (k.clone(), v)).collect();
        params.sort_by_key(|(k, _)| k.clone());
        let plist: Vec<String> = params.iter()
            .map(|(k, v)| format!(".{}({})", escape_id(k), expr_to_verilog(v)))
            .collect();
        parts.push(format!("#({})", plist.join(", ")));
    }

    parts.push(escape_id(&inst.name));

    // Connections
    if inst.connections.is_empty() {
        parts.push("()".to_string());
    } else {
        let mut conns: Vec<(String, &hdl_ir::expr::Expr)> =
            inst.connections.iter().collect::<Vec<_>>()
                .into_iter().map(|(k, v)| (k.clone(), v)).collect();
        conns.sort_by_key(|(k, _)| k.clone());
        let clist: Vec<String> = conns.iter()
            .map(|(k, v)| format!(".{}({})", escape_id(k), expr_to_verilog(v)))
            .collect();
        parts.push(format!("({})", clist.join(", ")));
    }

    format!("{};\n", parts.join(" "))
}

// ---------------------------------------------------------------------------
// Expression → Verilog text
// ---------------------------------------------------------------------------

fn expr_to_verilog(expr: &Expr) -> String {
    match expr {
        Expr::Lit { value, ty, .. } => lit_to_verilog(value, ty),

        Expr::NetRef  { name, .. } => escape_id(name),
        Expr::PortRef { name, .. } => escape_id(name),
        Expr::VarRef  { name, .. } => escape_id(name),

        Expr::Slice { base, msb, lsb, .. } => {
            let b = expr_to_verilog(base);
            if msb == lsb {
                format!("{b}[{msb}]")
            } else {
                format!("{b}[{msb}:{lsb}]")
            }
        }

        Expr::Concat { parts, .. } => {
            let ps: Vec<String> = parts.iter().map(expr_to_verilog).collect();
            format!("{{{}}}", ps.join(", "))
        }

        Expr::Replication { count, body, .. } => {
            format!("{{{{{}}}{{{}}}}}", expr_to_verilog(count), expr_to_verilog(body))
        }

        Expr::Unary { op, operand, .. } => {
            let v_op = unary_op_to_verilog(op);
            format!("({v_op}{})", expr_to_verilog(operand))
        }

        Expr::Binary { op, lhs, rhs, .. } => {
            let v_op = binary_op_to_verilog(op);
            format!("({} {v_op} {})", expr_to_verilog(lhs), expr_to_verilog(rhs))
        }

        Expr::Ternary { cond, then_expr, else_expr, .. } => {
            format!(
                "({} ? {} : {})",
                expr_to_verilog(cond),
                expr_to_verilog(then_expr),
                expr_to_verilog(else_expr),
            )
        }

        Expr::FunCall { name, args, .. } => {
            let astr: Vec<String> = args.iter().map(expr_to_verilog).collect();
            format!("{}({})", name, astr.join(", "))
        }

        Expr::SystemCall { name, args, .. } => {
            let astr: Vec<String> = args.iter().map(expr_to_verilog).collect();
            format!("{}({})", name, astr.join(", "))
        }

        Expr::Attr { base, name: _, .. } => {
            format!("{}'event", expr_to_verilog(base))  // most common: clk'event
        }
    }
}

// ---------------------------------------------------------------------------
// Literal → Verilog text
// ---------------------------------------------------------------------------

fn lit_to_verilog(value: &LitValue, ty: &Ty) -> String {
    match value {
        LitValue::Bool(true)  => "1'b1".to_string(),
        LitValue::Bool(false) => "1'b0".to_string(),
        LitValue::Int(v) => {
            if let Ty::Vec { width } = ty {
                format!("{width}'d{v}")
            } else {
                v.to_string()
            }
        }
        LitValue::Bits(bits) => {
            let s: String = bits.iter().map(|b| b.to_string()).collect();
            format!("{}'b{s}", bits.len())
        }
        LitValue::Float(f) => f.to_string(),
        LitValue::Str(s)   => format!("\"{s}\""),
    }
}

// ---------------------------------------------------------------------------
// Operator maps
// ---------------------------------------------------------------------------

fn binary_op_to_verilog(op: &str) -> &str {
    match op {
        "+"    => "+",    "-"   => "-",    "*"   => "*",
        "/"    => "/",    "%"   => "%",    "**"  => "**",
        "AND"  => "&",    "OR"  => "|",    "XOR" => "^",
        "NAND" => "~&",   "NOR" => "~|",   "XNOR"=> "~^",
        "&"    => "&",    "|"   => "|",    "^"   => "^",
        "<<"   => "<<",   ">>"  => ">>",
        "<<<"  => "<<<",  ">>>" => ">>>",
        "<"    => "<",    "<="  => "<=",   ">"   => ">",  ">=" => ">=",
        "=="   => "==",   "!="  => "!=",
        "==="  => "===",  "!==" => "!==",
        "&&"   => "&&",   "||"  => "||",
        _      => "?",
    }
}

fn unary_op_to_verilog(op: &str) -> &str {
    match op {
        "NOT"      => "~",
        "NEG"      => "-",
        "POS"      => "+",
        "LOGIC_NOT"=> "!",
        "AND_RED"  => "&",
        "OR_RED"   => "|",
        "XOR_RED"  => "^",
        "NAND_RED" => "~&",
        "NOR_RED"  => "~|",
        "XNOR_RED" => "~^",
        _          => "?",
    }
}

// ---------------------------------------------------------------------------
// Identifier escaping
// ---------------------------------------------------------------------------

/// Escape a Verilog identifier if needed.
///
/// Rules (Verilog LRM §2.7):
/// - Simple identifier: starts with letter or `_`, only contains `[a-zA-Z0-9_$]`.
/// - Reserved words must be escaped even if they'd otherwise be valid.
/// - An empty name is returned as-is (should not appear in well-formed HIR).
fn escape_id(name: &str) -> String {
    if name.is_empty() {
        return name.to_string();
    }

    let is_reserved = VERILOG_RESERVED.contains(&name);

    let first_ok = {
        let c = name.chars().next().unwrap();
        c.is_ascii_alphabetic() || c == '_'
    };
    let all_ok = name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');

    if !is_reserved && first_ok && all_ok {
        name.to_string()
    } else {
        format!("\\{name} ")
    }
}
