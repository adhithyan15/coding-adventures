//! # Three-file pipeline entry point for the React backend.
//!
//! This module implements **UI24 — emit→dispatch Flux pattern**. It is the
//! React backend's consumer of the three-language pipeline output produced by
//! [`mosmodel-compiler`], [`moslayout-compiler`], and [`mosstyle-compiler`].
//!
//! It exists alongside the legacy [`crate::ReactRenderer`] that is driven by
//! [`mosaic_vm::MosaicVM`]; the two code paths share no state. The legacy
//! path continues to compile single-file `.mosaic` source and is left
//! untouched.
//!
//! ## What this module produces
//!
//! For a component named `Grid` with slots `column-headers: list<text>`,
//! `total-rows: number`, and emits `onNavigate(row: number, col: number)`,
//! `onEditCommit(value: text)`, this module produces a `.tsx` file shaped
//! like this:
//!
//! ```tsx
//! // Auto-generated by mosaic-emit-react. Do not edit.
//! import React from "react";
//!
//! type GridEvent =
//!   | { type: "navigate"; row: number; col: number }
//!   | { type: "editCommit"; value: string };
//!
//! interface GridProps {
//!   columnHeaders: Array<string>;
//!   totalRows: number;
//!   dispatch: (event: GridEvent) => void;
//! }
//!
//! export function Grid({
//!   columnHeaders,
//!   totalRows,
//!   dispatch,
//! }: GridProps) {
//!   return (
//!     <div></div>
//!   );
//! }
//! ```
//!
//! Three things to notice in the output:
//!
//! 1. The **event union** comes first, after the React import — one variant
//!    per declared emit, with the `on` prefix stripped and the rest converted
//!    to camelCase as the `type` field's string literal.
//! 2. The **props interface** lists slots first (all camelCased) and ends with
//!    a single required `dispatch` prop. This is the entire UI24 promise.
//! 3. The **function body** walks the moslayout tree. This first cut of the
//!    pipeline supports the simple container and leaf primitives — Box, Row,
//!    Column, Text, Image, Spacer, Scroll, Divider, Stack, Icon. The
//!    `Grid` and `Input` primitives, the `connects` wiring that fires
//!    dispatch calls in response to JSX events, and full style inlining are
//!    follow-up work (see §"What is NOT in this first pass" below).
//!
//! ## What is NOT in this first pass
//!
//! This module focuses on getting **the interface shape** of UI24 right —
//! the event union and the dispatch prop — because those are what host code
//! sees and binds against. The function body is intentionally minimal:
//!
//! - ~~No `connects` wiring yet.~~ As of the connects-wiring PR, every
//!   moslayout prop whose value is an `EmitRef` produces a JSX event handler
//!   attribute that fires the matching dispatch variant (void emits only).
//!   Payload-carrying emits still produce a void dispatch; mapping a JSX
//!   event payload to the emit's parameters needs grammar work that is
//!   tracked separately.
//! - **No `Grid` primitive rendering yet.** The dedicated table-rendering
//!   logic that the legacy `ReactRenderer` has for `Grid` (see UI20 §5) is
//!   significant. Rather than copy it, this PR emits a placeholder `<div>`
//!   for `Grid` and tracks the real implementation as a follow-up.
//! - ~~No `Input` primitive yet.~~ As of the Input-primitive PR, the
//!   `Input` moslayout tag lowers to `<input type="text" />` (or
//!   `<textarea />` when `multiline: true`) with `value`, `readOnly`,
//!   and `maxLength` attributes bound from slot refs / numbers, plus an
//!   `onChange` handler that carries `e.target.value` as the dispatch
//!   payload and an `onKeyDown` handler that fires `onCommit` on Enter
//!   and `onCancel` on Escape.
//! - **No style inlining yet.** The mosstyle `StyleDef` is accepted but not
//!   yet inlined into the JSX `style={{...}}` objects.
//!
//! Each of these is a focused, additive follow-up PR. The current PR proves
//! the interface contract (event union + dispatch prop) end-to-end and
//! exercises it from `mosaic-compile --pipeline` in PR #2 of this sequence.

