// GenerateTwigParser generates the content of cst-parser.tw from a ParserGrammar.
//
// The generated module is compiler/cst-parser, exporting cst-parse-program
// and cst-parse-expr.  Each grammar rule becomes one or more Twig functions
// following the recursive-descent PEG pattern.
//
// Function naming convention:
//   cst-parse-<rule>           — main rule function
//   cst-parse-<rule>-alt<n>   — Nth alternative of a top-level alternation
//   cst-parse-<rule>-opt<n>   — optional element wrapper (always succeeds)
//   cst-parse-<rule>-rep<n>   — repetition accumulator (always succeeds)
func GenerateTwigParser(pg *ParserGrammar, tg *TokenGrammar, sourceFile string) string {
	var w strings.Builder

	wl := func(s string) { w.WriteString(s); w.WriteString("\n") }

	// Build keyword set from token grammar for fast lookup
	kwSet := make(map[string]bool)
	for _, kw := range tg.Keywords {
		kwSet[kw] = true
	}

	// ── Module header ────────────────────────────────────────────────────────
	wl("; Generated by grammar-tools from " + sourceFile + " — DO NOT EDIT")
	wl(";")
	wl("; Twig CST parser: converts a token list into a Concrete Syntax Tree.")
	wl("; Regenerate with:")
	wl(";   grammar-tools compile-grammar-twig " + sourceFile + " -o cst-parser.tw")
	wl(";")
	wl("; CST node format:")
	wl(";   Non-terminal: (cons \"rule-name\" (list child ...))")
	wl(";   Terminal:     Token record from compiler/token")
	wl(";   Failure:      nil")
	wl(";   Success:      (cons rest-tokens cst-node)")
	wl("")
	wl("(module compiler/cst-parser")
	wl("  (typed lenient)")
	wl("  (export cst-parse-program cst-parse-expr)")
	wl("  (import compiler/token))")
	wl("")

	// ── Token-matching helpers ───────────────────────────────────────────────
	wl("; ─── Token-matching helpers ──────────────────────────────────────────────────────")
	wl(";")
	wl("; cst-match-<Kind>: match a token of given kind.")
	wl(";   Returns (cons rest-tokens token) on match, nil on failure.")
	wl(";")
	wl("; cst-match-kw: match a TkIdentifier with a specific lexeme (keyword).")
	wl("")

	// Generate a match helper for each unique Twig kind used in the grammar
	emittedKinds := map[string]bool{}
	for _, td := range tg.Definitions {
		kind := twigKindFor(td.Name)
		if emittedKinds[kind] {
			continue
		}
		emittedKinds[kind] = true
		fnName := "cst-match-" + kind
		predName := kind + "?"
		wl(fmt.Sprintf("(define (%s tokens)", fnName))
		wl(fmt.Sprintf("  ; Match %s token.", kind))
		wl("  (if (null? tokens) nil")
		wl("    (let* ((tok (car tokens)))")
		wl(fmt.Sprintf("      (if (%s (token-kind tok))", predName))
		wl("        (cons (cdr tokens) tok)")
		wl("        nil))))")
		wl("")
	}

	wl("(define (cst-match-kw tokens kw)")
	wl("  ; Match a TkIdentifier token whose lexeme equals kw.")
	wl("  ; Used for keywords (define, lambda, if, …) and ARROW (\"->\").")
	wl("  (if (null? tokens) nil")
	wl("    (let* ((tok  (car tokens))")
	wl("           (kind (token-kind tok))")
	wl("           (lex  (token-lexeme tok)))")
	wl("      (if (and (TkIdentifier? kind) (string=? lex kw))")
	wl("        (cons (cdr tokens) tok)")
	wl("        nil))))")
	wl("")

	// ── Grammar rules ────────────────────────────────────────────────────────
	wl("; ─── Grammar rules (one function per rule, grammar-file order) ──────────────────")
	wl("")

	// Generate code for each rule
	for _, rule := range pg.Rules {
		gen := &ruleGen{
			ruleName: kebabCase(rule.Name),
			out:      &strings.Builder{},
		}
		gen.generateRule(rule)
		w.WriteString(gen.out.String())
	}

	return w.String()
}

// ============================================================================
// Rule code generator
// ============================================================================

// ruleGen generates Twig functions for one grammar rule.
type ruleGen struct {
	ruleName string
	out      *strings.Builder
	counter  int
}

func (g *ruleGen) freshN() int {
	n := g.counter
	g.counter++
	return n
}

func (g *ruleGen) wl(s string) { g.out.WriteString(s); g.out.WriteString("\n") }
func (g *ruleGen) wf(f string, args ...interface{}) {
	g.out.WriteString(fmt.Sprintf(f, args...))
}

// generateRule emits all Twig functions needed for this grammar rule.
func (g *ruleGen) generateRule(rule GrammarRule) {
	cstName := g.ruleName
	fnName := "cst-parse-" + g.ruleName

	// Emit rule comment
	g.wl(fmt.Sprintf("; %s", rule.Name))
	g.wl(fmt.Sprintf("(define (%s tokens)", fnName))

	body := g.genElem(rule.Body, "tokens", cstName)
	// Indent the body
	for _, line := range strings.Split(body, "\n") {
		if line != "" {
			g.wl("  " + line)
		} else {
			g.wl("")
		}
	}
	g.wl(")")
	g.wl("")
}

// genElem generates a Twig expression that matches the given element.
// tokVar: the Twig variable holding the current token list.
// cstName: the rule name for CST node construction (used by Sequence).
// Returns a Twig expression that evaluates to (cons rest cst-node) or nil.
func (g *ruleGen) genElem(elem GrammarElement, tokVar string, cstName string) string {
	switch e := elem.(type) {
	case Sequence:
		return g.genSequence(e.Elements, tokVar, cstName)

	case Alternation:
		return g.genAlternation(e.Choices, tokVar, cstName)

	case Repetition:
		return g.genRepetition(e.Element, tokVar)

	case OneOrMoreRepetition:
		return g.genOneOrMoreRepetition(e.Element, tokVar)

	case Optional:
		return g.genOptional(e.Element, tokVar)

	case Group:
		return g.genElem(e.Element, tokVar, cstName)

	case RuleReference:
		if e.IsToken {
			return g.genTokenMatch(e.Name, tokVar)
		}
		return fmt.Sprintf("(cst-parse-%s %s)", kebabCase(e.Name), tokVar)

	case Literal:
		return fmt.Sprintf("(cst-match-kw %s %q)", tokVar, e.Value)

	default:
		return fmt.Sprintf("; TODO: unhandled %T\n nil", elem)
	}
}

// genTokenMatch generates a match expression for a terminal token.
func (g *ruleGen) genTokenMatch(tokenName string, tokVar string) string {
	kind := twigKindFor(tokenName)
	switch tokenName {
	case "ARROW":
		// ARROW "->" is a TkIdentifier with lexeme "->"
		return fmt.Sprintf("(cst-match-kw %s \"->\")", tokVar)
	case "BOOL_TRUE":
		// Match TkBoolean with lexeme "#t"
		return fmt.Sprintf(`(let* ((tok-bt (if (null? %s) nil (car %s))))
  (if (or (null? %s) (not (TkBoolean? (token-kind (car %s))) ) (not (string=? (token-lexeme (car %s)) "#t")))
    nil
    (cons (cdr %s) (car %s))))`, tokVar, tokVar, tokVar, tokVar, tokVar, tokVar, tokVar)
	case "BOOL_FALSE":
		return fmt.Sprintf(`(let* ((tok-bf (if (null? %s) nil (car %s))))
  (if (or (null? %s) (not (TkBoolean? (token-kind (car %s)))) (not (string=? (token-lexeme (car %s)) "#f")))
    nil
    (cons (cdr %s) (car %s))))`, tokVar, tokVar, tokVar, tokVar, tokVar, tokVar, tokVar)
	default:
		return fmt.Sprintf("(cst-match-%s %s)", kind, tokVar)
	}
}

// genAlternation generates code for an alternation.
// For single-element alternatives (terminal references, non-terminal references),
// the code is inlined.  For alternatives that are sequences, sub-functions are
// generated.
func (g *ruleGen) genAlternation(choices []GrammarElement, tokVar string, cstName string) string {
	if len(choices) == 0 {
		return "nil"
	}
	if len(choices) == 1 {
		return g.genElem(choices[0], tokVar, cstName)
	}

	// Generate sub-functions for complex alternatives (sequences)
	altFns := make([]string, len(choices))
	for i, ch := range choices {
		switch e := ch.(type) {
		case RuleReference:
			if e.IsToken {
				altFns[i] = g.genTokenMatch(e.Name, tokVar)
			} else {
				altFns[i] = fmt.Sprintf("(cst-parse-%s %s)", kebabCase(e.Name), tokVar)
			}
		case Literal:
			altFns[i] = fmt.Sprintf("(cst-match-kw %s %q)", tokVar, e.Value)
		default:
			// Complex alternative: generate a named sub-function
			n := g.freshN()
			subFnName := fmt.Sprintf("cst-parse-%s-alt%d", g.ruleName, n)
			subBody := g.genElem(ch, "tokens", g.ruleName+"-alt")
			// Emit the sub-function before the rule function (prepend to output)
			var subFn strings.Builder
			subFn.WriteString(fmt.Sprintf("(define (%s tokens)\n", subFnName))
			for _, line := range strings.Split(subBody, "\n") {
				if line != "" {
					subFn.WriteString("  " + line + "\n")
				}
			}
			subFn.WriteString(")\n\n")
			// Prepend sub-function: insert before current rule's output
			existing := g.out.String()
			g.out.Reset()
			g.out.WriteString(subFn.String())
			g.out.WriteString(existing)
			altFns[i] = fmt.Sprintf("(%s %s)", subFnName, tokVar)
		}
	}

	// Build the alternation chain from right to left
	result := altFns[len(altFns)-1]
	for i := len(altFns) - 2; i >= 0; i-- {
		n := g.freshN()
		rVar := fmt.Sprintf("r-alt%d", n)
		result = fmt.Sprintf("(let* ((%s %s))\n(if (not (null? %s)) %s\n%s))",
			rVar, altFns[i], rVar, rVar, result)
	}
	return result
}

// genSequence generates code for a sequence of elements.
// Returns a Twig expression that:
//   - Matches each element in order
//   - Fails (nil) if any mandatory element fails
//   - Succeeds with (cons final-tokens (cons cstName (list children...)))
func (g *ruleGen) genSequence(elements []GrammarElement, tokVar string, cstName string) string {
	if len(elements) == 0 {
		return fmt.Sprintf("(cons %s (cons %q (list)))", tokVar, cstName)
	}

	// Build frames: one per element
	type frame struct {
		rVar    string
		tVar    string
		chVar   string
		expr    string
		isMand  bool // false for Optional and Repetition (always succeed)
	}

	var frames []frame
	currTok := tokVar

	for _, elem := range elements {
		n := g.freshN()
		rVar := fmt.Sprintf("r%d", n)
		tVar := fmt.Sprintf("t%d", n)
		chVar := fmt.Sprintf("ch%d", n)

		var expr string
		var isMand bool

		switch e := elem.(type) {
		case Optional:
			// Optional always succeeds; generate a named wrapper
			expr = g.genOptional(e.Element, currTok)
			isMand = false
		case Repetition:
			// Repetition always succeeds; generate a named accumulator
			expr = g.genRepetition(e.Element, currTok)
			isMand = false
		case OneOrMoreRepetition:
			// One-or-more can fail
			expr = g.genOneOrMoreRepetition(e.Element, currTok)
			isMand = true
		default:
			expr = g.genElem(elem, currTok, cstName+"-sub")
			isMand = true
		}

		frames = append(frames, frame{rVar, tVar, chVar, expr, isMand})
		currTok = tVar
	}

	// Build children list and final expression
	childVars := make([]string, len(frames))
	for i, f := range frames {
		childVars[i] = f.chVar
	}
	inner := fmt.Sprintf("(cons %s (cons %q (list %s)))",
		currTok, cstName, strings.Join(childVars, " "))

	// Wrap from inside out
	for i := len(frames) - 1; i >= 0; i-- {
		f := frames[i]
		if f.isMand {
			inner = fmt.Sprintf(
				"(let* ((%s %s))\n(if (null? %s) nil\n(let* ((%s (car %s)) (%s (cdr %s)))\n%s)))",
				f.rVar, f.expr, f.rVar,
				f.tVar, f.rVar, f.chVar, f.rVar,
				inner)
		} else {
			// No nil check needed (always succeeds)
			inner = fmt.Sprintf(
				"(let* ((%s %s)\n       (%s (car %s)) (%s (cdr %s)))\n%s)",
				f.rVar, f.expr,
				f.tVar, f.rVar, f.chVar, f.rVar,
				inner)
		}
	}

	return inner
}

// genRepetition generates code for zero-or-more repetition { element }.
// Generates a named accumulator helper function and returns the call expression.
// Always succeeds (returns (cons rest (list children...))).
func (g *ruleGen) genRepetition(elem GrammarElement, tokVar string) string {
	n := g.freshN()
	helperName := fmt.Sprintf("cst-parse-%s-rep%d", g.ruleName, n)

	// Generate the helper function body
	innerExpr := g.genElem(elem, "tok-rep", g.ruleName+"-rep-item")

	var helperFn strings.Builder
	helperFn.WriteString(fmt.Sprintf("; Repetition helper for %s rule\n", g.ruleName))
	helperFn.WriteString(fmt.Sprintf("(define (%s tok-rep acc)\n", helperName))
	helperFn.WriteString("  (let* ((r-rep\n")
	for _, line := range strings.Split(innerExpr, "\n") {
		helperFn.WriteString("    " + line + "\n")
	}
	helperFn.WriteString("  ))\n")
	helperFn.WriteString("  (if (null? r-rep)\n")
	helperFn.WriteString("    (cons tok-rep (reverse acc))\n")
	helperFn.WriteString(fmt.Sprintf("    (%s (car r-rep) (cons (cdr r-rep) acc)))))\n\n", helperName))

	// Prepend helper before the current rule output
	existing := g.out.String()
	g.out.Reset()
	g.out.WriteString(helperFn.String())
	g.out.WriteString(existing)

	return fmt.Sprintf("(%s %s (list))", helperName, tokVar)
}

// genOneOrMoreRepetition generates code for { element }+ (one or more).
// Tries one mandatory match then calls a zero-or-more helper.
func (g *ruleGen) genOneOrMoreRepetition(elem GrammarElement, tokVar string) string {
	n := g.freshN()
	helperName := fmt.Sprintf("cst-parse-%s-rep%d", g.ruleName, n)

	// Generate the zero-or-more helper
	innerExpr := g.genElem(elem, "tok-rep", g.ruleName+"-rep-item")

	var helperFn strings.Builder
	helperFn.WriteString(fmt.Sprintf("; One-or-more repetition helper for %s rule\n", g.ruleName))
	helperFn.WriteString(fmt.Sprintf("(define (%s tok-rep acc)\n", helperName))
	helperFn.WriteString("  (let* ((r-rep\n")
	for _, line := range strings.Split(innerExpr, "\n") {
		helperFn.WriteString("    " + line + "\n")
	}
	helperFn.WriteString("  ))\n")
	helperFn.WriteString("  (if (null? r-rep)\n")
	helperFn.WriteString("    (cons tok-rep (reverse acc))\n")
	helperFn.WriteString(fmt.Sprintf("    (%s (car r-rep) (cons (cdr r-rep) acc)))))\n\n", helperName))

	existing := g.out.String()
	g.out.Reset()
	g.out.WriteString(helperFn.String())
	g.out.WriteString(existing)

	// First mandatory match, then zero-or-more
	firstExpr := g.genElem(elem, tokVar, g.ruleName+"-first")
	n2 := g.freshN()
	r0 := fmt.Sprintf("r-1or%d", n2)
	t0 := fmt.Sprintf("t-1or%d", n2)
	ch0 := fmt.Sprintf("ch-1or%d", n2)
	return fmt.Sprintf(
		"(let* ((%s %s))\n(if (null? %s) nil\n(let* ((%s (car %s)) (%s (cdr %s))\n       (r-rest (%s %s (list %s))))\n(cons (car r-rest) (cons (cdr r-rest) (list %s))))))",
		r0, firstExpr, r0,
		t0, r0, ch0, r0,
		helperName, t0, ch0,
		ch0)
}

// genOptional generates code for optional [ element ].
// Always succeeds: returns (cons tok nil) if element fails, or element's result.
func (g *ruleGen) genOptional(elem GrammarElement, tokVar string) string {
	n := g.freshN()
	helperName := fmt.Sprintf("cst-parse-%s-opt%d", g.ruleName, n)

	innerExpr := g.genElem(elem, "tok-opt", g.ruleName+"-opt-item")

	var helperFn strings.Builder
	helperFn.WriteString(fmt.Sprintf("; Optional element helper for %s rule\n", g.ruleName))
	helperFn.WriteString(fmt.Sprintf("(define (%s tok-opt)\n", helperName))
	helperFn.WriteString("  (let* ((r-opt\n")
	for _, line := range strings.Split(innerExpr, "\n") {
		helperFn.WriteString("    " + line + "\n")
	}
	helperFn.WriteString("  ))\n")
	helperFn.WriteString("  (if (null? r-opt)\n")
	helperFn.WriteString("    (cons tok-opt nil)\n")
	helperFn.WriteString("    r-opt)))\n\n")

	existing := g.out.String()
	g.out.Reset()
	g.out.WriteString(helperFn.String())
	g.out.WriteString(existing)

	return fmt.Sprintf("(%s %s)", helperName, tokVar)
}
