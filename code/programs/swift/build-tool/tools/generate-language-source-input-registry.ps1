param(
    [string]$RegistryPath,
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"

$packageRoot = Split-Path -Parent $PSScriptRoot
if (-not $RegistryPath) {
    $RegistryPath = Join-Path $packageRoot "../../../specs/fixtures/build-tool-v1/language-source-input-registry.json"
}
if (-not $OutputPath) {
    $OutputPath = Join-Path $packageRoot "Sources/BuildToolCore/LanguageSourceInputRegistry.swift"
}

$registry = Get-Content -LiteralPath $RegistryPath -Raw
$null = $registry | ConvertFrom-Json
$indentedRegistry = ($registry.TrimEnd() -split "`r?`n" | ForEach-Object { "        $_" }) -join "`n"

$header = @'
// Generated by tools/generate-language-source-input-registry.ps1.
// Do not edit this projection by hand; edit the checked neutral registry and
// regenerate it so the production selector and conformance authority cannot
// drift independently.

import Foundation

struct LanguageSourceInputRegistry: Codable, Equatable, Sendable {
    let schemaVersion: Int
    let universalInputs: UniversalSourceInputs
    let languages: [LanguageSourceInputs]

    enum CodingKeys: String, CodingKey {
        case schemaVersion = "schema_version"
        case universalInputs = "universal_inputs"
        case languages
    }

    func inputs(for language: String) -> LanguageSourceInputs? {
        languages.first { $0.language == language }
    }
}

struct UniversalSourceInputs: Codable, Equatable, Sendable {
    let buildFilenames: [String]
    let generatedDirectoryComponents: [String]
    let rootExactBasenames: [String]

    enum CodingKeys: String, CodingKey {
        case buildFilenames = "build_filenames"
        case generatedDirectoryComponents = "generated_directory_components"
        case rootExactBasenames = "root_exact_basenames"
    }
}

struct LanguageSourceInputs: Codable, Equatable, Sendable {
    let language: String
    let recursiveSuffixes: [String]
    let recursiveExactBasenames: [String]
    let rootExactBasenames: [String]
    let rootVariableSuffixes: [String]
    let rootExactRelativePaths: [String]
    let packageExactInputs: [PackageExactSourceInputs]
    let caseAliasGroups: [[String]]
    let scopedInputs: [ScopedSourceInputs]

    enum CodingKeys: String, CodingKey {
        case language
        case recursiveSuffixes = "recursive_suffixes"
        case recursiveExactBasenames = "recursive_exact_basenames"
        case rootExactBasenames = "root_exact_basenames"
        case rootVariableSuffixes = "root_variable_suffixes"
        case rootExactRelativePaths = "root_exact_relative_paths"
        case packageExactInputs = "package_exact_inputs"
        case caseAliasGroups = "case_alias_groups"
        case scopedInputs = "scoped_inputs"
    }
}

struct PackageExactSourceInputs: Codable, Equatable, Sendable {
    let id: String
    let packageRoot: String
    let paths: [String]
    let reason: String
    let owner: String

    enum CodingKeys: String, CodingKey {
        case id
        case packageRoot = "package_root"
        case paths
        case reason
        case owner
    }
}

struct ScopedSourceInputs: Codable, Equatable, Sendable {
    let id: String
    let role: String
    let decision: String
    let scope: String
    let pathPrefix: String?
    let suffixes: [String]
    let exactBasenames: [String]
    let reason: String
    let owner: String

    enum CodingKeys: String, CodingKey {
        case id
        case role
        case decision
        case scope
        case pathPrefix = "path_prefix"
        case suffixes
        case exactBasenames = "exact_basenames"
        case reason
        case owner
    }

    func matches(path: String, basename: String) -> Bool {
        if scope == "root" {
            guard !path.contains("/") else { return false }
        } else {
            guard let pathPrefix, path.hasPrefix(pathPrefix + "/") else {
                return false
            }
        }
        return exactBasenames.contains(basename)
            || suffixes.contains { basename.hasSuffix($0) }
    }
}

enum LanguageSourceInputRegistryProjection {
    static let value: LanguageSourceInputRegistry = {
        do {
            return try JSONDecoder().decode(
                LanguageSourceInputRegistry.self,
                from: Data(embeddedJSON.utf8)
            )
        } catch {
            fatalError("checked language source-input projection is invalid")
        }
    }()

    private static let embeddedJSON = #"""
'@

$footer = @'
        """#
}
'@

$content = $header + "`n" + $indentedRegistry + "`n" + $footer
$outputDirectory = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
[System.IO.File]::WriteAllText(
    $OutputPath,
    $content.Replace("`r`n", "`n"),
    [System.Text.UTF8Encoding]::new($false)
)
