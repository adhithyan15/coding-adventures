<!-- hl-knowledge: introduces=[]; assesses=[IT-ETYMON-FRATELLO-SORELLA-02, IT-LEX-ZUCCHERO-02, IT-GRAMMAR-ZUCCHERO-04, IT-LEX-LATTE-02] -->

