# frozen_string_literal: true

# extconf.rb — RubyGems install-time hook for the silicon_rust_ruby_native ext
# ==============================================================================
#
# When a user runs `gem install coding_adventures_silicon_rust_ruby`, RubyGems
# runs this file from inside `ext/silicon_rust_ruby_native/`, expecting it to
# generate a `Makefile`.  We write a tiny Makefile that shells out to
# `cargo build -p silicon-rust-ruby-native --release` and copies the resulting
# shared library into the gem's lib/ directory.

require "rbconfig"
require_relative "build_config"

dlext = RbConfig::CONFIG["DLEXT"]
cargo_lib = case RbConfig::CONFIG["host_os"]
            when /darwin/
              "libsilicon_rust_ruby_native.dylib"
            when /mingw|mswin|cygwin/
              "silicon_rust_ruby_native.dll"
            else
              "libsilicon_rust_ruby_native.so"
            end

target        = "silicon_rust_ruby_native.#{dlext}"
lib_dir       = File.expand_path("../../lib/coding_adventures/silicon_rust_ruby", __dir__)
target_dir    = SiliconRustRubyNativeBuildConfig.target_release_dir(File.expand_path(__dir__))
cargo_command = SiliconRustRubyNativeBuildConfig.cargo_make_command
cargo_workdir = File.expand_path("../../../../rust", __dir__)

File.write("Makefile", <<~MAKEFILE)
  # Auto-generated by extconf.rb.  Do not edit by hand.
  CARGO_WORKDIR = #{cargo_workdir}
  TARGET_DIR    = #{target_dir}
  CARGO         = #{cargo_command}
  CARGO_LIB     = $(TARGET_DIR)/#{cargo_lib}
  INSTALL_DIR   = #{lib_dir}
  TARGET        = $(INSTALL_DIR)/#{target}

  all: $(TARGET)

  $(TARGET): $(CARGO_LIB)
  \t@mkdir -p $(INSTALL_DIR)
  \tcp $(CARGO_LIB) $(TARGET)

  $(CARGO_LIB):
  \tcd $(CARGO_WORKDIR) && $(CARGO)

  clean:
  \tcd $(CARGO_WORKDIR) && #{SiliconRustRubyNativeBuildConfig.cargo_clean_command.join(" ")}
  \trm -f $(TARGET)

  install: $(TARGET)

  .PHONY: all clean install
MAKEFILE

puts "Makefile generated; will build via `#{cargo_command}`"
