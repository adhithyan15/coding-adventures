<!-- hl-knowledge: introduces=[ES-GRAMMAR-SER-PRESENT-2PL]; assesses=[ES-GRAMMAR-AR-PRESENT-2PL, ES-CULTURE-VOSOTROS-USTEDES-SPLIT] -->

