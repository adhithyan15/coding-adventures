/// Map a mosmodel slot type to a TypeScript type string.
fn slot_type_to_ts(t: &SlotType) -> String {
    match t {
        SlotType::Text => "string".to_string(),
        SlotType::Number => "number".to_string(),
        SlotType::Bool => "boolean".to_string(),
        SlotType::Image => "string".to_string(),
        SlotType::Color => "string".to_string(),
        SlotType::Node => "React.ReactNode".to_string(),
        SlotType::List(inner) => format!("Array<{}>", list_inner_to_ts(inner)),
        SlotType::Component(name) => format!("React.ReactNode /* {name} */"),
    }
}

fn list_inner_to_ts(t: &ListInnerType) -> String {
    match t {
        ListInnerType::Text => "string".to_string(),
        ListInnerType::Number => "number".to_string(),
        ListInnerType::Bool => "boolean".to_string(),
        ListInnerType::Image => "string".to_string(),
        ListInnerType::Color => "string".to_string(),
        ListInnerType::Node => "React.ReactNode".to_string(),
        ListInnerType::Component(name) => format!("React.ReactNode /* {name} */"),
    }
    // NB: `mosmodel-compiler::ListInnerType` does not currently model nested
    // lists (`list<list<text>>`), even though UI13 §1 allows them in the
    // mosmodel grammar. That discrepancy is tracked separately as a
    // mosmodel-compiler bug; lowering `list<list<text>>` (needed for the
    // Grid component's `viewport-rows` slot) will work once the inner enum
    // gains a `List(Box<ListInnerType>)` variant.
}

/// Map a mosmodel emit-payload type to a TypeScript type string.
fn emit_payload_to_ts(t: &EmitPayloadType) -> String {
    match t {
        EmitPayloadType::Text => "string".to_string(),
        EmitPayloadType::Number => "number".to_string(),
        EmitPayloadType::Bool => "boolean".to_string(),
        EmitPayloadType::Color => "string".to_string(),
        EmitPayloadType::Component(name) => format!("any /* {name} */"),
    }
}

