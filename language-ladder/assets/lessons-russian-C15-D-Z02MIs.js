<!-- hl-knowledge: introduces=[]; assesses=[RU-LEX-ILI-01, RU-LEX-PISAT, RU-ETYMON-PISAT-PAINT, RU-SCRIPT-SHA, RU-LEX-BRAT, RU-ETYMON-BRAT-BEAR, RU-GRAMMAR-SUPPLETIVE-ASPECT-PAIR, RU-ETYMON-ILI-I-PLUS-LI] -->

