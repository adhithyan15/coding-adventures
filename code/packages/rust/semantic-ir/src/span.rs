//! Source positions.
//!
//! Every SIR node carries a [`Span`].  Frontends populate spans from
//! their AST's position info; backends emit position-tagged errors
//! and may insert source-trace comments in generated code.
//!
//! Positions are 1-indexed for both line and column (matching the
//! convention used by `twig-lexer`, `twig-parser`, and most other
//! grammar-driven tooling in this repo).  The filename is a logical
//! identifier — `"<inline>"` for sources that came from an in-memory
//! string.

use std::fmt;

/// A half-open source range `[start, end)` within a single file.
///
/// Inline construction example:
/// ```
/// use semantic_ir::Span;
/// let s = Span::new("a.twig", 1, 1, 1, 10);
/// assert_eq!(s.start_line, 1);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct Span {
    pub file: String,
    pub start_line: usize,
    pub start_col: usize,
    pub end_line: usize,
    pub end_col: usize,
}

impl Span {
    /// Construct a span.
    pub fn new(
        file: impl Into<String>,
        start_line: usize,
        start_col: usize,
        end_line: usize,
        end_col: usize,
    ) -> Self {
        Self {
            file: file.into(),
            start_line,
            start_col,
            end_line,
            end_col,
        }
    }

    /// Construct a zero-width span at a single point.  Useful when a
    /// frontend has only one position to work with.
    pub fn point(file: impl Into<String>, line: usize, col: usize) -> Self {
        Self {
            file: file.into(),
            start_line: line,
            start_col: col,
            end_line: line,
            end_col: col,
        }
    }

    /// A synthetic span with no real source.  Used for IR nodes
    /// generated by the IR itself (e.g. the synthesised `main`).
    pub fn synthetic() -> Self {
        Self::point("<synthetic>", 0, 0)
    }
}

impl fmt::Display for Span {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}:{}:{}-{}:{}",
            self.file, self.start_line, self.start_col, self.end_line, self.end_col
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn new_constructs() {
        let s = Span::new("x.twig", 1, 2, 3, 4);
        assert_eq!(s.file, "x.twig");
        assert_eq!(s.start_line, 1);
        assert_eq!(s.end_col, 4);
    }

    #[test]
    fn point_is_zero_width() {
        let s = Span::point("a", 5, 7);
        assert_eq!(s.start_line, s.end_line);
        assert_eq!(s.start_col, s.end_col);
    }

    #[test]
    fn synthetic_has_marker() {
        let s = Span::synthetic();
        assert_eq!(s.file, "<synthetic>");
    }

    #[test]
    fn display_is_compact() {
        let s = Span::new("a.twig", 1, 2, 3, 4);
        assert_eq!(format!("{}", s), "a.twig:1:2-3:4");
    }
}
