/// Find a prop on `node` by name and return its value, regardless of kind.
/// Returns `None` if the prop is absent.
fn find_prop<'a>(node: &'a LayoutNode, prop_name: &str) -> Option<&'a LayoutPropValue> {
    node.props
        .iter()
        .find(|p| p.name == prop_name)
        .map(|p| &p.value)
}

