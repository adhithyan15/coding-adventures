/// Write a drag identity prop as a `data-*` attribute.
///
/// A string literal is escaped for attribute context; a slot binding becomes a
/// `{{mustache}}` the template pass fills in. Anything else is skipped rather
/// than guessed at — see `emit_host_drop_target`'s callers for why an empty key
/// is not a safe default.
fn append_drag_value(attrs: &mut String, node: &LayoutNode, prop: &str, attr: &str) {
    match find_prop(node, prop) {
        Some(LayoutPropValue::String(lit)) => {
            write!(attrs, " {attr}=\"{}\"", escape_html_attr(lit)).unwrap();
        }
        Some(LayoutPropValue::SlotRef(slot)) => {
            write!(attrs, " {attr}=\"{{{{{}}}}}\"", camel(slot)).unwrap();
        }
        _ => {}
    }
}

/// Write a boolean drag prop. `false` is omitted rather than written out, so the
/// runtime's `truthy()` check on a missing attribute is the default.
fn append_drag_flag(attrs: &mut String, node: &LayoutNode, prop: &str, attr: &str) {
    match find_prop(node, prop) {
        Some(LayoutPropValue::Keyword(k)) if k == "true" => {
            write!(attrs, " {attr}=\"true\"").unwrap();
        }
        Some(LayoutPropValue::SlotRef(slot)) => {
            write!(attrs, " {attr}=\"{{{{{}}}}}\"", camel(slot)).unwrap();
        }
        _ => {}
    }
}

/// Shared helper: build the `style="..."` attribute for a node by
/// merging the primitive's built-in style with any author-declared part
/// style. Returns an empty string when the merged style is empty.
///
/// Extracted from `emit_html_tree` so the `HostInput` / `HostButton` /
/// `HostTable*` paths can apply the same merge without duplicating the
/// logic.
fn build_style_attr(
    node: &LayoutNode,
    builtin: &str,
    part_styles: &HashMap<String, String>,
) -> String {
    let part_style = node
        .part_name
        .as_deref()
        .and_then(|n| part_styles.get(n).map(String::as_str))
        .unwrap_or("");
    let merged = merge_styles(builtin, part_style);
    if merged.is_empty() {
        String::new()
    } else {
        format!(" style=\"{merged}\"")
    }
}

/// Preserve a typed host-owned node boundary in the static HTML template.
/// Triple braces are intentional: a `node` slot is trusted host markup, not a
/// text value. The data attribute gives non-Handlebars hosts a stable mount
/// point for a canvas, webview, or other browser viewport.
fn emit_host_surface_html(
    node: &LayoutNode,
    indent: usize,
    part_styles: &HashMap<String, String>,
) -> String {
    let pad = " ".repeat(indent);
    let slot = match find_prop(node, "content") {
        Some(LayoutPropValue::SlotRef(slot)) => slot.as_str(),
        _ => "",
    };
    let mut content = String::new();
    if !slot.is_empty() {
        content.push_str("{{{");
        content.push_str(&camel(slot));
        content.push_str("}}}");
    }
    let style = build_style_attr(node, "", part_styles);
    format!("{pad}<div data-mosaic-host-surface=\"{slot}\"{style}>{content}</div>\n")
}

