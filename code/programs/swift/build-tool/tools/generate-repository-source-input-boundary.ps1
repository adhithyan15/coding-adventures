struct RepositorySourceApplicability: Codable, Equatable, Sendable {
    let exactRoots: [String]
    let descendantRoots: [String]
    let excludedRoots: [String]

    enum CodingKeys: String, CodingKey {
        case exactRoots = "exact_roots"
        case descendantRoots = "descendant_roots"
