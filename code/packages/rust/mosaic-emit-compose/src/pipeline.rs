/// Inherited text styling threaded from a HostTable's `sheet` part (and
/// overridden by a cell's own part) down to the `Text` / `BasicTextField`
/// it wraps.  Compose has NO inherited text style on a `Box` the way CSS
/// cascades `color` / `font` from a `<table>` to its `<td>`s — so the
/// emitter threads the resolved style explicitly onto each leaf text
/// call.  `color` may be a layered `if/else` expression (the cell's
/// `state selected { color: ... }` override).
#[derive(Clone, Default)]
struct TextStyleCtx {
    /// Kotlin `Color(...)` expression (possibly a layered `if/else`).
    color: Option<String>,
    /// `true` when `font-family: monospace` is in effect.
    mono: bool,
    /// Font size in CSS px (unit-stripped), threaded as `N.sp`.
    size: Option<String>,
}

impl TextStyleCtx {
    /// Render the `Text(...)` argument suffix, e.g.
    /// `, color = Color(0xFF..), fontFamily = FontFamily.Monospace, fontSize = 12.sp`.
    /// Empty when no text styling is in effect.
    fn text_args(&self) -> String {
        let mut s = String::new();
        if let Some(c) = &self.color {
            s.push_str(&format!(", color = {c}"));
        }
        if self.mono {
            s.push_str(", fontFamily = FontFamily.Monospace");
        }
        if let Some(sz) = &self.size {
            s.push_str(&format!(", fontSize = {sz}.sp"));
        }
        s
    }

    fn text_style_expr(&self) -> Option<String> {
        let mut fields = Vec::new();
        if let Some(c) = &self.color {
            fields.push(format!("color = {c}"));
        }
        if self.mono {
            fields.push("fontFamily = FontFamily.Monospace".to_string());
        }
        if let Some(sz) = &self.size {
            fields.push(format!("fontSize = {sz}.sp"));
        }
        if fields.is_empty() {
            None
        } else {
            Some(format!("TextStyle({})", fields.join(", ")))
        }
    }
}

/// Extract the inherited text style a HostTable's `sheet` part defines —
/// `color` / `font-family: monospace` / `font-size` — so descendant cells
/// can thread it onto their `Text`.  Returns the default (no styling)
/// when the part is absent.
fn sheet_text_style(part_styles: &PartStyleMap, part_name: &str) -> TextStyleCtx {
    let mut ctx = TextStyleCtx::default();
    if let Some(props) = part_styles.get(part_name) {
        for p in props {
            match p.name.as_str() {
                "color" => ctx.color = Some(compose_color_value(&p.value)),
                "font-family" if p.value.trim() == "monospace" => ctx.mono = true,
                "font-size" => ctx.size = Some(strip_css_px(&p.value).to_string()),
                _ => {}
            }
        }
    }
    ctx
}

/// Compute the text style a cell's children should wear: start from the
/// inherited sheet style, then override `color` from the cell's own part
/// (base + any `state-when-*` color layers).  Font family / size keep the
/// inherited values unless the part redefines them (the VisiCalc cell
/// part doesn't, so the sheet's monospace/12sp flow through).
fn cell_text_style(inherited: &TextStyleCtx, style: &ComposeStyle) -> TextStyleCtx {
    let mut ctx = inherited.clone();
    if let Some(c) = &style.text_color {
        ctx.color = Some(c.clone());
    }
    if style.font_family_mono {
        ctx.mono = true;
    }
    if let Some(sz) = &style.font_size {
        ctx.size = Some(sz.clone());
    }
    ctx
}

fn text_call(value_expr: &str, text_ctx: Option<&TextStyleCtx>, modifier: Option<&str>) -> String {
    let args = text_ctx.map(TextStyleCtx::text_args).unwrap_or_default();
    let modifier_arg = modifier
        .map(|value| format!(", modifier = {value}"))
        .unwrap_or_default();
    if args.is_empty() {
        format!("Text(text = {value_expr}{modifier_arg})")
    } else {
        format!("Text({value_expr}{modifier_arg}{args})")
    }
}

// Threads the full lowering context (styles, table/for scopes, inherited text
// styling) through the recursive tree walk; splitting would obscure the flow.
#[allow(clippy::too_many_arguments)]
fn emit_compose_tree(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    // Inherited text styling for any `Text` this subtree emits; consumed
    // by `emit_text` / the inline-edit `BasicTextField`.
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    // Threaded column-width Kotlin expression (e.g.
    // `columnWidths[_kotlinIdxc]`) for THIS node only — `Some` exactly
    // when this is a direct body child of a width-threading HostTable
    // cell `For`.  Consumed by the container emitter (merged into the
    // node's own Modifier chain).  NOT propagated to children.
    injected_width: Option<&str>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    match node.tag.as_str() {
        "HostSurface" => emit_host_surface_compose(node, depth),
        // `Stack` (UI29's `position: relative` + absolutely-positioned-children
        // container) lowers to Compose's `Box` — the same composable `Box`
        // itself already uses. Jetpack Compose's `Box` natively layers its
        // children (later children paint over earlier ones at the same
        // origin) so this is a close analog, not a degradation the way
        // `HostDraggable`/`HostDropTarget` → `Column` below is. What v1
        // doesn't yet do: turn a child's static `position: absolute` +
        // `top`/`left` into `Modifier.offset(...)`, so a Stack's children
        // currently all render at the Box's origin instead of the pixel
        // positions the web/Flutter backends place them at — the same
        // "anything else silently skipped" v1 posture `compose_box_style`
        // already documents for every other static prop it doesn't lower.
        "Box" | "Stack" => emit_container(
            node,
            "Box",
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        ),
        "Row" => emit_container(
            node,
            "Row",
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        ),
        "HostDraggable" => emit_host_draggable(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        ),
        "HostDropTarget" => emit_host_drop_target(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        ),
        "Column" => emit_container(
            node,
            "Column",
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        ),
        // UI29 §2.1 — `HostTable` lowers to a vertical `Column`.  Before
        // walking its sections we discover the column-widths slot from a
        // nested `HostTableColGroup` (TableContext) AND the inherited
        // text style from the table's own `sheet` part, then thread both
        // down so cells get explicit widths + monospace text.
        "HostTable" => {
            let ctx = extract_table_context(node);
            let sheet_text = node
                .part_name
                .as_deref()
                .map(|p| sheet_text_style(part_styles, p))
                .unwrap_or_default();
            emit_container(
                node,
                "Column",
                depth,
                component_name,
                emits,
                part_styles,
                Some(&ctx),
                Some(&sheet_text),
                for_payload,
                injected_width,
            )
        }
        // The structural sub-tags lower to `Column` too, preserving the
        // discovered table context + inherited text style so deeply
        // nested Rows still see them.
        "HostTableHead" | "HostTableBody" | "HostTableFoot" => {
            let section_ctx = table_ctx.map(|ctx| ctx.in_section(node.tag.as_str()));
            emit_container(
                node,
                "Column",
                depth,
                component_name,
                emits,
                part_styles,
                section_ctx.as_ref(),
                text_ctx,
                for_payload,
                injected_width,
            )
        }
        "HostTableColGroup" => {
            // The col-group itself produces no visible Compose output —
            // column widths reach the cells via TableContext threading.
            // We still emit a `Column` so any `Col` children iterate,
            // documented as a no-op.
            emit_container(
                node,
                "Column",
                depth,
                component_name,
                emits,
                part_styles,
                table_ctx,
                text_ctx,
                for_payload,
                injected_width,
            )
        }
        "Col" => {
            // `Col` is a column-width hint inside `HostTableColGroup`.
            // It has no Compose analog and never renders visually.
            Ok(format!(
                "{pad}// Col (column-width hint — no Compose analog)\n"
            ))
        }
        "Text" => emit_text(node, depth, text_ctx, for_payload),
        "Icon" => emit_icon_compose(node, depth, part_styles, text_ctx),
        "Spacer" => Ok(format!("{pad}Spacer(modifier = Modifier.weight(1f))\n")),
        // `Input` is the pre-UI29 spelling retained for capabilities such as
        // multiline editing that were not present on the first HostInput
        // contract. Both spellings are native text fields on Compose.
        "HostInput" | "Input" => {
            emit_host_input(node, depth, component_name, emits, part_styles, text_ctx)
        }
        "HostButton" => emit_host_button(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            text_ctx,
            for_payload,
        ),
        "HostCheckbox" => {
            emit_host_checkbox(node, depth, component_name, emits, part_styles, text_ctx)
        }
        "HostRadio" => emit_host_radio(node, depth, component_name, emits, part_styles, text_ctx),
        "HostLink" => emit_host_link(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            text_ctx,
            for_payload,
        ),
        "HostDialog" => emit_host_dialog(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
        ),
        "HostNumberInput" => {
            emit_host_number_input(node, depth, component_name, emits, part_styles, text_ctx)
        }
        "HostSlider" => emit_host_slider(node, depth, component_name, emits, part_styles, text_ctx),
        "HostTooltip" => emit_host_tooltip(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
        ),
        // UI29 §3.1 / §3.2 — meta-primitives.
        "For" => emit_for_compose(
            node,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            /*width_thread=*/ false,
        ),
        "If" => emit_if_compose(
            node,
            None,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
        ),
        // An orphan `Else` renders as a documenting Kotlin comment.
        "Else" => Ok(format!("{pad}// orphan Else — ignored\n")),
        other => Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    }
}

/// Emit a `Box` / `Row` / `Column` container.
///
/// When the node carries a `part_name` whose `.msl` part declares
/// styles (or a column width is injected), the container's `Modifier`
/// is built from [`compose_box_style`] — `.width/.height/.background/`
/// `.border/.padding` — and, for a `Box`, the `contentAlignment`
/// argument is set from `text-align`.  Otherwise the container falls
/// back to the styleless `Modifier.fillMaxWidth()` shape.
///
/// A `Row` inside a HostTable dispatches each child through
/// [`emit_table_cell`] so a child `For` in cell-position picks up the
/// threaded column width.
struct ContainerFrame {
    opener: String,
    closer: String,
    child_text: Option<TextStyleCtx>,
}

/// Lower UI35's drag source to Compose's native pointer drag modifier plus the
/// shared keyboard/screen-reader controller emitted once per component file.
#[allow(clippy::too_many_arguments)]
fn emit_host_draggable(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    injected_width: Option<&str>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let key = drag_text_prop_expr(node, "drag-key", "\"\"")?;
    let kind = drag_text_prop_expr(node, "drag-kind", "\"\"")?;
    let label = drag_text_prop_expr(node, "drag-label", &key)?;
    let disabled = drag_disabled_expr(node, "drag-disabled")?;
    let mut out = String::new();
    writeln!(out, "{pad}_mosaicDraggable(").unwrap();
    writeln!(out, "{inner}key = {key},").unwrap();
    writeln!(out, "{inner}kind = {kind},").unwrap();
    writeln!(out, "{inner}label = {label},").unwrap();
    writeln!(out, "{inner}disabled = {disabled},").unwrap();
    if let Some(dispatch) = drag_event_dispatch(
        node,
        "onDragStart",
        component_name,
        emits,
        &[("key", &key), ("kind", &kind)],
    )? {
        writeln!(out, "{inner}onDragStart = {{ {dispatch} }},").unwrap();
    }
    if let Some(dispatch) = drag_event_dispatch(
        node,
        "onDragEnd",
        component_name,
        emits,
        &[("key", &key), ("kind", &kind), ("dropped", "dropped")],
    )? {
        writeln!(out, "{inner}onDragEnd = {{ dropped -> {dispatch} }},").unwrap();
    }
    writeln!(out, "{pad}) {{").unwrap();
    out.push_str(&emit_container(
        node,
        "Column",
        depth + 1,
        component_name,
        emits,
        part_styles,
        table_ctx,
        text_ctx,
        for_payload,
        injected_width,
    )?);
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Lower UI35's target to the native Compose target modifier. Pointer and
/// keyboard paths share `_MosaicDropTargetState.accept`, preserving one event
/// payload construction path and the accepted-only `dropped` outcome.
#[allow(clippy::too_many_arguments)]
fn emit_host_drop_target(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    injected_width: Option<&str>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let target_key = drag_text_prop_expr(node, "drop-key", "\"\"")?;
    let disabled = drag_disabled_expr(node, "drop-disabled")?;
    let accepts = drag_accepts_expr(node)?.unwrap_or_else(|| "null".to_string());
    let enter_values = [("key", "data.key"), ("kind", "data.kind")];
    let drop_values = [
        ("key", "data.key"),
        ("kind", "data.kind"),
        ("targetKey", target_key.as_str()),
        ("position", "position"),
    ];

    let mut out = String::new();
    writeln!(out, "{pad}_mosaicDropTarget(").unwrap();
    writeln!(out, "{inner}targetKey = {target_key},").unwrap();
    writeln!(out, "{inner}acceptsKinds = {accepts},").unwrap();
    writeln!(out, "{inner}disabled = {disabled},").unwrap();
    for (prop, signature, values) in [
        ("onDragEnter", "data", enter_values.as_slice()),
        ("onDragLeave", "data", enter_values.as_slice()),
        ("onDropHover", "data, position", drop_values.as_slice()),
        ("onDrop", "data, position", drop_values.as_slice()),
    ] {
        if let Some(dispatch) = drag_event_dispatch(node, prop, component_name, emits, values)? {
            writeln!(out, "{inner}{prop} = {{ {signature} -> {dispatch} }},").unwrap();
        }
    }
    writeln!(out, "{pad}) {{").unwrap();
    out.push_str(&emit_container(
        node,
        "Column",
        depth + 1,
        component_name,
        emits,
        part_styles,
        table_ctx,
        text_ctx,
        for_payload,
        injected_width,
    )?);
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

fn drag_text_prop_expr(
    node: &LayoutNode,
    name: &str,
    fallback: &str,
) -> Result<String, PipelineEmitError> {
    match find_prop_value(node, name) {
        Some(LayoutPropValue::String(value)) => Ok(format!("\"{}\"", escape_kotlin_string(value))),
        Some(LayoutPropValue::SlotRef(slot)) | Some(LayoutPropValue::Keyword(slot)) => {
            let field = to_camel_case_first_lower(slot);
            validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(format!("{field}.toString()"))
        }
        Some(LayoutPropValue::Expr(expression)) => {
            Ok(format!("({}).toString()", expression.trim()))
        }
        Some(LayoutPropValue::Number(number)) => Ok(format!("\"{number}\"")),
        Some(LayoutPropValue::EmitRef(_)) | None => Ok(fallback.to_string()),
    }
}

fn drag_disabled_expr(node: &LayoutNode, specific: &str) -> Result<String, PipelineEmitError> {
    if find_prop_value(node, specific).is_some() {
        bool_prop_expr(node, specific, "false")
    } else {
        bool_prop_expr(node, "disabled", "false")
    }
}

fn drag_accepts_expr(node: &LayoutNode) -> Result<Option<String>, PipelineEmitError> {
    let Some(value) = find_prop_value(node, "accepts") else {
        return Ok(None);
    };
    match value {
        LayoutPropValue::String(kind) => {
            Ok(Some(format!("listOf(\"{}\")", escape_kotlin_string(kind))))
        }
        LayoutPropValue::SlotRef(slot) | LayoutPropValue::Keyword(slot) => {
            let field = to_camel_case_first_lower(slot);
            validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(Some(field))
        }
        LayoutPropValue::Expr(expression) => Ok(Some(format!(
            "({}).map {{ it.toString() }}",
            expression.trim()
        ))),
        LayoutPropValue::Number(_) | LayoutPropValue::EmitRef(_) => {
            Ok(Some("emptyList()".to_string()))
        }
    }
}

fn drag_event_dispatch(
    node: &LayoutNode,
    prop: &str,
    component_name: &str,
    emits: &[EmitDecl],
    values: &[(&str, &str)],
) -> Result<Option<String>, PipelineEmitError> {
    let Some(emit_name) = find_emit_ref_prop(node, prop) else {
        return Ok(None);
    };
    let case = pascalize(&strip_on_prefix(emit_name));
    validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
    let Some(emit) = emits.iter().find(|emit| emit.name == emit_name) else {
        return Ok(Some(format!("dispatch({component_name}Event.{case})")));
    };
    if emit.params.is_empty() {
        return Ok(Some(format!("dispatch({component_name}Event.{case})")));
    }
    let args = emit
        .params
        .iter()
        .map(|param| {
            let field = to_camel_case_first_lower(&param.name);
            validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(values
                .iter()
                .find_map(|(name, value)| (*name == field).then_some(*value))
                .map(ToString::to_string)
                .unwrap_or_else(|| match &param.r#type {
                    EmitPayloadType::Text | EmitPayloadType::Color => "\"\"".to_string(),
                    EmitPayloadType::Number => "0.0".to_string(),
                    EmitPayloadType::Bool => "false".to_string(),
                    EmitPayloadType::Component(_) => "TODO()".to_string(),
                }))
        })
        .collect::<Result<Vec<_>, PipelineEmitError>>()?;
    Ok(Some(format!(
        "dispatch({component_name}Event.{case}({}))",
        args.join(", ")
    )))
}

fn emit_container_frame(
    node: &LayoutNode,
    composable: &str,
    depth: usize,
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    injected_width: Option<&str>,
) -> ContainerFrame {
    let pad = "    ".repeat(depth);
    let mut opener = String::new();
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style: Option<ComposeStyle> = if let Some(part) = &node.part_name {
        let base_props = part_styles.get(part).map(|v| v.as_slice()).unwrap_or(&[]);
        let state_layers = collect_state_layers(node, part, part_styles);
        if !base_props.is_empty() || !state_layers.is_empty() || injected_width.is_some() {
            Some(compose_box_style(
                base_props,
                &state_layers,
                injected_width,
                chain_indent,
                inherited_color,
            ))
        } else {
            None
        }
    } else if injected_width.is_some() {
        Some(compose_box_style(
            &[],
            &[],
            injected_width,
            chain_indent,
            inherited_color,
        ))
    } else {
        None
    };

    let has_style_chain = style
        .as_ref()
        .map(|s| !s.modifier.is_empty())
        .unwrap_or(false);
    let semantic_modifier = table_semantics_modifier(node, table_ctx);
    let has_chain = has_style_chain || semantic_modifier.is_some();
    let content_alignment = style.as_ref().and_then(|s| s.content_alignment.clone());
    let child_text: Option<TextStyleCtx> = match &style {
        Some(s) => {
            let inherited = text_ctx.cloned().unwrap_or_default();
            Some(cell_text_style(&inherited, s))
        }
        None => text_ctx.cloned(),
    };

    if has_chain || content_alignment.is_some() {
        let modifier_pad = "    ".repeat(depth + 1);
        writeln!(opener, "{pad}{composable}(").unwrap();
        if has_style_chain {
            let chain = style.as_ref().map(|s| s.modifier.as_str()).unwrap_or("");
            write!(opener, "{modifier_pad}modifier = Modifier{chain}").unwrap();
        } else {
            write!(opener, "{modifier_pad}modifier = Modifier.fillMaxWidth()").unwrap();
        }
        if let Some(semantics) = &semantic_modifier {
            write!(opener, "\n{}.{semantics}", " ".repeat(chain_indent)).unwrap();
        }
        writeln!(opener, ",").unwrap();
        if let Some(a) = &content_alignment {
            writeln!(opener, "{modifier_pad}contentAlignment = {a},").unwrap();
        }
        if node.children.is_empty() {
            writeln!(opener, "{pad}) {{ }}").unwrap();
            return ContainerFrame {
                opener,
                closer: String::new(),
                child_text,
            };
        }
        writeln!(opener, "{pad}) {{").unwrap();
    } else if node.children.is_empty() {
        writeln!(
            opener,
            "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{ }}"
        )
        .unwrap();
        return ContainerFrame {
            opener,
            closer: String::new(),
            child_text,
        };
    } else {
        writeln!(
            opener,
            "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{"
        )
        .unwrap();
    }

    ContainerFrame {
        opener,
        closer: format!("{pad}}}\n"),
        child_text,
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_container(
    node: &LayoutNode,
    composable: &str,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    injected_width: Option<&str>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let mut out = String::new();

    // Build the part-style chain for this node (if any).  The chain
    // lines are indented one level deeper than the `Box(` opener so the
    // multi-line `modifier = Modifier\n    .width(...)` reads cleanly.
    let chain_indent = (depth + 2) * 4;
    // The inherited sheet text color (if any) becomes the foreground
    // fall-back arm of a cell's `color` `if/else`, so a `state selected`
    // override doesn't blow away the sheet's base color in the
    // not-selected case.
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style: Option<ComposeStyle> = if let Some(part) = &node.part_name {
        let base_props = part_styles.get(part).map(|v| v.as_slice()).unwrap_or(&[]);
        let state_layers = collect_state_layers(node, part, part_styles);
        if !base_props.is_empty() || !state_layers.is_empty() || injected_width.is_some() {
            Some(compose_box_style(
                base_props,
                &state_layers,
                injected_width,
                chain_indent,
                inherited_color,
            ))
        } else {
            None
        }
    } else if injected_width.is_some() {
        // Width injected onto a part-less node — still emit the frame.
        Some(compose_box_style(
            &[],
            &[],
            injected_width,
            chain_indent,
            inherited_color,
        ))
    } else {
        None
    };

    let has_style_chain = style
        .as_ref()
        .map(|s| !s.modifier.is_empty())
        .unwrap_or(false);
    let semantic_modifier = table_semantics_modifier(node, table_ctx);
    let has_chain = has_style_chain || semantic_modifier.is_some();
    let content_alignment = style.as_ref().and_then(|s| s.content_alignment.clone());

    // The text style children inherit: a styled Box may override the
    // inherited (sheet) color / font for its own cell text.
    let child_text: Option<TextStyleCtx> = match &style {
        Some(s) => {
            let inherited = text_ctx.cloned().unwrap_or_default();
            Some(cell_text_style(&inherited, s))
        }
        None => text_ctx.cloned(),
    };

    // ---- opener -----------------------------------------------------
    if has_chain || content_alignment.is_some() {
        // Multi-line styled opener.
        let modifier_pad = "    ".repeat(depth + 1);
        writeln!(out, "{pad}{composable}(").unwrap();
        if has_style_chain {
            let chain = style.as_ref().map(|s| s.modifier.as_str()).unwrap_or("");
            write!(out, "{modifier_pad}modifier = Modifier{chain}").unwrap();
        } else {
            write!(out, "{modifier_pad}modifier = Modifier.fillMaxWidth()").unwrap();
        }
        if let Some(semantics) = &semantic_modifier {
            write!(out, "\n{}.{semantics}", " ".repeat(chain_indent)).unwrap();
        }
        writeln!(out, ",").unwrap();
        if let Some(a) = &content_alignment {
            writeln!(out, "{modifier_pad}contentAlignment = {a},").unwrap();
        }
        if node.children.is_empty() {
            writeln!(out, "{pad}) {{ }}").unwrap();
            return Ok(out);
        }
        writeln!(out, "{pad}) {{").unwrap();
    } else {
        // Styleless fall-back — unchanged from v0.1.0.
        if node.children.is_empty() {
            writeln!(
                out,
                "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{ }}"
            )
            .unwrap();
            return Ok(out);
        }
        writeln!(
            out,
            "{pad}{composable}(modifier = Modifier.fillMaxWidth()) {{"
        )
        .unwrap();
    }

    // ---- body -------------------------------------------------------
    // A `Row` inside a HostTable routes each child through
    // `emit_table_cell` so cell-position `For`s get width threading.
    if composable == "Row" && table_ctx.is_some() {
        for cell in &node.children {
            out.push_str(&emit_table_cell(
                cell,
                depth + 1,
                component_name,
                emits,
                part_styles,
                table_ctx,
                child_text.as_ref(),
                for_payload,
            )?);
        }
    } else {
        out.push_str(&emit_children_compose(
            &node.children,
            depth + 1,
            component_name,
            emits,
            part_styles,
            table_ctx,
            child_text.as_ref(),
            for_payload,
            None,
        )?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Emit a single cell of a `Row` inside a `HostTable`.  When the cell is
/// a `For` with both an `index:` binding AND a live `column_widths_slot`,
/// route through [`emit_for_compose`]'s width-threading mode so each
/// iteration's `Box` picks up `.width(columnWidths[_kotlinIdx<idx>].dp)`.
/// Anything else falls through to the normal walker.
#[allow(clippy::too_many_arguments)]
fn emit_table_cell(
    cell: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    if let Some(ctx) = table_ctx {
        if ctx.column_widths_slot.is_some()
            && cell.tag == "For"
            && find_keyword_prop(cell, "index").is_some()
        {
            return emit_for_compose(
                cell,
                depth,
                component_name,
                emits,
                part_styles,
                table_ctx,
                text_ctx,
                for_payload,
                /*width_thread=*/ true,
            );
        }
    }
    emit_compose_tree(
        cell,
        depth,
        component_name,
        emits,
        part_styles,
        table_ctx,
        text_ctx,
        for_payload,
        None,
    )
}

/// Walk a list of sibling children with explicit If/Else pairing
/// (mirrors the equivalent helpers in `mosaic-emit-html` and
/// `mosaic-emit-swiftui`).  When the walker sees an `If`, it peeks
/// the next sibling; if it's `Else`, both branches are handed to
/// [`emit_if_compose`] together and the walker advances past both.
/// All other nodes flow through [`emit_compose_tree`] unchanged.
#[allow(clippy::too_many_arguments)]
fn emit_children_compose(
    children: &[LayoutNode],
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    // Threaded column-width expression to inject into each DIRECT plain
    // child's Modifier chain.  `Some` only on the body-children dispatch
    // of a width-threading HostTable cell `For`.
    injected_width: Option<&str>,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    let mut i = 0;
    while i < children.len() {
        let child = &children[i];
        if child.tag == "If" {
            let else_node = children.get(i + 1).filter(|n| n.tag == "Else");
            out.push_str(&emit_if_compose(
                child,
                else_node,
                depth,
                component_name,
                emits,
                part_styles,
                table_ctx,
                text_ctx,
                for_payload,
            )?);
            i += if else_node.is_some() { 2 } else { 1 };
            continue;
        }
        out.push_str(&emit_compose_tree(
            child,
            depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            injected_width,
        )?);
        i += 1;
    }
    Ok(out)
}

/// Lower a `For ( each: <coll>, as: <name>, index: <name>? )` to a
/// Kotlin `forEachIndexed { idx, item -> ... }` (when `index:` is
/// present) or `forEach { item -> ... }` (when it isn't).
///
/// Compose's preferred iteration shape is plain Kotlin collection
/// extensions inside a layout container — `Column { rows.forEach { … } }`
/// composes naturally because the trailing lambda is a `@Composable`
/// content block.  The `forEachIndexed` form drops the `Int` index
/// directly into scope; moslayout's `index:` binding is a number-
/// typed slot in the runtime's expression-language scope, and Kotlin
/// accepts `Int == Double` via its `Number` coercion in `==` calls,
/// so verbatim Expr text like `( r == editRow && c == editCol )`
/// compiles without further widening.
#[allow(clippy::too_many_arguments)]
fn emit_for_compose(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
    // When true AND a `column_widths_slot` is live AND this For has an
    // `index:` binding, each iteration's body Box gets a threaded
    // `.width(<slot>[_kotlinIdx<idx>].dp)`.  See [`emit_table_cell`].
    width_thread: bool,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner_depth = depth + 1;

    let coll = match node.props.iter().find(|p| p.name == "each") {
        Some(p) => match &p.value {
            LayoutPropValue::SlotRef(s) => to_camel_case_first_lower(s),
            LayoutPropValue::Expr(text) => text.trim().to_string(),
            // UI29 §3.4 — a bare `Keyword` names an enclosing For's
            // `as:` binding (nested For over the outer's element).
            LayoutPropValue::Keyword(name) => to_camel_case_first_lower(name),
            _ => "emptyList<Any>()".to_string(),
        },
        None => "emptyList<Any>()".to_string(),
    };

    let as_name = find_keyword_prop(node, "as")
        .as_deref()
        .map(to_camel_case_first_lower)
        .unwrap_or_else(|| "item".to_string());
    let index_name = find_keyword_prop(node, "index")
        .as_deref()
        .map(to_camel_case_first_lower);

    let header = match &index_name {
        Some(idx) => {
            // The closure parameter binds the offset as an `Int`
            // under a `_kotlinIdx<idx>` shadow name, and we
            // immediately re-bind `<idx>` to a `Double` so the
            // moslayout author's verbatim expression text (e.g.
            // `( r == editRow && c == editCol )`) compiles cleanly
            // against `number`-typed slots that lower to `Double`.
            //
            // Kotlin's `==` operator does NOT allow `Int == Double`
            // (it desugars to a strict-type `.equals` call), so
            // without this cast the visicalc Grid's per-cell
            // `is-editing` predicate would fail to compile.
            //
            // The moslayout NAME grammar
            // `[a-zA-Z][a-zA-Z0-9]*(-...)*` can never produce a
            // leading underscore, so `_kotlinIdx<idx>` is
            // collision-free against any author-supplied name.  The
            // pattern mirrors `mosaic-emit-swiftui`'s
            // `_swiftIdx<idx>` rename for the same reason.
            let inner_pad = "    ".repeat(inner_depth);
            format!(
                "{pad}{coll}.forEachIndexed {{ _kotlinIdx{idx}, {as_name} ->\n\
                 {inner_pad}val {idx}: Double = _kotlinIdx{idx}.toDouble()\n",
                coll = coll,
                idx = idx,
                as_name = as_name,
            )
        }
        None => format!(
            "{pad}{coll}.forEach {{ {as_name} ->\n",
            coll = coll,
            as_name = as_name,
        ),
    };

    // HostTable column-width threading.  When this For sits in
    // cell-position inside a HostTable Row AND the TableContext carries a
    // `column_widths_slot` AND we have an `index:` binding, each
    // iteration's cell Box takes an explicit width
    // `columnWidths[_kotlinIdx<idx>].dp` rather than auto-sizing.  We
    // index with the `_kotlinIdx<idx>` Int SHADOW (not `<idx>`, which is
    // re-bound to a `Double` for the predicates and cannot index a
    // Kotlin `List`).  The width threads into the body child's Modifier
    // chain (via `injected_width`) so it lands BEFORE background/border.
    let width_expr: Option<String> = if width_thread {
        match (
            &index_name,
            table_ctx.and_then(|c| c.column_widths_slot.as_deref()),
        ) {
            (Some(idx), Some(slot)) => Some(format!("{slot}[_kotlinIdx{idx}]")),
            _ => None,
        }
    } else {
        None
    };

    let scoped_payload = Some(ForPayloadScope {
        item: as_name.as_str(),
        index: index_name
            .as_deref()
            .or(for_payload.and_then(|scope| scope.index)),
    });
    let scoped_table_ctx = table_ctx.map(|ctx| ctx.in_loop(index_name.as_deref()));

    let mut out = header;
    if node.children.is_empty() {
        // Compose's content lambda is fine with no children — the
        // forEach loop just runs zero times' worth of layout.  Still
        // we emit a comment so the generated body is greppable.
        out.push_str(&format!(
            "{}// (empty For body)\n",
            "    ".repeat(inner_depth)
        ));
    } else {
        out.push_str(&emit_children_compose(
            &node.children,
            inner_depth,
            component_name,
            emits,
            part_styles,
            scoped_table_ctx.as_ref(),
            text_ctx,
            scoped_payload,
            width_expr.as_deref(),
        )?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Lower an `If ( when: <expr> ) { ... } Else { ... }` pair to a
/// Kotlin `if (cond) { ... } else { ... }` block.  The condition is
/// the `when:` prop's expression text verbatim (moslayout's
/// expression grammar is a strict subset of Kotlin's so identifiers,
/// member access, indexing, `==`, `!=`, `<`, `<=`, `>`, `>=`, `&&`,
/// `||`, `!` all carry across unchanged).  Literal `when: true` /
/// `when: false` fold at compile time so the generated file omits
/// the dead branch entirely.
///
/// The `else_node` parameter is `None` when the parent walker found
/// no sibling `Else` after the `If`.  In that case we emit just the
/// then-branch — Compose accepts a bare `if (cond) { … }` inside a
/// layout block because the trailing-else type is `Unit?`.
#[allow(clippy::too_many_arguments)]
fn emit_if_compose(
    node: &LayoutNode,
    else_node: Option<&LayoutNode>,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner_depth = depth + 1;

    let when = find_prop_value(node, "when");

    // Compile-time fold for `when: true` / `when: false`.
    if let Some(LayoutPropValue::Keyword(k)) = when {
        match k.as_str() {
            "true" => {
                return emit_children_compose(
                    &node.children,
                    depth,
                    component_name,
                    emits,
                    part_styles,
                    table_ctx,
                    text_ctx,
                    for_payload,
                    None,
                );
            }
            "false" => {
                if let Some(e) = else_node {
                    return emit_children_compose(
                        &e.children,
                        depth,
                        component_name,
                        emits,
                        part_styles,
                        table_ctx,
                        text_ctx,
                        for_payload,
                        None,
                    );
                }
                return Ok(String::new());
            }
            _ => {}
        }
    }

    let cond_expr = match when {
        Some(LayoutPropValue::SlotRef(s)) => {
            format!("_mosaicTruthy({})", to_camel_case_first_lower(s))
        }
        Some(LayoutPropValue::Expr(e)) => format!("_mosaicTruthy({})", e.trim()),
        Some(LayoutPropValue::Keyword(k)) => {
            format!("_mosaicTruthy({})", to_camel_case_first_lower(k))
        }
        Some(LayoutPropValue::String(s)) => format!("_mosaicTruthy(\"{s}\")"),
        Some(LayoutPropValue::Number(n)) => format!("_mosaicTruthy({n})"),
        Some(LayoutPropValue::EmitRef(name)) => format!("_mosaicTruthy({name})"),
        None => "false".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}if ({cond_expr}) {{").unwrap();
    out.push_str(&emit_children_compose(
        &node.children,
        inner_depth,
        component_name,
        emits,
        part_styles,
        table_ctx,
        text_ctx,
        for_payload,
        None,
    )?);
    if let Some(e) = else_node {
        writeln!(out, "{pad}}} else {{").unwrap();
        out.push_str(&emit_children_compose(
            &e.children,
            inner_depth,
            component_name,
            emits,
            part_styles,
            table_ctx,
            text_ctx,
            for_payload,
            None,
        )?);
    }
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

/// Find a prop whose value is a `Keyword` and return its NAME text.
/// Used by `emit_for_compose` for the `as:` / `index:` props.
fn find_keyword_prop(node: &LayoutNode, prop_name: &str) -> Option<String> {
    node.props.iter().find_map(|p| {
        if p.name == prop_name {
            if let LayoutPropValue::Keyword(s) = &p.value {
                return Some(s.clone());
            }
        }
        None
    })
}

fn emit_icon_compose(
    node: &LayoutNode,
    depth: usize,
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|text| text.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);

    let glyph = match text_prop_expr(node, "glyph")? {
        Some(value) => value,
        None => match text_prop_expr(node, "source")? {
            Some(value) => value,
            None => text_prop_expr(node, "name")?.unwrap_or_else(|| "\"star\"".to_string()),
        },
    };
    let description = match text_prop_expr(node, "aria-label")? {
        Some(value) => value,
        None => match text_prop_expr(node, "content-description")? {
            Some(value) => value,
            None => match find_prop_value(node, "glyph")
                .or_else(|| find_prop_value(node, "source"))
                .or_else(|| find_prop_value(node, "name"))
            {
                Some(LayoutPropValue::String(value)) if value.eq_ignore_ascii_case("spinner") => {
                    "\"Loading\"".to_string()
                }
                Some(LayoutPropValue::String(value)) => {
                    format!("\"{}\"", escape_kotlin_string(value))
                }
                _ => glyph.clone(),
            },
        },
    };

    let mut modifier =
        host_control_modifier_expr(node, style.as_ref()).unwrap_or_else(|| "Modifier".to_string());
    if let Some(size) = style.as_ref().and_then(|style| style.font_size.as_deref()) {
        write!(modifier, ".width(({size}).dp).height(({size}).dp)").unwrap();
    }

    let mut out = String::new();
    writeln!(out, "{pad}_mosaicIcon(").unwrap();
    writeln!(out, "{inner}glyph = {glyph},").unwrap();
    writeln!(out, "{inner}description = {description},").unwrap();
    writeln!(out, "{inner}modifier = {modifier},").unwrap();
    if let Some(tint) = style.as_ref().and_then(|style| style.text_color.as_deref()) {
        writeln!(out, "{inner}tint = {tint},").unwrap();
    }
    if let Some(size) = style.as_ref().and_then(|style| style.font_size.as_deref()) {
        writeln!(out, "{inner}fontSize = ({size}).sp,").unwrap();
    }
    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

fn emit_text(
    node: &LayoutNode,
    depth: usize,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let value_expr = match find_prop_value(node, "content") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Expr(text)) => compose_collection_index_expr(text, for_payload),
        _ => "\"\"".to_string(),
    };
    // When an inherited/cell text style is in effect, emit the value
    // POSITIONALLY with the `color` / `fontFamily` / `fontSize` named
    // args appended (`Text(( v ), color = ..., fontFamily = ...)`).
    // With no styling, keep the labelled `Text(text = ...)` shape so the
    // styleless passthrough (e.g. FormulaBar) is byte-identical to before.
    let modifier = if layout_node_is_accessibility_hidden(node) {
        Some("Modifier.clearAndSetSemantics { }".to_string())
    } else {
        let label = text_prop_expr(node, "a11y-label")?;
        let is_heading = matches!(
            find_prop_value(node, "a11y-role"),
            Some(LayoutPropValue::Keyword(value)) if value == "heading"
        );
        match (label, is_heading) {
            (Some(label), true) => Some(format!(
                "Modifier.clearAndSetSemantics {{ contentDescription = {label}; heading() }}"
            )),
            (Some(label), false) => Some(format!(
                "Modifier.clearAndSetSemantics {{ contentDescription = {label} }}"
            )),
            (None, true) => Some("Modifier.semantics { heading() }".to_string()),
            (None, false) => None,
        }
    };
    Ok(format!(
        "{pad}{}\n",
        text_call(&value_expr, text_ctx, modifier.as_deref())
    ))
}

/// Mosaic loop indices are exposed as `number`, so Compose keeps the authored
/// binding as a `Double` for comparisons and an internal `Int` shadow for
/// Kotlin collection access. Route an expression such as `bodies[i]` through
/// that shadow while leaving ordinary arithmetic and comparisons untouched.
fn compose_collection_index_expr(
    expression: &str,
    for_payload: Option<ForPayloadScope<'_>>,
) -> String {
    let Some(index) = for_payload.and_then(|scope| scope.index) else {
        return expression.to_string();
    };
    let replacement = format!("[_kotlinIdx{index}]");
    let mut lowered = expression.to_string();
    for authored in [
        format!("[{index}]"),
        format!("[ {index}]"),
        format!("[{index} ]"),
        format!("[ {index} ]"),
    ] {
        lowered = lowered.replace(&authored, &replacement);
    }
    lowered
}

fn emit_host_input(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let inherited_text = text_ctx.cloned().unwrap_or_default();
    let input_text = match &style {
        Some(s) => cell_text_style(&inherited_text, s),
        None => inherited_text,
    };

    let value_expr = text_prop_expr(node, "value")?.unwrap_or_else(|| "\"\"".to_string());

    let mut out = String::new();
    writeln!(out, "{pad}BasicTextField(").unwrap();
    writeln!(out, "{inner}value = {value_expr},").unwrap();

    let multiline = matches!(
        find_prop_value(node, "multiline"),
        Some(LayoutPropValue::Keyword(value)) if value == "true"
    );
    if multiline {
        // BasicTextField is multiline by default, but emitting the contract
        // explicitly prevents a future default change and gives editor-shaped
        // inputs a useful native minimum without app-specific Compose code.
        writeln!(out, "{inner}singleLine = false,").unwrap();
        writeln!(out, "{inner}minLines = 8,").unwrap();
    }

    // onChange — wraps the new value in a dispatched event whose
    // case mirrors the .mil declaration.  The strict-Flux contract
    // matches mosaic-emit-flutter's `dispatch(<Component>Event<Case>(value:
    // value))` shape — same naming, same arity, same idiomatic shape
    // adapted to Kotlin's `data class` / `data object`.
    if let Some(emit_name) = find_emit_ref_prop(node, "onChange") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        let dispatch_call = if arity == 0 {
            format!("{component_name}Event.{case}")
        } else {
            format!("{component_name}Event.{case}(v)")
        };
        writeln!(
            out,
            "{inner}onValueChange = {{ v -> dispatch({dispatch_call}) }},"
        )
        .unwrap();
    } else {
        // Without an onChange we still need an onValueChange to
        // satisfy BasicTextField's required parameter — emit a
        // no-op closure.
        writeln!(out, "{inner}onValueChange = {{ }},").unwrap();
    }

    // onCommit — "the user finished editing" (Enter). A zero-argument event is
    // dispatched as a data object; a one-argument event receives the input's
    // current controlled value. This supports both toolkit inputs and native
    // editing primitives such as Grid.Cell's `onCommit(value: text)`. Compose
    // has no free-standing submit on a BasicTextField, so wire it to the soft
    // keyboard's Done IME action and make the field single-line, so Enter (soft or
    // hardware keyboard) fires the commit instead of inserting a newline. Without
    // this the generated field could take keystrokes but never dispatch onCommit —
    // the host's write-through / recompute was unreachable. Mirrors the SwiftUI
    // emitter's `.onSubmit { dispatch(.commit) }`.
    if let Some(emit_name) = find_emit_ref_prop(node, "onCommit") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let emit = emits.iter().find(|e| e.name == *emit_name);
        let dispatch_call = match emit.and_then(|e| e.params.first()) {
            None => format!("{component_name}Event.{case}"),
            Some(param) => {
                let payload = match &param.r#type {
                    EmitPayloadType::Text
                    | EmitPayloadType::Color
                    | EmitPayloadType::Component(_) => value_expr.clone(),
                    EmitPayloadType::Number => {
                        format!("({value_expr}).toDoubleOrNull() ?: 0.0")
                    }
                    EmitPayloadType::Bool => format!("_mosaicTruthy({value_expr})"),
                };
                format!("{component_name}Event.{case}({payload})")
            }
        };
        if !multiline {
            writeln!(out, "{inner}singleLine = true,").unwrap();
        }
        writeln!(
            out,
            "{inner}keyboardOptions = KeyboardOptions(imeAction = ImeAction.Done),"
        )
        .unwrap();
        writeln!(
            out,
            "{inner}keyboardActions = KeyboardActions(onDone = {{ dispatch({dispatch_call}) }}),"
        )
        .unwrap();
    }

    if let Some(modifier) = host_control_modifier_expr(node, style.as_ref()) {
        writeln!(out, "{inner}modifier = {modifier},").unwrap();
    }
    if let Some(text_style) = input_text.text_style_expr() {
        writeln!(out, "{inner}textStyle = {text_style},").unwrap();
    }

    if let Some(placeholder) = text_prop_expr(node, "placeholder")? {
        writeln!(out, "{inner}decorationBox = {{ innerTextField ->").unwrap();
        writeln!(out, "{inner}    Box {{").unwrap();
        writeln!(out, "{inner}        if ({value_expr}.isEmpty()) {{").unwrap();
        writeln!(out, "{inner}            Text(text = {placeholder})").unwrap();
        writeln!(out, "{inner}        }}").unwrap();
        writeln!(out, "{inner}        innerTextField()").unwrap();
        writeln!(out, "{inner}    }}").unwrap();
        writeln!(out, "{inner}}},").unwrap();
    }

    // read-only -> enabled when the optional flag is not explicitly true.
    if find_prop_value(node, "read-only").is_some() {
        let read_only = bool_prop_expr(node, "read-only", "false")?;
        writeln!(out, "{inner}enabled = !({read_only}),").unwrap();
    }

    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

fn emit_host_button(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let inherited_text = text_ctx.cloned().unwrap_or_default();
    let label_text = match &style {
        Some(s) => cell_text_style(&inherited_text, s),
        None => inherited_text,
    };

    // onTap → onClick dispatch
    let on_click = if let Some(emit_name) =
        find_emit_ref_prop(node, "onClick").or_else(|| find_emit_ref_prop(node, "onTap"))
    {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else if arity == 1 {
            match host_button_single_payload_expr(emit_name, emits, for_payload) {
                Some(payload) => format!("dispatch({component_name}Event.{case}({payload}))"),
                None => format!("dispatch({component_name}Event.{case}(/* TODO: payload */))"),
            }
        } else {
            format!("dispatch({component_name}Event.{case}(/* TODO: payload */))")
        }
    } else {
        "/* no onClick bound */".to_string()
    };

    let label = match find_prop_value(node, "label") {
        Some(LayoutPropValue::String(s)) => format!("\"{}\"", escape_kotlin_string(s)),
        Some(LayoutPropValue::SlotRef(slot)) => to_camel_case_first_lower(slot),
        Some(LayoutPropValue::Keyword(name)) => to_camel_case_first_lower(name),
        Some(LayoutPropValue::Expr(text)) => text.trim().to_string(),
        _ => "\"\"".to_string(),
    };
    let enabled_expr = disabled_prop_enabled_expr(node)?;
    let modifier_expr = host_control_modifier_expr(node, style.as_ref());

    let mut out = String::new();
    if enabled_expr.is_some() || modifier_expr.is_some() {
        writeln!(out, "{pad}Button(").unwrap();
        writeln!(out, "{inner}onClick = {{ {on_click} }},").unwrap();
        if let Some(enabled) = enabled_expr {
            writeln!(out, "{inner}enabled = {enabled},").unwrap();
        }
        if let Some(modifier) = modifier_expr {
            writeln!(out, "{inner}modifier = {modifier},").unwrap();
        }
        writeln!(out, "{pad}) {{").unwrap();
    } else {
        writeln!(out, "{pad}Button(onClick = {{ {on_click} }}) {{").unwrap();
    }
    writeln!(out, "{inner}{}", text_call(&label, Some(&label_text), None)).unwrap();
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

fn host_control_modifier_expr(node: &LayoutNode, style: Option<&ComposeStyle>) -> Option<String> {
    let mut modifier = String::from("Modifier");
    if let Some(style) = style {
        modifier.push_str(&style.modifier);
    }
    if let Some(part) = &node.part_name {
        write!(modifier, ".testTag(\"{}\")", escape_kotlin_string(part)).unwrap();
    }
    (modifier != "Modifier").then_some(modifier)
}

fn host_button_single_payload_expr(
    emit_name: &str,
    emits: &[EmitDecl],
    for_payload: Option<ForPayloadScope<'_>>,
) -> Option<String> {
    let param_type = emits
        .iter()
        .find(|e| e.name == emit_name)
        .and_then(|e| e.params.first())
        .map(|p| &p.r#type)?;
    let scope = for_payload?;
    match param_type {
        EmitPayloadType::Text | EmitPayloadType::Color | EmitPayloadType::Component(_) => {
            Some(scope.item.to_string())
        }
        EmitPayloadType::Number => scope.index.map(str::to_string),
        EmitPayloadType::Bool => None,
    }
}

/// Lower `HostLink` to Compose's native annotated-text link API.
///
/// External links use `LinkAnnotation.Url`, which opens through the platform
/// `UriHandler`. Internal links use `LinkAnnotation.Clickable` and dispatch the
/// declared Mosaic event without opening a browser. Both shapes retain native
/// link semantics instead of presenting navigation as a button.
#[allow(clippy::too_many_arguments)]
fn emit_host_link(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    if !node.children.is_empty() && find_prop_value(node, "label").is_none() {
        return Err(PipelineEmitError::UnsupportedHostLink(
            "child composables require a serializable inline-content contract; use label for now"
                .to_string(),
        ));
    }

    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|text| text.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let inherited_text = text_ctx.cloned().unwrap_or_default();
    let link_text = match &style {
        Some(style) => cell_text_style(&inherited_text, style),
        None => inherited_text,
    };

    let href = host_link_href_expr(node)?.unwrap_or_else(|| "\"\"".to_string());
    let label = host_link_text_prop_expr(node, "label")?.unwrap_or_else(|| href.clone());
    let external = bool_prop_expr(node, "external", "true")?;
    let on_activate = host_link_on_activate(node, component_name, emits, for_payload, &href)?;
    let modifier =
        host_control_modifier_expr(node, style.as_ref()).unwrap_or_else(|| "Modifier".to_string());
    let text_style = link_text
        .text_style_expr()
        .unwrap_or_else(|| "TextStyle.Default".to_string());

    let mut out = String::new();
    writeln!(out, "{pad}_mosaicHostLink(").unwrap();
    writeln!(out, "{inner}href = {href},").unwrap();
    writeln!(out, "{inner}label = {label},").unwrap();
    writeln!(out, "{inner}external = {external},").unwrap();
    writeln!(out, "{inner}modifier = {modifier},").unwrap();
    writeln!(out, "{inner}textStyle = {text_style},").unwrap();
    if let Some(dispatch) = on_activate {
        writeln!(out, "{inner}onActivate = {{ {dispatch} }},").unwrap();
    }
    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

fn host_link_text_prop_expr(
    node: &LayoutNode,
    name: &str,
) -> Result<Option<String>, PipelineEmitError> {
    match find_prop_value(node, name) {
        Some(LayoutPropValue::String(value)) => {
            Ok(Some(format!("\"{}\"", escape_kotlin_string(value))))
        }
        Some(LayoutPropValue::SlotRef(slot)) | Some(LayoutPropValue::Keyword(slot)) => {
            let identifier = to_camel_case_first_lower(slot);
            validate_safe_identifier(&identifier).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(Some(identifier))
        }
        Some(LayoutPropValue::Expr(expression)) => Ok(Some(expression.clone())),
        _ => Ok(None),
    }
}

/// #13052: the `href`-specific analogue of [`host_link_text_prop_expr`]
/// above -- identical except a literal `String` is checked against the
/// URI scheme allowlist first. `label` keeps using the generic
/// function since it's never handed to `uriHandler.openUri`.
fn host_link_href_expr(node: &LayoutNode) -> Result<Option<String>, PipelineEmitError> {
    if let Some(LayoutPropValue::String(value)) = find_prop_value(node, "href") {
        if has_disallowed_uri_scheme(value) {
            return Err(PipelineEmitError::UnsupportedHostLink(format!(
                "href {value:?} uses a disallowed URI scheme -- only http, https, mailto, \
                 or a relative reference are allowed"
            )));
        }
    }
    host_link_text_prop_expr(node, "href")
}

/// #13052: does `href` carry an explicit URI scheme outside the
/// `http`/`https`/`mailto` allowlist? A relative reference (no scheme
/// at all -- `"#"`, a route path) returns `false`, since a relative
/// reference never reaches `uriHandler.openUri` as an external
/// navigation target in the first place (see `_mosaicHostLink`'s
/// runtime guard, which only gates the `external == true` branch).
/// Only a *present, disallowed* scheme (`javascript:`, `data:`,
/// `intent:`, a custom protocol handler, ...) returns `true`.
///
/// Security-review hardening: normalizes exactly like the WHATWG URL
/// parser does before looking for a scheme -- trims leading/trailing
/// C0-control-or-space and strips every embedded tab/CR/LF. Without
/// this, `" javascript:alert(1)"` or `"java\tscript:alert(1)"` fails
/// the alphabetic-first-character check below and gets classified as
/// "no scheme, therefore a safe relative reference" -- but a real
/// consumer strips that same whitespace before parsing the scheme, so
/// it actually navigates as `javascript:`. A first review pass of
/// #13052 missed this; caught and fixed in the same PR. The matching
/// runtime `_mosaicIsSafeUri` Kotlin helper normalizes identically.
fn has_disallowed_uri_scheme(href: &str) -> bool {
    let normalized: String = href
        .trim_matches(|c: char| (c as u32) <= 0x20)
        .chars()
        .filter(|c| !matches!(c, '\t' | '\r' | '\n'))
        .collect();
    let href = normalized.as_str();
    let Some(colon) = href.find(':') else {
        return false;
    };
    let prefix = &href[..colon];
    if prefix.is_empty() || prefix.contains(['/', '?', '#']) {
        return false;
    }
    let mut chars = prefix.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !first.is_ascii_alphabetic() {
        return false;
    }
    if !chars.all(|c| c.is_ascii_alphanumeric() || c == '+' || c == '-' || c == '.') {
        return false;
    }
    const ALLOWED: [&str; 3] = ["http", "https", "mailto"];
    !ALLOWED.iter().any(|s| s.eq_ignore_ascii_case(prefix))
}

fn host_link_on_activate(
    node: &LayoutNode,
    component_name: &str,
    emits: &[EmitDecl],
    for_payload: Option<ForPayloadScope<'_>>,
    href: &str,
) -> Result<Option<String>, PipelineEmitError> {
    let Some(emit_name) = find_emit_ref_prop(node, "onActivate") else {
        return Ok(None);
    };
    let case = pascalize(&strip_on_prefix(emit_name));
    validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
    let Some(emit) = emits.iter().find(|emit| emit.name == emit_name) else {
        return Ok(Some(format!("dispatch({component_name}Event.{case})")));
    };
    if emit.params.is_empty() {
        return Ok(Some(format!("dispatch({component_name}Event.{case})")));
    }

    let args = emit
        .params
        .iter()
        .map(|param| host_link_payload_expr(param, for_payload, href))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(Some(format!(
        "dispatch({component_name}Event.{case}({}))",
        args.join(", ")
    )))
}

fn host_link_payload_expr(
    param: &mosmodel_compiler::EmitParam,
    for_payload: Option<ForPayloadScope<'_>>,
    href: &str,
) -> Result<String, PipelineEmitError> {
    let field = to_camel_case_first_lower(&param.name);
    validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
    if field == "href" {
        return match param.r#type {
            EmitPayloadType::Text | EmitPayloadType::Color => Ok(href.to_string()),
            _ => Err(PipelineEmitError::UnsupportedHostLink(format!(
                "event field '{}' must be text-compatible to receive href",
                param.name
            ))),
        };
    }

    match &param.r#type {
        EmitPayloadType::Number => for_payload
            .and_then(|scope| scope.index)
            .map(str::to_string)
            .ok_or_else(|| {
                PipelineEmitError::UnsupportedHostLink(format!(
                    "numeric event field '{}' requires an enclosing For index",
                    param.name
                ))
            }),
        EmitPayloadType::Text | EmitPayloadType::Color => Ok(for_payload
            .map(|scope| scope.item.to_string())
            .unwrap_or_else(|| href.to_string())),
        EmitPayloadType::Bool | EmitPayloadType::Component(_) => {
            Err(PipelineEmitError::UnsupportedHostLink(format!(
                "cannot synthesize event field '{}' from a link activation",
                param.name
            )))
        }
    }
}

/// Lower `HostDialog` to Compose's native overlay primitives.
///
/// Modal dialogs use `Dialog`, which supplies platform focus trapping,
/// keyboard dismissal, and backdrop behavior. The contract's compile-time
/// `modal: false` variant uses `Popup` so the rest of the app remains
/// interactive. In both cases the title is a semantic heading and the body is
/// walked normally, preserving nested Mosaic controls and styles.
#[allow(clippy::too_many_arguments)]
fn emit_host_dialog(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    table_ctx: Option<&TableContext>,
    text_ctx: Option<&TextStyleCtx>,
    for_payload: Option<ForPayloadScope<'_>>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let content = "    ".repeat(depth + 2);
    let body = "    ".repeat(depth + 3);
    let open = bool_prop_expr(node, "open", "false")?;
    let dismiss = bool_prop_expr(node, "dismiss-on-backdrop", "true")?;
    let modal = match find_prop_value(node, "modal") {
        None => true,
        Some(LayoutPropValue::Keyword(value)) if value == "true" => true,
        Some(LayoutPropValue::Keyword(value)) if value == "false" => false,
        Some(_) => {
            return Err(PipelineEmitError::UnsupportedHostDialog(
                "modal must be the compile-time keyword true or false".to_string(),
            ));
        }
    };
    let on_open = host_dialog_dispatch(node, "onOpen", component_name, emits)?;
    let on_close = host_dialog_dispatch(node, "onClose", component_name, emits)?
        .unwrap_or_else(|| "/* no onClose bound */".to_string());
    let title = text_prop_expr(node, "title")?;

    let chain_indent = (depth + 4) * 4;
    let inherited_color = text_ctx.and_then(|text| text.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let modifier =
        host_control_modifier_expr(node, style.as_ref()).unwrap_or_else(|| "Modifier".to_string());
    let child_text = match &style {
        Some(style) => Some(cell_text_style(
            &text_ctx.cloned().unwrap_or_default(),
            style,
        )),
        None => text_ctx.cloned(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}if ({open}) {{").unwrap();
    if modal {
        writeln!(out, "{inner}Dialog(").unwrap();
        writeln!(out, "{content}onDismissRequest = {{ {on_close} }},").unwrap();
        writeln!(out, "{content}properties = DialogProperties(").unwrap();
        writeln!(out, "{body}dismissOnBackPress = {dismiss},").unwrap();
        writeln!(out, "{body}dismissOnClickOutside = {dismiss},").unwrap();
        writeln!(out, "{content}),").unwrap();
        writeln!(out, "{inner}) {{").unwrap();
    } else {
        writeln!(out, "{inner}Popup(").unwrap();
        writeln!(out, "{content}alignment = Alignment.Center,").unwrap();
        writeln!(out, "{content}onDismissRequest = {{ {on_close} }},").unwrap();
        writeln!(out, "{content}properties = PopupProperties(").unwrap();
        writeln!(out, "{body}focusable = true,").unwrap();
        writeln!(out, "{body}dismissOnBackPress = {dismiss},").unwrap();
        writeln!(out, "{body}dismissOnClickOutside = {dismiss},").unwrap();
        writeln!(out, "{content}),").unwrap();
        writeln!(out, "{inner}) {{").unwrap();
    }
    if let Some(dispatch) = on_open {
        writeln!(out, "{content}LaunchedEffect(Unit) {{ {dispatch} }}").unwrap();
    }
    writeln!(out, "{content}Surface(").unwrap();
    writeln!(out, "{body}modifier = {modifier},").unwrap();
    writeln!(out, "{body}shape = MaterialTheme.shapes.medium,").unwrap();
    writeln!(out, "{body}elevation = 8.dp,").unwrap();
    writeln!(out, "{content}) {{").unwrap();
    writeln!(out, "{body}Column(modifier = Modifier.padding(24.dp)) {{").unwrap();
    if let Some(title) = title {
        let title_pad = "    ".repeat(depth + 4);
        writeln!(
            out,
            "{title_pad}Text(text = {title}, style = MaterialTheme.typography.h6, modifier = Modifier.semantics {{ heading() }})"
        )
        .unwrap();
    }
    out.push_str(&emit_children_compose(
        &node.children,
        depth + 4,
        component_name,
        emits,
        part_styles,
        table_ctx,
        child_text.as_ref(),
        for_payload,
        None,
    )?);
    writeln!(out, "{body}}}").unwrap();
    writeln!(out, "{content}}}").unwrap();
    writeln!(out, "{inner}}}").unwrap();
    writeln!(out, "{pad}}}").unwrap();
    Ok(out)
}

fn host_dialog_dispatch(
    node: &LayoutNode,
    prop_name: &str,
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<Option<String>, PipelineEmitError> {
    let Some(emit_name) = find_emit_ref_prop(node, prop_name) else {
        return Ok(None);
    };
    let case = pascalize(&strip_on_prefix(emit_name));
    validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
    if let Some(emit) = emits.iter().find(|emit| emit.name == emit_name) {
        if !emit.params.is_empty() {
            return Err(PipelineEmitError::UnsupportedHostDialog(format!(
                "{prop_name} event '{emit_name}' must not declare payload fields"
            )));
        }
    }
    Ok(Some(format!("dispatch({component_name}Event.{case})")))
}

fn emit_host_checkbox(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let inherited_text = text_ctx.cloned().unwrap_or_default();
    let label_text = match &style {
        Some(s) => cell_text_style(&inherited_text, s),
        None => inherited_text,
    };
    let checked_expr = bool_prop_expr(node, "checked", "false")?;
    let enabled_expr = disabled_prop_enabled_expr(node)?;

    let on_checked = if let Some(emit_name) = find_emit_ref_prop(node, "onToggle") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!("dispatch({component_name}Event.{case}(checked))")
        }
    } else {
        "/* no onToggle bound */".to_string()
    };

    let mut checkbox_lines = Vec::new();
    checkbox_lines.push(format!("{inner}Checkbox("));
    checkbox_lines.push(format!("{inner}    checked = {checked_expr},"));
    checkbox_lines.push(format!(
        "{inner}    onCheckedChange = {{ checked -> {on_checked} }},"
    ));
    if let Some(enabled) = enabled_expr.as_deref() {
        checkbox_lines.push(format!("{inner}    enabled = {enabled},"));
    }
    checkbox_lines.push(format!("{inner})"));

    if let Some(label) = text_prop_expr(node, "label")? {
        let mut out = String::new();
        if let Some(style) = &style {
            if !style.modifier.is_empty() {
                writeln!(out, "{pad}Row(").unwrap();
                writeln!(out, "{inner}modifier = Modifier{},", style.modifier).unwrap();
                writeln!(out, "{pad}) {{").unwrap();
            } else {
                writeln!(out, "{pad}Row(modifier = Modifier.fillMaxWidth()) {{").unwrap();
            }
        } else {
            writeln!(out, "{pad}Row(modifier = Modifier.fillMaxWidth()) {{").unwrap();
        }
        for line in checkbox_lines {
            writeln!(out, "{line}").unwrap();
        }
        writeln!(out, "{inner}{}", text_call(&label, Some(&label_text), None)).unwrap();
        writeln!(out, "{pad}}}").unwrap();
        Ok(out)
    } else {
        let mut out = String::new();
        writeln!(out, "{pad}Checkbox(").unwrap();
        writeln!(out, "{inner}checked = {checked_expr},").unwrap();
        writeln!(
            out,
            "{inner}onCheckedChange = {{ checked -> {on_checked} }},"
        )
        .unwrap();
        if let Some(style) = &style {
            if !style.modifier.is_empty() {
                writeln!(out, "{inner}modifier = Modifier{},", style.modifier).unwrap();
            }
        }
        if let Some(enabled) = enabled_expr.as_deref() {
            writeln!(out, "{inner}enabled = {enabled},").unwrap();
        }
        writeln!(out, "{pad})").unwrap();
        Ok(out)
    }
}

fn emit_host_radio(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);
    let inherited_text = text_ctx.cloned().unwrap_or_default();
    let label_text = match &style {
        Some(s) => cell_text_style(&inherited_text, s),
        None => inherited_text,
    };
    let checked_expr = bool_prop_expr(node, "checked", "false")?;
    let enabled_expr = disabled_prop_enabled_expr(node)?;
    let value_expr = text_prop_expr(node, "value")?.unwrap_or_else(|| "\"\"".to_string());

    let on_select = if let Some(emit_name) = find_emit_ref_prop(node, "onSelect") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|e| e.name == *emit_name)
            .map(|e| e.params.len())
            .unwrap_or(0);
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!("dispatch({component_name}Event.{case}({value_expr}))")
        }
    } else {
        "/* no onSelect bound */".to_string()
    };

    let mut radio_lines = Vec::new();
    radio_lines.push(format!("{inner}RadioButton("));
    radio_lines.push(format!("{inner}    selected = {checked_expr},"));
    radio_lines.push(format!("{inner}    onClick = {{ {on_select} }},"));
    if let Some(enabled) = enabled_expr.as_deref() {
        radio_lines.push(format!("{inner}    enabled = {enabled},"));
    }
    radio_lines.push(format!("{inner})"));

    if let Some(label) = text_prop_expr(node, "label")? {
        let mut out = String::new();
        if let Some(style) = &style {
            if !style.modifier.is_empty() {
                writeln!(out, "{pad}Row(").unwrap();
                writeln!(out, "{inner}modifier = Modifier{},", style.modifier).unwrap();
                writeln!(out, "{pad}) {{").unwrap();
            } else {
                writeln!(out, "{pad}Row(modifier = Modifier.fillMaxWidth()) {{").unwrap();
            }
        } else {
            writeln!(out, "{pad}Row(modifier = Modifier.fillMaxWidth()) {{").unwrap();
        }
        for line in radio_lines {
            writeln!(out, "{line}").unwrap();
        }
        writeln!(out, "{inner}{}", text_call(&label, Some(&label_text), None)).unwrap();
        writeln!(out, "{pad}}}").unwrap();
        Ok(out)
    } else {
        let mut out = String::new();
        writeln!(out, "{pad}RadioButton(").unwrap();
        writeln!(out, "{inner}selected = {checked_expr},").unwrap();
        writeln!(out, "{inner}onClick = {{ {on_select} }},").unwrap();
        if let Some(style) = &style {
            if !style.modifier.is_empty() {
                writeln!(out, "{inner}modifier = Modifier{},", style.modifier).unwrap();
            }
        }
        if let Some(enabled) = enabled_expr.as_deref() {
            writeln!(out, "{inner}enabled = {enabled},").unwrap();
        }
        writeln!(out, "{pad})").unwrap();
        Ok(out)
    }
}

/// Lower `HostSlider` to Compose Material's native adjustable range control.
///
/// Compose models slider values as `Float`, while Mosaic's portable `number`
/// payload is a `Double`. The generated boundary converts in both directions:
/// controlled slot/literal values become floats for the widget, and change or
/// commit callbacks dispatch doubles back to the Rust engine. A positive
/// Mosaic `step` becomes Compose's count of discrete interior stops; `step: 0`
/// deliberately leaves the slider continuous.
fn emit_host_slider(
    node: &LayoutNode,
    depth: usize,
    component_name: &str,
    emits: &[EmitDecl],
    part_styles: &PartStyleMap,
    text_ctx: Option<&TextStyleCtx>,
) -> Result<String, PipelineEmitError> {
    let pad = "    ".repeat(depth);
    let inner = "    ".repeat(depth + 1);
    let chain_indent = (depth + 2) * 4;
    let inherited_color = text_ctx.and_then(|t| t.color.as_deref());
    let style = compose_style_for_node(node, part_styles, None, chain_indent, inherited_color);

    let number_expr = |name: &str, default: &str| -> Result<String, PipelineEmitError> {
        match find_prop_value(node, name) {
            Some(LayoutPropValue::SlotRef(slot)) => {
                let camel = to_camel_case_first_lower(slot);
                validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
                Ok(camel)
            }
            Some(LayoutPropValue::Number(number)) => Ok(number.to_string()),
            Some(LayoutPropValue::Expr(expr)) => Ok(expr.clone()),
            _ => Ok(default.to_string()),
        }
    };

    let value_expr = number_expr("value", "0.0")?;
    let min_expr = number_expr("min", "0.0")?;
    let max_expr = number_expr("max", "100.0")?;

    let on_value_change = if let Some(emit_name) = find_emit_ref_prop(node, "onChange") {
        let case = pascalize(&strip_on_prefix(emit_name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        let arity = emits
            .iter()
            .find(|emit| emit.name == *emit_name)
            .map(|emit| emit.params.len())
            .unwrap_or(0);
        if arity == 0 {
            format!("dispatch({component_name}Event.{case})")
        } else {
            format!("dispatch({component_name}Event.{case}(value))")
        }
    } else {
        String::new()
    };

    let on_commit = find_emit_ref_prop(node, "onCommit")
        .map(|emit_name| {
            let case = pascalize(&strip_on_prefix(emit_name));
            validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
            let arity = emits
                .iter()
                .find(|emit| emit.name == emit_name)
                .map(|emit| emit.params.len())
                .unwrap_or(0);
            if arity == 0 {
                Ok(format!("dispatch({component_name}Event.{case})"))
            } else {
                Ok(format!("dispatch({component_name}Event.{case}(value))"))
            }
        })
        .transpose()?;
    let accessibility_label = text_prop_expr(node, "a11y-label")?;

    let steps = match find_prop_value(node, "step") {
        Some(LayoutPropValue::Number(step)) if *step == 0.0 => "0".to_string(),
        Some(LayoutPropValue::Number(step)) if *step > 0.0 => {
            let range = match (find_prop_value(node, "min"), find_prop_value(node, "max")) {
                (Some(LayoutPropValue::Number(min)), Some(LayoutPropValue::Number(max))) => {
                    max - min
                }
                _ => 100.0,
            };
            ((range / step).round() as i64 - 1).max(0).to_string()
        }
        Some(LayoutPropValue::Number(_)) => "0".to_string(),
        Some(LayoutPropValue::SlotRef(_) | LayoutPropValue::Expr(_)) => {
            let step_expr = number_expr("step", "1.0")?;
            format!(
                "if (({step_expr}).toDouble() > 0.0) (((({max_expr}).toDouble() - ({min_expr}).toDouble()) / ({step_expr}).toDouble()).roundToInt() - 1).coerceAtLeast(0) else 0"
            )
        }
        _ => "99".to_string(),
    };

    let mut out = String::new();
    writeln!(out, "{pad}_mosaicHostSlider(").unwrap();
    writeln!(out, "{inner}value = ({value_expr}).toDouble(),").unwrap();
    if !on_value_change.is_empty() {
        writeln!(
            out,
            "{inner}onValueChange = {{ value -> {on_value_change} }},"
        )
        .unwrap();
    }
    if let Some(on_commit) = on_commit {
        writeln!(
            out,
            "{inner}onValueChangeFinished = {{ value -> {on_commit} }},"
        )
        .unwrap();
    }
    let style_modifier = style
        .as_ref()
        .map(|style| style.modifier.as_str())
        .unwrap_or_default();
    if let Some(label) = accessibility_label {
        writeln!(
            out,
            "{inner}modifier = Modifier{style_modifier}.semantics {{ contentDescription = {label} }},"
        )
        .unwrap();
    } else if !style_modifier.is_empty() {
        writeln!(out, "{inner}modifier = Modifier{style_modifier},").unwrap();
    }
    if let Some(enabled) = disabled_prop_enabled_expr(node)? {
        writeln!(out, "{inner}enabled = {enabled},").unwrap();
    } else {
        writeln!(out, "{inner}enabled = true,").unwrap();
    }
    writeln!(
        out,
        "{inner}valueRange = ({min_expr}).toFloat()..({max_expr}).toFloat(),"
    )
    .unwrap();
    writeln!(out, "{inner}steps = {steps},").unwrap();
    writeln!(out, "{pad})").unwrap();
    Ok(out)
}

