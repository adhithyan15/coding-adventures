#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ArrayBound {
    pub lower: i64,
    pub upper: i64,
}

impl ArrayBound {
    pub fn len(self) -> Result<usize, LoweringError> {
        if self.lower > self.upper {
            return Err(LoweringError::new(format!(
                "array lower bound {} exceeds upper bound {}",
                self.lower, self.upper
            )));
        }
        let len = self.upper - self.lower + 1;
        if len > ARRAY_MAX_ELEMENTS as i64 {
            return Err(LoweringError::new(format!(
                "array dimension length {len} exceeds {ARRAY_MAX_ELEMENTS}"
            )));
        }
        Ok(len as usize)
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ArrayAllocationPlan {
    pub element_type: AlgolType,
    pub dimensions: Vec<ArrayBound>,
    pub lengths: Vec<usize>,
    pub strides: Vec<usize>,
    pub total_elements: usize,
    pub descriptor_bytes: usize,
    pub data_bytes: usize,
    pub allocation_bytes: usize,
    pub bounds_offset: usize,
    pub data_offset: usize,
}

impl ArrayAllocationPlan {
    pub fn new(
        element_type: AlgolType,
        dimensions: Vec<ArrayBound>,
    ) -> Result<Self, LoweringError> {
        if dimensions.is_empty() {
            return Err(LoweringError::new("array must have at least one dimension"));
        }
        if dimensions.len() > ARRAY_MAX_DIMENSIONS {
            return Err(LoweringError::new(format!(
                "array has {} dimensions, exceeding {ARRAY_MAX_DIMENSIONS}",
                dimensions.len()
            )));
        }

        let mut lengths = Vec::with_capacity(dimensions.len());
        let mut total_elements = 1usize;
        for dimension in &dimensions {
            let len = dimension.len()?;
            let allowed_total = ARRAY_MAX_ELEMENTS / len;
            if total_elements > allowed_total {
                return Err(LoweringError::new(format!(
                    "array total element count would exceed {ARRAY_MAX_ELEMENTS}"
                )));
            }
            total_elements *= len;
            lengths.push(len);
        }

        let mut strides = vec![0usize; lengths.len()];
        let mut stride = 1usize;
        for index in (0..lengths.len()).rev() {
            strides[index] = stride;
            stride *= lengths[index];
        }

        let descriptor_bytes =
            ARRAY_DESCRIPTOR_SIZE + dimensions.len() * ARRAY_DIMENSION_ENTRY_SIZE;
        let data_bytes = total_elements * element_type.array_element_width();
        let allocation_bytes = descriptor_bytes + data_bytes;
        let bounds_offset = ARRAY_DESCRIPTOR_SIZE;
        let data_offset = bounds_offset + dimensions.len() * ARRAY_DIMENSION_ENTRY_SIZE;

        Ok(Self {
            element_type,
            dimensions,
            lengths,
            strides,
            total_elements,
            descriptor_bytes,
            data_bytes,
            allocation_bytes,
            bounds_offset,
            data_offset,
        })
    }
}

