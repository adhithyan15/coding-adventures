#!/usr/bin/env python3
"""anemia_edge_ground.py — the write gate for the anemia (hematology) edges (REL-11).

The THIRD recall domain — anemia classification, a board-classic, high-yield area.
Same machinery as the IEM/vitamin gates: it REUSES iem_edge_ground._edge_block (the
pure renderer) and the shared organism_id_ground gate/safe_status helpers. Only the
controlled vocabulary and the edges differ:

    has_mcv(anemia, mcv_class)        iron_deficiency_anemia → microcytic, …
    classic_finding(anemia, finding)  b12_deficiency_anemia → hypersegmented_neutrophils, …

The gate owns anemia-edges.adj: a grounded edge lifts to `trust authoritative` with
its byte-quote + URL; an ungrounded edge stays `trust consensus` + `% [FLAG: …]`
(authored-debt visible). With no grounding JSON it regenerates byte-identically.

Usage:  python3 anemia_edge_ground.py            # regenerate anemia-edges.adj + manifest
        python3 anemia_edge_ground.py --check    # verify the .adj matches the manifest
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ADJ = HERE / "anemia-edges.adj"
GROUNDING = HERE / "anemia-edge-grounding.json"
MANIFEST = HERE / "anemia-edge-manifest.json"
sys.path.insert(0, str(HERE))
import iem_edge_ground as iem  # noqa: E402  (reuse the pure _edge_block renderer)

# The anemia knowledge graph, grouped by anemia for the rendered `% ---` headers.
# (relation, subject, object, AUTHORED fallback source). Board-classic findings.
GROUPS: list[tuple[str, list[tuple[str, str, str, str]]]] = [
    ("Iron-deficiency anemia", [
        ("has_mcv", "iron_deficiency_anemia", "microcytic",
         "Iron-deficiency anemia is a microcytic anemia (low mean corpuscular volume)."),
        ("classic_finding", "iron_deficiency_anemia", "koilonychia",
         "Iron-deficiency anemia can cause koilonychia (spoon-shaped nails)."),
    ]),
    ("Thalassemia", [
        ("has_mcv", "thalassemia", "microcytic",
         "Thalassemia is a microcytic anemia."),
        ("classic_finding", "thalassemia", "target_cells",
         "Thalassemia classically shows target cells on the peripheral blood smear."),
    ]),
    ("Sideroblastic anemia", [
        ("has_mcv", "sideroblastic_anemia", "microcytic",
         "Sideroblastic anemia is typically a microcytic anemia."),
        ("classic_finding", "sideroblastic_anemia", "ringed_sideroblasts",
         "Sideroblastic anemia is defined by ringed sideroblasts in the bone marrow."),
    ]),
    ("Vitamin B12 deficiency anemia", [
        ("has_mcv", "b12_deficiency_anemia", "macrocytic",
         "Vitamin B12 deficiency causes a macrocytic (megaloblastic) anemia."),
        ("classic_finding", "b12_deficiency_anemia", "hypersegmented_neutrophils",
         "Megaloblastic anemia (B12 or folate deficiency) shows hypersegmented neutrophils."),
    ]),
    ("Hereditary spherocytosis", [
        ("has_mcv", "hereditary_spherocytosis", "normocytic",
         "Hereditary spherocytosis is a normocytic hemolytic anemia."),
        ("classic_finding", "hereditary_spherocytosis", "spherocytes",
         "Hereditary spherocytosis shows spherocytes on the peripheral smear."),
    ]),
    ("G6PD deficiency", [
        ("has_mcv", "g6pd_deficiency", "normocytic",
         "G6PD deficiency causes an episodic normocytic hemolytic anemia."),
        ("classic_finding", "g6pd_deficiency", "bite_cells",
         "G6PD deficiency shows bite cells and Heinz bodies on the peripheral smear."),
    ]),
]

HEADER = """\
% ============================================================================
% anemia-edges — the anemia (hematology) knowledge-graph (MYCIN-2026 REL-11).
% ============================================================================
% A THIRD recall domain — anemia classification. "What is the MCV category of
% iron-deficiency anemia?" becomes the binding query
%   ? has_mcv(iron_deficiency_anemia, $Class).
%
% GENERATED by recall/anemia_edge_ground.py from recall/anemia-edge-grounding.json
% (the spider's byte-provenanced output). Do not hand-edit — re-ground and regenerate.
% A grounded edge carries its byte-quote as `source` + `trust authoritative` (+ URL as
% `locator`); an ungrounded edge stays `trust consensus`, tagged `% [FLAG: <status>]`,
% so the authored-debt is visible and drives to zero. (See feedback_nothing_human_authored.)
% ============================================================================

dictionary anemia_vocab {
    define anemia    : entity   surface "anemia"
    define mcv_class : entity   surface "MCV category", "red cell size"
    define finding   : entity   surface "smear finding", "classic finding"

    define has_mcv         : relation from anemia to mcv_class
    define classic_finding : relation from anemia to finding
}
"""


def build(check: bool = False) -> int:
    recs = {}
    if GROUNDING.exists():
        recs = {r["id"]: r for r in json.loads(GROUNDING.read_text()).get("records", [])}

    body = [HEADER, "rulebook anemia_facts {", "    use anemia_vocab"]
    clauses: dict[str, dict] = {}
    for label, edges in GROUPS:
        body.append("")
        body.append(f"    % --- {label} " + "-" * max(0, 64 - len(label)))
        for rel, subj, obj, authored in edges:
            eid = f"{rel}__{subj}"
            block, entry = iem._edge_block(rel, subj, obj, authored, recs.get(eid))
            body.append(block)
            clauses[eid] = entry
    body.append("}")
    adj_text = "\n".join(body) + "\n"

    accepted = sum(1 for c in clauses.values() if c["verdict"] == "ACCEPT")
    flagged = sum(1 for c in clauses.values() if c["verdict"] != "ACCEPT")
    manifest = {"kind": "anemia-edge", "clauses": clauses,
                "hash": hashlib.sha256(json.dumps(clauses, sort_keys=True).encode()).hexdigest()[:16]}

    if check:
        ok = ADJ.exists() and ADJ.read_text() == adj_text
        mok = MANIFEST.exists() and json.loads(MANIFEST.read_text()).get("hash") == manifest["hash"]
        print("anemia_edge_ground --check:", "up to date" if (ok and mok) else "OUT OF DATE")
        return 0 if (ok and mok) else 1

    ADJ.write_text(adj_text)
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"anemia_edge_ground: regenerated anemia-edges.adj + anemia-edge-manifest.json "
          f"({accepted} ACCEPT grounded, {flagged} consensus/flagged authored-debt). "
          f"Run grounding/ground_sources.py to rebuild the provenance ledger.")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
