/// Strip a leading `on` (case-insensitive) and return the rest of the name.
///
/// Per UI24 §5: the leading `on` prefix on emit names is conventional in
/// mosmodel (mirroring the React idiom `onClick`) and would be redundant in a
/// union variant whose discriminator is already named `type`.
fn strip_on_prefix(s: &str) -> String {
    let bytes = s.as_bytes();
    if bytes.len() >= 2
        && (bytes[0] == b'o' || bytes[0] == b'O')
        && (bytes[1] == b'n' || bytes[1] == b'N')
    {
        s[2..].to_string()
    } else {
        s.to_string()
    }
}

/// Convert a kebab-case identifier to camelCase with the first character
/// lowered. Repeated calls are idempotent on already-camelCase input.
///
/// Examples (truth table):
///
/// | Input          | Output      |
/// |----------------|-------------|
/// | `avatar-url`   | `avatarUrl` |
/// | `display-name` | `displayName` |
/// | `Navigate`     | `navigate`  |
/// | `formula`      | `formula`   |
/// | `start-row`    | `startRow`  |
fn to_camel_case_first_lower(s: &str) -> String {
    let mut out = String::new();
    let mut cap_next = false;
    let mut first = true;
    for ch in s.chars() {
        if ch == '-' {
            cap_next = true;
            continue;
        }
        if first {
            out.push(ch.to_ascii_lowercase());
            first = false;
        } else if cap_next {
            out.push(ch.to_ascii_uppercase());
            cap_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// Validate that a slot or destructured-field name is a safe JavaScript
/// identifier. Returns `Err(name)` on failure so the caller can wrap it in
/// the appropriate error variant.
fn validate_slot_or_field_name(s: &str) -> Result<(), String> {
    if is_safe_js_identifier(s) {
        Ok(())
    } else {
        Err(s.to_string())
    }
}

/// Validate that an emit's lowered `type` literal is safe and not one of the
/// reserved React prop names called out in UI24 §5.1.
fn validate_emit_name(s: &str) -> Result<(), PipelineEmitError> {
    if !is_safe_js_identifier(s) {
        return Err(PipelineEmitError::UnsafeEmitName(s.to_string()));
    }
    match s {
        "dispatch" | "children" | "key" => Err(PipelineEmitError::ReservedEmitName(s.to_string())),
        _ => Ok(()),
    }
}

/// `true` iff `s` is `[_a-zA-Z][_a-zA-Z0-9]*`. Mirrors the legacy emitter's
/// helper of the same name (lib.rs §10).
fn is_safe_js_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

