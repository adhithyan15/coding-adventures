#[test]
fn test_evaluator_limits_and_diagnostics() {
    let src = "warrant limits_test\n  model loop_fn(x: Int) -> Int = loop_fn(x + 1)\n  op dummy() -> Bool\n  assume platform:\n    none\n  assume environment:\n    none\n  bound dummy:\n    steps <= 1\n  example ex:\n    dummy() == true\n";
    with_parsed(src, |file| {
        // Exceed recursion depth
        let mut deep_evaluator = Evaluator::new(
            file,
            CodegenLimits {
                max_depth: 5,
                max_work: 10_000,
                max_value_bytes: 65_536,
            },
        );
        let call = Expression::Reference {
            name: QualifiedName {
                segments: vec!["loop_fn"],
                span: (0, 0),
            },
            widths: vec![],
            args: Some(vec![Expression::Literal {
                lit: Literal::Int(0),
                span: (0, 0),
            }]),
            span: (0, 0),
        };
        let err = deep_evaluator.eval(&call, &HashMap::new()).unwrap_err();
        assert_eq!(err.code, DiagnosticCode::W0703);
        assert_eq!(err.kind, CodegenErrorKind::RecursionDepthExceeded);

        // Exceed work quota
        let mut work_evaluator = Evaluator::new(
            file,
            CodegenLimits {
                max_depth: 100,
                max_work: 4,
                max_value_bytes: 65_536,
            },
        );
        let err = work_evaluator.eval(&call, &HashMap::new()).unwrap_err();
        assert_eq!(err.code, DiagnosticCode::W0703);
        assert_eq!(err.kind, CodegenErrorKind::WorkBudgetExceeded);
    });
}

