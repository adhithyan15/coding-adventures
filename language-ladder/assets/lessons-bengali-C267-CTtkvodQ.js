<!-- hl-knowledge: introduces=[BN-LEX-C268-KARON-01]; assesses=[BN-LEX-C169-JINIS169-04, BN-LEX-C81-PLACE81-03, BN-LEX-C255-JINIS255-02, BN-GRAMMAR-C266-ONGOING-NOW-01, BN-GRAMMAR-C265-FUTURE-PERSON-01] -->

