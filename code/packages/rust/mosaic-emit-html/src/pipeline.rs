/// Convert kebab-case to camelCase (first letter lowered). Used to
/// produce the slot-reference identifier inside `{{...}}` placeholders.
/// Matches the React backend's `to_camel_case_first_lower` so the same
/// host code can substitute placeholders against both outputs.
fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut cap_next = false;
    let mut first = true;
    for ch in s.chars() {
        if ch == '-' {
            cap_next = true;
            continue;
        }
        if first {
            out.push(ch.to_ascii_lowercase());
            first = false;
        } else if cap_next {
            out.push(ch.to_ascii_uppercase());
            cap_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// Convert a camelCase or kebab-case name to canonical kebab-case CSS
/// property syntax. mosstyle generally emits kebab-case already, but
/// hand-authored grammars sometimes round-trip a camelCase value (e.g.
/// `backgroundColor`); normalising here makes the output stable.
///
/// Truth table:
///
/// | Input             | Output             |
/// |-------------------|--------------------|
/// | `background`      | `background`       |
/// | `background-color`| `background-color` |
/// | `backgroundColor` | `background-color` |
/// | `fontSize`        | `font-size`        |
fn camel_to_kebab(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for (i, ch) in s.chars().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            out.push('-');
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch.to_ascii_lowercase());
        }
    }
    out
}

// =====================================================================
// HTML escaping
// =====================================================================

/// Escape a string for safe inclusion as HTML text content.
///
/// We escape the standard five: `&`, `<`, `>`, `"`, `'`. The single-quote
/// escape uses the numeric `&#39;` form (rather than `&apos;`) because
/// the latter is not a defined entity in pre-XHTML HTML4.
fn escape_html_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
    out
}

/// Escape a string for safe inclusion in a double-quoted HTML attribute.
///
/// Inside `attr="..."` the only character that must be escaped is `"`
/// (which would close the attribute) and `&` (which would start an entity
/// reference). We also escape `<` for defence-in-depth even though
/// the spec doesn't strictly require it inside attribute values.
fn escape_html_attr(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '"' => out.push_str("&quot;"),
            '<' => out.push_str("&lt;"),
            other => out.push(other),
        }
    }
    out
}

