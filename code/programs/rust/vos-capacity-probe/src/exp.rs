/// The experiments of section 9.7, in report order.
///
/// This is also the plan order the shard rule walks (section 9.2): B5 follows B4 and D5 follows
/// D4, each a contiguous block of 24 knobs outside B3's run (VOS-D135).
pub const EXPERIMENTS: [&str; 16] = [
    "A1", "A2", "B1", "B2", "B3", "B4", "B5", "C1", "C2", "D1", "D2", "D3", "D4", "D5", "E1", "E2",
];

/// Which tier a run covers.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tier {
    /// The smallest knob of every experiment.
    Quick,
    /// Every knob.
    Full,
}

/// One row to run.
#[derive(Clone, Debug, PartialEq)]
pub struct RowSpec {
    /// Experiment id.
    pub experiment: String,
    /// The sweep point.
    pub knob: Knob,
    /// The mode.
    pub mode: String,
    /// The seed (1-based).
    pub seed: u64,
    /// Seeds per knob.
    pub seeds: u32,
    /// `quick` or `full`.
    pub tier: String,
}

/// A planned knob: the point, its mode and whether it belongs to the quick tier.
pub struct Planned {
    /// The sweep point.
    pub knob: Knob,
    /// The mode.
    pub mode: &'static str,
    /// In the quick tier.
    pub quick: bool,
}

const LENGTHS: [i64; 6] = [25, 50, 100, 200, 500, 1000];
const DIVERGENCES: [f64; 3] = [0.05, 0.25, 1.0];
const CUTS: [&str; 3] = ["every1", "every8", "every32"];
/// Additional B3 cut spacings of VOS30 section 8.6.2 (VOS-028c3a; registered in `knobs("B3")`
/// by VOS-028c3c commit A, after the `every1`/`every8`/`every32` knobs and contiguous with them).
pub const C3_CUTS: [&str; 2] = ["every2", "every4"];
const TS: [i64; 5] = [4, 8, 16, 64, 256];
const KS: [i64; 5] = [1, 2, 4, 8, 16];
/// Table sizes of experiment D5 (VOS30 section 8.6.3).
pub const D5_TS: [i64; 4] = [4, 16, 64, 256];
/// Access counts of experiment D5 (VOS30 section 8.6.3).
pub const D5_KS: [i64; 3] = [1, 4, 16];
/// Split modes of experiment D5 (VOS30 section 8.6.3).
pub const D5_SPLITS: [&str; 2] = ["index", "none"];

/// The B3 `every2` and `every4` knobs of VOS30 section 8.6.3 (360 rows at 5 seeds, none quick).
pub fn b3_c3_knobs() -> Vec<Planned> {
    let mut v = Vec::new();
    for len in LENGTHS {
        for d in DIVERGENCES {
            for c in C3_CUTS {
                for m in ["certified", "incremental"] {
                    v.push(Planned {
                        knob: Knob::of(&[
                            ("length", Kv::I(len)),
                            ("divergence", Kv::F(d)),
                            ("cut", Kv::S(c.to_string())),
                        ]),
                        mode: m,
                        quick: false,
                    });
                }
            }
        }
    }
    v
}

/// Lengths of experiment B5 (VOS30 section 8.6.3).
pub const B5_LENGTHS: [i64; 3] = [25, 200, 1000];
/// Divergences of experiment B5.
pub const B5_DIVERGENCES: [f64; 2] = [0.25, 1.0];
/// The `fuse` values of experiment B5: adds per run, 1 being B2.
pub const B5_FUSES: [i64; 4] = [1, 2, 4, 8];

/// The 24 knobs of experiment B5 (VOS30 section 8.6.3; 120 rows at 5 seeds), registered in
/// [`knobs`] by VOS-028c3c commit A.  Plan order: length, then divergence, then fuse.  The quick
/// tier is the smallest knob, length 25 at `fuse = 1` (both divergences; VOS-D118).
pub fn b5_knobs() -> Vec<Planned> {
    let mut v = Vec::new();
    for len in B5_LENGTHS {
        for d in B5_DIVERGENCES {
            for fuse in B5_FUSES {
                v.push(Planned {
                    knob: Knob::of(&[
                        ("length", Kv::I(len)),
                        ("divergence", Kv::F(d)),
                        ("fuse", Kv::I(fuse)),
                    ]),
                    mode: "certified",
                    // The smallest knob, as for every experiment: the quick tier fails on an
                    // `unknown` row, and fuse 4 and 8 are not expected to finish even at 25
                    // instructions (VOS-D118), so they are full-tier only.
                    quick: len == 25 && fuse == 1,
                });
            }
        }
    }
    v
}

/// The 24 knobs of experiment D5 (VOS30 section 8.6.3; 120 rows at 5 seeds, quick at `T = 4, k = 1`).
pub fn d5_knobs() -> Vec<Planned> {
    let mut v = Vec::new();
    for t in D5_TS {
        for k in D5_KS {
            for split in D5_SPLITS {
                v.push(Planned {
                    knob: Knob::of(&[
                        ("t", Kv::I(t)),
                        ("k", Kv::I(k)),
                        ("split", Kv::S(split.to_string())),
                    ]),
                    mode: "certified",
                    quick: t == 4 && k == 1,
                });
            }
        }
    }
    v
}

/// The knobs of one experiment.
pub fn knobs(exp: &str) -> Vec<Planned> {
    let p = |knob: Knob, mode: &'static str, quick: bool| Planned { knob, mode, quick };
    let mut v = Vec::new();
    match exp {
        "A1" | "A2" => {
            for (i, n) in [8, 16, 32, 64].iter().enumerate() {
                v.push(p(Knob::of(&[("n", Kv::I(*n))]), "monolithic", i == 0));
            }
        }
        "B1" => {
            for (i, len) in [200, 500, 1000].iter().enumerate() {
                v.push(p(
                    Knob::of(&[("length", Kv::I(*len)), ("divergence", Kv::F(0.0))]),
                    "monolithic",
                    i == 0,
                ));
            }
        }
        "B2" | "B3" => {
            let modes: &[&'static str] = if exp == "B3" {
                &["certified", "incremental"]
            } else {
                &["monolithic"]
            };
            for (li, len) in LENGTHS.iter().enumerate() {
                for (di, d) in DIVERGENCES.iter().enumerate() {
                    if exp == "B2" {
                        v.push(p(
                            Knob::of(&[("length", Kv::I(*len)), ("divergence", Kv::F(*d))]),
                            "monolithic",
                            li == 0 && di == 0,
                        ));
                    } else {
                        for (ci, c) in CUTS.iter().enumerate() {
                            for m in modes {
                                v.push(p(
                                    Knob::of(&[
                                        ("length", Kv::I(*len)),
                                        ("divergence", Kv::F(*d)),
                                        ("cut", Kv::S(c.to_string())),
                                    ]),
                                    m,
                                    li == 0 && di == 0 && ci == 0,
                                ));
                            }
                        }
                    }
                }
            }
            // The 72 `every2`/`every4` knobs (VOS30 8.6.3), after the 108 above and inside this
            // arm: one contiguous B3 run, so no shard holds more than three B3 knobs (VOS-D135).
            if exp == "B3" {
                v.extend(b3_c3_knobs());
            }
        }
        "B5" => v.extend(b5_knobs()),
        "D5" => v.extend(d5_knobs()),
        "B4" => {
            // n = 2 is `a + b` against `a + b`: one adder, hash-consed into itself (a collapse by
            // construction, not a re-association), so the sweep starts at three terms.
            for n in 3..=7 {
                v.push(p(
                    Knob::of(&[
                        ("shape", Kv::S("assoc".into())),
                        ("n", Kv::I(n)),
                        ("w", Kv::I(32)),
                    ]),
                    "monolithic",
                    n == 3,
                ));
            }
            for shape in ["mul5", "mul12"] {
                for w in [8, 16, 32] {
                    v.push(p(
                        Knob::of(&[("shape", Kv::S(shape.into())), ("w", Kv::I(w))]),
                        "monolithic",
                        false,
                    ));
                }
            }
        }
        "C1" => {
            for (i, n) in [8, 16, 32, 64].iter().enumerate() {
                v.push(p(
                    Knob::of(&[("base", Kv::S("a1".into())), ("n", Kv::I(*n))]),
                    "monolithic",
                    i == 0,
                ));
            }
            for len in LENGTHS {
                for d in DIVERGENCES {
                    v.push(p(
                        Knob::of(&[
                            ("base", Kv::S("b".into())),
                            ("length", Kv::I(len)),
                            ("divergence", Kv::F(d)),
                        ]),
                        "monolithic",
                        false,
                    ));
                }
            }
        }
        "C2" => {
            for (i, t) in [8, 16, 64].iter().enumerate() {
                v.push(p(Knob::of(&[("t", Kv::I(*t))]), "monolithic", i == 0));
            }
        }
        "D1" | "D2" | "D3" | "D4" => {
            for t in TS {
                for k in KS {
                    let quick = t == 4 && k == 1;
                    match exp {
                        "D1" | "D2" => v.push(p(
                            Knob::of(&[("t", Kv::I(t)), ("k", Kv::I(k))]),
                            "monolithic",
                            quick,
                        )),
                        "D3" => v.push(p(
                            Knob::of(&[("t", Kv::I(t)), ("k", Kv::I(k))]),
                            "split",
                            quick,
                        )),
                        _ => {
                            v.push(p(
                                Knob::of(&[("t", Kv::I(t)), ("k", Kv::I(k))]),
                                "certified",
                                quick,
                            ));
                            v.push(p(
                                Knob::of(&[("t", Kv::I(t)), ("k", Kv::I(k))]),
                                "incremental",
                                quick,
                            ));
                        }
                    }
                }
            }
        }
        "E1" => {
            for (claim, fixture, binders, quick) in enumx::E1_KNOBS {
                v.push(p(
                    Knob::of(&[
                        ("claim", Kv::S(claim.to_string())),
                        ("fixture", Kv::S(fixture.to_string())),
                        ("binders", Kv::I(*binders)),
                    ]),
                    "enum",
                    *quick,
                ));
            }
        }
        "E2" => {
            for w in [1, 8, 64, 256, 4096] {
                for k in [1, 2, 3, 4] {
                    v.push(p(
                        Knob::of(&[("width", Kv::I(w)), ("binders", Kv::I(k))]),
                        "enum",
                        w == 1 && k == 1,
                    ));
                }
            }
        }
        _ => {}
    }
    v
}

/// Every row of a tier (all seeds), optionally restricted to some experiments.
pub fn plan(tier: Tier, only: &[String], seeds: u32) -> Vec<RowSpec> {
    let mut out = Vec::new();
    for exp in EXPERIMENTS {
        if !only.is_empty() && !only.iter().any(|o| o == exp) {
            continue;
        }
        for k in knobs(exp) {
            if tier == Tier::Quick && !k.quick {
                continue;
            }
            for seed in 1..=seeds as u64 {
                out.push(RowSpec {
                    experiment: exp.to_string(),
                    knob: k.knob.clone(),
                    mode: k.mode.to_string(),
                    seed,
                    seeds,
                    tier: if k.quick { "quick" } else { "full" }.to_string(),
                });
            }
        }
    }
    out
}

