//! # Three-file pipeline entry point for the HTML backend.
//!
//! This module is the static-HTML consumer of the three-language pipeline
//! output produced by [`mosmodel-compiler`], [`moslayout-compiler`], and
//! [`mosstyle-compiler`]. It is the HTML-backend twin of
//! [`mosaic_emit_react::pipeline::from_pipeline`] and sits alongside the
//! legacy single-file [`crate::HtmlRenderer`] (driven by [`mosaic_vm::MosaicVM`]);
//! the two code paths share no state.
//!
//! ## What this module produces
//!
//! An HTML *fragment* — not a full `<!DOCTYPE html>` document. The host is
//! expected to wrap the output in whatever shell it likes (a single-page
//! framework's view, a server-side template, a Markdown-driven docsite, …).
//! Producing a fragment instead of a full document keeps the output composable.
//!
//! Example output for a component `Button` declared with a single slot
//! `label : text` and a `Text [ label-part ] { content: slot: label }` layout:
//!
//! ```html
//! <!-- Auto-generated by mosaic-emit-html (pipeline path). Do not edit. -->
//! <div data-mosaic-component="Button">
//!   <span>{{label}}</span>
//! </div>
//! ```
//!
//! Three things to notice:
//!
//! 1. The **slot placeholder syntax** is Handlebars-style `{{slotName}}`. The
//!    host either pre-substitutes those tokens before serving the page (any
//!    server-side template engine — Handlebars, Mustache, Liquid, Jinja with
//!    minor config, …) or runs a downstream JS hydrator (out of scope for
//!    this PR).
//! 2. **Styles are inlined as `style="..."` attributes** on the matching
//!    elements. The alternative (emit a `<style>` block with
//!    `[data-part="..."]` selectors) was rejected here because inline styles
//!    don't require any extra wrapping element and don't pollute the global
//!    CSS namespace when the fragment is dropped into a larger page.
//! 3. **Emits are silently dropped.** Static HTML has no analog for the Flux
//!    `dispatch` callback the React backend wires up — a future JS-hydrator
//!    PR could change that, but for now an `EmitRef` prop on a layout node
//!    is *not* an error; it simply produces no attribute on the element.
//!    A `<!-- emit dropped -->` comment is emitted at the point of the drop
//!    so the generated HTML is self-documenting.
//!
//! ## Primitive coverage
//!
//! The original eight (UI24) plus the UI29 kernel additions (`Stack`,
//! `HostInput`, `HostButton`, `HostScroll`, `HostTable` + sub-tags, and
//! the meta-primitives `If` / `Else` / `For`):
//!
//! | mosmodel tag           | HTML element                                                    |
//! |------------------------|-----------------------------------------------------------------|
//! | `Box`                  | `<div>`                                                         |
//! | `Row`                  | `<div style="display: flex; flex-direction: row">`              |
//! | `Column`               | `<div style="display: flex; flex-direction: column">`           |
//! | `Text`                 | `<span>` (with `{{slot}}` placeholder when content is a slot)   |
//! | `Image`                | `<img src="...">` (self-closing — HTML5-style void element)     |
//! | `Spacer`               | `<div style="flex: 1">`                                         |
//! | `Divider`              | `<hr>` (void element)                                           |
//! | `Icon`                 | `<span class="icon">`                                           |
//! | `Stack`                | `<div style="position: relative">` (children layered)           |
//! | `HostInput`            | `<input type="text" value="{{value}}">` (UI29 §2.1)             |
//! | `HostButton`           | `<button>{{label}}</button>` (UI29 §2.1)                        |
//! | `HostScroll`           | `<div style="overflow: auto">` (UI29 §2.1)                      |
//! | `HostTable`            | `<table>` semantic data table (UI29 §2.1)                       |
//! | `HostTableColGroup`    | `<colgroup>` (sub-tag of `HostTable`)                           |
//! | `HostTableHead`        | `<thead>` with `<tr>`/`<th>` (sub-tag of `HostTable`)           |
//! | `HostTableBody`        | `<tbody>` with `<tr>`/`<td>` (sub-tag of `HostTable`)           |
//! | `HostTableFoot`        | `<tfoot>` with `<tr>`/`<td>` (sub-tag of `HostTable`)           |
//! | `HostDialog`           | `<dialog>` (UI29-1) — native browser modal/focus-trap/top-layer |
//! | `If` / `Else`          | `<!-- mosaic-if when="…" -->` comment-bracketed branches        |
//! | `For`                  | `<!-- mosaic-for each="…" as="…" index="…" -->` comment wrapper |
//!
//! ## The `If` / `For` static-HTML compromise
//!
//! HTML is static — there is no rendering pass to evaluate a conditional
//! or expand a loop at view time. The HTML backend handles this by lowering
//! `If` and `For` to *machine-readable HTML comments* with `mosaic-if` /
//! `mosaic-for` markers carrying the original `when:` / `each:` / `as:` /
//! `index:` source text. A downstream template engine (Handlebars,
//! Mustache, Jinja with minor config, the host's own renderer, …) walks
//! the fragment and resolves them at render time. For literal
//! `when: true` / `when: false`, the emitter shortcuts to just the
//! appropriate branch with no markers — pure dead-code elimination at
//! compile time.
//!
//! A future "Mosaic HTML runtime" PR could replace the comment markers
//! with a small JS runtime that expands them client-side; that's out of
//! scope for this PR. The marker format is deliberately neutral about
//! what resolves it.
//!
//! ## Out of scope
//!
//! `Grid` (UI28) and `Cell` are still deferred. An unrecognised primitive
//! returns [`PipelineEmitError::UnknownPrimitive`] rather than producing
//! wrong HTML silently.

use std::cell::Cell;
use std::collections::HashMap;
use std::fmt::Write as _;

use mosmodel_compiler::MosmodelComponent;
use moslayout_compiler::{LayoutDef, LayoutNode, LayoutPropValue};
use mosstyle_compiler::{StyleDef, StyleProp};

// =====================================================================
// HostDialog id counter (UI29-1 §3.5)
// =====================================================================
//
// HostDialog needs a deterministic per-call id so the inline modal-init
// / dismiss-intercept scripts can target the right `<dialog>` element by
// `id`. The walker is recursion-friendly stateless code; we lift the
// counter into a thread-local `Cell` that's reset at the top of every
// `from_pipeline` call. The reset means two consecutive emits produce
// byte-identical output for the same input — important for snapshot
// tests and for the build tool's cache keys.
//
// Why thread-local instead of plumbing `&mut counter`: every existing
// walker function (`emit_html_tree`, `emit_children`, `emit_table_node`,
// etc.) would need a new parameter, and the only state being passed is
// a single `usize`. The thread-local keeps the rest of the file
// undisturbed and the counter is invisible to callers.

thread_local! {
    static DIALOG_ID_COUNTER: Cell<usize> = const { Cell::new(0) };
}

fn next_dialog_id() -> usize {
    DIALOG_ID_COUNTER.with(|c| {
        let n = c.get();
        c.set(n + 1);
        n
    })
}

fn reset_dialog_id_counter() {
    DIALOG_ID_COUNTER.with(|c| c.set(0));
}

