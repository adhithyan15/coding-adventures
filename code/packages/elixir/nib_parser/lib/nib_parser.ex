defmodule CodingAdventures.NibParser do
  @moduledoc """
  Nib parser built on the shared grammar-driven parser engine.
  """

  alias CodingAdventures.GrammarTools.ParserGrammar
  alias CodingAdventures.NibLexer
  alias CodingAdventures.NibParser.Grammar
  alias CodingAdventures.Parser.{GrammarParser, ASTNode}

  @spec parse_nib(String.t()) :: {:ok, ASTNode.t()} | {:error, String.t()}
  def parse_nib(source) do
    grammar = get_grammar()

    case NibLexer.tokenize_nib(source) do
      {:ok, tokens} -> GrammarParser.parse(tokens, grammar)
      {:error, msg} -> {:error, msg}
    end
  end

  @doc """
  Return the pre-compiled Nib `ParserGrammar`.

  The grammar is embedded as pre-compiled Elixir data in
  `CodingAdventures.NibParser.Grammar` (generated by `grammar-tools
  compile-grammar` from `code/grammars/nib/nib.grammar`) — this module no
  longer reads the `.grammar` file from disk at runtime.
  """
  @spec create_nib_parser() :: {:ok, ParserGrammar.t()}
  def create_nib_parser do
    {:ok, Grammar.parser_grammar()}
  end

  defp get_grammar do
    case :persistent_term.get({__MODULE__, :grammar}, nil) do
      nil ->
        {:ok, grammar} = create_nib_parser()
        :persistent_term.put({__MODULE__, :grammar}, grammar)
        grammar

      grammar ->
        grammar
    end
  end
end
