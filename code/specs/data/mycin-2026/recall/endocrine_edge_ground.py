#!/usr/bin/env python3
"""endocrine_edge_ground.py — the write gate for the endocrine edges (REL-12).

The FOURTH recall domain — endocrine hormones. Same machinery as the IEM / vitamin /
anemia gates: it REUSES iem_edge_ground._edge_block (the pure renderer) and the shared
organism_id_ground helpers. Only the vocabulary and edges differ:

    secreted_by(hormone, gland)            insulin → pancreatic_beta_cells, …
    deficiency_syndrome(hormone, syndrome) cortisol → addison_disease, …

Owns endocrine-edges.adj. A grounded edge lifts to `trust authoritative` with its
byte-quote + URL; an ungrounded edge stays `trust consensus` + `% [FLAG: …]`. With no
grounding JSON it regenerates byte-identically.

Usage:  python3 endocrine_edge_ground.py            # regenerate endocrine-edges.adj + manifest
        python3 endocrine_edge_ground.py --check    # verify the .adj matches the manifest
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ADJ = HERE / "endocrine-edges.adj"
GROUNDING = HERE / "endocrine-edge-grounding.json"
MANIFEST = HERE / "endocrine-edge-manifest.json"
sys.path.insert(0, str(HERE))
import iem_edge_ground as iem  # noqa: E402  (reuse the pure _edge_block renderer)

# The endocrine knowledge graph, grouped by hormone for the rendered `% ---` headers.
# (relation, subject, object, AUTHORED fallback source). Board-classic endocrinology.
GROUPS: list[tuple[str, list[tuple[str, str, str, str]]]] = [
    ("Insulin", [
        ("secreted_by", "insulin", "pancreatic_beta_cells",
         "Insulin is secreted by the beta cells of the pancreatic islets of Langerhans."),
        ("deficiency_syndrome", "insulin", "diabetes_mellitus",
         "Insulin deficiency (or resistance) causes diabetes mellitus."),
    ]),
    ("Cortisol", [
        ("secreted_by", "cortisol", "adrenal_cortex",
         "Cortisol is secreted by the adrenal cortex (zona fasciculata)."),
        ("deficiency_syndrome", "cortisol", "addison_disease",
         "Cortisol deficiency (primary adrenal insufficiency) causes Addison disease."),
    ]),
    ("Thyroxine (T4)", [
        ("secreted_by", "thyroxine", "thyroid_gland",
         "Thyroxine (T4) is secreted by the thyroid gland."),
        ("deficiency_syndrome", "thyroxine", "hypothyroidism",
         "Thyroid hormone deficiency causes hypothyroidism."),
    ]),
    ("Antidiuretic hormone (ADH)", [
        ("secreted_by", "adh", "posterior_pituitary",
         "Antidiuretic hormone (ADH/vasopressin) is released from the posterior pituitary."),
        ("deficiency_syndrome", "adh", "central_diabetes_insipidus",
         "ADH deficiency causes central diabetes insipidus."),
    ]),
    ("Parathyroid hormone (PTH)", [
        ("secreted_by", "pth", "parathyroid_gland",
         "Parathyroid hormone is secreted by the parathyroid glands."),
        ("deficiency_syndrome", "pth", "hypoparathyroidism",
         "PTH deficiency causes hypoparathyroidism (hypocalcemia)."),
    ]),
    ("Growth hormone (GH)", [
        ("secreted_by", "growth_hormone", "anterior_pituitary",
         "Growth hormone is secreted by the anterior pituitary (somatotrophs)."),
        ("deficiency_syndrome", "growth_hormone", "pituitary_dwarfism",
         "Childhood growth hormone deficiency causes pituitary dwarfism (short stature)."),
    ]),
]

HEADER = """\
% ============================================================================
% endocrine-edges — the endocrine (hormone) knowledge-graph (MYCIN-2026 REL-12).
% ============================================================================
% A FOURTH recall domain — endocrine hormones. "Which gland secretes cortisol?"
% becomes the binding query  ? secreted_by(cortisol, $Gland).
%
% GENERATED by recall/endocrine_edge_ground.py from recall/endocrine-edge-grounding.json
% (the spider's byte-provenanced output). Do not hand-edit — re-ground and regenerate.
% A grounded edge carries its byte-quote as `source` + `trust authoritative` (+ URL as
% `locator`); an ungrounded edge stays `trust consensus`, tagged `% [FLAG: <status>]`,
% so the authored-debt is visible and drives to zero. (See feedback_nothing_human_authored.)
% ============================================================================

dictionary endocrine_vocab {
    define hormone  : entity   surface "hormone"
    define gland    : entity   surface "endocrine gland", "secreting tissue"
    define syndrome : entity   surface "deficiency syndrome", "endocrine disorder"

    define secreted_by         : relation from hormone to gland
    define deficiency_syndrome : relation from hormone to syndrome
}
"""


def build(check: bool = False) -> int:
    recs = {}
    if GROUNDING.exists():
        recs = {r["id"]: r for r in json.loads(GROUNDING.read_text()).get("records", [])}

    body = [HEADER, "rulebook endocrine_facts {", "    use endocrine_vocab"]
    clauses: dict[str, dict] = {}
    for label, edges in GROUPS:
        body.append("")
        body.append(f"    % --- {label} " + "-" * max(0, 64 - len(label)))
        for rel, subj, obj, authored in edges:
            eid = f"{rel}__{subj}"
            block, entry = iem._edge_block(rel, subj, obj, authored, recs.get(eid))
            body.append(block)
            clauses[eid] = entry
    body.append("}")
    adj_text = "\n".join(body) + "\n"

    accepted = sum(1 for c in clauses.values() if c["verdict"] == "ACCEPT")
    flagged = sum(1 for c in clauses.values() if c["verdict"] != "ACCEPT")
    manifest = {"kind": "endocrine-edge", "clauses": clauses,
                "hash": hashlib.sha256(json.dumps(clauses, sort_keys=True).encode()).hexdigest()[:16]}

    if check:
        ok = ADJ.exists() and ADJ.read_text() == adj_text
        mok = MANIFEST.exists() and json.loads(MANIFEST.read_text()).get("hash") == manifest["hash"]
        print("endocrine_edge_ground --check:", "up to date" if (ok and mok) else "OUT OF DATE")
        return 0 if (ok and mok) else 1

    ADJ.write_text(adj_text)
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"endocrine_edge_ground: regenerated endocrine-edges.adj + endocrine-edge-manifest.json "
          f"({accepted} ACCEPT grounded, {flagged} consensus/flagged authored-debt). "
          f"Run grounding/ground_sources.py to rebuild the provenance ledger.")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
