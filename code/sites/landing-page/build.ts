import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createOrchestrator } from "@coding-adventures/forme-orchestrator";
import { consoleLogger } from "@coding-adventures/forme-stage";
import type { DeployArtifact } from "@coding-adventures/forme-types";
import config from "./forme.config.ts";

const here = dirname(fileURLToPath(import.meta.url));
process.chdir(here);

const logger = consoleLogger({ level: "info" }).child({ pipeline: config.name });
const orchestrator = createOrchestrator({ logger });

try {
  logger.info("Building pipeline", { name: config.name });
  const pipeline = await orchestrator.buildPipeline(config);
  const result = await orchestrator.runOnce(pipeline);
  if (result.outcome !== "success") {
    for (const error of result.errors) {
      logger.error(`Pipeline error in ${error.instanceId}`, {
        stage: error.stageName,
        code: error.code,
        error: error.message,
      });
    }
    throw new Error(`Landing pipeline completed with outcome ${result.outcome}`);
  }

  const site = result.outputs.site as DeployArtifact | undefined;
  if (site === undefined) throw new Error("Landing pipeline did not expose its site artifact");
  const routes = site.manifest.routes.map(route => route.pattern);
  if (routes.length !== 1 || routes[0] !== "/index.html") {
    throw new Error(`Landing routes differ: ${JSON.stringify(routes)}`);
  }
  if (site.manifest.assets.length !== 1) {
    throw new Error(`Landing manifest must contain exactly one asset, got ${site.manifest.assets.length}`);
  }
  const asset = site.manifest.assets[0];
  if (
    asset === undefined ||
    asset.id !== "01952c0d-7e63-7000-8000-000000000302" ||
    !asset.path.startsWith("assets/og.") ||
    !asset.path.endsWith(".jpg") ||
    asset.mime !== "image/jpeg"
  ) {
    throw new Error(`Landing asset entry differs: ${JSON.stringify(asset)}`);
  }
  const assetBytes = site.files[asset.path];
  const htmlBytes = site.files["index.html"];
  if (assetBytes === undefined || htmlBytes === undefined) {
    throw new Error("Landing artifact is missing index.html or its social image");
  }
  const html = new TextDecoder().decode(htmlBytes);
  const expectedAssetUrl = `/coding-adventures/${asset.path}`;
  const requiredFragments = [
    '<meta name="generator" content="Forme">',
    "Generated by Forme",
    expectedAssetUrl,
    'id="paths"',
    'id="labs"',
    'id="forme"',
    "5,003",
    "1,498",
    "61",
    "Headless CLI and preview",
  ];
  for (const fragment of requiredFragments) {
    if (!html.includes(fragment)) throw new Error(`Landing HTML is missing ${JSON.stringify(fragment)}`);
  }
  if (html.includes("forme-asset:") || html.includes("<script")) {
    throw new Error("Landing HTML contains an unresolved asset or unexpected script");
  }
  const sha256 = createHash("sha256").update(assetBytes).digest("hex");
  if (sha256 !== asset.sha256 || !asset.path.includes(sha256)) {
    throw new Error("Landing asset filename, manifest SHA, and bytes differ");
  }
  const diskHtml = await readFile(resolve(here, "dist/index.html"));
  const diskAsset = await readFile(resolve(here, "dist", asset.path));
  if (!diskHtml.equals(Buffer.from(htmlBytes)) || !diskAsset.equals(Buffer.from(assetBytes))) {
    throw new Error("Landing artifact and on-disk bytes differ");
  }

  logger.info("Build complete", {
    outcome: result.outcome,
    elapsedMs: result.elapsedMs,
    buildId: result.buildId,
    stages: result.stages.length,
    pages: routes.length,
    assets: site.manifest.assets.length,
    files: Object.keys(site.files).length,
  });
  logger.info("dist/ written under", { absolute: resolve(here, "dist") });
} finally {
  await orchestrator.dispose();
}
