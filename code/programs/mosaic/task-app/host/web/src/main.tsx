// Web host entry — wires the Mosaic-emitted TaskApp component to the pure task-core
// engine (via task-wasm's createTaskEngine) using plain React state, and persists the
// workspace through the pluggable storage layer (IndexedDB, in-memory fallback). No
// window.mosaicHost facade: the component only needs {...slotProps, dispatch}. React-isms
// and persistence both live here, in the web backend, where they belong — the engine
// stays a pure computation.
import {
  StrictMode,
  useCallback,
  useEffect,
  useLayoutEffect,
  useRef,
  useState,
} from "react";
import { createRoot } from "react-dom/client";
// One emitted component per theme: mosstyle bakes colours into inline styles, so
// switching means swapping the component, not toggling a class. Both are generated by
// scripts/build-web; the event type is identical, so either can be used interchangeably.
import { TaskApp as TaskAppLight, type TaskAppEvent } from "./TaskApp.light";
import { TaskApp as TaskAppDark } from "./TaskApp.dark";
import {
  applyThemeGround,
  boardAccent,
  resolveTheme,
  ringGradient as computeRingGradient,
  storeTheme,
  watchSystemTheme,
  type Theme,
} from "./theme";
import { StartupFailure, StartupLoading } from "./startup";
import { createTaskEngine } from "./task-engine.mjs";
import { makeController } from "./controller";
import {
  loadWorkspace,
  makeWorkspaceRecord,
  openWorkspaceStorage,
  preserveRejectedWorkspace,
  saveWorkspace,
} from "./persistence";

export { makeController } from "./controller";

/**
 * One React root for the document, created on first use.
 *
 * Retry re-renders into this same root rather than calling createRoot again —
 * a second createRoot on a container React already owns warns and orphans the
 * first tree.
 */
let appRoot: ReturnType<typeof createRoot> | undefined;
function hostRoot(): ReturnType<typeof createRoot> {
  const el = document.getElementById("root");
  if (!el) throw new Error("#root not found");
  appRoot ??= createRoot(el);
  return appRoot;
}

/**
 * Paint a startup state, run initialization, and replace the state with the app.
 *
 * The theme is resolved here rather than inside the states so that both of them
 * and the app agree on the ground colour through the swap; once startApp() wins,
 * Root owns the theme (including live OS changes) as before.
 */
export async function boot(): Promise<void> {
  const theme = resolveTheme();
  applyThemeGround(theme);
  hostRoot().render(
    <StrictMode>
      <StartupLoading theme={theme} />
    </StrictMode>,
  );
  try {
    await startApp();
  } catch (err) {
    const detail = err instanceof Error ? err.message : String(err);
    hostRoot().render(
      <StrictMode>
        <StartupFailure theme={theme} detail={detail} onRetry={() => void boot()} />
      </StrictMode>,
    );
  }
}

async function startApp() {
  // A 404 or an offline fetch still resolves, so `ok` has to be checked
  // explicitly. Without it a missing bundle reaches WebAssembly.compile as an
  // HTML error page and surfaces as a CompileError, which reads like a corrupt
  // engine rather than a missing file.
  // Bundle-relative, not domain-absolute. "/task_engine.wasm" only resolves
  // when the app is served from a domain root; published to a subdirectory
  // (GitHub Pages serves this at /task-app/) it requests the wrong URL and
  // 404s, while the file sits correctly inside the bundle. Same reasoning and
  // same shape as Engram's host, which passes the relocatable-bundle check.
  const response = await fetch("./task_engine.wasm");
  if (!response.ok) {
    throw new Error(
      `The scheduling engine could not be downloaded (HTTP ${response.status} ${response.statusText}).`,
    );
  }
  const bytes = await response.arrayBuffer();
  const wasmModule = await WebAssembly.compile(bytes);
  const engine = createTaskEngine(wasmModule);

  // Restore the persisted workspace before the first render (no loading spinner):
  // load the engine snapshot, then seed the controller with the saved host state.
  const storageSession = await openWorkspaceStorage();
  const storage = storageSession.storage;
  let persistenceWarning = storageSession.warning;
  let saved: Awaited<ReturnType<typeof loadWorkspace>>;
  try {
    saved = await loadWorkspace(storage);
  } catch (err) {
    const detail = err instanceof Error ? err.message : String(err);
    persistenceWarning = `Saved data could not be read. Trestle started a fresh workspace: ${detail}`;
    saved = undefined;
  }
  if (saved) {
    try {
      engine.load(saved.snapshot);
    } catch (err) {
      const detail = err instanceof Error ? err.message : String(err);
      try {
        await preserveRejectedWorkspace(storage, saved);
        persistenceWarning =
          `Saved data could not be restored. Trestle started a fresh workspace and kept the ` +
          `rejected record as workspace/web-corrupt for recovery: ${detail}`;
      } catch (preserveError) {
        const preserveDetail =
          preserveError instanceof Error ? preserveError.message : String(preserveError);
        persistenceWarning =
          `Saved data could not be restored, and its recovery copy could not be written. ` +
          `Do not clear this site's browser data: ${detail}; ${preserveDetail}`;
      }
      saved = undefined;
    }
    // `load` clears the engine's selection (it pointed into the replaced workspace),
    // so re-apply the remembered one. A project that no longer exists is rejected and
    // we simply stay on the default.
    if (saved?.activeProject) {
      engine.setActiveProject({ id: saved.activeProject });
    }
  }

  let updatePersistenceWarning: ((warning: string) => void) | undefined;
  const reportPersistenceWarning = (warning: string) => {
    persistenceWarning = warning;
    updatePersistenceWarning?.(warning);
  };

  const controller = makeController(engine, {
    initialOrder: saved?.order ?? [],
    initialCounter: saved?.counter ?? 0,
    onMutate: (snapshot, order, counter, activeProject) =>
      saveWorkspace(
        storage,
        makeWorkspaceRecord(snapshot, order, counter, Date.now(), activeProject),
        reportPersistenceWarning,
      ),
  });

  function Root() {
    const [props, setProps] = useState(() => controller.getProps());
    const [theme, setTheme] = useState<Theme>(resolveTheme);
    const [storageWarning, setStorageWarning] = useState(persistenceWarning);

    useEffect(() => {
      updatePersistenceWarning = setStorageWarning;
      return () => {
        updatePersistenceWarning = undefined;
      };
    }, []);

    // Switching theme swaps the rendered component *type*, so React unmounts the old
    // tree and builds a new one — which destroys the focused <input> and drops the
    // caret. Harmless when you click the toggle (that already blurred the field), but
    // the OS can flip at sunset while you are mid-sentence. So: remember which field
    // had focus and where the caret sat, and put it back after the swap.
    const focused = useRef<{ placeholder: string; start: number | null; end: number | null } | null>(
      null,
    );
    const rememberFocus = () => {
      const el = document.activeElement as HTMLInputElement | null;
      focused.current =
        el && el.tagName === "INPUT"
          ? { placeholder: el.placeholder, start: el.selectionStart, end: el.selectionEnd }
          : null;
    };
    const changeTheme = useCallback((next: Theme) => {
      rememberFocus();
      setTheme(next);
    }, []);

    // Restore before paint, so the swap is invisible rather than a visible blink of
    // lost focus. Placeholders are authored in the .mll (never user input), and
    // CSS.escape keeps a stray quote from breaking the selector regardless.
    useLayoutEffect(() => {
      const want = focused.current;
      focused.current = null;
      if (!want) return;
      const escape = (globalThis as any).CSS?.escape ?? ((v: string) => v.replace(/"/g, ""));
      const el = document.querySelector<HTMLInputElement>(
        `input[placeholder="${escape(want.placeholder)}"]`,
      );
      if (!el) return;
      el.focus();
      try {
        el.setSelectionRange(want.start ?? el.value.length, want.end ?? el.value.length);
      } catch {
        // Some input types reject setSelectionRange; focus alone is the win here.
      }
    }, [theme]);

    // Follow the OS while the user hasn't overridden it — so a machine that flips to
    // dark at sunset takes the app with it, without a reload.
    useEffect(() => watchSystemTheme(changeTheme), [changeTheme]);

    // Repaint the page ground. index.html guesses from the OS before React mounts;
    // an explicit choice outranks the OS, so the guess can be wrong.
    useEffect(() => applyThemeGround(theme), [theme]);

    const toggle = useCallback(() => {
      // Compute off the rendered value, not inside the updater: React double-invokes
      // updaters in StrictMode, and a persist belongs outside that.
      const next: Theme = theme === "dark" ? "light" : "dark";
      storeTheme(next); // an explicit choice from here on; stops following the OS
      changeTheme(next);
    }, [theme, changeTheme]);

    // The toggle is now a real HostButton in the topbar (task-app-icon-assets-v1.md),
    // emitting `toggleTheme` like any other control — but theme lives here in Root,
    // not in `controller`'s engine-backed state, so it's intercepted before reaching
    // `controller.apply`, which has never heard of it and shouldn't need to.
    const dispatch = useCallback(
      (event: TaskAppEvent) => {
        if (event.type === "toggleTheme") {
          toggle();
          return;
        }
        controller.apply(event);
        setProps(controller.getProps());
      },
      [toggle],
    );

    const Emitted = theme === "dark" ? TaskAppDark : TaskAppLight;
    return (
      <Emitted
        {...props}
        storageStatus={storageSession.status}
        storageLocation={storageSession.location}
        storageWarning={storageWarning}
        themeIsDark={theme === "dark" ? "dark" : ""}
        ringGradient={computeRingGradient(theme, props.ringPercentValue)}
        // `board.columns`' 4th cell is a placeholder — same reasoning as
        // ringGradient above, the controller never sees the resolved theme.
        boardColumns={props.boardColumns.map((row: string[]) => [
          row[0],
          row[1],
          row[2],
          boardAccent(theme, row[1]),
        ])}
        dispatch={dispatch}
      />
    );
  }

  hostRoot().render(
    <StrictMode>
      <Root />
    </StrictMode>,
  );
}

// The guard keeps the presentation controller importable in headless contract
// tests without booting React. The production document always owns this root.
if (document.getElementById("root")) void boot();
