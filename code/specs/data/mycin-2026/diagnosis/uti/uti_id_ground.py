#!/usr/bin/env python3
"""uti_id_ground.py — the adversarial WRITE GATE for UTI organism identification (G4).

The FIRST specialty expansion. A new disease enters MYCIN-2026 exactly like the
meningitis organism-id did (G1): the spider (grounding/workflows/ground-uti-id.workflow.js)
grounds each epidemiologic prior + each urinalysis finding→organism association against a
primary source with a verbatim byte-quote + an independent adversarial re-extraction; this
gate consumes that output (grounding/uti-id-grounding.json) and regenerates uti-id.adj so
every gradeable clause is GROUNDED, byte-cited, and gated — never authored.

The gate verdicts + the proportion parser + the citation escaper are REUSED from the
meningitis organism-id gate (organism_id_ground.py), not duplicated — a new specialty is
new GROUNDED FACTS pointed through the same machinery, not new code. (Those helpers should
migrate to a shared grounding util as more specialties land; noted for a later cleanup.)

Usage:  python3 uti_id_ground.py [--check]
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MYCIN = HERE.parent.parent
GROUNDING = MYCIN / "grounding" / "uti-id-grounding.json"
sys.path.insert(0, str(MYCIN / "diagnosis" / "organisms"))
import organism_id_ground as oid  # noqa: E402  (reuse: parse_proportion, cite, gate)

# Rulebook STRUCTURE (closed vocabulary). VALUES + provenance + trust come from the
# grounding, never authored here. Fallback prior is used only if a clause is ungrounded.
PRIORS = [  # (grounding id, organism, fallback prior)
    ("uti_prior_ecoli", "e_coli", 0.80),
    ("uti_prior_saprophyticus", "s_saprophyticus", 0.10),
    ("uti_prior_klebsiella", "klebsiella", 0.035),
    ("uti_prior_proteus", "proteus", 0.03),
    ("uti_prior_enterococcus", "enterococcus", 0.048),
    ("uti_prior_pseudomonas", "pseudomonas", 0.02),
    ("uti_prior_gbs", "group_b_strep", 0.015),
]
# Urinalysis finding → organism associations. The mapping is what the spider grounds; the
# LR magnitude is a structural identifier strength (like the meningitis morphology LRs).
# (grounding id, finding, value, [organisms it points at], LR)
FINDINGS = [
    ("uti_finding_nitrite", "urine_nitrite", "positive",
     ["e_coli", "klebsiella", "proteus"], 8),       # nitrate-reducing Enterobacterales
    ("uti_finding_urease_proteus", "urine_urease_alkaline", "present", ["proteus"], 20),
]
# Note: uti_finding_leuk_esterase grounds pyuria (infection PRESENT), which does not
# discriminate the organism, so it is defined in the vocab but is not an organism
# contributor here — it belongs to the "is this a UTI?" arm, not "which uropathogen?".


def build(check: bool = False) -> int:
    if not GROUNDING.exists():
        print(f"uti_id_ground: {GROUNDING} not found — run the UTI spider first.", file=sys.stderr)
        return 2
    recs = {r["id"]: r for r in json.loads(GROUNDING.read_text())["records"]}

    lines = [
        "% ============================================================================",
        "% uti-id — GROUNDED UTI organism-identification rulebook (spider + write gate).",
        "% ============================================================================",
        "% GENERATED by uti_id_ground.py from grounding/uti-id-grounding.json. Do NOT",
        "% hand-edit values — correct a wrong fact by editing the grounding (the spider's",
        "% record) and re-running the gate. Every prior/finding clause is byte-cited to a",
        "% primary source; ACCEPTed clauses carry the source value, FLAGged clauses are",
        "% kept at trust inferred (direction grounded / pending).",
        "",
        'import "uti-vocab.adj"',
        "",
        "rulebook uti_id {",
        "    use uti_vocab",
        "",
        "    % ===================== Epidemiologic priors (spider-grounded) =====================",
    ]
    manifest = {"kind": "uti-id", "clauses": {}}

    def record(cid, status, verdict, trust, value, rec):
        manifest["clauses"][cid] = {
            "status": status, "verdict": verdict, "trust": trust, "value": value,
            "byte_quote": ((rec or {}).get("grounded") or {}).get("byte_quote"),
            "url": ((rec or {}).get("grounded") or {}).get("resolved_url"),
        }

    for cid, org, fallback in PRIORS:
        rec = recs.get(cid)
        status = rec["spider_status"] if rec else "missing"
        verdict, trust = oid.gate(status)
        grounded_val = oid.parse_proportion((rec or {}).get("grounded", {}).get("value_found", "")) if rec else None
        value = grounded_val if (verdict == "ACCEPT" and grounded_val is not None) else fallback
        tag = "" if verdict == "ACCEPT" else "   % [FLAG: " + oid.safe_status(status) + "]"
        lines += [f"    prior {value} for {org}",
                  f'        source "{oid.cite(rec)}"',
                  f"        trust {trust}{tag}"]
        record(cid, status, verdict, trust, value, rec)

    lines += ["", "    % ===================== Urinalysis findings (spider-grounded mapping) ====================="]
    for cid, finding, fval, orgs, lr in FINDINGS:
        rec = recs.get(cid)
        status = rec["spider_status"] if rec else "missing"
        verdict, _ = oid.gate(status)
        trust = "consensus" if verdict == "ACCEPT" else "inferred"
        tag = "" if verdict == "ACCEPT" else "   % [FLAG: " + oid.safe_status(status) + "]"
        for org in orgs:
            lines += [f"    contributes {lr} from {finding}({fval}) to {org}",
                      f'        source "{oid.cite(rec)}"',
                      f"        trust {trust}{tag}"]
        record(cid, status, verdict, trust, lr, rec)

    lines += ["}", ""]
    for _, org, _ in PRIORS:
        lines.append(f"? {org}")
    adj_text = "\n".join(lines) + "\n"
    manifest["hash"] = hashlib.sha256(adj_text.encode()).hexdigest()[:16]

    accepted = sum(1 for c in manifest["clauses"].values() if c["verdict"] == "ACCEPT")
    flagged = sum(1 for c in manifest["clauses"].values() if c["verdict"] == "FLAG")

    if check:
        cur = (HERE / "uti-id.adj").read_text() if (HERE / "uti-id.adj").exists() else ""
        ok = cur == adj_text
        print("uti_id_ground --check:", "up to date" if ok else "OUT OF DATE")
        return 0 if ok else 1

    (HERE / "uti-id.adj").write_text(adj_text)
    (HERE / "uti-id-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"uti_id_ground: regenerated uti-id.adj from grounding "
          f"({accepted} ACCEPTED grounded, {flagged} FLAGGED). Run grounding/ground_sources.py "
          f"to rebuild the provenance ledger.")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv[1:]))
