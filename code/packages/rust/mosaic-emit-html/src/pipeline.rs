/// The result of compiling a three-file pipeline triple to an HTML fragment.
///
/// Mirrors the shape of [`mosaic_emit_react::pipeline::PipelineEmitResult`]
/// so downstream tooling can treat both backends uniformly.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PipelineEmitResult {
    /// The complete HTML fragment (no `<!DOCTYPE html>` / `<html>` /
    /// `<body>` wrapper — host responsibility).
    pub output: String,
    /// The component's PascalCase name (matches the source `.mil`/`.mll` files).
    pub component_name: String,
}

/// Errors the HTML pipeline emitter can return.
///
/// Kept lean by design — HTML is the least expressive backend and most of
/// the React-side error cases (reserved emit names, unsafe JS identifiers)
/// have no analog here.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PipelineEmitError {
    /// The mosmodel component name and the moslayout component name disagree.
    /// Almost always a manifest authoring error.
    ComponentNameMismatch { mosmodel: String, moslayout: String },
    /// A moslayout primitive tag is not recognised by the HTML backend yet.
    /// See the module-level table for the current coverage.
    UnknownPrimitive(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PipelineEmitError::ComponentNameMismatch {
                mosmodel,
                moslayout,
            } => write!(
                f,
                "component name mismatch: mosmodel says '{mosmodel}', moslayout says '{moslayout}'"
            ),
            PipelineEmitError::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the pipeline HTML emitter"
            ),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

