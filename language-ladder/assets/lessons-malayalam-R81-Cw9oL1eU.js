<!-- hl-knowledge: introduces=[]; assesses=[ML-LEX-C41-DEIXIS-03, ML-LEX-C41-DEIXIS-04, ML-LEX-C81-DISTANCE-01, ML-LEX-C81-DISTANCE-02, ML-LEX-C81-DISTANCE-03] -->

