"""Generate the zero-filesystem Dart mirror of the trig-reference-v1 vectors.

PHY00a section 6.5 says a package that declares no filesystem capability (Dart)
must not read the TSV at test time.  This script emits the vectors as Dart
source instead, the same pattern as ``generate_phy00_phy01_dart_fixtures.py``:
one canonical base64 constant per group, decoded and validated at test time by
``code/packages/dart/trig/test/support/vector_loader.dart``.

The output is ``code/packages/dart/trig/test/generated/trig_reference_vectors.dart``.
It lives in the package, not under ``fixtures/trig-reference-v1/``, because both
``generate_trig_reference_fixture.py --check`` and its validator reject any
unexpected entry in that directory.

What is embedded, besides the bytes:

* the manifest's SHA-256 of every group (Dart has no offline hash, so the loader
  does not hash; THIS script refuses to run, and ``--check`` fails, unless the
  TSVs hash to exactly those values),
* the manifest's constant table of PHY00a 3.2, so the Dart tests can assert the bits
  of every constant the port embeds (6.5 e),
* the row count of every group, from the manifest, and the row count of every
  op inside every group, counted here, so a truncated or padded constant is
  caught by the loader.

    python3 code/scripts/generate_trig_reference_dart_fixtures.py          # write
    python3 code/scripts/generate_trig_reference_dart_fixtures.py --check  # verify
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import textwrap
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE_ROOT = ROOT / "code" / "specs" / "fixtures" / "trig-reference-v1"
OUTPUT = (
    ROOT / "code" / "packages" / "dart" / "trig" / "test" / "generated"
    / "trig_reference_vectors.dart"
)
_CONSTANTS: dict[str, str] = {}
GROUPS = ("edge", "sweep-binade", "sweep-cw", "sweep-prng")


def _ident(group: str) -> str:
    """edge -> edge, sweep-binade -> sweepBinade."""
    head, *rest = group.split("-")
    return head + "".join(part.capitalize() for part in rest)


def _wrap(name: str, value: str) -> str:
    chunks = textwrap.wrap(value, width=96)
    lines = [f"const String {name} ="]
    lines.extend(f"    '{chunk}'" for chunk in chunks)
    lines[-1] += ";"
    return "\n".join(lines)


def load_groups() -> list[dict]:
    """Read the TSVs, verify them against the manifest, return group records."""
    manifest = json.loads((FIXTURE_ROOT / "manifest.json").read_text("utf-8"))
    if manifest["algorithm"] != "TRIG-REF-1":
        raise SystemExit("manifest is not TRIG-REF-1")
    by_name = {g["name"]: g for g in manifest["groups"]}
    if set(by_name) != set(GROUPS):
        raise SystemExit(f"manifest groups {sorted(by_name)} != {sorted(GROUPS)}")
    out = []
    global _CONSTANTS
    _CONSTANTS = dict(manifest["constants"])
    for name in GROUPS:
        entry = by_name[name]
        raw = (FIXTURE_ROOT / entry["file"]).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest != entry["sha256"]:
            raise SystemExit(f"{entry['file']}: sha256 {digest} != manifest {entry['sha256']}")
        lines = raw.decode("utf-8", errors="strict").split("\n")
        if lines[-1] != "":
            raise SystemExit(f"{entry['file']}: missing final newline")
        lines.pop()
        if len(lines) != entry["rows"]:
            raise SystemExit(f"{entry['file']}: {len(lines)} rows != manifest {entry['rows']}")
        ops = Counter(line.split("\t", 1)[0] for line in lines)
        out.append(
            {"name": name, "raw": raw, "sha256": digest, "rows": entry["rows"], "ops": ops}
        )
    return out


def render() -> str:
    groups = load_groups()
    header = (
        "// Generated by code/scripts/generate_trig_reference_dart_fixtures.py.\n"
        "// Do not edit: the Python contract test verifies an exact byte-for-byte mirror\n"
        "// of code/specs/fixtures/trig-reference-v1/*.tsv (PHY00a 6.5).\n"
        "//\n"
        "// One base64 constant per vector group; the validated loader is\n"
        "// test/support/vector_loader.dart."
    )
    parts = [header]
    for g in groups:
        b64 = base64.b64encode(g["raw"]).decode("ascii")
        ident = _ident(g["name"])
        parts.append(_wrap(f"trigReference{ident[0].upper()}{ident[1:]}Base64", b64))
    meta = ["/// Group name -> manifest SHA-256 of the decoded bytes."]
    meta.append("const Map<String, String> trigReferenceSha256 = {")
    for g in groups:
        # The key and value go on separate lines when the pair is wider than 80
        # columns, which is exactly what `dart format` produces; emitting it
        # already formatted keeps `dart format --set-exit-if-changed` green.
        line = f"  '{g['name']}': '{g['sha256']}',"
        if len(line) > 80:
            line = f"  '{g['name']}':\n      '{g['sha256']}',"
        meta.append(line)
    meta.append("};")
    meta.append("")
    meta.append("/// Group name -> manifest row count.")
    meta.append("const Map<String, int> trigReferenceRows = {")
    for g in groups:
        meta.append(f"  '{g['name']}': {g['rows']},")
    meta.append("};")
    meta.append("")
    meta.append("/// Group name -> op -> row count (counted from the TSV by the generator).")
    meta.append("const Map<String, Map<String, int>> trigReferenceOpRows = {")
    for g in groups:
        meta.append(f"  '{g['name']}': {{")
        for op in sorted(g["ops"]):
            meta.append(f"    '{op}': {g['ops'][op]},")
        meta.append("  },")
    meta.append("};")
    meta.append("")
    meta.append("/// The manifest's constant table (PHY00a 3.2): name -> binary64 bits as hex.")
    meta.append("const Map<String, String> trigReferenceConstants = {")
    for name in sorted(_CONSTANTS):
        meta.append(f"  '{name}': '{_CONSTANTS[name]}',")
    meta.append("};")
    parts.append("\n".join(meta))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != expected.encode("utf-8"):
            raise SystemExit(
                "generated Dart vectors are stale; run "
                "python3 code/scripts/generate_trig_reference_dart_fixtures.py"
            )
        print("dart vectors reproduced byte for byte:", OUTPUT.name)
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(expected.encode("utf-8"))
    print("wrote", OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
