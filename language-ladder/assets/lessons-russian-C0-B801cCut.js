<!-- hl-knowledge: introduces=[RU-LEX-PISAT]; assesses=[RU-LEX-YA, RU-GRAMMAR-PRESENT-FIRST-PERSON-U, RU-GRAMMAR-NO-PROGRESSIVE, RU-LEX-CHITAT] -->

