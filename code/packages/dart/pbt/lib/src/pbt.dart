/// Property-based testing engine: the Dart lane of VER05/VER05b.
///
/// A zero-dependency Level 2 engine: generator algebra ([Gen]), integrated
/// shrinking that preserves invariants, deterministic [SplitMix64] replay with
/// isolated sub-seeds, step budgets, closed failure vocabulary, and
/// privacy-preserving CI failure reporting.
///
/// This is a behavioral port of the TypeScript VER05a engine. Stream semantics
/// are bit-exact: the same seed produces the same outputs in both lanes (the
/// pbt-v1 corpus pins this). One deliberate upgrade: all 64-bit state lives in
/// [BigInt], which is exact on both the Dart VM and compiled JavaScript, so
/// this lane has no 53-bit truncation caveat.
///
/// ```dart
/// import 'package:coding_adventures_pbt/coding_adventures_pbt.dart';
///
/// void main() {
///   assertProperty(
///     Gen.integer(BigInt.zero, BigInt.from(100)),
///     (n) => n >= BigInt.zero && n <= BigInt.from(100),
///     PbtOptions(numTests: 200, seed: BigInt.from(7)),
///   );
/// }
/// ```
library pbt;

import 'dart:convert';
import 'dart:typed_data';

// ─── PRNG: SplitMix64 & FNV-1a ──────────────────────────────────────────────
//
// SplitMix64 (Steele et al.) is a tiny splittable PRNG: add a golden-ratio
// constant to the state, then scramble with two multiply-xorshifts. It is
// chosen because the algorithm is four lines, needs no seeding ceremony, and
// — most importantly — is specified exactly enough that two lanes written
// independently produce the same stream. The pbt-v1 corpus pins the first
// outputs of seeds 0, 42, 12345, and others, so any drift fails loudly.

/// 2^64, the SplitMix64 state modulus.
final BigInt _mask64Plus1 = BigInt.one << 64;

/// 2^64 - 1, for masking state back into 64 bits.
final BigInt _mask64 = _mask64Plus1 - BigInt.one;

const int _goldenGammaLow = 0x7f4a7c15;
const int _goldenGammaHigh = 0x9e3779b9;

/// Deterministic 64-bit PRNG. Same seed, same stream, on every platform.
class SplitMix64 {
  BigInt _state;

  /// Seeds the generator; the seed is reduced modulo 2^64.
  SplitMix64(BigInt seed) : _state = seed & _mask64;

  /// Draws the next unsigned 64-bit value.
  BigInt nextU64() {
    _state = (_state + _goldenGamma()) & _mask64;
    var z = _state;
    z = (((z ^ (z >> 30)) * _scramble1()) & _mask64);
    z = (((z ^ (z >> 27)) * _scramble2()) & _mask64);
    return (z ^ (z >> 31)) & _mask64;
  }

  /// Draws a uniform `int` from `0` (inclusive) to `n` (exclusive).
  ///
  /// Uses Lemire's near-divisionless rejection: values below
  /// `threshold = (2^64 - n) mod n` would bias the modulo, so they are
  /// redrawn. `n <= 1` returns 0; `n > 2^32` throws.
  int bounded(int n) {
    final bn = BigInt.from(n);
    if (bn <= BigInt.one) return 0;
    if (bn > BigInt.from(0x100000000)) {
      throw ArgumentError('bounded(n) needs 1 <= n <= 2^32, got $n');
    }
    final threshold = (_mask64Plus1 - bn) % bn;
    while (true) {
      final x = nextU64();
      if (x >= threshold) {
        return (x % bn).toInt();
      }
    }
  }
}

BigInt _goldenGamma() =>
    (BigInt.from(_goldenGammaHigh) << 32) | BigInt.from(_goldenGammaLow);

BigInt _scramble1() =>
    (BigInt.from(0xbf58476d) << 32) | BigInt.from(0x1ce4e5b9);

BigInt _scramble2() =>
    (BigInt.from(0x94d049bb) << 32) | BigInt.from(0x133111eb);

/// 64-bit FNV-1a hash over [data].
BigInt fnv1a64(Uint8List data) {
  var hash = (BigInt.from(0xcbf29ce4) << 32) | BigInt.from(0x84222325);
  final prime = BigInt.from(0x100000001b3);
  for (final byte in data) {
    hash ^= BigInt.from(byte);
    hash = (hash * prime) & _mask64;
  }
  return hash;
}

/// Derives an isolated sub-seed for one property from a run seed.
///
/// XOR-ing the run seed with the FNV-1a of the property id means two
/// properties in one run never share a stream, and reordering properties
/// never changes any property's draws.
BigInt subSeed(BigInt runSeed, String propertyId) {
  final idHash = fnv1a64(Uint8List.fromList(utf8.encode(propertyId)));
  return ((runSeed & _mask64) ^ idHash) & _mask64;
}

// ─── Value & Verdict Types ──────────────────────────────────────────────────

/// A generated corpus value: a bool, a decimal-text int, or raw bytes.
sealed class PbtValue {
  const PbtValue();
}

/// A boolean generated value.
class BoolValue extends PbtValue {
  /// The generated bool.
  final bool value;
  const BoolValue(this.value);
}

/// An integer generated value, rendered as decimal text (arbitrary width).
class IntValue extends PbtValue {
  /// Decimal rendering of the generated integer.
  final String text;
  const IntValue(this.text);
}

/// A byte-string generated value.
class BytesValue extends PbtValue {
  /// The generated bytes.
  final Uint8List value;
  const BytesValue(this.value);
}

/// The outcome of one property run: pass, or fail with a closed failure id.
sealed class Verdict {
  const Verdict();
}

/// The property held for every tested candidate.
class Pass extends Verdict {
  const Pass();
}

/// The property run failed. [failureId] is one of the closed vocabulary.
class Fail extends Verdict {
  /// Closed failure id (`property-counterexample`, ...).
  final String failureId;

  /// Human-readable detail; redacted to a repro digest on CI.
  final String message;
  const Fail(this.failureId, this.message);
}

// ─── Closed Failure Vocabulary (VER05 §5.1) ─────────────────────────────────

/// Property was falsified; minimal witness found.
const String fidCounterexample = 'property-counterexample';

/// Precondition filter rejected all candidates within retry budget.
const String fidExhausted = 'property-exhausted';

/// Evaluation step budget exceeded.
const String fidTimeout = 'property-timeout';

/// Uncaught exception escaped during property evaluation.
const String fidPanic = 'property-panic';

/// Every registered PBT failure id.
const List<String> allPbtFailureIds = [
  fidCounterexample,
  fidExhausted,
  fidTimeout,
  fidPanic,
];

/// Returns true if [id] is a registered PBT failure id.
bool isPbtFailureId(String id) =>
    id == fidCounterexample ||
    id == fidExhausted ||
    id == fidTimeout ||
    id == fidPanic;

/// Alias kept for the cross-lane `isRegisteredFailureId` spelling.
bool isRegisteredFailureId(String id) => isPbtFailureId(id);

/// Thrown when a `filter` precondition rejects every candidate.
class ExhaustedError implements Exception {
  /// What was exhausted (retries, iterations).
  final String message;
  const ExhaustedError(this.message);
  @override
  String toString() => 'ExhaustedError: $message';
}

// ─── Primitive Generators (VER05 §3.1) ──────────────────────────────────────
//
// Every generator draws from the stream in a fixed order shared with the
// sibling lanes. That order is the compatibility contract: the pbt-v1 vectors
// pin exact outputs per seed, so reordering draws here breaks conformance.

/// Uniform boolean (`bounded(2) == 1`).
bool genBool(SplitMix64 rng) => rng.bounded(2) == 1;

/// Uniform 8-bit integer (`0..255`).
int genU8(SplitMix64 rng) => rng.bounded(256);

/// Uniform 64-bit unsigned integer as [BigInt].
BigInt genU64(SplitMix64 rng) => rng.nextU64();

/// Signed 128-bit integer from two stream words, signed past 2^127.
BigInt genI128(SplitMix64 rng) {
  final w1 = rng.nextU64();
  final w2 = rng.nextU64();
  var val = (w1 << 64) | w2;
  if (val >= BigInt.one << 127) {
    val -= BigInt.one << 128;
  }
  return val;
}

/// Corpus entry point: [count] primitives of [typeName] from [seed].
List<PbtValue> genPrimitive(BigInt seed, String typeName, int count) {
  final rng = SplitMix64(seed);
  final outputs = <PbtValue>[];
  for (var i = 0; i < count; i++) {
    switch (typeName) {
      case 'bool':
        outputs.add(BoolValue(genBool(rng)));
      case 'u8':
        outputs.add(IntValue(genU8(rng).toString()));
      case 'u64':
        outputs.add(IntValue(genU64(rng).toString()));
      case 'i128':
        outputs.add(IntValue(genI128(rng).toString()));
      default:
        throw ArgumentError('unknown primitive type: $typeName');
    }
  }
  return outputs;
}

// ─── Bounded Integer Generator (VER05 §3.1) ─────────────────────────────────

/// Uniform `BigInt` below `n`, with Lemire rejection for wide spans.
BigInt boundedU64(SplitMix64 rng, BigInt n) {
  if (n <= BigInt.from(0x100000000)) {
    return BigInt.from(rng.bounded(n.toInt()));
  }
  final threshold = (_mask64Plus1 - n) % n;
  while (true) {
    final x = rng.nextU64();
    if (x >= threshold) {
      return x % n;
    }
  }
}

/// Uniform `BigInt` over `[minVal, maxVal]`.
///
/// Span routing matches the sibling lanes exactly: spans up to 2^32 go
/// through `bounded`, spans below 2^64 through [boundedU64], a full 2^64
/// span takes one raw draw, and wider spans accumulate words then reduce
/// modulo the span.
BigInt genBoundedInt(SplitMix64 rng, BigInt minVal, BigInt maxVal) {
  if (minVal > maxVal) {
    throw ArgumentError('minVal must be <= maxVal');
  }
  final span = maxVal - minVal + BigInt.one;
  late final BigInt offset;
  if (span <= BigInt.from(0x100000000)) {
    offset = BigInt.from(rng.bounded(span.toInt()));
  } else if (span < (BigInt.one << 64)) {
    offset = boundedU64(rng, span);
  } else if (span == (BigInt.one << 64)) {
    offset = rng.nextU64();
  } else {
    // Multi-word BigInt span.
    final wordsNeeded = ((span.bitLength + 63) ~/ 64) + 1;
    var raw = BigInt.zero;
    for (var w = 0; w < wordsNeeded; w++) {
      raw = (raw << 64) | rng.nextU64();
    }
    offset = raw % span;
  }
  return minVal + offset;
}

/// Corpus entry point: [count] bounded ints over `[minVal, maxVal]`.
List<PbtValue> genBounded(
    BigInt seed, BigInt minVal, BigInt maxVal, int count) {
  final rng = SplitMix64(seed);
  final outputs = <PbtValue>[];
  for (var i = 0; i < count; i++) {
    outputs.add(IntValue(genBoundedInt(rng, minVal, maxVal).toString()));
  }
  return outputs;
}

// ─── Byte Sequence Generator (VER05 §3.1) ───────────────────────────────────

/// Corpus entry point: [count] byte strings of length `[minLen, maxLen].
List<PbtValue> genBytes(BigInt seed, int minLen, int maxLen, int count) {
  if (minLen > maxLen || minLen < 0) {
    throw ArgumentError(
        'invalid byte lengths: minLen <= maxLen and minLen >= 0');
  }
  final rng = SplitMix64(seed);
  final span = maxLen - minLen + 1;
  final outputs = <PbtValue>[];
  for (var i = 0; i < count; i++) {
    final length = minLen + rng.bounded(span);
    final data = Uint8List(length);
    for (var j = 0; j < length; j++) {
      data[j] = rng.bounded(256);
    }
    outputs.add(BytesValue(data));
  }
  return outputs;
}

// ─── Euclidean Division for Integer Shrinking ───────────────────────────────
//
// Dart's `~/` truncates toward zero (like the sibling lanes' bigint `/`),
// but Dart's `%` takes the divisor's sign — so the remainder here is derived
// from the truncated quotient instead of `%`. Getting this wrong shifts every
// bisection candidate and breaks shrink step counts.

/// Euclidean quotient of `a ~/ b`: truncate, then step down on sign mismatch.
BigInt divEuclid(BigInt a, BigInt b) {
  if (b == BigInt.zero) throw ArgumentError('division by zero');
  final q = a ~/ b;
  final r = a - q * b;
  if (r != BigInt.zero && ((a < BigInt.zero) != (b < BigInt.zero))) {
    return q - BigInt.one;
  }
  return q;
}

// ─── Integrated Shrinking (VER05 §4) ────────────────────────────────────────
//
// Shrinking turns a failing candidate into the smallest witness that still
// fails: probe the target first, then bisect toward it, then walk linearly.
// Step counts are part of the conformance contract, so the phase order and
// the "count only accepted moves" rule match the sibling lanes exactly.

typedef IntProp = bool Function(BigInt x);

/// Shrinks a falsifying [initial] toward [target] within `[minVal, maxVal]`.
///
/// Returns `(minimal, steps)`. Throws if [initial] satisfies [prop].
(BigInt, int) shrinkInt(
  BigInt initial,
  BigInt target,
  BigInt minVal,
  BigInt maxVal,
  IntProp prop, [
  int maxSteps = 1000,
]) {
  if (prop(initial)) {
    throw ArgumentError('initial value $initial must falsify property');
  }
  var current = initial;
  var steps = 0;

  if (minVal <= target &&
      target <= maxVal &&
      target != current &&
      !prop(target)) {
    return (target, 1);
  }

  while (steps < maxSteps) {
    if (current == target) break;
    final diff = current - target;
    var progress = false;
    final absDiff = diff < BigInt.zero ? -diff : diff;

    if (absDiff > BigInt.one) {
      final step = divEuclid(diff, BigInt.two);
      final candidate = current - step;
      if (minVal <= candidate &&
          candidate <= maxVal &&
          !prop(candidate) &&
          candidate != current) {
        current = candidate;
        steps++;
        progress = true;
      }
    }

    if (!progress) {
      final step = diff > BigInt.zero ? BigInt.one : -BigInt.one;
      final candidate = current - step;
      if (minVal <= candidate &&
          candidate <= maxVal &&
          !prop(candidate) &&
          candidate != current) {
        current = candidate;
        steps++;
        progress = true;
      }
    }

    if (!progress) break;
  }

  return (current, steps);
}

/// Shrinks a falsifying list: empty probe, bisection, deletion, elementwise.
(List<BigInt>, int) shrinkList(
  List<BigInt> initial,
  BigInt elemTarget,
  bool Function(List<BigInt> slice) prop, [
  int maxSteps = 1000,
]) {
  if (prop(initial)) {
    throw ArgumentError('initial list must falsify property');
  }
  var current = [...initial];
  var steps = 0;

  if (!prop(const []) && current.isNotEmpty) {
    return (const [], 1);
  }

  // Phase 1: bisection.
  while (current.length > 1 && steps < maxSteps) {
    final mid = current.length ~/ 2;
    final left = current.sublist(0, mid);
    if (!prop(left)) {
      current = left;
      steps++;
      continue;
    }
    final right = current.sublist(mid);
    if (!prop(right)) {
      current = right;
      steps++;
      continue;
    }
    break;
  }

  // Phase 2: single-element deletion from right to left.
  var i = current.length - 1;
  while (i >= 0 && current.length > 1 && steps < maxSteps) {
    final cand = [...current.sublist(0, i), ...current.sublist(i + 1)];
    if (!prop(cand)) {
      current = cand;
      steps++;
      i = i < current.length ? i : current.length - 1;
    } else {
      i--;
    }
  }

  // Phase 3: element-wise reduction from left to right.
  for (var idx = 0; idx < current.length; idx++) {
    while (steps < maxSteps) {
      if (current[idx] == elemTarget) break;
      final diff = current[idx] - elemTarget;
      var progress = false;
      final absDiff = diff < BigInt.zero ? -diff : diff;

      if (absDiff > BigInt.one) {
        final step = divEuclid(diff, BigInt.two);
        final candVal = current[idx] - step;
        final candList = [
          ...current.sublist(0, idx),
          candVal,
          ...current.sublist(idx + 1),
        ];
        if (!prop(candList)) {
          current = candList;
          steps++;
          progress = true;
        }
      }

      if (!progress) {
        final step = diff > BigInt.zero ? BigInt.one : -BigInt.one;
        final candVal = current[idx] - step;
        final candList = [
          ...current.sublist(0, idx),
          candVal,
          ...current.sublist(idx + 1),
        ];
        if (!prop(candList)) {
          current = candList;
          steps++;
          progress = true;
        }
      }

      if (!progress) break;
    }
  }

  return (current, steps);
}

/// Shrinks falsifying bytes via list shrinking toward `0x00`.
(Uint8List, int) shrinkBytes(
  Uint8List initialBytes,
  bool Function(Uint8List b) prop, [
  int maxSteps = 1000,
]) {
  final initial = [for (final b in initialBytes) BigInt.from(b)];
  final (shrunkList, steps) = shrinkList(
    initial,
    BigInt.zero,
    (slice) => prop(Uint8List.fromList([for (final x in slice) x.toInt()])),
    maxSteps,
  );
  return (Uint8List.fromList([for (final x in shrunkList) x.toInt()]), steps);
}

// ─── Replay Consistency Simulation (VER05 §5) ───────────────────────────────

/// Draws up to 1000 `bounded(1000)` values for a falsifier, then shrinks it.
///
/// Returns `(initialFail, minimal)`. Throws if nothing falsifies.
(BigInt, BigInt) simulateReplay(BigInt seed, IntProp prop) {
  final rng = SplitMix64(seed);
  BigInt? initialFail;
  for (var i = 0; i < 1000; i++) {
    final val = BigInt.from(rng.bounded(1000));
    if (!prop(val)) {
      initialFail = val;
      break;
    }
  }
  if (initialFail == null) {
    throw StateError('property was not falsified within 1000 draws');
  }
  final (minimal, _) =
      shrinkInt(initialFail, BigInt.zero, BigInt.zero, BigInt.from(1000), prop);
  return (initialFail, minimal);
}

// ─── Generator Combinator Algebra (`Gen<T>`) ────────────────────────────────
//
// A generator is a function from PRNG to value. Combinators build complex
// generators from simple ones without ever touching the stream order of the
// primitives: `sample` calls nest exactly as written.

/// A composable deterministic generator of `T`.
class Gen<T> {
  /// Samples one value, advancing [rng].
  final T Function(SplitMix64 rng) sample;

  /// Wraps a sampling function.
  const Gen(this.sample);

  /// Maps sampled values through [fn].
  Gen<U> map<U>(U Function(T val) fn) => Gen((rng) => fn(sample(rng)));

  /// Rejects samples until [predicate] holds (or [maxRetries] runs out).
  Gen<T> filter(bool Function(T val) predicate, [int maxRetries = 100]) =>
      Gen((rng) {
        for (var i = 0; i < maxRetries; i++) {
          final val = sample(rng);
          if (predicate(val)) return val;
        }
        throw ExhaustedError(
          'Filter precondition rejected all candidates after $maxRetries attempts',
        );
      });

  /// Chains a dependent generator: sample, then sample from `fn(value)`.
  Gen<U> flatMap<U>(Gen<U> Function(T val) fn) => Gen((rng) {
        final intermediate = sample(rng);
        return fn(intermediate).sample(rng);
      });

  /// Always generates [val] (draws nothing).
  static Gen<T> constant<T>(T val) => Gen((_) => val);

  /// Uniform booleans.
  static Gen<bool> boolean() => Gen(genBool);

  /// Uniform bytes as `int` (`0..255`).
  static Gen<int> u8() => Gen(genU8);

  /// Uniform 64-bit unsigned integers as [BigInt].
  static Gen<BigInt> u64() => Gen(genU64);

  /// Uniform integers over `[min, max]` as [BigInt].
  static Gen<BigInt> integer(BigInt min, BigInt max) =>
      Gen((rng) => genBoundedInt(rng, min, max));

  /// Byte strings of length `[minLen, maxLen]` as [Uint8List].
  static Gen<Uint8List> bytes(int minLen, int maxLen) {
    if (minLen > maxLen || minLen < 0) {
      throw ArgumentError(
          'invalid byte lengths: minLen <= maxLen and minLen >= 0');
    }
    return Gen((rng) {
      final span = maxLen - minLen + 1;
      final length = minLen + rng.bounded(span);
      final buf = Uint8List(length);
      for (var i = 0; i < length; i++) {
        buf[i] = rng.bounded(256);
      }
      return buf;
    });
  }

  /// Lists of length `[minLen, maxLen]` with elements from [elemGen].
  static Gen<List<T>> list<T>(int minLen, int maxLen, Gen<T> elemGen) {
    if (minLen > maxLen || minLen < 0) {
      throw ArgumentError(
          'invalid list lengths: minLen <= maxLen and minLen >= 0');
    }
    return Gen((rng) {
      final span = maxLen - minLen + 1;
      final length = minLen + rng.bounded(span);
      final arr = <T>[];
      for (var i = 0; i < length; i++) {
        arr.add(elemGen.sample(rng));
      }
      return arr;
    });
  }

  /// Uniformly samples from one of [gens]. Needs at least one generator.
  static Gen<T> oneOf<T>(List<Gen<T>> gens) {
    if (gens.isEmpty) {
      throw ArgumentError('oneOf requires at least one generator');
    }
    return Gen((rng) {
      final idx = rng.bounded(gens.length);
      return gens[idx].sample(rng);
    });
  }

  /// Samples a 2-tuple from [a] then [b] (Dart record).
  static Gen<(A, B)> tuple2<A, B>(Gen<A> a, Gen<B> b) =>
      Gen((rng) => (a.sample(rng), b.sample(rng)));

  /// Samples a 3-tuple left to right (Dart record).
  static Gen<(A, B, C)> tuple3<A, B, C>(Gen<A> a, Gen<B> b, Gen<C> c) =>
      Gen((rng) => (a.sample(rng), b.sample(rng), c.sample(rng)));
}

// ─── Property Verification Options & Runner ─────────────────────────────────

/// Options for [checkProperty] / [assertProperty].
class PbtOptions {
  /// Candidates per run (default 100).
  final int numTests;

  /// Run seed (default 42).
  final BigInt seed;

  /// Filter retries (carried for harness parity; filters take their own).
  final int maxRetries;

  /// Shrink step budget (default 1000).
  final int maxShrinkSteps;

  /// Redact witnesses to repro digests. Null auto-detects from `--define=CI`.
  final bool? isCI;

  /// Creates options with documented defaults.
  PbtOptions({
    this.numTests = 100,
    this.maxRetries = 100,
    this.maxShrinkSteps = 1000,
    this.isCI,
    BigInt? seed,
  }) : seed = seed ?? BigInt.from(42);
}

String _safeStringify(Object? val) {
  try {
    return jsonEncode(val, toEncodable: (v) {
      if (v is BigInt) return v.toString();
      if (v is Uint8List) return v.toList();
      return v.toString();
    });
  } catch (_) {
    return '$val';
  }
}

/// Runs [prop] over [numTests] candidates from [seed], shrinking failures.
///
/// Sampling exceptions become `property-exhausted`, property exceptions
/// become `property-panic`, and falsifications become
/// `property-counterexample` (with CI redaction when [PbtOptions.isCI] or
/// `--define=CI=true` applies).
Verdict checkProperty<T>(
  BigInt seed,
  PbtOptions options,
  T Function(SplitMix64 rng) genSample,
  bool Function(T val) prop, [
  (T, int) Function(T val, bool Function(T v) prop, int maxSteps)? shrink,
]) {
  final rng = SplitMix64(seed);
  final numTests = options.numTests;
  const envCI = bool.fromEnvironment('CI', defaultValue: false);
  final isCI = options.isCI ?? envCI;

  for (var iteration = 1; iteration <= numTests; iteration++) {
    late final T candidate;
    try {
      candidate = genSample(rng);
    } on ExhaustedError {
      return Fail(
        fidExhausted,
        'filter precondition rejected all candidates at iteration $iteration',
      );
    } catch (err) {
      return Fail(
        fidExhausted,
        'generator error at iteration $iteration: $err',
      );
    }

    late final bool pass;
    try {
      pass = prop(candidate);
    } catch (err) {
      return Fail(
        fidPanic,
        'property evaluation panicked at iteration $iteration: $err',
      );
    }

    if (!pass) {
      var minimal = candidate;
      var steps = 0;
      if (shrink != null) {
        try {
          final result = shrink(candidate, prop, options.maxShrinkSteps);
          minimal = result.$1;
          steps = result.$2;
        } catch (_) {
          // Shrink error fallback: report the unshrunk candidate.
        }
      }

      if (isCI) {
        final reproStr =
            'iter:$iteration;steps:$steps;shrunk:${_safeStringify(minimal)}';
        final digest = fnv1a64(Uint8List.fromList(utf8.encode(reproStr)));
        return Fail(
          fidCounterexample,
          'property falsified after $iteration iterations '
          '(shrunk in $steps steps, repro-fnv: '
          '${digest.toRadixString(16).padLeft(16, '0')})',
        );
      }

      return Fail(
        fidCounterexample,
        'property falsified at iteration $iteration: '
        'initial=${_safeStringify(candidate)}, '
        'minimal=${_safeStringify(minimal)} after $steps shrink steps',
      );
    }
  }

  return const Pass();
}

/// Thrown by [assertProperty] when a property run fails.
class PbtFailure implements Exception {
  /// Closed failure id of the verdict.
  final String failureId;

  /// The verdict message (possibly CI-redacted).
  final String message;
  const PbtFailure(this.failureId, this.message);
  @override
  String toString() => '[$failureId] $message';
}

/// Runs [prop] over [gen] and throws [PbtFailure] on failure.
void assertProperty<T>(
  Gen<T> gen,
  bool Function(T val) prop, [
  PbtOptions? options,
]) {
  final opts = options ?? PbtOptions();
  final verdict = checkProperty(
    opts.seed,
    opts,
    (rng) => gen.sample(rng),
    prop,
  );

  if (verdict is Fail) {
    throw PbtFailure(verdict.failureId, verdict.message);
  }
}
