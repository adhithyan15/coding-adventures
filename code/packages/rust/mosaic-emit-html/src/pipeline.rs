        a.part_name = None;
        let b = node_with_props("Text", vec![prop_string("content", "BBB")]);
        let c = node("Divider");
        root.children = vec![a, b, c];

        let result = from_pipeline(
            &component("Nest", vec![]),
            &layout("Nest", root),
            &empty_style("Nest"),
        )
        .expect("emit ok");

