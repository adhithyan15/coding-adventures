<!-- hl-knowledge: introduces=[]; assesses=[AR-CONCEPT-C07-ASIF-01, AR-CULTURE-SHUKRAN-22, AR-SCRIPT-SHIN-KAF-20, AR-CONCEPT-C06-MIN-FADLIK-02] -->

