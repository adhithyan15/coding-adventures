//! # mosaic-emit-swiftui — SwiftUI backend for the Mosaic three-language pipeline.
//!
//! This crate is the SwiftUI backend for the Mosaic UI compiler (UI28 WB4).
//! It consumes the three-file pipeline output produced by
//! [`mosmodel-compiler`], [`moslayout-compiler`], and [`mosstyle-compiler`]
//! and produces a `.swift` source string containing a SwiftUI `View` struct.
//!
//! ## Why a separate crate?
//!
//! SwiftUI's declarative tree, its property-driven re-rendering model, and its
//! struct-based component shape map fairly directly onto the Mosaic three-file
//! IR — but the *syntax* is foreign enough that grafting a Swift codegen path
//! into the React backend would dilute both. The same separation already
//! exists for `mosaic-emit-react`, `mosaic-emit-html`, `mosaic-emit-webcomponent`,
//! and `mosaic-emit-paint`; this crate is the SwiftUI peer.
//!
//! ## Output file shape
//!
//! For a component named `ProfileCard` with slots `display-name: text`,
//! `avatar-url: image`, and emits `onTap`, this crate emits:
//!
//! ```swift
//! // Auto-generated by mosaic-emit-swiftui. Do not edit.
//! import SwiftUI
//!
//! enum ProfileCardEvent {
//!     case tap
//! }
//!
//! struct ProfileCardView: View {
//!     let displayName: String
//!     let avatarUrl: String
//!     let dispatch: (ProfileCardEvent) -> Void
//!
//!     var body: some View {
//!         VStack {
//!             Text(displayName)
//!         }
//!     }
//! }
//! ```
//!
//! Three things to notice in the output:
//!
//! 1. The **event enum** comes first, after the SwiftUI import — one case per
//!    declared emit, with the `on` prefix stripped and the rest lower-camelCased
//!    (mirroring the React event-union variant `type` field).
//! 2. The **`View` struct** lists slots as `let` properties first (all
//!    camelCased) and ends with a single required `dispatch` closure
//!    property. This is the SwiftUI analog of the React UI24 promise.
//! 3. The **`body` computed property** walks the moslayout tree.
//! 4. A part with UI15's built-in `state hover` is wrapped in a local native
//!    hover-state view. Each wrapper instance owns its own `@State`, so
//!    repeated `ForEach` content does not share pointer state.
//!
//! ## Primitive coverage in this first cut
//!
//! | mosmodel tag | SwiftUI lowering                                   |
//! |--------------|----------------------------------------------------|
//! | Box          | `Group { ... }`                                    |
//! | Row          | `HStack { ... }`                                   |
//! | Column       | `VStack { ... }`  (see TODO below)                 |
//! | Text         | `Text("...")` or `Text(slotName)`                  |
//! | Spacer       | `Spacer()`                                         |
//! | Image        | `Image(systemName: "...")` placeholder             |
//! | Divider      | `Divider()`                                        |
//! | Stack        | `ZStack { ... }` *(v0.2.0; UI29 kernel)*           |
//! | HostScroll   | `ScrollView { ... }` *(v0.2.0; UI29 kernel)*       |
//! | HostInput    | `TextField(placeholder, text: .constant(value))`   |
//! | HostButton   | `Button(action: { dispatch(.tap) }) { Text(label) }` |
//! | HostSurface  | Host-supplied `AnyView` from a `node` slot          |
//! | HostTable    | `VStack(alignment: .leading, spacing: 0) { HStack { ... } }` |
//! | HostDialog   | `Color.clear.frame(...).sheet(isPresented:)` *(v0.5.0; UI29-1 kernel)* |
//!
//! `HostDialog` lowers to an invisible `Color.clear` anchor view
//! carrying a `.sheet(...)` (modal=true, default) or `.popover(...)`
//! (modal=false) view modifier. SwiftUI exposes dialogs as view
//! modifiers, not standalone views; anchoring on `Color.clear` lets
//! `HostDialog` remain a single tree-walker node. See
//! `pipeline::emit_host_dialog` for the full prop→modifier mapping.
//!
//! `HostTable` lowers to a `VStack` of `HStack` rows rather than
//! SwiftUI's data-driven `Table` view: the data-driven form needs a
//! row-shape that the IR does not yet carry. See the per-function doc
//! comment on `pipeline::emit_host_table` for the full rationale. The
//! Legacy primitives (`Icon`, `Grid` v2) still return `UnknownPrimitive`
//! and will land in their own follow-up PRs. `Cell` +
//! `Column`-as-metadata + `Grid` v3
//! from UI28 §2 are deliberately deferred — the `Column` primitive in
//! this PR still maps to `VStack` (i.e. UI14 `Column`, not UI28
//! `Column`-metadata).
//!
//! ## TODO — UI28 §2.2 conflict
//!
//! Per UI28 §2.2, `Column` is being repurposed as Grid-metadata: it carries
//! a header label, a sort key, a width, and the per-cell template — and is
//! discarded as a SwiftUI view (its data becomes a `TableColumn(...)`
//! definition inside a `Table { ... }`). This first cut keeps the legacy
//! `Column → VStack` lowering so existing UI14 demos still compile; the
//! UI28 Cell/Column/Grid v3 SwiftUI lowering (per spec §4.4) will be a
//! separate follow-up PR.

