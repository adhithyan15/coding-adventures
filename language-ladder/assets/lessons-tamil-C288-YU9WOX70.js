<!-- hl-knowledge: introduces=[]; assesses=[TA-LEX-C72-FEEL-01, TA-LEX-C72-FEEL-02, TA-LEX-C49-COURTESY-03, TA-LEX-DATIVE-SUBJECT-01, TA-LEX-C285-IRAM-01] -->

