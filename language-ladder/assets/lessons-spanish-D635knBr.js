<!-- hl-knowledge: introduces=[ES-GRAMMAR-ER-IR-PRETERITE-CONVERGENCE]; assesses=[ES-GRAMMAR-ER-PRETERITE-SINGULAR, ES-GRAMMAR-IR-PRETERITE-SINGULAR, ES-ORTHOGRAPHY-ER-IR-PRETERITE-FINAL-STRESS] -->

