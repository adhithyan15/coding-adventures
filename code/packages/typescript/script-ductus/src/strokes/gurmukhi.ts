/** The cited source a letter's own inventory row records — one source of truth. */
const gurmukhiLetterSource = (glyph: string): StrokeSource => {
  const letter = gurmukhi.letters.find((candidate) => candidate.glyph === glyph);
  if (!letter || !("strokeOrderSource" in letter) || !letter.strokeOrderSource) {
    throw new Error(`Gurmukhi ${glyph} has no verified source`);
  }
  return letter.strokeOrderSource;
};

