<!-- hl-knowledge: introduces=[MW-GRAMMAR-C160-PAST-YO-01]; assesses=[MW-LEX-C52-VERBS52-03, MW-LEX-C52-VERBS52-01, MW-LEX-C52-VERBS52-04, MW-LEX-C110-ACT110-03] -->

