<!-- hl-knowledge: introduces=[]; assesses=[AR-CONCEPT-C23-AFWAN-02, AR-CONCEPT-C24-ILA-AL-GHAD-02, AR-CONCEPT-C27-TUSBIH-ALA-KHAYR-02, AR-CONCEPT-W10-AYN-02] -->

