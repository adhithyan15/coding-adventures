//! `UI11` (`window-core`) to Flash `Stage` input & lifecycle dispatch bridge (`SWF07`).

#![forbid(unsafe_code)]

use flash_display_list::{DisplayListEvent, Stage};
use window_core::{ElementState, Key, ModifiersState, NamedKey, PointerButton, WindowEvent};

use crate::error::{PlayerHostError, MAX_STAGE_DIM_PX};

/// Maximum simultaneously tracked pressed character keys (CWE-400 guard).
pub const MAX_TRACKED_KEYS: usize = 32;

/// Deterministic keyboard state tracking `UI11` key transitions for the Flash host.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct KeyboardState {
    modifiers: ModifiersState,
    pressed_named: Vec<NamedKey>,
    pressed_chars: Vec<String>,
    last_key_code: u32,
}

impl KeyboardState {
    /// Creates an empty keyboard state.
    pub fn kbd_empty() -> Self {
        Self::default()
    }

    /// Returns the active modifier state.
    #[inline]
    pub fn kbd_modifiers(&self) -> ModifiersState {
        self.modifiers
    }

    /// Returns the Flash/AVM virtual key code of the most recently pressed key.
    #[inline]
    pub fn kbd_last_key_code(&self) -> u32 {
        self.last_key_code
    }

    /// Returns `true` if the given named key is currently depressed.
    pub fn kbd_is_named_down(&self, key: &NamedKey) -> bool {
        self.pressed_named.contains(key)
    }

    /// Returns `true` if the given character key string is currently depressed.
    pub fn kbd_is_char_down(&self, ch: &str) -> bool {
        self.pressed_chars.iter().any(|c| c == ch)
    }

    /// Clears all pressed keys and modifier flags (e.g. on focus loss).
    pub fn kbd_clear(&mut self) {
        self.modifiers = ModifiersState::default();
        self.pressed_named.clear();
        self.pressed_chars.clear();
    }

    /// Applies a normalized `UI11` key transition.
    pub fn kbd_apply_key_event(
        &mut self,
        key: &Key,
        state: ElementState,
        modifiers: ModifiersState,
    ) {
        self.modifiers = modifiers;
        match state {
            ElementState::Pressed => {
                self.last_key_code = key_to_flash_code(key);
                match key {
                    Key::Named(nk) => {
                        if !self.pressed_named.contains(nk)
                            && self.pressed_named.len() < MAX_TRACKED_KEYS
                        {
                            self.pressed_named.push(nk.clone());
                        }
                    }
                    Key::Character(s) => {
                        if !self.pressed_chars.iter().any(|c| c == s)
                            && self.pressed_chars.len() < MAX_TRACKED_KEYS
                        {
                            self.pressed_chars.push(s.clone());
                        }
                    }
                }
            }
            ElementState::Released => match key {
                Key::Named(nk) => {
                    self.pressed_named.retain(|k| k != nk);
                }
                Key::Character(s) => {
                    self.pressed_chars.retain(|c| c != s);
                }
            },
        }
    }
}

/// Outcome produced by dispatching a single `window_core::WindowEvent`.
#[derive(Debug, Clone, PartialEq)]
pub struct HostInputDispatchResult {
    /// Display-list events generated by `Stage` hit-testing and pointer tracking.
    pub display_events: Vec<DisplayListEvent>,
    /// Whether the window backend signaled `CloseRequested` or `Destroyed`.
    pub close_requested: bool,
    /// Whether the window backend signaled `RedrawRequested` or `Resized`.
    pub redraw_requested: bool,
}

/// Maps a `window_core::Key` to a standard Flash virtual key code.
pub fn key_to_flash_code(key: &Key) -> u32 {
    match key {
        Key::Named(NamedKey::Backspace) => 8,
        Key::Named(NamedKey::Tab) => 9,
        Key::Named(NamedKey::Enter) => 13,
        Key::Named(NamedKey::Escape) => 27,
        Key::Named(NamedKey::Space) => 32,
        Key::Named(NamedKey::PageUp) => 33,
        Key::Named(NamedKey::PageDown) => 34,
        Key::Named(NamedKey::End) => 35,
        Key::Named(NamedKey::Home) => 36,
        Key::Named(NamedKey::ArrowLeft) => 37,
        Key::Named(NamedKey::ArrowUp) => 38,
        Key::Named(NamedKey::ArrowRight) => 39,
        Key::Named(NamedKey::ArrowDown) => 40,
        Key::Character(s) => s
            .chars()
            .next()
            .map(|c| c.to_ascii_uppercase() as u32)
            .unwrap_or(0),
    }
}

/// Dispatches a `UI11` (`window_core::WindowEvent`) into `Stage` and [`KeyboardState`].
pub fn dispatch_window_event_to_stage(
    stage: &mut Stage,
    keyboard: &mut KeyboardState,
    event: &WindowEvent,
) -> Result<HostInputDispatchResult, PlayerHostError> {
    let mut display_events = Vec::new();
    let mut close_requested = false;
    let mut redraw_requested = false;

    match event {
        WindowEvent::PointerMoved { x, y, .. } => {
            if !x.is_finite() || !y.is_finite() || x.abs() > 1.0e9 || y.abs() > 1.0e9 {
                return Err(PlayerHostError::NonFiniteCoordinate);
            }
            display_events = stage.stage_handle_mouse_move(*x, *y);
        }
        WindowEvent::PointerButton {
            button: PointerButton::Primary,
            state: ElementState::Pressed,
            ..
        } => {
            display_events = stage.stage_handle_mouse_down();
        }
        WindowEvent::PointerButton {
            button: PointerButton::Primary,
            state: ElementState::Released,
            ..
        } => {
            display_events = stage.stage_handle_mouse_up();
        }
        WindowEvent::Key {
            key,
            state,
            modifiers,
            ..
        } => {
            keyboard.kbd_apply_key_event(key, *state, *modifiers);
        }
        WindowEvent::FocusChanged { focused, .. } => {
            if !focused {
                keyboard.kbd_clear();
            }
        }
        WindowEvent::Resized { logical_size, .. } => {
            if !logical_size.width.is_finite()
                || !logical_size.height.is_finite()
                || logical_size.width < 1.0
                || logical_size.width > MAX_STAGE_DIM_PX as f64
                || logical_size.height < 1.0
                || logical_size.height > MAX_STAGE_DIM_PX as f64
            {
                return Err(PlayerHostError::InvalidStageDimension);
            }
            stage.stage_set_dimensions(logical_size.width, logical_size.height);
            redraw_requested = true;
        }
        WindowEvent::RedrawRequested { .. } => {
            redraw_requested = true;
        }
        WindowEvent::CloseRequested { .. } | WindowEvent::Destroyed { .. } => {
            close_requested = true;
        }
        WindowEvent::Created { .. }
        | WindowEvent::VisibilityChanged { .. }
        | WindowEvent::PointerButton { .. }
        | WindowEvent::Scroll { .. }
        | WindowEvent::TextInput { .. } => {}
    }

    Ok(HostInputDispatchResult {
        display_events,
        close_requested,
        redraw_requested,
    })
}
