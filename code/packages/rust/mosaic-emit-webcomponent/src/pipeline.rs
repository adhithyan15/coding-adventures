/// The result of compiling a three-file pipeline triple to a Custom
/// Element JavaScript source file.
///
/// Mirrors [`mosaic_emit_react::pipeline::PipelineEmitResult`] /
/// [`mosaic_emit_qt::pipeline::PipelineEmitResult`] so the
/// `mosaic-compile` CLI can treat all pipeline backends uniformly.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PipelineEmitResult {
    /// The complete JavaScript source — class definition plus the
    /// trailing `customElements.define(...)` call.
    pub output: String,
    /// The component's PascalCase name (matches the source `.mil` /
    /// `.mll` files). Unprefixed; the emitted class uses `Mos` + this.
    pub component_name: String,
}

/// Errors the Web Components pipeline emitter can return.
///
/// Diagnostic strings rather than rich values so the calling CLI can
/// print them verbatim. The offending name is embedded in the message
/// so callers do not need to plumb additional context.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PipelineEmitError {
    /// The mosmodel component name and the moslayout component name
    /// disagree. Almost always a manifest authoring error.
    ComponentNameMismatch {
        mosmodel: String,
        moslayout: String,
    },
    /// A slot name fails the safe-JS-identifier check after camelCase
    /// conversion. The mosmodel grammar restricts slot names to
    /// kebab-case `[a-z][a-z0-9]*(-[a-z][a-z0-9]*)*`, so this should
    /// never fire in practice — it is defense-in-depth in case of
    /// direct IR construction that bypasses the grammar.
    UnsafeSlotName(String),
    /// An emit name fails the same safe-identifier check after
    /// stripping the `on` prefix and lowering the first letter.
    UnsafeEmitName(String),
    /// A moslayout primitive tag is not recognised by this backend.
    /// See the primitive lowering table at the top of this module for
    /// the supported set; UI29 kernel primitives are a separate PR.
    UnknownPrimitive(String),
}

impl std::fmt::Display for PipelineEmitError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            PipelineEmitError::ComponentNameMismatch { mosmodel, moslayout } => write!(
                f,
                "component name mismatch: mosmodel says '{mosmodel}', moslayout says '{moslayout}'"
            ),
            PipelineEmitError::UnsafeSlotName(n) => {
                write!(f, "unsafe slot name '{n}' (post camelCase conversion)")
            }
            PipelineEmitError::UnsafeEmitName(n) => {
                write!(f, "unsafe emit name '{n}' (post conversion)")
            }
            PipelineEmitError::UnknownPrimitive(t) => write!(
                f,
                "moslayout primitive '{t}' is not yet supported by the pipeline Web Components emitter"
            ),
        }
    }
}

impl std::error::Error for PipelineEmitError {}

/// Compile a three-file Mosaic pipeline triple to a Custom Element
/// JavaScript source file.
///
/// This is the new (UI24-compliant) Web Components backend entry point.
/// It supersedes the [`crate::WebComponentRenderer`] +
/// [`mosaic_vm::MosaicVM`] flow for code paths that author components
/// in the three-language form.
///
/// The `style` argument is accepted now (rather than added later) so
/// downstream callers can build against the stable signature. Style
/// inlining is deferred — see the module-level "What is NOT in this
/// first pass" section.
pub fn from_pipeline(
    interface: &MosmodelComponent,
    layout: &LayoutDef,
    _style: &StyleDef,
) -> Result<PipelineEmitResult, PipelineEmitError> {
    // 1. Sanity check: the three IRs must agree on the component name.
    //    Style is allowed to differ when targeting a variant (UI23 §4);
    //    no constraint on style names here.
    if interface.component != layout.component_name {
        return Err(PipelineEmitError::ComponentNameMismatch {
            mosmodel: interface.component.clone(),
            moslayout: layout.component_name.clone(),
        });
    }

    let component_name = &interface.component;
    let class_name = format!("Mos{component_name}");
    let custom_tag = format!("mos-{}", to_kebab_case(component_name));

    let mut out = String::new();

    // 2. File header.
    writeln!(
        out,
        "// Auto-generated by mosaic-emit-webcomponent (pipeline path). Do not edit."
    )
    .unwrap();
    writeln!(out).unwrap();

    // 3. Class opener.
    writeln!(out, "class {class_name} extends HTMLElement {{").unwrap();

    // 4. observedAttributes — one entry per slot in kebab-case (the form
    //    HTML uses on attribute writes). Validate each slot name on
    //    BOTH the raw kebab form (which gets embedded as an HTML
    //    attribute string and into `getAttribute("...")`) and the
    //    camelCase form (which becomes a JS identifier in `_render`).
    //    The mosmodel grammar already restricts slot names to the
    //    kebab shape; this is defense-in-depth.
    for slot in &interface.slots {
        if !is_kebab_identifier(&slot.name) {
            return Err(PipelineEmitError::UnsafeSlotName(slot.name.clone()));
        }
        let camel = to_camel_case_first_lower(&slot.name);
        validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
    }
    out.push_str(&emit_observed_attributes(&interface.slots));

    // 5. constructor — attach the shadow root. No state setup needed
    //    because attributes are read on every render (the trade-off is
    //    simplicity now; per-attribute caching is a later optimisation).
    writeln!(out, "  constructor() {{").unwrap();
    writeln!(out, "    super();").unwrap();
    writeln!(out, "    this.attachShadow({{ mode: \"open\" }});").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    // 6. Lifecycle: render on connect and on any attribute change.
    writeln!(out, "  connectedCallback() {{ this._render(); }}").unwrap();
    writeln!(
        out,
        "  attributeChangedCallback(_name, _oldVal, _newVal) {{ this._render(); }}"
    )
    .unwrap();
    writeln!(out).unwrap();

    // 7. _render — read slot attributes into locals, set shadowRoot.innerHTML.
    out.push_str(&emit_render(&interface.slots, &layout.root)?);
    writeln!(out).unwrap();

    // 8. dispatch — UI24 Flux entry point. Wraps the event payload in a
    //    `CustomEvent` named `mosaic:<type>` that crosses the shadow
    //    boundary.
    writeln!(out, "  dispatch(event) {{").unwrap();
    writeln!(
        out,
        "    this.dispatchEvent(new CustomEvent(\"mosaic:\" + event.type, {{ detail: event, bubbles: true, composed: true }}));"
    )
    .unwrap();
    writeln!(out, "  }}").unwrap();

    // 9. One signal-like instance method per declared emit.
    for emit in &interface.emits {
        writeln!(out).unwrap();
        out.push_str(&emit_signal_method(emit)?);
    }

    // 10. Class closer.
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // 11. Registration. Each component is registered exactly once at
    //     module-load time; redefinition throws, so authors who load the
    //     same component twice get a clear runtime error rather than a
    //     silent overwrite.
    writeln!(
        out,
        "customElements.define(\"{custom_tag}\", {class_name});"
    )
    .unwrap();

    Ok(PipelineEmitResult {
        output: out,
        component_name: component_name.clone(),
    })
}

// =====================================================================
// Section emitters
// =====================================================================

/// Emit the `static get observedAttributes()` block.
///
/// Returns a fixed-shape JS array literal containing one entry per slot,
/// each in kebab-case. When there are no slots, returns `return [];`.
/// The whitespace shape matches the surrounding class (2-space indent
/// per level — the standard for JS class bodies in modern codebases).
fn emit_observed_attributes(slots: &[SlotDecl]) -> String {
    let mut out = String::new();
    writeln!(out, "  static get observedAttributes() {{").unwrap();
    if slots.is_empty() {
        writeln!(out, "    return [];").unwrap();
    } else {
        let names: Vec<String> = slots
            .iter()
            // mosmodel slot names are already kebab-case; copy verbatim.
            .map(|s| format!("\"{}\"", s.name))
            .collect();
        writeln!(out, "    return [{}];", names.join(", ")).unwrap();
    }
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    out
}

/// Emit the `_render()` method.
///
/// Two parts:
///
/// 1. `const <camel> = this.getAttribute("<kebab>") ?? "";` for every
///    slot — read once into a local so the template literal can
///    interpolate `${var}` directly. `??` (nullish coalescing) gives an
///    empty string default which is the right default for `text` slots;
///    `number` / `bool` slots will need coercion in a follow-up but the
///    string fallback is harmless because primitive HTML output is
///    string-based.
/// 2. `this.shadowRoot.innerHTML = \`<html-tree>\`;` where `<html-tree>`
///    is the result of walking the moslayout root via [`emit_html_tree`].
fn emit_render(
    slots: &[SlotDecl],
    layout_root: &LayoutNode,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "  _render() {{").unwrap();

    for slot in slots {
        let camel = to_camel_case_first_lower(&slot.name);
        validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
        writeln!(
            out,
            "    const {camel} = this.getAttribute(\"{}\") ?? \"\";",
            slot.name
        )
        .unwrap();
    }

    // The HTML walker also accumulates "post-render" snippets — small
    // imperative bits of JS that need to run after `innerHTML` is set
    // so that elements referenced by `id` exist in the shadow tree.
    // HostDialog (U29-1) is the first primitive to need this: the
    // `<dialog>` element is in the markup, but `showModal()` / `close()`
    // and a `close`-event listener must be attached after the tree is
    // live. Every `HostDialog` occurrence gets a unique id of the form
    // `mos-dlg-N` so the post-script can `getElementById` it.
    let mut ctx = RenderCtx::default();
    let html = emit_html_tree(layout_root, 0, &mut ctx)?;
    // The HTML tree is one flat string for now (no per-line indentation
    // inside the template literal — keeps the output compact and avoids
    // surprising whitespace inside `<span>` and `<div>` text content).
    writeln!(out, "    this.shadowRoot.innerHTML = `{html}`;").unwrap();
    for line in ctx.post_script_lines {
        writeln!(out, "    {line}").unwrap();
    }
    writeln!(out, "  }}").unwrap();
    Ok(out)
}

/// Emit one signal-like instance method for an emit declaration.
///
/// `onClick` → `onClick(...) { this.dispatch({ type: "click" }); }`.
/// `onNavigate(row, col)` →
/// `onNavigate(row, col) { this.dispatch({ type: "navigate", row, col }); }`.
///
/// The leading `on` is stripped from the dispatched event `type` field
/// (UI24 §5), but the method itself keeps the source `onFoo` form so
/// JS callers reading the class API see the same names they wrote in
/// the `.mil` file.
fn emit_signal_method(emit: &EmitDecl) -> Result<String, PipelineEmitError> {
    let lowered = strip_on_prefix(&emit.name);
    let type_field = to_camel_case_first_lower(&lowered);
    validate_safe_identifier(&type_field).map_err(PipelineEmitError::UnsafeEmitName)?;

    let method_name = if is_safe_identifier(&emit.name) {
        emit.name.clone()
    } else {
        // Fall back to the lowered form if the source name (e.g. has
        // unusual characters) isn't a safe identifier. The grammar
        // already forbids that, so this branch is defensive.
        type_field.clone()
    };

    // Build the comma-separated param list and matching payload-field
    // forwards. Each param name is kebab → camel for both positions.
    let mut params: Vec<String> = Vec::new();
    let mut fields: Vec<String> = Vec::new();
    for p in &emit.params {
        let field = to_camel_case_first_lower(&p.name);
        validate_safe_identifier(&field).map_err(PipelineEmitError::UnsafeSlotName)?;
        params.push(field.clone());
        // `{ row, col }` shorthand object literal form — the value
        // identifier is the same as the field name, so we lean on JS
        // object shorthand to keep the emitted code compact.
        fields.push(field);
        // EmitPayloadType is irrelevant to the JS plumbing (JS is
        // untyped at runtime); we keep the param ordering only.
        let _: &EmitPayloadType = &p.r#type;
    }

    let mut out = String::new();
    if fields.is_empty() {
        writeln!(out, "  {method_name}() {{").unwrap();
        writeln!(
            out,
            "    this.dispatch({{ type: \"{type_field}\" }});"
        )
        .unwrap();
    } else {
        writeln!(out, "  {method_name}({}) {{", params.join(", ")).unwrap();
        writeln!(
            out,
            "    this.dispatch({{ type: \"{type_field}\", {} }});",
            fields.join(", ")
        )
        .unwrap();
    }
    writeln!(out, "  }}").unwrap();
    Ok(out)
}

// =====================================================================
// HTML tree walker
// =====================================================================

/// Walk a `LayoutNode` and produce a flat HTML string for embedding in
/// the `_render()` template literal.
///
/// Each primitive lowers per the table at the top of this module. The
/// recursion is depth-first: child nodes are concatenated inside the
/// parent's open/close tag with no extra whitespace.
///
/// **Indentation**: the `_depth` parameter is currently unused — the
/// emitted HTML is one flat line so the `_render()` body stays a single
/// template-literal expression. (Browsers don't care about pretty
/// HTML inside a Shadow DOM; debug tooling shows the parsed tree
/// regardless.) The parameter is kept for symmetry with the React /
/// Qt / SwiftUI walkers and to leave a clear hook for a future
/// pretty-printer.
fn emit_html_tree(
    node: &LayoutNode,
    _depth: usize,
    ctx: &mut RenderCtx,
) -> Result<String, PipelineEmitError> {
    // -----------------------------------------------------------------
    // UI29 kernel — dedicated emitters first.
    //
    // Each of these primitives needs more than `primitive_to_html_tag`
    // can express (slot wiring on attributes, sub-tag row synthesis,
    // template-literal control-flow). They short-circuit before the
    // generic open/close walker below.
    // -----------------------------------------------------------------
    match node.tag.as_str() {
        "HostInput" => return Ok(emit_host_input(node)),
        "HostButton" => return Ok(emit_host_button(node)),
        "HostDialog" => return emit_host_dialog(node, ctx),
        "If" => return emit_if(node, None, ctx),
        "For" => return emit_for(node, ctx),
        // `Else` appearing as a top-level walker target means it was NOT
        // consumed by a preceding `If` (orphan). Validation in
        // moslayout-compiler already rejects this case; here we render
        // an empty string so the emitted JS is still well-formed.
        "Else" => return Ok(String::new()),
        _ => {}
    }

    let HtmlTag {
        open,
        close,
        self_closing,
    } = primitive_to_html_tag(&node.tag)?;

    // Build any emit-driven attributes (per UI24 connects wiring) onto
    // the open tag. For leaf primitives this is what wires
    // `onclick="this.dispatch({type:'click'})"` into the DOM.
    let mut open_with_attrs = open;
    let event_attrs = build_event_attributes(node);
    if !event_attrs.is_empty() {
        // Insert event attrs immediately before the closing `>` of the
        // opening tag.
        open_with_attrs = insert_attrs_before_close(&open_with_attrs, &event_attrs);
    }

    if self_closing {
        return Ok(open_with_attrs);
    }

    // HostTable section tags (HostTableHead/Body/Foot) synthesise a
    // single `<tr>` row inside their wrapper, mapping each direct child
    // to a `<th>` or `<td>` cell.
    if matches!(
        node.tag.as_str(),
        "HostTableHead" | "HostTableBody" | "HostTableFoot"
    ) {
        let cell_tag = if node.tag == "HostTableHead" { "th" } else { "td" };
        let mut inner = String::from("<tr>");
        for child in &node.children {
            inner.push_str(&format!("<{cell_tag}>"));
            inner.push_str(&emit_html_tree(child, _depth + 1, ctx)?);
            inner.push_str(&format!("</{cell_tag}>"));
        }
        inner.push_str("</tr>");
        return Ok(format!("{open_with_attrs}{inner}{close}"));
    }

    // Detect a Text-like leaf: a node with no children but a `content`
    // prop. Lower it to `<span>${slotName}</span>` for slot refs and
    // `<span>literal</span>` for string literals.
    if node.children.is_empty() {
        if let Some(text) = build_text_content(node) {
            return Ok(format!("{open_with_attrs}{text}{close}"));
        }
        return Ok(format!("{open_with_attrs}{close}"));
    }

    // Container with children — render children in source order with no
    // separator. `If` children consume an immediately-following `Else`
    // sibling so the pair lowers to a single ternary in the output.
    let mut inner = String::new();
    let mut i = 0;
    while i < node.children.len() {
        let child = &node.children[i];
        if child.tag == "If" {
            // Look ahead for a paired `Else` sibling.
            let else_node = node.children.get(i + 1).filter(|n| n.tag == "Else");
            inner.push_str(&emit_if(child, else_node, ctx)?);
            i += if else_node.is_some() { 2 } else { 1 };
            continue;
        }
        inner.push_str(&emit_html_tree(child, _depth + 1, ctx)?);
        i += 1;
    }
    Ok(format!("{open_with_attrs}{inner}{close}"))
}

// =====================================================================
// UI29 kernel — dedicated emitters
// =====================================================================

/// Walk an `If`'s (or `Else`'s) children to produce the HTML fragment
/// that fills one branch of the ternary. Children are concatenated
/// inline with the same rules as a container body, except no outer
/// open/close tag is emitted.
fn emit_branch_children(
    parent: &LayoutNode,
    ctx: &mut RenderCtx,
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    let mut i = 0;
    while i < parent.children.len() {
        let child = &parent.children[i];
        if child.tag == "If" {
            let else_node = parent.children.get(i + 1).filter(|n| n.tag == "Else");
            out.push_str(&emit_if(child, else_node, ctx)?);
            i += if else_node.is_some() { 2 } else { 1 };
            continue;
        }
        out.push_str(&emit_html_tree(child, 0, ctx)?);
        i += 1;
    }
    Ok(out)
}

/// Lower an `If { ... } [Else { ... }]` pair to a JS template-literal
/// ternary interpolation.
///
/// The output shape is `${(cond) ? `then-html` : `else-html`}` so that
/// it slots cleanly into the surrounding `_render()` template literal.
/// The `Else` is optional — if absent, the false branch emits an empty
/// string literal.
///
/// The `when:` expression is consumed verbatim from the source: a
/// `SlotRef("editing")` becomes the JS identifier `editing` (which is
/// already in scope thanks to the `getAttribute` reads in `_render()`),
/// an `Expr` value is dropped in as-is (the moslayout compiler already
/// reconstructed it as a JS-compatible substring), and a `Keyword` /
/// `Number` / `String` is interpreted as a literal.
fn emit_if(
    if_node: &LayoutNode,
    else_node: Option<&LayoutNode>,
    ctx: &mut RenderCtx,
) -> Result<String, PipelineEmitError> {
    // Pull the `when:` prop. moslayout-compiler's validator already
    // requires this and rejects any other prop name on an `If`; this
    // arm is defensive against direct IR construction.
    let cond = if_node
        .props
        .iter()
        .find(|p| p.name == "when")
        .map(|p| layout_value_to_js_expr(&p.value))
        .unwrap_or_else(|| "false".to_string());

    let then_branch = emit_branch_children(if_node, ctx)?;
    let else_branch = match else_node {
        Some(n) => emit_branch_children(n, ctx)?,
        None => String::new(),
    };

    // Backticks open/close nested template literals inside the outer
    // backticked `_render` string. The JS parser handles arbitrary
    // nesting depth here because each pair of backticks is balanced.
    Ok(format!(
        "${{({cond}) ? `{then_branch}` : `{else_branch}`}}"
    ))
}

/// Lower a `For ( each: ..., as: NAME [, index: NAME] ) { ... }` block
/// to a JS template-literal `.map(...).join('')` interpolation.
///
/// The body children render via [`emit_branch_children`] with the
/// per-iteration bindings (`as:`'s NAME and the optional `index:`'s
/// NAME) in scope as arrow-function parameters. Inside the body, any
/// `Text { content: slot: row }` style reference to the bound name
/// just works because slot interpolation lowers to `${row}` — and
/// `row` is the arrow-function parameter.
fn emit_for(node: &LayoutNode, ctx: &mut RenderCtx) -> Result<String, PipelineEmitError> {
    let mut each_expr = String::from("[]");
    let mut as_name = String::from("item");
    let mut index_name = String::from("idx");

    for prop in &node.props {
        match prop.name.as_str() {
            "each" => each_expr = layout_value_to_js_expr(&prop.value),
            "as" => {
                if let LayoutPropValue::Keyword(k) = &prop.value {
                    let camel = to_camel_case_first_lower(k);
                    if is_safe_identifier(&camel) {
                        as_name = camel;
                    }
                }
            }
            "index" => {
                if let LayoutPropValue::Keyword(k) = &prop.value {
                    let camel = to_camel_case_first_lower(k);
                    if is_safe_identifier(&camel) {
                        index_name = camel;
                    }
                }
            }
            _ => {}
        }
    }

    let body = emit_branch_children(node, ctx)?;
    Ok(format!(
        "${{{each_expr}.map(({as_name}, {index_name}) => `{body}`).join('')}}"
    ))
}

/// Convert a moslayout prop value to the JS expression text suitable
/// for splicing into a `${...}` interpolation. The mapping is:
///
/// | Value                | JS expression                          |
/// |---|---|
/// | `SlotRef("foo")`     | `foo` (camelCased, already in scope from `_render`) |
/// | `Expr("a == b")`     | `a == b` (already a JS-compatible string)           |
/// | `Keyword("true")`    | `true`                                              |
/// | `Number(2.0)`        | `2`                                                 |
/// | `String("hi")`       | `"hi"` (HTML-escape-free; string-literal context)   |
/// | `EmitRef(_)`         | `null` (emits can't appear in expression position)  |
fn layout_value_to_js_expr(v: &LayoutPropValue) -> String {
    match v {
        LayoutPropValue::SlotRef(name) => to_camel_case_first_lower(name),
        LayoutPropValue::Expr(text) => text.clone(),
        LayoutPropValue::Keyword(k) => k.clone(),
        LayoutPropValue::Number(n) => {
            if n.fract() == 0.0 {
                format!("{}", *n as i64)
            } else {
                format!("{n}")
            }
        }
        LayoutPropValue::String(s) => format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")),
        LayoutPropValue::EmitRef(_) => "null".to_string(),
    }
}

/// Lower a `HostInput` node to an `<input type="text" …>` tag inside
/// the shadow DOM.
///
/// The wiring follows the React backend's HostInput surface but adapts
/// to inline-attribute event handlers and template-literal value
/// interpolation:
///
/// - `value: slot: x`     → `value="${x}"`
/// - `placeholder: "..."` → `placeholder="..."`
/// - `read-only: slot: x` → `${x ? 'readonly' : ''}` (template-literal attr presence)
/// - `read-only: true`    → `readonly`
/// - `onChange: emit: onX` → `onchange="this.getRootNode().host.dispatch({type:'x', value:event.target.value})"`
/// - `onCommit: emit: onX` + `onCancel: emit: onY` → merged `onkeydown` handler
///
/// All inline handlers reach the host via `this.getRootNode().host`
/// because in the shadow DOM `this` inside an inline handler is the
/// element where the handler is declared, not the Custom Element.
fn emit_host_input(node: &LayoutNode) -> String {
    let mut attrs = String::from(r#"<input type="text""#);

    // value="${slot}"
    if let Some(slot) = find_slot_ref(node, "value") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            attrs.push_str(&format!(r#" value="${{{camel}}}""#));
        }
    }

    // placeholder="text"
    if let Some(s) = find_string(node, "placeholder") {
        attrs.push_str(&format!(
            r#" placeholder="{}""#,
            escape_html_attribute(s)
        ));
    }

    // readonly attribute — three cases. The kebab-name `read-only` is
    // the moslayout-compiler-emitted form (the React backend uses the
    // same).
    if let Some(slot) = find_slot_ref(node, "read-only") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            // Conditional attribute: emit `readonly` only when the
            // bound slot is truthy. The leading space inside the
            // ternary keeps the surrounding attributes properly
            // separated.
            attrs.push_str(&format!(r#"${{{camel} ? " readonly" : ""}}"#));
        }
    } else if let Some(kw) = find_keyword(node, "read-only") {
        if kw == "true" {
            attrs.push_str(" readonly");
        }
    }

    // onchange — wraps `event.target.value` into the dispatch payload.
    if let Some(emit_name) = find_emit_ref(node, "onChange") {
        let type_field = to_camel_case_first_lower(&strip_on_prefix(emit_name));
        if is_safe_identifier(&type_field) {
            attrs.push_str(&format!(
                r#" onchange="this.getRootNode().host.dispatch({{type:'{type_field}',value:event.target.value}})""#
            ));
        }
    }

    // onkeydown — merges onCommit (Enter) and onCancel (Escape).
    let commit = find_emit_ref(node, "onCommit");
    let cancel = find_emit_ref(node, "onCancel");
    if commit.is_some() || cancel.is_some() {
        let mut body = String::new();
        if let Some(e) = commit {
            let t = to_camel_case_first_lower(&strip_on_prefix(e));
            if is_safe_identifier(&t) {
                body.push_str(&format!(
                    "if(event.key==='Enter')this.getRootNode().host.dispatch({{type:'{t}'}});"
                ));
            }
        }
        if let Some(e) = cancel {
            let t = to_camel_case_first_lower(&strip_on_prefix(e));
            if is_safe_identifier(&t) {
                body.push_str(&format!(
                    "if(event.key==='Escape')this.getRootNode().host.dispatch({{type:'{t}'}});"
                ));
            }
        }
        attrs.push_str(&format!(r#" onkeydown="{body}""#));
    }

    attrs.push_str(" />");
    attrs
}

/// Lower a `HostButton` node to a `<button>` block inside the shadow
/// DOM. The `label:` prop supplies the button's text content; the
/// `onTap:` emit (kernel-canonical) is renamed to the DOM-native
/// `onclick` attribute. Like `HostInput`, the inline handler reaches
/// the Custom Element via `this.getRootNode().host`.
fn emit_host_button(node: &LayoutNode) -> String {
    let mut attrs = String::new();

    // disabled — slot ref → `${slot ? 'disabled' : ''}` attribute
    // presence; literal `true` → bare `disabled`; `false` → omitted.
    if let Some(slot) = find_slot_ref(node, "disabled") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            attrs.push_str(&format!(r#"${{{camel} ? " disabled" : ""}}"#));
        }
    } else if let Some(kw) = find_keyword(node, "disabled") {
        if kw == "true" {
            attrs.push_str(" disabled");
        }
    }

    // onclick — moslayout authors write `onTap:` (platform-neutral
    // kernel name); we rename to the DOM-native `onclick` here.
    if let Some(emit_name) = find_emit_ref(node, "onTap") {
        let type_field = to_camel_case_first_lower(&strip_on_prefix(emit_name));
        if is_safe_identifier(&type_field) {
            attrs.push_str(&format!(
                r#" onclick="this.getRootNode().host.dispatch({{type:'{type_field}'}})""#
            ));
        }
    }

    // Body: label may be a string literal or a slot ref.
    let body = if let Some(s) = find_string(node, "label") {
        escape_html_text(s)
    } else if let Some(slot) = find_slot_ref(node, "label") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            format!("${{{camel}}}")
        } else {
            String::new()
        }
    } else {
        String::new()
    };

    format!("<button{attrs}>{body}</button>")
}

// ---------------------------------------------------------------------
// U29-1 — HostDialog
//
// Unlike the other host primitives, `HostDialog` needs *imperative*
// post-render wiring because `showModal()`/`close()` and the dialog's
// `close` event are not expressible as plain inline attributes:
//
// 1. The `<dialog>` element is emitted into the shadow innerHTML with
//    a unique `id="mos-dlg-N"` so the post-script can find it.
// 2. Each `RenderCtx::next_dialog_id()` call hands out the next index;
//    every emitted dialog gets a distinct id so multiple HostDialogs
//    in the same component don't collide.
// 3. The post-script lines are appended to `_render()` AFTER the
//    `innerHTML` assignment — that's the earliest point at which
//    `shadowRoot.getElementById("mos-dlg-N")` returns a live element.
//
// Slot/keyword mapping (from UI29-1 §2.1 and §3.4):
//
// | Moslayout prop                    | WebComponent lowering                                          |
// |-----------------------------------|----------------------------------------------------------------|
// | `open: slot: x`                   | `this.getAttribute("x") === "true"` drives showModal/close     |
// | `modal: true` (default, keyword)  | `d.showModal()`                                                |
// | `modal: false` (keyword)          | `d.show()`                                                     |
// | `title: slot: x`                  | inject `<h2>${x}</h2>` as the first child of `<dialog>`        |
// | `title: "literal"`                | inject `<h2>literal</h2>`                                      |
// | `dismiss-on-backdrop: false`      | add a `cancel`-event interceptor that `preventDefault()`s      |
// | `onClose: emit: onX`              | `d.addEventListener("close", () => this.dispatch({type:"x"}))` |
// | `onOpen:  emit: onX`              | one-shot `this.dispatch({type:"x"})` immediately after showModal|
//
// The dispatch is `this.dispatch(...)` (not the inline
// `this.getRootNode().host.dispatch(...)` used by HostInput/HostButton)
// because the post-script runs in the Custom Element's own method body
// where `this` *is* the element.
fn emit_host_dialog(
    node: &LayoutNode,
    ctx: &mut RenderCtx,
) -> Result<String, PipelineEmitError> {
    let dlg_idx = ctx.next_dialog_id();
    let dlg_id = format!("mos-dlg-{dlg_idx}");
    // Single per-dialog JS variable name. Suffixed with the index so two
    // dialogs in the same component don't shadow each other.
    let var = format!("_d{dlg_idx}");

    // ----- compile-time keyword: modal -----
    // Default is `true` (modal). Per spec, this is a compile-time choice
    // — the keyword `modal: false` selects `show()` instead of `showModal()`.
    // Default is `true` (modal) when the keyword is absent or any value
    // other than the literal `"false"`. `matches!` keeps the intent
    // direct: "modal unless the author opted out".
    let modal = !matches!(find_keyword(node, "modal"), Some("false"));
    let show_call = if modal { "showModal()" } else { "show()" };

    // ----- compile-time keyword: dismiss-on-backdrop -----
    // Default is `true`. `dismiss-on-backdrop: false` adds a one-line
    // interceptor on the dialog's `cancel` event (`<dialog>` fires
    // `cancel` for Esc and for backdrop dismissal; preventDefault()
    // suppresses the auto-close).
    let dismiss_on_backdrop = !matches!(find_keyword(node, "dismiss-on-backdrop"), Some("false"));

    // ----- slot: open -----
    // The author binds `open: slot: <name>`; on the WebComponent side we
    // read the attribute back as a string and treat `"true"` as truthy.
    // (Custom Element string attributes don't auto-coerce to booleans.)
    let open_js = if let Some(slot) = find_slot_ref(node, "open") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            // The `_render()` body already declares `const <camel> =
            // this.getAttribute(...);` for every observed slot, so the
            // identifier is in scope. We compare strings because Custom
            // Element attributes are always strings.
            Some(format!("({camel} === \"true\")"))
        } else {
            None
        }
    } else if let Some(kw) = find_keyword(node, "open") {
        // Literal compile-time `open: true`/`open: false` keyword.
        Some((kw == "true").to_string())
    } else {
        // No `open:` prop at all — treat as closed by default.
        Some("false".to_string())
    };

    // ----- title — emitted inside the <dialog> markup -----
    // The title is rendered as an `<h2>` first child. Slot refs use the
    // template-literal `${var}` form; string literals are HTML-escaped.
    let title_html = if let Some(slot) = find_slot_ref(node, "title") {
        let camel = to_camel_case_first_lower(slot);
        if is_safe_identifier(&camel) {
            format!("<h2>${{{camel}}}</h2>")
        } else {
            String::new()
        }
    } else if let Some(s) = find_string(node, "title") {
        format!("<h2>{}</h2>", escape_html_text(s))
    } else {
        String::new()
    };

    // ----- children — recursively rendered into the dialog body -----
    // We re-use the standard branch walker so `If`/`Else`/`For` nested
    // inside a dialog body lower correctly.
    let body = emit_branch_children(node, ctx)?;

    // ----- markup -----
    let markup = format!(r#"<dialog id="{dlg_id}">{title_html}{body}</dialog>"#);

    // ----- post-script -----
    // Order matters: grab the element, attach listeners, *then* toggle
    // open. Doing it in that order means the very first `showModal()`
    // call (when `open` is true on the initial render) is already
    // covered by the `close` listener, so author-side `onClose` fires
    // even on the first close.
    ctx.post_script_lines.push(format!(
        "const {var} = this.shadowRoot.getElementById(\"{dlg_id}\");"
    ));

    // onClose listener — wired before showModal/close so we never miss
    // a close event that fires synchronously from a re-render.
    if let Some(emit_name) = find_emit_ref(node, "onClose") {
        let type_field = to_camel_case_first_lower(&strip_on_prefix(emit_name));
        if is_safe_identifier(&type_field) {
            ctx.post_script_lines.push(format!(
                "{var}.addEventListener(\"close\", () => this.dispatch({{type:\"{type_field}\"}}));"
            ));
        }
    }

    // dismiss-on-backdrop: false → suppress the native cancel-driven
    // close. `<dialog>`'s `cancel` event fires for both Esc and a
    // backdrop click on the closed-by-default dialog; `preventDefault()`
    // is the documented way to keep the dialog open.
    if !dismiss_on_backdrop {
        ctx.post_script_lines.push(format!(
            "{var}.addEventListener(\"cancel\", (e) => e.preventDefault());"
        ));
    }

    // open/close lifecycle. Both branches are emitted so flipping the
    // `open` slot from true back to false also drives the dialog
    // closed; without the `else` clause the dialog would latch open
    // after the first `true`.
    let open_expr = open_js.unwrap_or_else(|| "false".to_string());
    ctx.post_script_lines.push(format!(
        "if ({open_expr}) {{ if (!{var}.open) {{ {var}.{show_call}; }} }} else {{ if ({var}.open) {{ {var}.close(); }} }}"
    ));

    // onOpen — one-shot. Fires *after* the show call lands, so authors
    // can observe the transition. We re-check `open` so the dispatch
    // only happens on the open path, not on close.
    if let Some(emit_name) = find_emit_ref(node, "onOpen") {
        let type_field = to_camel_case_first_lower(&strip_on_prefix(emit_name));
        if is_safe_identifier(&type_field) {
            ctx.post_script_lines.push(format!(
                "if ({open_expr}) {{ this.dispatch({{type:\"{type_field}\"}}); }}"
            ));
        }
    }

    Ok(markup)
}

/// Per-render walker context — accumulates post-`innerHTML` JS lines
/// that need to run after the shadow tree is live. Currently the only
/// contributor is `emit_host_dialog`; future imperative primitives
/// (e.g. a `HostCanvas` that needs a `getContext("2d")` call) can
/// reuse the same hook.
#[derive(Default)]
struct RenderCtx {
    /// Monotonic counter — every `HostDialog` claims one id so multiple
    /// dialogs in a single component do not collide on `id="mos-dlg-…"`.
    dialog_count: usize,
    /// One JS statement per line, appended to `_render()` AFTER the
    /// `this.shadowRoot.innerHTML = ...` assignment.
    post_script_lines: Vec<String>,
}

impl RenderCtx {
    fn next_dialog_id(&mut self) -> usize {
        let id = self.dialog_count;
        self.dialog_count += 1;
        id
    }
}

// =====================================================================
// Prop-lookup helpers — find a named prop by its expected value shape.
// Returns `None` if the prop is missing OR has the wrong value variant
// so callers can chain alternatives (e.g. slot-ref first, then keyword
// literal) without a deep match.
// =====================================================================

fn find_slot_ref<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    node.props.iter().find_map(|p| match (&p.name, &p.value) {
        (n, LayoutPropValue::SlotRef(s)) if n == name => Some(s.as_str()),
        _ => None,
    })
}

fn find_string<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    node.props.iter().find_map(|p| match (&p.name, &p.value) {
        (n, LayoutPropValue::String(s)) if n == name => Some(s.as_str()),
        _ => None,
    })
}

fn find_keyword<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    node.props.iter().find_map(|p| match (&p.name, &p.value) {
        (n, LayoutPropValue::Keyword(s)) if n == name => Some(s.as_str()),
        _ => None,
    })
}

fn find_emit_ref<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    node.props.iter().find_map(|p| match (&p.name, &p.value) {
        (n, LayoutPropValue::EmitRef(s)) if n == name => Some(s.as_str()),
        _ => None,
    })
}

/// Escape a string for safe embedding inside a double-quoted HTML
/// attribute value that itself lives inside a JS template literal.
/// Inherits [`escape_html_text`]'s template-literal escaping for
/// backticks and `${`, and adds `"` → `&quot;` for the attribute
/// quoting layer.
fn escape_html_attribute(s: &str) -> String {
    escape_html_text(s).replace('"', "&quot;")
}

/// One primitive's lowering: the open tag, the matching close tag, and
/// whether the element is a void / self-closing HTML element.
struct HtmlTag {
    /// The full opening tag, e.g. `"<div>"` or `"<img>"`.
    open: String,
    /// The closing tag, empty for void elements.
    close: String,
    /// True for HTML void elements that have no closing tag (`<img>`,
    /// `<hr>`).
    self_closing: bool,
}

/// Map a moslayout primitive tag to its HTML decomposition.
///
/// See the primitive lowering table at the top of this module. Unknown
/// primitives return [`PipelineEmitError::UnknownPrimitive`] rather
/// than falling back to a default — silent fallback would lose layout
/// semantics and is exactly the bug class we want to surface at
/// compile time.
fn primitive_to_html_tag(tag: &str) -> Result<HtmlTag, PipelineEmitError> {
    Ok(match tag {
        "Box" => HtmlTag {
            open: "<div>".to_string(),
            close: "</div>".to_string(),
            self_closing: false,
        },
        "Row" => HtmlTag {
            open: r#"<div style="display: flex; flex-direction: row;">"#.to_string(),
            close: "</div>".to_string(),
            self_closing: false,
        },
        "Column" => HtmlTag {
            open: r#"<div style="display: flex; flex-direction: column;">"#.to_string(),
            close: "</div>".to_string(),
            self_closing: false,
        },
        "Text" => HtmlTag {
            open: "<span>".to_string(),
            close: "</span>".to_string(),
            self_closing: false,
        },
        "Image" => HtmlTag {
            // Image is a void element. Future PRs can wire in `src` /
            // `alt` props from `source` / `a11y-label`; this first cut
            // emits a bare `<img>` because there is no UI29-driven
            // primitive yet that needs binding.
            open: "<img>".to_string(),
            close: String::new(),
            self_closing: true,
        },
        "Spacer" => HtmlTag {
            open: r#"<div style="flex: 1"></div>"#.to_string(),
            // Spacer is structurally a container with empty body — we
            // emit the full `<div ...></div>` as the open and an empty
            // close so the tree walker treats it as self-closing.
            close: String::new(),
            self_closing: true,
        },
        "Divider" => HtmlTag {
            open: "<hr>".to_string(),
            close: String::new(),
            self_closing: true,
        },
        "Icon" => HtmlTag {
            open: r#"<span class="icon">"#.to_string(),
            close: "</span>".to_string(),
            self_closing: false,
        },
        // UI29 kernel primitives below ---------------------------------
        // `Stack` lays its children at the same origin via CSS positioning
        // — the children themselves opt into `position: absolute` via
        // mosstyle if they want to overlap; the stack just establishes
        // the containing block via `position: relative`.
        "Stack" => HtmlTag {
            open: r#"<div style="position: relative;">"#.to_string(),
            close: "</div>".to_string(),
            self_closing: false,
        },
        // `HostScroll` is the kernel-canonical name for what UI21 called
        // `Scroll`. The lowering matches the React backend: a div with
        // `overflow: auto` becomes a scroll container for any content that
        // exceeds its bounds. (Some other backends still ship `Scroll`;
        // adding that alias is a separate cleanup PR — U29-X1.)
        "HostScroll" => HtmlTag {
            open: r#"<div style="overflow: auto;">"#.to_string(),
            close: "</div>".to_string(),
            self_closing: false,
        },
        // `HostTable` and its four sub-tags lower to the matching native
        // HTML table elements. The semantic structure
        // (colgroup/thead/tbody/tfoot) is preserved 1:1 so accessibility
        // tooling sees a real table tree rather than a stack of divs.
        // Rendering of cells inside thead/tbody/tfoot is handled directly
        // in `emit_html_tree` because the row/cell shape (single `<tr>`
        // wrapping the body children as `<th>`/`<td>`) is fixed by the
        // sub-tag, not author-declarable.
        "HostTable" => HtmlTag {
            open: "<table>".to_string(),
            close: "</table>".to_string(),
            self_closing: false,
        },
        "HostTableHead" => HtmlTag {
            // The `<tr><th>…</th></tr>` shape is synthesised in
            // `emit_host_table_section`; the open/close here are just the
            // outer `<thead>` wrapper.
            open: "<thead>".to_string(),
            close: "</thead>".to_string(),
            self_closing: false,
        },
        "HostTableBody" => HtmlTag {
            open: "<tbody>".to_string(),
            close: "</tbody>".to_string(),
            self_closing: false,
        },
        "HostTableFoot" => HtmlTag {
            open: "<tfoot>".to_string(),
            close: "</tfoot>".to_string(),
            self_closing: false,
        },
        "HostTableColGroup" => HtmlTag {
            // Single `<col>` child per UI29 §2.1: column-width binding
            // arrives in a follow-up PR. The placeholder `<col>` is
            // semantically valid HTML and gives the host a hook to style.
            open: "<colgroup><col>".to_string(),
            close: "</colgroup>".to_string(),
            self_closing: false,
        },
        other => return Err(PipelineEmitError::UnknownPrimitive(other.to_string())),
    })
}

/// Build the inline text content for a leaf node that has a `content`
/// prop. Returns `None` if there is no `content` prop.
///
/// - `content: "literal"`         → `Some("literal")` (HTML-escaped).
/// - `content: slot: display-name` → `Some("${displayName}")` — the
///   template-literal interpolation that picks up the `const
///   displayName = ...` line from `_render()`.
fn build_text_content(node: &LayoutNode) -> Option<String> {
    let prop = node.props.iter().find(|p| p.name == "content")?;
    Some(match &prop.value {
        LayoutPropValue::String(s) => escape_html_text(s),
        LayoutPropValue::SlotRef(name) => {
            let camel = to_camel_case_first_lower(name);
            if is_safe_identifier(&camel) {
                format!("${{{camel}}}")
            } else {
                String::new()
            }
        }
        LayoutPropValue::Keyword(k) => escape_html_text(k),
        LayoutPropValue::Number(n) => format!("{n}"),
        LayoutPropValue::EmitRef(_) => String::new(),
        // An `Expr` shouldn't appear as a `content:` prop today (the
        // grammar only produces it for `when:` / `each:` arguments),
        // but defensively render it as empty rather than crashing.
        LayoutPropValue::Expr(_) => String::new(),
    })
}

/// Collect the per-emit event-attribute pairs for a layout node.
///
/// For every prop whose value is `LayoutPropValue::EmitRef(...)`, this
/// returns a string fragment to splice into the open tag — e.g.
/// `onclick="this.dispatch({type:'click'})"`.
///
/// The set of DOM event names we wire is mapped from the moslayout
/// prop name; today only `onClick` → `onclick` is implemented, which
/// is sufficient for the UI29-prereq scope. Adding more event hooks
/// (mouseover, keydown, …) is a single-site addition in
/// [`prop_name_to_dom_event`].
fn build_event_attributes(node: &LayoutNode) -> String {
    let mut attrs: Vec<String> = Vec::new();
    for prop in &node.props {
        let LayoutPropValue::EmitRef(emit_name) = &prop.value else {
            continue;
        };
        let Some(dom_event) = prop_name_to_dom_event(&prop.name) else {
            continue;
        };
        let lowered = strip_on_prefix(emit_name);
        let type_field = to_camel_case_first_lower(&lowered);
        if !is_safe_identifier(&type_field) {
            continue;
        }
        // HTML attribute values use double quotes, so the inline JS
        // body uses single quotes to keep escaping minimal.
        attrs.push(format!(
            "{dom_event}=\"this.dispatch({{type:'{type_field}'}})\""
        ));
    }
    if attrs.is_empty() {
        String::new()
    } else {
        format!(" {}", attrs.join(" "))
    }
}

/// Map a moslayout prop name like `onClick` to a DOM event-handler
/// attribute name like `onclick`.
///
/// Returns `None` for prop names that don't correspond to a known DOM
/// event — those are silently ignored so an unknown prop doesn't
/// produce broken HTML.
fn prop_name_to_dom_event(prop_name: &str) -> Option<&'static str> {
    match prop_name {
        "onClick" => Some("onclick"),
        // Hooks for the UI29 follow-up PR live here — onInput,
        // onChange, onKeyDown, etc. Each is a one-line addition.
        _ => None,
    }
}

/// Splice an attribute fragment into the position immediately before
/// the closing `>` of an HTML opening tag.
///
/// Used by [`build_event_attributes`] to graft `onclick="..."` onto a
/// primitive's built-in opening tag (`<div>` → `<div onclick="...">`,
/// or `<div style="...">` → `<div style="..." onclick="...">`).
fn insert_attrs_before_close(open_tag: &str, attrs: &str) -> String {
    // Self-closing void elements (`<img>` / `<hr>` / fully-formed
    // `<div ...></div>` for Spacer) won't normally carry event attrs
    // today, but if they did, we want to handle both `<foo>` and
    // `<foo />` shapes. The simplest correct rule: find the last `>`
    // in the open tag and splice before it. Spacer's `<div ...></div>`
    // shape would attach attrs to the *closing* `</div>` position
    // (after the inner `>`); to avoid that, we look for the first `>`.
    if let Some(pos) = open_tag.find('>') {
        let mut result = String::with_capacity(open_tag.len() + attrs.len());
        result.push_str(&open_tag[..pos]);
        result.push_str(attrs);
        result.push_str(&open_tag[pos..]);
        result
    } else {
        format!("{open_tag}{attrs}")
    }
}

