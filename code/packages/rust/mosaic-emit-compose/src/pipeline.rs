fn emit_event_sealed_class(
    component_name: &str,
    emits: &[EmitDecl],
) -> Result<String, PipelineEmitError> {
    let mut out = String::new();
    writeln!(out, "sealed class {component_name}Event {{").unwrap();
    writeln!(out, "    abstract val mosaicName: String").unwrap();
    writeln!(
        out,
        "    open val mosaicPayload: Map<String, Any?> = emptyMap()"
    )
    .unwrap();
    writeln!(
        out,
        "    val mosaicEnvelope: Map<String, Any?> get() = mapOf(\"event\" to mosaicName) + mosaicPayload"
    )
    .unwrap();
    for e in emits {
        let case = pascalize(&strip_on_prefix(&e.name));
        validate_safe_identifier(&case).map_err(PipelineEmitError::UnsafeEmitName)?;
        if e.params.is_empty() {
            // Parameterless events are singletons in Kotlin — `data object`
            // is the idiomatic shape and exposes `equals` / `hashCode`
            // automatically.
            writeln!(out, "    data object {case} : {component_name}Event() {{").unwrap();
            writeln!(
                out,
                "        override val mosaicName: String = \"{}\"",
                escape_kotlin_string(&e.name)
            )
            .unwrap();
            writeln!(out, "    }}").unwrap();
        } else {
            let params: Vec<String> = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    let ty = emit_payload_type_to_kotlin(&p.r#type);
                    format!("val {field}: {ty}")
                })
                .collect();
            writeln!(
                out,
                "    data class {case}({params}) : {component_name}Event() {{",
                params = params.join(", ")
            )
            .unwrap();
            writeln!(
                out,
                "        override val mosaicName: String = \"{}\"",
                escape_kotlin_string(&e.name)
            )
            .unwrap();
            let payload_entries = e
                .params
                .iter()
                .map(|p| {
                    let field = to_camel_case_first_lower(&p.name);
                    format!("\"{}\" to {field}", escape_kotlin_string(&field))
                })
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "        override val mosaicPayload: Map<String, Any?> get() = mapOf({payload_entries})"
            )
            .unwrap();
            writeln!(out, "    }}").unwrap();
        }
    }
    writeln!(out, "}}").unwrap();
    Ok(out)
}

