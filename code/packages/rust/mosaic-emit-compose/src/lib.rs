//! # mosaic-emit-compose — Jetpack Compose backend for the Mosaic three-language pipeline.
//!
//! Consumes the three-file pipeline output produced by
//! [`mosmodel-compiler`], [`moslayout-compiler`], and [`mosstyle-compiler`]
//! and produces a `.kt` source string containing a `@Composable`
//! function plus a sealed-class event hierarchy.
//!
//! ## Why a separate crate?
//!
//! Jetpack Compose's declarative tree, its property-driven recomposition
//! model, and its `@Composable fun ...` shape map fairly directly onto
//! the Mosaic IR — but the *syntax* (Kotlin, annotations, sealed
//! classes, `Modifier` chaining) is foreign enough that grafting a
//! Kotlin codegen path into the React or Flutter backend would dilute
//! both.  This crate is the Compose peer to `mosaic-emit-react`,
//! `mosaic-emit-flutter`, `mosaic-emit-swiftui`, and `mosaic-emit-qt`.
//!
//! ## Why one crate covers both Android + Desktop
//!
//! Jetpack Compose (Android) and Compose for Desktop share the
//! `androidx.compose.*` package and runtime.  A `@Composable fun X(...)`
//! authored against those packages renders unmodified on:
//!
//!  - Android phones / tablets (Jetpack Compose for Android)
//!  - macOS / Linux / Windows desktops (Compose for Desktop)
//!  - iOS (Compose Multiplatform for iOS, EAP)
//!  - The Web (Compose Multiplatform for Web, Wasm target)
//!
//! So `mosaic-compile --backend compose` produces ONE Kotlin file that
//! targets every Compose-supported platform.  That's the whole point of
//! Compose Multiplatform's design and the reason this backend can ship
//! a single emitter instead of a per-platform fork.
//!
//! ## Output file shape
//!
//! For a component named `FormulaBar` with slots `cell-address: text`,
//! `formula: text`, `read-only: bool`, and emits `onFormulaChange(value:
//! text)`, `onCommit`, `onCancel`, this crate emits:
//!
//! ```kotlin
//! // Auto-generated by mosaic-emit-compose. Do not edit.
//! package com.example
//!
//! import androidx.compose.foundation.layout.Row
//! import androidx.compose.foundation.text.BasicTextField
//! import androidx.compose.material.Text
//! import androidx.compose.runtime.Composable
//!
//! sealed class FormulaBarEvent {
//!     data class FormulaChange(val value: String) : FormulaBarEvent()
//!     data object Commit : FormulaBarEvent()
//!     data object Cancel : FormulaBarEvent()
//! }
//!
//! @Composable
//! fun FormulaBar(
//!     cellAddress: String,
//!     formula: String,
//!     readOnly: Boolean,
//!     dispatch: (FormulaBarEvent) -> Unit,
//! ) {
//!     Row {
//!         Text(text = cellAddress)
//!         BasicTextField(
//!             value = formula,
//!             onValueChange = { v -> dispatch(FormulaBarEvent.FormulaChange(v)) },
//!             enabled = !readOnly,
//!         )
//!     }
//! }
//! ```
//!
//! Notable points:
//!
//! 1. Event hierarchy is a `sealed class` with `data class` /
//!    `data object` per emit case — matches the strict-Flux
//!    `IMosaicAction`/`MosaicAction` shape used by `mosaic-flux-compose`.
//! 2. The `@Composable` function takes slots as named parameters and
//!    ends with a single `dispatch: (Event) -> Unit` closure parameter,
//!    mirroring the React `dispatch` prop and the Flutter
//!    `dispatch: void Function(Event)` field.
//! 3. The body walks the moslayout tree, emitting one Composable call
//!    per node.
//!
//! ## Primitive coverage in this first cut
//!
//! | mosmodel tag | Compose lowering                            |
//! |--------------|---------------------------------------------|
//! | Box          | `Box { ... }`                               |
//! | Row          | `Row { ... }`                               |
//! | Column       | `Column { ... }`                            |
//! | Text         | `Text(text = "..."), Text(text = slotName)` |
//! | Spacer       | `Spacer(modifier = Modifier.weight(1f))`    |
//! | HostInput    | `BasicTextField(value, onValueChange, ...)` |
//! | HostButton   | `Button(onClick = { ... }) { Text(label) }` |
//!
//! `For`, `If`/`Else`, and other UI29 meta-primitives fall through
//! to a `UnknownPrimitive` error for v0.1.0 — they land in follow-up
//! PRs as the Compose Grid emitter (the eventual `grid-emit-compose`
//! cycle in the autonomous loop's roadmap) needs them.

