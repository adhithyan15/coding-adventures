fn find_prop_value<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a LayoutPropValue> {
    node.props
        .iter()
        .find(|p| p.name == name)
        .map(|p: &LayoutProp| &p.value)
}

fn find_slot_ref_prop<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    match find_prop_value(node, name)? {
        LayoutPropValue::SlotRef(s) => Some(s.as_str()),
        _ => None,
    }
}

fn find_emit_ref_prop<'a>(node: &'a LayoutNode, name: &str) -> Option<&'a str> {
    match find_prop_value(node, name)? {
        LayoutPropValue::EmitRef(s) => Some(s.as_str()),
        _ => None,
    }
}

fn text_prop_expr(node: &LayoutNode, name: &str) -> Result<Option<String>, PipelineEmitError> {
    match find_prop_value(node, name) {
        Some(LayoutPropValue::String(s)) => Ok(Some(format!("\"{}\"", escape_kotlin_string(s)))),
        Some(LayoutPropValue::SlotRef(slot)) => {
            let camel = to_camel_case_first_lower(slot);
            validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(Some(camel))
        }
        Some(LayoutPropValue::Expr(expr)) => Ok(Some(expr.clone())),
        _ => Ok(None),
    }
}

fn bool_prop_expr(
    node: &LayoutNode,
    name: &str,
    default: &str,
) -> Result<String, PipelineEmitError> {
    match find_prop_value(node, name) {
        Some(LayoutPropValue::Keyword(k)) if k == "true" || k == "false" => Ok(k.clone()),
        Some(LayoutPropValue::SlotRef(slot)) => {
            let camel = to_camel_case_first_lower(slot);
            validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(format!("{camel} == true"))
        }
        Some(LayoutPropValue::Expr(expr)) => Ok(expr.clone()),
        _ => Ok(default.to_string()),
    }
}

fn disabled_prop_enabled_expr(node: &LayoutNode) -> Result<Option<String>, PipelineEmitError> {
    match find_prop_value(node, "disabled") {
        Some(LayoutPropValue::Keyword(k)) if k == "true" => Ok(Some("false".to_string())),
        Some(LayoutPropValue::Keyword(k)) if k == "false" => Ok(Some("true".to_string())),
        Some(LayoutPropValue::SlotRef(slot)) => {
            let camel = to_camel_case_first_lower(slot);
            validate_safe_identifier(&camel).map_err(PipelineEmitError::UnsafeSlotName)?;
            Ok(Some(format!("{camel} != true")))
        }
        Some(LayoutPropValue::Expr(expr)) => Ok(Some(format!("!({expr})"))),
        _ => Ok(None),
    }
}

/// `onFooBar` → `FooBar`.  Strip the leading `on` if and only if it
/// is followed by an upper-cased letter (so `online` stays `online`).
fn strip_on_prefix(s: &str) -> String {
    if let Some(rest) = s.strip_prefix("on") {
        if rest
            .chars()
            .next()
            .map(|c| c.is_ascii_uppercase())
            .unwrap_or(false)
        {
            return rest.to_string();
        }
    }
    s.to_string()
}

/// `formula-change` → `FormulaChange`.  PascalCase from kebab-case.
fn pascalize(s: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for c in s.chars() {
        if c == '-' || c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// `read-only` → `readOnly`.  camelCase from kebab-case.
fn to_camel_case_first_lower(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for (i, c) in s.chars().enumerate() {
        if c == '-' || c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else if i == 0 {
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Defence-in-depth: reject anything that wouldn't survive being
/// interpolated into a Kotlin identifier position.
fn validate_safe_identifier(s: &str) -> Result<(), String> {
    if s.is_empty() {
        return Err(s.to_string());
    }
    let mut chars = s.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_alphabetic() || first == '_') {
        return Err(s.to_string());
    }
    for c in chars {
        if !(c.is_ascii_alphanumeric() || c == '_') {
            return Err(s.to_string());
        }
    }
    Ok(())
}

/// Escape a Rust string into a Kotlin single-line string literal.
///
/// Beyond the obvious `\` and `"`, this also escapes:
///
/// - `$` — Kotlin's string interpolation sigil.  An unescaped `$` in
///   a literal expression (e.g. `"$dispatch"`) reads the named
///   variable from lexical scope.  Inside our `@Composable` function
///   the `dispatch` lambda *is* in scope, so a `.mll` literal
///   containing `"$dispatch"` would silently dereference it.  Escape
///   to `\$`.
/// - `\n`, `\r`, `\t` — newlines and tabs.  Without escaping, a
///   literal newline in the source would break out of the
///   single-line `"..."` literal.
///
/// Triple-quoted (raw) Kotlin strings are not emitted by this
/// crate, so we don't have to model their separate escape rules.
fn escape_kotlin_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

