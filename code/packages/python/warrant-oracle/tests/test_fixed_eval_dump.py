def test_the_fault_dump_records_both_gates():
    f = load(FAULTS)
    assert f["gate_shipped"] == ["ir.core"] and f["gate_on"] == ["ir.core", "ir.fixed", "ir.tuple"]
    assert f["accepted_blind_faults"] == []
    names = {(row["op"], row["fault"]) for row in f["faults"]}
    profile = [line.split(" ")[1:] for line in PROFILE.read_text().splitlines() if line.startswith("fault ")]
    assert names == {(op, fault) for op, fault in profile}
    shipped = {c["id"]: c for c in f["controls_shipped"]}
    opened = {c["id"]: c for c in f["controls_gate_on"]}
    assert shipped.keys() == opened.keys() and len(shipped) == len(profile)
    for cid, control in shipped.items():
        gated = [lv for lv in control["requires"] if lv != "ir.core"]
        (w,) = control["slim_witness"]
        if gated:
            assert w == {"claim": w["claim"], "deferred": gated[0]}, cid  # R12: the first level, sorted
        else:
            assert "chunk" in w, cid
        for w2 in opened[cid]["slim_witness"]:
            assert "chunk" in w2 and "deferred" not in w2 and "unproven" not in w2, cid
        assert opened[cid]["blind_claims"] == [] == control["blind_claims"], cid
        assert opened[cid]["requires"] == control["requires"]
    # the core faults are the same under both gates
    for cid, control in shipped.items():
        if control["requires"] == ["ir.core"]:
            assert opened[cid] == control


