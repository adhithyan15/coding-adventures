<!-- hl-knowledge: introduces=[]; assesses=[TE-LEX-C07-NUMBERS-1-5-01, TE-ETYMON-C07-NUMBERS-1-5-02, TE-SCRIPT-C07-NUMBERS-1-5-03] -->

