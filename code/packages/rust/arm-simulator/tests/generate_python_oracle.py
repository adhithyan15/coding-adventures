#!/usr/bin/env python3
"""Regenerate the Spec 07b common-surface corpus from the Python oracle.

The Python implementation predates the checked Rust lifecycle and only
executes MOV-immediate, ADD-register, SUB-register, and HLT.  This corpus
captures every comparable architectural field for that common surface.  R15
is normalized to Python's separate ``cpu.pc`` because ARMState documents R15
as the PC alias even though the legacy generic CPU storage does not mirror it.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
for package in ("arm-simulator", "cpu-simulator", "simulator-protocol"):
    sys.path.insert(0, str(ROOT / "code" / "packages" / "python" / package / "src"))

from arm_simulator.simulator import ARMSimulator  # noqa: E402


def seed_register(seed: int, index: int) -> int:
    return (((seed + 1) * 0x9E37_79B9) ^ (index * 0xD1B5_4A33)) & 0xFFFF_FFFF


def fnv1a(parts: list[bytes]) -> int:
    value = 0xCBF2_9CE4_8422_2325
    for part in parts:
        for byte in part:
            value ^= byte
            value = (value * 0x100_0000_01B3) & 0xFFFF_FFFF_FFFF_FFFF
    return value


def projected_hash(sim: ARMSimulator) -> int:
    pc = sim.cpu.pc & 0xFFFF_FFFF
    registers = [sim.cpu.registers.read(index) for index in range(15)] + [pc]
    return fnv1a(
        [pc.to_bytes(4, "little")]
        + [value.to_bytes(4, "little") for value in registers]
        + [bytes((0, 0, 0, 0)), bytes(sim.cpu.memory._data), bytes((sim.cpu.halted,))]
    )


def oracle(raw: int, seed: int) -> int:
    sim = ARMSimulator()
    for address in range(sim.cpu.memory.size):
        sim.cpu.memory._data[address] = (address * 37 + seed * 53 + 11) & 0xFF
    sim.cpu.memory._data[:4] = raw.to_bytes(4, "little")
    for index in range(15):
        sim.cpu.registers.write(index, seed_register(seed, index))
    sim.cpu.pc = 0
    sim.cpu.halted = False
    sim.step()
    return projected_hash(sim)


def words() -> list[tuple[str, int]]:
    cases: list[tuple[str, int]] = []
    for index in range(32):
        rd = index % 15
        rotate = (index * 5) & 0xF
        imm8 = (index * 73 + 1) & 0xFF
        raw = 0xE3A0_0000 | (rd << 12) | (rotate << 8) | imm8
        cases.append((f"mov_{index:02d}", raw))
    for opcode, name in ((0x4, "add"), (0x2, "sub")):
        for index in range(32):
            rd = index % 12
            rn = (index * 3 + 1) % 12
            rm = (index * 5 + 2) % 12
            raw = 0xE000_0000 | (opcode << 21) | (rn << 16) | (rd << 12) | rm
            cases.append((f"{name}_{index:02d}", raw))
    cases.append(("hlt", 0xFFFF_FFFF))
    return cases


def main() -> None:
    destination = Path(__file__).with_name("python_oracle_hashes.txt")
    lines = [
        "# Generated by generate_python_oracle.py from the legacy Python ARM oracle.",
        "# name|seed|raw_le_word|projected_full_state_fnv1a64",
    ]
    for name, raw in words():
        for seed in range(4):
            lines.append(f"{name}|{seed}|{raw:08x}|{oracle(raw, seed):016x}")
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
